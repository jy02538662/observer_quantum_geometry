"""
远景线 5（质量谱）· 族维度第十刀：反对易 = Kramers = 同一个 Z₂（±i）的最后一环

第九刀张力：「弱同位旋 = 反对易（断裂 SU(2)）还是 Kramers（T²=-1）？」
本刀坐实：反对易、Kramers、有向（手征）都在「±i」层面统一。

线索（15 号种子）：π 磁通 = Z₂；自旋 1/2 = π₁(SO(3)) = Z₂——同一个 Z₂ 的两张脸。
  反对易 T_xT_y=-T_yT_x = π 磁通（holonomy=-1）的后果
  Kramers T²=-1 = 自旋 1/2 的后果

本脚本检验：
  (1) 反对易 T_xT_y=-T_yT_x → T_xT_y 本征值 ±i（反对称）；
  (2) Kramers T²=-1 → T 本征值 ±i；
  (3) 有向 J=iσ_y（反对称）本征值 ±i（手征）；
  (4) 三者都在「±i」层面统一 ⟹ 反对易 = Kramers = 手征（同一个 Z₂）。
"""
import numpy as np
from sympy import Matrix, I, sqrt, simplify
from experiments._common import report

R = {}

sx = Matrix([[0, 1], [1, 0]])
sy = Matrix([[0, -I], [I, 0]])
sz = Matrix([[1, 0], [0, -1]])

# ---------------------------------------------------------------------------
# (1) 反对易 T_xT_y=-T_yT_x → T_xT_y 本征值 ±i
# ---------------------------------------------------------------------------
# T_x = σ_x, T_y = σ_y，T_xT_y = σ_xσ_y = iσ_z
TxTy = simplify(sx * sy)  # = iσ_z
TxTy_eigs = TxTy.eigenvals()

# 反对易：σ_xσ_y + σ_yσ_x = 0
anti = simplify(sx*sy + sy*sx)

R["anticommutation_eigs"] = {
    "T_xT_y = σ_xσ_y = iσ_z": TxTy == I * sz,
    "T_xT_y 本征值（应 ±i）": {str(k): v for k, v in TxTy_eigs.items()},
    "反对易 σ_xσ_y+σ_yσ_x=0": anti == Matrix.zeros(2),
    "关键": "反对易 T_xT_y=-T_yT_x 的产物 T_xT_y=iσ_z 本征值 ±i（反对称）",
}

# ---------------------------------------------------------------------------
# (2) Kramers T²=-1 → T 本征值 ±i
# ---------------------------------------------------------------------------
# 时间反演 T（Kramers），T²=-1，反酉
# 酉表示：T = iσ_y（反对称，T² = (iσ_y)² = -1）
T = I * sy  # = iσ_y（Kramers 的时间反演酉表示）
T_sq = simplify(T * T)  # T² = -1？
T_eigs = T.eigenvals()  # 本征值 ±i

R["kramers_eigs"] = {
    "T = iσ_y（Kramers 时间反演）": T == I * sy,
    "T² = -1？": T_sq == -Matrix([[1, 0], [0, 1]]),
    "T 本征值（应 ±i）": {str(k): v for k, v in T_eigs.items()},
    "关键": "Kramers T²=-1 的 T=iσ_y 本征值 ±i（自旋 1/2）",
}

# ---------------------------------------------------------------------------
# (3) 有向 J = iσ_y（反对称）本征值 ±i（手征）
# ---------------------------------------------------------------------------
J = Matrix([[0, 1], [-1, 0]])  # = iσ_y（有向，反对称）
J_is_T = simplify(J - T)  # J - T = 0？（J 就是 Kramers T）
J_eigs = J.eigenvals()

R["oriented_equals_kramers"] = {
    "有向 J = iσ_y = Kramers T？": J_is_T == Matrix.zeros(2),
    "J 本征值 ±i（手征）": {str(k): v for k, v in J_eigs.items()},
    "关键发现": "有向 J（手征）= iσ_y = Kramers T（时间反演）——「有向区分」的「有向」部分就是 Kramers 时间反演！",
}

# ---------------------------------------------------------------------------
# (4) 统一：反对易 = Kramers = 手征（同一个 ±i）
# ---------------------------------------------------------------------------
# T_xT_y = iσ_z（反对易，±i），T = iσ_y（Kramers，±i），J = iσ_y（有向/手征，±i）
# 三者都在「±i」层面统一
# 而 T_xT_y = iσ_z 和 T = iσ_y 是「同一个 ±i 空间的两个方向」（σ_z vs σ_y）
R["unification"] = {
    "反对易 T_xT_y=iσ_z（±i）": "π 磁通（holonomy=-1）的后果",
    "Kramers T=iσ_y（±i）": "自旋 1/2（π₁(SO(3))=Z₂）的后果",
    "有向 J=iσ_y（±i）": "手征（有向区分的箭头）",
    "统一": "反对易、Kramers、有向（手征）都在「±i」层面——是同一个 Z₂（π 磁通=自旋 1/2）的多个面",
    "15 号种子印证": "π 磁通 = Z₂，自旋 1/2 = π₁(SO(3)) = Z₂——同一个 Z₂ 的两张脸（空间 vs 内部）",
}

# ---------------------------------------------------------------------------
# (5) 化解第九刀张力
# ---------------------------------------------------------------------------
R["resolve_tension"] = {
    "第九刀张力": "弱同位旋 = 反对易（断裂 SU(2)）还是 Kramers（T²=-1）？",
    "化解": "反对易 = Kramers = 同一个 Z₂（±i）——弱同位旋 = 反对易 = Kramers 自旋，是同一个 SU(2)（来自 π 磁通=自旋 1/2 的 Z₂）",
    "完整链条": "π 磁通 Z₂（=自旋 1/2 Z₂）→ 反对易（T_xT_y=-T_yT_x）→ SU(2)（弱同位旋）→ 作用在 σ 空间 → 对易手征 γ⁵（τ 空间）→ 只作用左手",
}

# ---------------------------------------------------------------------------
# (6) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实（精确）": "① 反对易 T_xT_y=iσ_z 本征值 ±i；② Kramers T=iσ_y 本征值 ±i（T²=-1）；③ 有向 J=iσ_y=Kramers T（手征）；④ 三者都在 ±i 层面统一",
    "关键发现": "有向 J（手征）= iσ_y = Kramers T（时间反演）——「有向区分的箭头」就是「Kramers 时间反演」，而反对易 T_xT_y=iσ_z 是同一个 ±i 空间的另一个方向",
    "化解张力": "反对易 = Kramers = 同一个 Z₂（π 磁通 = 自旋 1/2）——弱同位旋 = 反对易 = Kramers 自旋，第九刀张力化解",
    "完整手征性链条": "π 磁通 Z₂ → 反对易 → SU(2)（弱同位旋）→ 作用 σ 空间 → 对易手征 γ⁵（τ 空间）→ 只作用左手——手征性 = 有向区分箭头（= Kramers 时间反演）的 ±i",
    "待坐实": "「反对易 T_xT_y=iσ_z」和「Kramers T=iσ_y」是同一个 ±i 空间的两个方向（σ_z vs σ_y），它们如何构成完整的 SU(2)（σ_x σ_y σ_z）需精确化",
    "措辞": "符号坐实（反对易=Kramers=手征=±i）+ 张力化解候选",
}

report(R, "exp_anticommutation_kramers")
