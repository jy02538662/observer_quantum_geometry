"""
路2（本征态解耦）· 三代质量矩阵 M = diag，解耦 = 标量指数的推论

问题（承接 [[路2：本征态解耦（矩阵化）]]）：
质量谱的「本征态」（代）解耦成独立指数 e^{λ·n}，其矩阵形式和解耦机制。

- 数学形式：m_n = e^{λ·n} 是「标量」（每代一个 n），标量 → diag → 对角 → 解耦（严格）；
- 物理机制：代 = S₃ 共轭类（守恒量）→ 代间无跃迁 → 解耦（条件严格，依赖「代=共轭类」识别）；
- 耦合（非对角）= 味结构（CKM/PMNS 混合角）= 路3 的缺口（框架无机制）。
"""
import sympy as sp
from experiments._common import report

R = {}

lam = sp.symbols("lambda", positive=True)

# ---------------------------------------------------------------------------
# 1. 三代质量矩阵 M = diag(e^λ, e^{2λ}, e^{3λ})
# ---------------------------------------------------------------------------
M = sp.diag(*[sp.exp(lam * k) for k in [1, 2, 3]])
eigs = [sp.exp(lam * k) for k in [1, 2, 3]]

# 对角性：非对角元全 0
offdiag_zero = all(M[i, j] == 0 for i in range(3) for j in range(3) if i != j)

R["step1_matrix"] = {
    "M = diag(e^λ, e^{2λ}, e^{3λ})": str(M),
    "非对角元全 0（对角）": bool(offdiag_zero),
    "本征值 = 对角元": [str(e) for e in eigs],
}

# ---------------------------------------------------------------------------
# 2. 解耦 = 对角 = 标量指数的推论
# ---------------------------------------------------------------------------
R["step2_decoupling_form"] = {
    "m_n = e^{λ·n} 是标量": "每代一个 n，不是矩阵（代间耦合）",
    "标量 → diag → 对角 → 解耦": "严格",
    "解耦的数学形式": "M 对角 = 代间无跃迁（严格，标量指数的推论）",
}

# ---------------------------------------------------------------------------
# 3. 解耦的物理机制 = 代守恒（条件严格）
# ---------------------------------------------------------------------------
R["step3_mechanism"] = {
    "代 = S₃ 共轭类": "阶 {1,2,3}",
    "共轭类在群作用下不变": "g C g⁻¹ = C（共轭类 = 轨道）",
    "⟹ 代是守恒量": "代间跃迁（改变代）被禁止",
    "⟹ 解耦": "代间无跃迁",
    "但": "「代 = 共轭类」是识别（= 路1 统一识别），所以「代守恒」是条件严格",
}

# ---------------------------------------------------------------------------
# 4. 耦合（非对角）= 味结构 = 路3
# ---------------------------------------------------------------------------
R["step4_coupling"] = {
    "框架给对角（解耦）": True,
    "框架给非对角（耦合）": False,
    "耦合 = 味混合（CKM/PMNS）": "路3 的缺口（代守恒禁止代间跃迁，但混合角恰需要跃迁）",
    "关键对立": "路2 的解耦 vs 路3 的耦合——要混合角需打破代守恒",
}

# ---------------------------------------------------------------------------
# 5. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "对角形式": "严格（标量指数的推论）",
    "代守恒机制": "条件严格（依赖「代=共轭类」识别）",
    "耦合（非对角）": "框架无机制，= 路3 缺口",
    "路2 定位": "形式工作，为路3 铺路（路3 要解决「打破代守恒的非对角从哪来」）",
}

report(R, "exp_route2_decoupling")
