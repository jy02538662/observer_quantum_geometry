"""
付费桥2 攻击（翻转：link→site = 模流）· 算 link 在模流下的长时间演化

翻转（用户）：「link→site」不是静态映射，是「模流（时间演化）」——
site = link 在模流 σ_t = ρ^{it} · ρ^{-it} 下的长时间极限（像退相干/热化）。

关键数学事实（先查）：
模流 σ_t(J) = ρ^{it} J ρ^{-it} 在 ρ 的对角基下，对角元不变、非对角元振荡 e^{it(lnρ_i-lnρ_j)}。
长时间平均 = 投影到 ρ 的简并子空间（退相干）：
  - 非简并非对角元 → 0（振荡平均掉）；
  - 对角元 → 保留。

而 link 算子的「site 对角 = 0」（P_x J P_x = 0）。所以退相干（对角化）后 = 0，不是 site。

本脚本坐实这个「退相干到 0」的结果，并诚实判断翻转是否成立。
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. link 算子 J（3×3，纯非对角，对角元 = 0）
# ---------------------------------------------------------------------------
J = np.array([[0, 1, 0],
              [0, 0, 1],
              [1, 0, 0]], dtype=complex)   # 平移型 link（site 对角 = 0）

R["step1_link"] = {
    "link 算子 J（平移型）": str(J.tolist()),
    "site 对角 J_ii = 0": bool(np.allclose(np.diag(J), 0)),
}

# ---------------------------------------------------------------------------
# 2. 观察者态 ρ（对角，非简并）
# ---------------------------------------------------------------------------
rho_diag = np.array([1.0, 2.0, 3.0])   # 非简并
rho = np.diag(rho_diag)

R["step2_rho"] = {
    "观察者态 ρ（对角，非简并）": rho_diag.tolist(),
    "说明": "ρ = C/λ 的离散版（尺度态，非简并）",
}

# ---------------------------------------------------------------------------
# 3. 模流 σ_t(J) = ρ^{it} J ρ^{-it}
# ---------------------------------------------------------------------------
def modular_flow(J, rho, t):
    rho_it = np.diag(rho_diag ** (1j * t))
    rho_minus_it = np.diag(rho_diag ** (-1j * t))
    return rho_it @ J @ rho_minus_it

# 验证：对角元不变，非对角元振荡
t_test = 0.5
flow_test = modular_flow(J, rho, t_test)
R["step3_flow"] = {
    "模流 σ_t(J) 对角元（应 = 0，不变）": [f"{flow_test[i,i]:.2e}" for i in range(3)],
    "模流 σ_t(J) 非对角元（振荡 e^{it(lnρi-lnρj)}）": f"{flow_test[0,1]:.3f}",
}

# ---------------------------------------------------------------------------
# 4. 长时间平均（退相干）
# ---------------------------------------------------------------------------
T = 200.0
N_samples = 5000
t_list = np.linspace(0, T, N_samples)

avg = np.zeros((3, 3), dtype=complex)
for t in t_list:
    avg += modular_flow(J, rho, t)
avg /= N_samples

R["step4_time_avg"] = {
    "长时间平均 ⟨σ_t(J)⟩ 的模": [[round(abs(avg[i,j]), 4) for j in range(3)] for i in range(3)],
    "退相干结果": "非对角元 → 0（振荡平均掉），对角元 = 0（link 的 site 对角本来 = 0）→ 整体 → 0",
}

# ---------------------------------------------------------------------------
# 5. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "模流长时间平均 = 退相干": "非简并非对角元振荡平均掉，对角元保留",
    "link 的对角元 = 0": "site 对角 P_x J P_x = 0（link 定义）",
    "∴ 退相干后 = 0": "模流把 link 变成 0，不是 site——因为「对角化」只保留已有对角元，不产生新对角元",
    "翻转是否成立": "在最简模型（ρ 位置基对角）下不成立——link 退相干到 0；但「尺度基 ≠ 位置基」时（ρ 在尺度基对角），link 在尺度基可能有对角元，需进一步分析",
}

report(R, "exp_bridge2_modular_flow")
