"""
远景线 5（质量谱）· 族维度第八刀：手征性 = 有向区分的箭头（反对称 J 的 ±i）

用户直觉：手征性来自「有向区分」的箭头本身。「区分」对称、「有向」不对称——
反对称矩阵 J 天然手征（本征值 ±i）。断裂产生 SU(2)，SU(2) 来自反对易
T_xT_y=-T_yT_x——反对易本身带方向，SU(2) 继承方向，只作用「箭头发出端」一侧。

本脚本检验：
  (1) 反对称 J=[[0,1],[-1,0]] 的本征值 = ±i（有向 = 手征）；
  (2) 反对易 T_xT_y=-T_yT_x 是否「带方向」（反对称 = 有向）；
  (3) SU(2)（反对易）是否只作用「箭头发出端」（+i 或 Γ=+1 侧）；
  (4) 具体：T_x,T_y 与 Γ 的对易/反对易关系，σ_z=-iT_xT_y 与 Γ 的关系。
"""
import numpy as np
from sympy import Matrix, I, sqrt, simplify
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (1) 反对称 J = 有向区分「有向」部分，本征值 ±i
# ---------------------------------------------------------------------------
# 有向区分 = 区分（对称，±1）+ 有向（反对称，±i）
J = Matrix([[0, 1], [-1, 0]])  # 反对称（有向）
J_eigs = J.eigenvals()          # 本征值 ±i
J_antisym = J + J.T             # 反对称：J+J^T=0

# 区分（对称）部分 = diag(1,-1)，本征值 ±1
D_dist = Matrix([[1, 0], [0, -1]])
D_eigs = D_dist.eigenvals()

R["oriented_distinction"] = {
    "有向（反对称 J=[[0,1],[-1,0]]）本征值": {str(k): v for k, v in J_eigs.items()},
    "区分（对称 diag(1,-1)）本征值": {str(k): v for k, v in D_eigs.items()},
    "J 反对称（J+J^T=0）": J_antisym == Matrix.zeros(2),
    "关键": "反对称 J（有向）本征值 ±i——天然手征（±i = 号差/左右手）",
}

# ---------------------------------------------------------------------------
# (2) 反对易 T_xT_y=-T_yT_x 是否「带方向」（= 反对称 = 有向）
# ---------------------------------------------------------------------------
# T_x = σ_x, T_y = σ_y（泡利，反对易 σ_xσ_y=-σ_yσ_x）
sx = Matrix([[0, 1], [1, 0]])
sy = Matrix([[0, -I], [I, 0]])
sz = Matrix([[1, 0], [0, -1]])

# 反对易：σ_xσ_y + σ_yσ_x = 0
anti = simplify(sx*sy + sy*sx)
# σ_z = -iσ_xσ_y（反对易的产物 = 方向）
sz_from_anti = simplify(-I*sx*sy)

R["anticommutation_direction"] = {
    "σ_xσ_y + σ_yσ_x（反对易，应 0）": anti == Matrix.zeros(2),
    "σ_z = -iσ_xσ_y（反对易的产物）": sz_from_anti == sz,
    "σ_z 本征值": {str(k): v for k, v in sz.eigenvals().items()},
    "关键": "反对易 T_xT_y=-T_yT_x 的产物 σ_z=-iT_xT_y 带「方向」（本征值 ±1 = 上下），是「有向」的体现",
}

# ---------------------------------------------------------------------------
# (3) 反对易带方向 → 手征：σ_z（方向）与 Γ（二分）的关系
# ---------------------------------------------------------------------------
# Γ = 二分 sign = σ_z（在 2×2 最小模型里，二分 = σ_z）
# 检验 T_x=σ_x, T_y=σ_y 与 Γ=σ_z 的对易/反对易
Gamma = sz
Tx_comm_Gamma = simplify(sx*Gamma + Gamma*sx)  # σ_xσ_z + σ_zσ_x（反对易 = 0）
Ty_comm_Gamma = simplify(sy*Gamma + Gamma*sy)  # σ_yσ_z + σ_zσ_y（反对易 = 0）
Tz_comm_Gamma = simplify(sz*Gamma - Gamma*sz)  # σ_zσ_z - σ_zσ_z（对易 = 0）

R["Tx_Ty_vs_Gamma"] = {
    "T_x 与 Γ 反对易（σ_xσ_z+σ_zσ_x=0）": Tx_comm_Gamma == Matrix.zeros(2),
    "T_y 与 Γ 反对易（σ_yσ_z+σ_zσ_y=0）": Ty_comm_Gamma == Matrix.zeros(2),
    "σ_z 与 Γ 对易（σ_zσ_z-σ_zσ_z=0）": Tz_comm_Gamma == Matrix.zeros(2),
    "结论": "T_x,T_y 反对易 Γ（连接 A↔B，翻转 Γ）；σ_z=-iT_xT_y 对易 Γ（保持 A/B，带方向）",
}

# ---------------------------------------------------------------------------
# (4) 关键：σ_z（方向）作用在 Γ=+1 侧 vs Γ=-1 侧
# ---------------------------------------------------------------------------
# Γ=σ_z 的本征态：|+⟩=(1,0)（Γ=+1），|-⟩=(0,1)（Γ=-1）
# σ_z 作用在 |+⟩ = +1·|+⟩（保持），作用在 |-⟩ = -1·|-⟩（保持）
# 而 σ_x 作用在 |+⟩ = |-⟩（翻转 Γ=+1 → Γ=-1）
plus = Matrix([1, 0]); minus = Matrix([0, 1])
sz_plus = sz * plus   # σ_z|+⟩ = +1|+⟩
sz_minus = sz * minus # σ_z|-⟩ = -1|-⟩
sx_plus = sx * plus   # σ_x|+⟩ = |-⟩（翻转）

R["direction_on_gamma"] = {
    "σ_z|+⟩（Γ=+1 侧）": str(sz_plus),  # 保持 +1 侧
    "σ_z|-⟩（Γ=-1 侧）": str(sz_minus),  # 保持 -1 侧
    "σ_x|+⟩（翻转 Γ=+1 → Γ=-1）": str(sx_plus),
    "关键发现": "σ_z=-iT_xT_y（反对易的方向）保持 Γ 的 ±1 侧（对易）；而 T_x,T_y（反对易本身）翻转 Γ（连接 A↔B）",
}

# ---------------------------------------------------------------------------
# (5) 手征性：SU(2) 只作用「箭头发出端」的精确形式
# ---------------------------------------------------------------------------
# 「有向区分」的箭头 = J=[[0,1],[-1,0]]（有向），本征值 ±i
# J 的本征向量：|+i⟩=(1,-i)/√2, |-i⟩=(1,i)/√2
# 检验「SU(2)（反对易）只作用 +i 侧」
J_eigvecs = J.eigenvects()
R["J_eigenvectors"] = {
    "J=[[0,1],[-1,0]] 的本征向量": [f"λ={str(e[0])}: {str(e[2])}" for e in J_eigvecs],
    "手征 ±i": "有向 J 的本征值 ±i = 号差 = 左右手（家底 11：时间=有向区分 J，本征值 ±i）",
    "候选对应": "「弱同位旋 SU(2) = 断裂 = 反对易 = 有向 J（±i）」→ 只作用 +i 侧（箭头发出端 = 左手）",
}

# ---------------------------------------------------------------------------
# (6) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实（精确）": "① 反对称 J（有向）本征值 ±i（手征）；② 反对易 T_xT_y=-T_yT_x 的产物 σ_z=-iT_xT_y 带方向（±1）；③ T_x,T_y 反对易 Γ（翻转），σ_z 对易 Γ（保持）",
    "核心发现": "「有向」= 反对称 J（±i）= 手征；「反对易」= 有向（σ_z=-iT_xT_y 带方向）——所以 SU(2)（反对易）天然带「方向」（手征 ±i）",
    "手征性的精确形式（候选）": "弱同位旋 SU(2) = 断裂 = 反对易 → 反对称（有向）→ 本征值 ±i（手征）——「只作用左手」= 「只作用 +i 侧（箭头发出端）」",
    "待坐实": "「σ_z=-iT_xT_y 只作用 +i 侧」需精确坐实（σ_z 对易 Γ，保持 A/B 两侧，不是「只作用 +i」；「+i 侧」需定义 = J 的本征向量 |+i⟩）",
    "措辞": "符号坐实（有向=反对称=手征 ±i）+ 候选机制（手征性=箭头发出端）——「反对易带方向」坐实，「SU(2) 只作用 +i 侧」待精确定义",
}

report(R, "exp_arrow_direction")
