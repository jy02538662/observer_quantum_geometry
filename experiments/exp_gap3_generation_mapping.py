"""
缺口 3 · 代 → N 映射 → 跨代质量比 能否先验给出 29.2（先结构后数扫描）

背景：
  - 29.2 = (m_c/m_u)/(m_s/m_d) = 上型跨代比 ÷ 下型跨代比 ≈ 27(3³)~32(2⁵)，误差 ~20%
  - 补十：结构路线四候选全排除（27/32/转置投影/缺陷能级），核心障碍 = 框架「区分=二分」只给 2 的幂
  - 本轮（2026-10-03）：Yukawa 顶点内生 S_int=ΣδD ψ†ψ；选择点①收回 λ_min=π²/N² = 2−δ_N 领头阶
  - 预印本 1.25 三合一：质量 = 尺度破缺 = 2−δ_N

本脚本问（先结构后数，不反推 29.2）：
  若「质量」通过某个「代 → 截断 N」的结构映射接到 N，两个候选量——
    (a) 尺度破缺 2−δ_N = 4sin²(π/(2(N+1)))        （O(1/N²) 精细小量）
    (b) 模流频率 λ_mod(N) = log(N²/(π² ln(2N²/π²)))（给指数层级 e^{λ_mod}≈207）
  ——能否先验给出跨代比 m_2/m_1（靶点 577 上型 / 19.8 下型）与上下型不对称 29.2？

诚实纪律（AGENTS 三问①）：
  「代阶 n（S₃ 共轭类阶 1,2,3）」与「截断 N（区分节点数）」不是同一对象。
  本脚本枚举的所有「代 → N」映射都是【候选】，无一有结构等式背书。
  判据：先看有没有【先验命中】，再看命中是否是「先结构后数」而非「先数后结构」。

靶点（PDG 2022，复用 exp_gap3_29p2 的数据）：
  m_c/m_u = 577（上型跨代比，第二代/第一代）
  m_s/m_d = 19.8（下型跨代比）
  29.2 = 577/19.8（上下型不对称）
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 0. 靶点
# ---------------------------------------------------------------------------
TARGET = {
    "up_gen12": 577.0,     # m_c/m_u
    "down_gen12": 19.8,    # m_s/m_d
    "asymmetry": 577.0 / 19.8,  # = 29.2
    "ln_asymmetry": float(np.log(577.0 / 19.8)),
}
R["targets"] = {
    "m_c/m_u (上型跨代比)": TARGET["up_gen12"],
    "m_s/m_d (下型跨代比)": TARGET["down_gen12"],
    "29.2 = 上型/下型不对称": round(TARGET["asymmetry"], 3),
    "ln(29.2)": round(TARGET["ln_asymmetry"], 4),
    "候选整数 27(3³) 与 32(2⁵) 距中心": {
        "27": round(29.2 - 27, 2),
        "32": round(29.2 - 32, 2),
        "都在 1σ 内 (σ≈20%)": True,
    },
}

# ---------------------------------------------------------------------------
# 1. 两个候选量作为 N 的函数（量级分析）
# ---------------------------------------------------------------------------
def delta_N(N):
    return 2 * np.cos(np.pi / (N + 1))

def scale_break(N):
    """2 − δ_N = 4sin²(π/(2(N+1)))"""
    return 2 - delta_N(N)

def lam_mod(N):
    """模流频率 λ_mod(N) = log(N²/(π² ln(2N²/π²)))。N 太小使内层 log 为负时无定义 → NaN。"""
    N = float(N)
    inner = 2 * N**2 / np.pi**2
    if inner <= 1.0:  # ln(inner) <= 0 → 外层 log 无定义
        return np.nan
    denom = np.pi**2 * np.log(inner)
    if denom <= 0:
        return np.nan
    return np.log(N**2 / denom)

N_probe = [2, 3, 4, 5, 6, 8, 14, 16, 21, 49, 128]
R["quantity_vs_N"] = {
    str(N): {
        "2−δ_N": float(scale_break(N)),
        "λ_mod(N)": float(lam_mod(N)),
        "e^{λ_mod}": float(np.exp(lam_mod(N))),
    }
    for N in N_probe
}

_lam128 = lam_mod(128)
R["scale_analysis"] = {
    "2−δ_N 量级": f"O(1/N²)：N=128 时 {scale_break(128):.2e}，是精细小量",
    "λ_mod 量级": f"对数级：N=128 时 λ_mod={_lam128:.3f}，e^λ_mod={np.exp(_lam128):.1f}（指数层级）",
    "N 过小的无定义": "N=1 时内层 ln(2N²/π²)<0 → λ_mod 无定义（标记 NaN）。这本身是信息：N=1（恒等/第一代）给不出有意义的模流频率。",
    "初步判断": "2−δ_N（O(1/N²)小量）的比值给不出 577/19.8 的指数层级；λ_mod 的指数 e^{λ_mod} 才是层级主因。29.2 若要来自「N 的分量差」，应看 λ_mod 的差 Δλ=λ_mod(N_up)−λ_mod(N_down)。",
}

# ---------------------------------------------------------------------------
# 2. 候选「代 → N」映射（明确标注：候选，无结构等式背书）
# ---------------------------------------------------------------------------
# 三代 = S₃ 共轭类（阶 1,2,3）。上型/下型 = 颜色 SU(3) 表示（3 vs 3̄，超荷 ±2/3 vs ∓1/3）。
# 候选映射：代阶 n → 截断 N（都要标注「候选」）
candidate_maps = {
    "A_Nn=2^n (二分递归 n 次)": [2, 4, 8],
    "B_Nn=n (阶本身)": [1, 2, 3],
    "C_Nn=共轭类大小": [1, 3, 2],
    "D_Nn=中心化子阶": [6, 2, 3],
    "E_Nn=128×阶权重": [128.0/3, 128.0/2, 128.0],  # 权重 1/3,1/2,1
}

R["candidate_maps"] = {
    name: {
        "三代 N 值": vals,
        "标注": "候选映射，无一有『代阶 n → 截断 N』的结构等式背书（AGENTS 三问①）",
    }
    for name, vals in candidate_maps.items()
}

# ---------------------------------------------------------------------------
# 3. 跨代比计算（两种质量形式）——先结构后数，对比靶点
# ---------------------------------------------------------------------------
def gen_ratio(form, N1, N2):
    """第二代/第一代 质量比。form='exp'（指数）或 'scale_break'（尺度破缺）。
    返回 float 或 None（N 过小使 λ_mod 无定义时）。"""
    if form == "exp":
        lm1, lm2 = lam_mod(N1), lam_mod(N2)
        if np.isnan(lm1) or np.isnan(lm2):
            return None
        return float(np.exp(lm2 - lm1))
    elif form == "scale_break":
        # m ∝ √(2−δ_N)，第二代更重 → N 更小。比 = √(2−δ_{N2})/√(2−δ_{N1})
        return float(np.sqrt(scale_break(N2) / scale_break(N1)))
    else:
        raise ValueError(form)

scan_results = {}
for name, (N1, N2, N3) in candidate_maps.items():
    # 跨代比：第二代/第一代（用 N2 vs N1）
    r_exp = gen_ratio("exp", N1, N2)
    r_sb = gen_ratio("scale_break", N1, N2)
    scan_results[name] = {
        "N(第1代),N(第2代)": (N1, N2),
        "跨代比 指数形式 e^{Δλ}": (round(r_exp, 2) if r_exp is not None else "无定义(N过小)"),
        "跨代比 尺度破缺 √(2−δ) 比": round(r_sb, 4),
        "靶点 577(上)/19.8(下)": "见下判定",
    }

R["gen_ratio_scan"] = scan_results

# ---------------------------------------------------------------------------
# 4. 上下型不对称（29.2 = 上型跨代比 / 下型跨代比）
#    若上型 N_up、下型 N_down 不同，29.2 = e^{λ_mod(N_up) − λ_mod(N_down)}（指数形式）
# ---------------------------------------------------------------------------
# 反解：要 Δλ = ln(29.2)，N_down 需满足 λ_mod(N_up)−λ_mod(N_down)=ln(29.2)。
# 用「上型=128（总截断）、下型=候选小 N」算 Δλ，看哪个候选落在 ln(29.2) 附近。
asym_target = TARGET["ln_asymmetry"]
asym_scan = {}
for N_down in [2, 3, 4, 5, 6, 7, 8, 14, 16, 21, 49]:
    lm_d = lam_mod(N_down)
    if np.isnan(lm_d):
        asym_scan[f"上型128 vs 下型{N_down}"] = {
            "Δλ": "无定义(N过小)",
            "e^{Δλ}": "无定义",
            "距 ln(29.2) 的差": "无定义",
        }
        continue
    dlam = lam_mod(128) - lm_d
    asym_scan[f"上型128 vs 下型{N_down}"] = {
        "Δλ = λ_mod(128)−λ_mod(N)": round(float(dlam), 4),
        "e^{Δλ}": round(float(np.exp(dlam)), 2),
        "距 ln(29.2) 的差": round(float(dlam - asym_target), 4),
    }

R["asymmetry_scan"] = asym_scan

# 找最接近 ln(29.2) 的 N_down（诚实标注：这是「先数后结构」的观察，不是结构推导）
best = min(
    (kv for kv in asym_scan.items() if kv[1]["距 ln(29.2) 的差"] != "无定义"),
    key=lambda kv: abs(kv[1]["距 ln(29.2) 的差"]),
)
R["asymmetry_best"] = {
    "最接近的 N_down": best[0],
    "其 Δλ": best[1]["Δλ = λ_mod(128)−λ_mod(N)"],
    "距 ln(29.2) 的差": best[1]["距 ln(29.2) 的差"],
    "诚实标注": "这是『反解观察』（先数后结构），不是『结构推导』——N_down 没有结构等式背书",
}

# ---------------------------------------------------------------------------
# 5. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "量级事实": "2−δ_N（O(1/N²)）给不出指数层级；λ_mod 的指数 e^{λ_mod} 才是跨代比主因。",
    "跨代比扫描": "所有候选『代→N』映射（2^n/阶/类大小/中心化子/权重）的指数形式跨代比都远小于 577 或远大于 19.8——无一同时命中上型 577 与下型 19.8（更别说它们的比 29.2）。",
    "上下型不对称": "若强行用『上型=128、下型=小 N』反解，最接近 ln(29.2) 的 N 差 ≈2%（见 asymmetry_best），但这是反解（先数后结构），N 无结构背书。",
    "三问判定": "① 代阶 n 与截断 N 不是同一对象——『代→N』映射无结构等式，直接拼是空中楼阁；② 计数：候选映射里 2^n 是递归（幂次）、类大小/中心化子是状态数，混用是补十警告的同款错误；③ 反解命中 = 先数后结构 = 事后合理化。",
    "定位": "【未证实/存疑】档。2−δ_N / λ_mod 的『代分量比』未能先验给出 29.2——这条『有限 N 修正解释 29.2』的路，在『先结构后数』纪律下不成立。29.2 仍是动力学缺口（β 函数/RG），与本轮『四费米子≠Yukawa』的诚实边界一致。",
    "对下一步的意义": "关掉『2−δ_N 解释 29.2』这一线，29.2 继续留活口，主线转桥 C。除非将来『代→N』有独立的结构等式（目前没有）。",
}

report(R, "exp_gap3_generation_mapping")
