"""
用户思路判生死：框架的「涌现规范场」能不能给「禁闭力」（线性势 V~r）？

物理（搜到的）：电子分数化（自旋-电荷分离）→ spinon + holon，它们之间有力 =
涌现规范场的「禁闭」（线性势，V~r，不放手）。用户直觉「旋冲力」可能就是这个禁闭力。

本脚本验证（干净，无红外发散）：
  - 环上（周期边界，N 格点）无质量 Green 函数（去零模 k=0）是二次型：
      G_0(x) = (x − N/2)²/(2N) − (N²+2)/(24N)   ← 短距离线性 = 禁闭
  - 环上有质量 Green 函数（m>0）是指数衰减（log G 线性）：
      log G_m(x) ≈ −m|x| + const   ← 指数 = 屏蔽

判据（干净）：无质量 → 二次型（线性，禁闭）；有质量 → 指数（屏蔽）。
无质量用解析式比对（误差 ~1e-14），有质量用「log G 线性」验证。

Code: `py -m experiments.exp_confinement_1D`
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 环上（周期边界）Green 函数
# ---------------------------------------------------------------------------
def green_numeric(N, m):
    """环上 Green 函数数值（谱和，去零模避免 m=0 红外发散）。"""
    k = 2 * np.pi * np.arange(N) / N
    D2 = 4 * np.sin(k / 2) ** 2
    Gk = np.zeros(N)
    if m < 1e-12:
        nonzero = np.abs(k) > 1e-12
        Gk[nonzero] = 1.0 / D2[nonzero]
    else:
        Gk = 1.0 / (D2 + m * m)
    Gx = np.zeros(N)
    for x in range(N):
        Gx[x] = np.real(np.sum(Gk * np.exp(1j * k * x)) / N)
    return Gx

N = 64
x = np.arange(N)

# 无质量：解析式比对（二次型 = 线性禁闭）
G0_num = green_numeric(N, 0.0)
G0_ana = (x - N / 2) ** 2 / (2 * N) - (N ** 2 + 2) / (24 * N)
err0 = float(np.max(np.abs(G0_num - G0_ana)))
R["massless_quadratic"] = {
    "无质量 Green 数值 vs 解析式误差": f"{err0:.2e}",
    "无质量 = 二次型 (x−N/2)²/2N（短距离线性 = 禁闭）": err0 < 1e-8,
}

# 有质量：log G 线性（指数 = 屏蔽）
Gm_num = green_numeric(N, 0.5)
# 环上距离 |x|（短的那边）
d = np.minimum(x, N - x)
logG = np.log(np.abs(Gm_num) + 1e-30)
# 拟合 log G ~ a·d + b（只取 d>0 的点，避开 d=0）
mask = d > 0
a, b = np.polyfit(d[mask], logG[mask], 1)
resid = logG[mask] - (a * d[mask] + b)
r2 = 1 - np.sum(resid ** 2) / np.sum((logG[mask] - logG[mask].mean()) ** 2)
R["massive_exponential"] = {
    "有质量 log G 拟合斜率（应 <0 = 指数衰减）": round(float(a), 4),
    "log G 线性拟合 R²": round(float(r2), 6),
    "有质量 = 指数（屏蔽，非禁闭）": r2 > 0.99 and a < 0,
}

R["confinement_criterion"] = {
    "禁闭 = 无质量 1D 规范场（线性势 V~r）": True,
    "屏蔽 = 有质量 1D 规范场（指数势 e^{-mr}）": True,
}

# ---------------------------------------------------------------------------
# 框架的「尺度方向」是无质量还是有质量？
# ---------------------------------------------------------------------------
Ns = [16, 64, 256, 1024]
mass = [2 - 2 * np.cos(np.pi / (n + 1)) for n in Ns]   # 2−δ_N = 尺度破缺（质量）
R["scale_direction_mass"] = {
    "N": Ns,
    "尺度破缺 2−δ_N（= 尺度方向的「质量」）": [round(m, 8) for m in mass],
    "N→∞ 时质量→0（禁闭恢复）": mass[-1] < 1e-4,
    "判读": "有限 N 时尺度方向「有质量」（屏蔽，非禁闭）；N→∞ 连续极限时「无质量」（禁闭）",
}

# ---------------------------------------------------------------------------
# 结论
# ---------------------------------------------------------------------------
R["verdict"] = {
    "禁闭（线性势）的机制": "1D 无质量规范场给线性势 V~r（禁闭）；有质量给指数（屏蔽）。框架的尺度方向是 1D，禁闭在尺度方向无质量时出现",
    "框架的尺度方向": "质量 = 尺度破缺 2−δ_N = π²/N²。有限 N 有质量（屏蔽）；N→∞ 无质量（禁闭）",
    "对「旋冲力」的含义": "框架的「禁闭力」（线性势）在连续极限（N→∞，无质量）处，不是有限 N。「禁闭」和「长程 1/r」都是「无质量模 = 连续极限」——同一个「离散→连续」主墙的两张脸",
    "诚实边界": "这是「禁闭 = 1D 无质量」的标准结果（数值+解析式验证），不是「框架内生旋冲力」已证明——「尺度方向」和「涌现规范场（内涨落 A）」的精确对接还没建立",
}

report(R, "exp_confinement_1D")
