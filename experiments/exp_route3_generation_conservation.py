"""
路3（味结构）A 一轮侦察 · 代守恒 = S₃ 共轭类守恒（S₃ 内严格）

问题（承接 [[路3：味结构（代守恒vs味混合，A一轮侦察）]]）：
路2 埋的伏笔 =「代守恒禁止跃迁、味混合需要跃迁」。A 一轮先攻「代守恒能否自发打破」。
第一步 = 坐实「代守恒」的精确数学结构：代 = S₃ 共轭类，共轭作用保持它（严格），
且 S₃ 无非平凡外自同构（Aut(S₃)=Inn(S₃)），所以 S₃ 内部无法打破代守恒。

结论：打破代守恒必须来自 S₃ 之外的结构（颜色 SU(3)/缺陷/有向 J/键序）。
"""
from sympy.combinatorics import Permutation
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. S3 元素 + 共轭类（= 代）
# ---------------------------------------------------------------------------
S3 = [Permutation([0, 1, 2]),   # 恒等
      Permutation([1, 0, 2]),   # (12)
      Permutation([0, 2, 1]),   # (23)
      Permutation([2, 1, 0]),   # (13)
      Permutation([1, 2, 0]),   # (123)
      Permutation([2, 0, 1])]   # (132)

def cycle_type(p):
    return tuple(sorted([len(c) for c in p.cyclic_form]))

classes = {}
for p in S3:
    classes.setdefault(cycle_type(p), []).append(p)

class_summary = {}
for ct, els in sorted(classes.items()):
    class_summary[str(ct)] = {"阶": int(els[0].order()), "类大小": len(els)}

R["step1_classes"] = {
    "S3 共轭类（= 代）": class_summary,
    "说明": "代 = 共轭类（循环类型），阶 {1,2,3}",
}

# ---------------------------------------------------------------------------
# 2. 共轭作用是否改变循环类型（代）
# ---------------------------------------------------------------------------
changed = 0
for g in S3:
    for p in S3:
        gp = g * p * (~g)
        if cycle_type(gp) != cycle_type(p):
            changed += 1

R["step2_conjugation"] = {
    "共轭作用 g p g⁻¹ 改变循环类型（代）的次数": changed,
    "代守恒（0 = 严格不变）": changed == 0,
    "说明": "代 = 循环类型，在 S₃ 共轭作用下严格不变 ⟹ 代守恒",
}

# ---------------------------------------------------------------------------
# 3. S3 有无非平凡外自同构
# ---------------------------------------------------------------------------
# Aut(S3) = Inn(S3) = S3：S3 的所有自同构都是内自同构（共轭），无外自同构
# （S3 的生成元 {转置} 的像必须仍是转置，共 3 个转置，故 |Aut(S3)| = 6 = |Inn(S3)|）
R["step3_outer_aut"] = {
    "Aut(S3) = Inn(S3) = S3": "S3 的自同构全为内自同构（共轭），无非平凡外自同构",
    "推论": "S3 内部【没有】能改变共轭类（代）的作用 ⟹ 代守恒在 S3 内严格",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "代守恒 = S3 共轭类守恒": "严格（共轭作用 0 次改变循环类型）",
    "S3 内能否打破": "不能（Aut(S3)=Inn(S3)，无外自同构）",
    "打破代守恒的来源": "必须 S3 之外的结构（颜色 SU(3)/缺陷/有向 J/键序）",
    "三档措辞": "「代守恒在 S3 内严格」=【严格（群论）】；「S3 外结构能否自发打破」=【待查（A 一轮候选）】",
}

report(R, "exp_route3_generation_conservation")
