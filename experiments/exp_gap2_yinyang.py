import numpy as np
from sympy import Matrix, I, Rational, simplify, sqrt
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (1) 有向 J = iσ_y，±i 本征态
# ---------------------------------------------------------------------------
J = I * Matrix([[0, -I], [I, 0]])          # iσ_y，反对称，J²=-I
# J = [[0,1],[-1,0]] 实矩阵，本征值 ±i
J_real = Matrix([[0, 1], [-1, 0]])
ev = J_real.eigenvects()                   # [(i,1,[v]), (-i,1,[v])]
R["oriented_J"] = {
    "J = iσ_y = [[0,1],[-1,0]]": "反对称，J²=-I",
    "本征值": [str(e[0]) for e in ev],
}

# ---------------------------------------------------------------------------
# (2) 谱投影 P_+ = (I - iJ)/2（+i 侧，上型）、P_- = (I + iJ)/2（-i 侧，下型）
# ---------------------------------------------------------------------------
I2 = Matrix.eye(2)
P_plus  = simplify((I2 - I * J_real) / 2)   # (I - iJ)/2，+i 谱投影
P_minus = simplify((I2 + I * J_real) / 2)   # (I + iJ)/2，-i 谱投影

R["spectral_projections"] = {
    "P_+ = (I-iJ)/2（+i 侧，上型/抱阳）": str(P_plus),
    "P_- = (I+iJ)/2（-i 侧，下型/负阴）": str(P_minus),
}

# ---------------------------------------------------------------------------
# (3) 「同时负阴抱阳」= 谱投影完备性 + 正交性（核心新点）
# ---------------------------------------------------------------------------
completeness = simplify(P_plus + P_minus)   # = I₂
orthogonality = simplify(P_plus * P_minus)  # = 0
idempotent_p = simplify(P_plus * P_plus - P_plus)   # P_+² = P_+
idempotent_m = simplify(P_minus * P_minus - P_minus) # P_-² = P_-

R["simultaneous_yin_yang"] = {
    "P_+ + P_- = I₂（完备性 = 「同时」）": str(completeness),
    "P_+ · P_- = 0（正交性 = 阴阳不重叠）": str(orthogonality),
    "P_+² = P_+（幂等）": str(idempotent_p),
    "P_-² = P_-（幂等）": str(idempotent_m),
    "物理含义": "上型/下型 = 同一个有向区分 J 的两个互补投影（同一枚硬币的两个朝向），非两个独立粒子",
}

# ---------------------------------------------------------------------------
# (4) 「朝向 → 三重态/单态」的对应（识别，已坐实于 exp_singlet_projection）
# ---------------------------------------------------------------------------
