"""
缺口 15 · N=128 形式化 /「观察层独立」的可验证结构（DD 自反的信息层）

问题（承接 N=128 有向区分推导链段 2）：「7 盏灯 → 2⁷=128 种观察模式」的
「观察层独立」——观察者对 7 盏灯各自独立「看/不看」——是「从公设推导」还是「换公设」？

之前卡在「语义争论」：「观察层独立」到底合不合法。本脚本把它搬到「算子层」，
算三个可验证的量：

1. 【HS 正交】7 个非平凡元素作为矩阵，在 Hilbert–Schmidt 内积 Tr(A†B) 下是否两两正交？
   —— 这是「群表示正交性」，如果成立则是【严格】。
2. 【结果空间】7 个元素的本征值是否只有 3 个独立（γ,κ,σ 三个生成元的本征值）？
   —— 这是「群论计数坑」：7=2³−1 是状态数，不是自由度数。
3. 【选择空间】观察者对 7 个元素各自「测量/不测量」，选择空间是否是 2⁷=128？
   —— 这是「观察层独立」真正用的「7」：不是「独立本征值数」，是「可观察量个数」。

关键区分（本脚本的核心贡献）：
  「HS 正交」和「独立本征值」是两回事。7 个元素在 HS 内积下正交（群表示正交性，
  严格），但它们的本征值只有 3 个独立（群论计数坑，也严格）。两者不矛盾——
  「观察层独立」的「7」是「HS 正交的可观察量个数」，不是「独立本征值数」。

  「观察层独立」的最终卡点 = 第 3 步「观察者独立选择看/不看」的合法性：
  它是「观察 = 有向区分」（区分可作用于任何可观察量）的推论，还是「新公设」
  （观察者有独立看/不看的自由）？—— 这是本脚本算不出、需要公设级形式化的最后一步。

构造：三个对合 Z₂（Γ 手征 / K 共轭 / s 尺度对偶），用 Pauli σ_z 的 3 体张量积表示，
8×8 矩阵（2³=8 维态空间）。Z_2^3 阿贝尔，8 元素，7 非平凡。
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 0. 构造三个对合生成元 Γ, K, s（Pauli σ_z 的 3 体张量积，8×8）
# ---------------------------------------------------------------------------
I2 = np.eye(2)
sz = np.array([[1, 0], [0, -1]])   # 对合：sz²=I

def kron3(a, b, c):
    return np.kron(np.kron(a, b), c)

Gamma = kron3(sz, I2, I2)   # Γ = σ_z ⊗ I ⊗ I（谱面/手征）
K     = kron3(I2, sz, I2)   # K = I ⊗ σ_z ⊗ I（复面/共轭）
s     = kron3(I2, I2, sz)   # s = I ⊗ I ⊗ σ_z（尺度对偶面）

gens = {"Γ": Gamma, "K": K, "s": s}

# 7 个非平凡元素（三个生成元的非平凡乘积）
nontrivial = {
    "Γ":  Gamma,
    "K":  K,
    "s":  s,
    "ΓK": Gamma @ K,
    "Γs": Gamma @ s,
    "Ks": K @ s,
    "ΓKs": Gamma @ K @ s,
}

R["construction"] = {
    "三个生成元": ["Γ=σ_z⊗I⊗I", "K=I⊗σ_z⊗I", "s=I⊗I⊗σ_z"],
    "态空间维数": "2³=8",
    "非平凡元素数": len(nontrivial),
    "说明": "Z_2^3 阿贝尔群，8 元素（含单位元），7 非平凡",
}

# ---------------------------------------------------------------------------
# 1.【对合】7 个元素都是对合（平方 = I）—— 严格
# ---------------------------------------------------------------------------
involutions = {name: np.allclose(A @ A, np.eye(8)) for name, A in nontrivial.items()}
R["step1_involution"] = {
    "每个元素平方=I": involutions,
    "状态": "【严格】对合（Z₂ 元素平方=单位元）",
}

# ---------------------------------------------------------------------------
# 2.【对易】7 个元素两两对易（Z_2^3 阿贝尔）—— 严格
# ---------------------------------------------------------------------------
names = list(nontrivial.keys())
commute = {}
for i in range(len(names)):
    for j in range(i+1, len(names)):
        a, b = nontrivial[names[i]], nontrivial[names[j]]
        commute[f"[{names[i]},{names[j]}]=0"] = bool(np.allclose(a @ b, b @ a))
R["step2_commute"] = {
    "两两对易": commute,
    "状态": "【严格】Z_2^3 阿贝尔，生成元对易",
}

# ---------------------------------------------------------------------------
# 3.【HS 正交】7 个元素在 Hilbert–Schmidt 内积 Tr(A†B) 下两两正交 —— 严格
#    这是「群表示正交性」：8 个元素（含单位元）是 8×8 矩阵空间的 8 个正交方向
# ---------------------------------------------------------------------------
orthogonal = {}
for i in range(len(names)):
    for j in range(i+1, len(names)):
        a, b = nontrivial[names[i]], nontrivial[names[j]]
        # A†=A（厄米对合），Tr(AB) 用 trace
        inner = np.trace(a @ b)
        orthogonal[f"Tr({names[i]}·{names[j]})=0"] = bool(np.isclose(inner, 0.0))
all_orthogonal = all(orthogonal.values())
R["step3_HS_orthogonal"] = {
    "两两 HS 正交 Tr(A·B)=0": orthogonal,
    "全部正交": all_orthogonal,
    "状态": "【严格】群表示正交性——7 个非平凡元素 + 单位元 = 8 个 HS 正交方向",
}

# ---------------------------------------------------------------------------
# 4.【结果空间】7 个元素的本征值是否只有 3 个独立 —— 严格（群论计数坑）
#    7 个元素的本征值由 3 个生成元本征值 (γ,κ,σ)∈{±1}³ 决定，结果空间 2³=8
# ---------------------------------------------------------------------------
# 验证：7 个元素的迹（=本征值和）。对合的本征值 ±1，迹=+1数 − −1数。
# 关键：7 个元素的对角元是 3 个生成元对角元的乘积，所以本征值由 (γ,κ,σ) 决定。
traces = {name: float(np.trace(A)) for name, A in nontrivial.items()}
# 结果空间：8 个本征向量，每个对应 (γ,κ,σ)∈{±1}³，7 个非平凡元素的本征值 = 乘积
R["step4_result_space"] = {
    "7 元素迹（=本征值和，全 0）": traces,
    "本征值由 3 独立变量决定": "Γ→γ, K→κ, s→σ, ΓK→γκ, Γs→γσ, Ks→κσ, ΓKs→γκσ",
    "结果空间维数": "2³=8（3 个独立本征值 γ,κ,σ）",
    "状态": "【严格】群论计数坑——7 个元素的本征值只有 3 个独立自由度，7=2³−1 是状态数",
}

# ---------------------------------------------------------------------------
# 5.【选择空间】观察者对 7 个元素各自「测量/不测量」—— 2⁷=128 —— 组合计数
#    这是「观察层独立」真正用的「7」：不是「独立本征值数」(3)，是「可观察量个数」(7)
# ---------------------------------------------------------------------------
choice_space = 2 ** 7
R["step5_choice_space"] = {
    "7 个元素各自测量/不测量": "x=(x₁,...,x₇)∈{0,1}⁷",
    "选择空间维数": f"2⁷={choice_space}",
    "状态": "【组合计数】观察者对 7 个可观察量各自独立二选 = 2⁷",
}

# ---------------------------------------------------------------------------
# 6. 关键区分：HS 正交（7 个方向）vs 独立本征值（3 个变量）
# ---------------------------------------------------------------------------
R["step6_key_distinction"] = {
    "HS 正交方向数": 7,   # 群表示正交性，严格
    "独立本征值数": 3,    # 群论计数坑，严格
    "选择空间维数": "2⁷=128",
    "结果空间维数": "2³=8",
    "两者不矛盾的原因": "「HS 正交」是「7 个元素作为矩阵正交」（表示正交性）；「独立本征值」是「7 个元素的本征值由 3 个变量决定」（群论计数）。一个是「方向数」，一个是「自由度数」",
    "「观察层独立」的「7」是哪个": "「可观察量个数」（HS 正交方向数 7），不是「独立本征值数」（3）",
}

# ---------------------------------------------------------------------------
# 7. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "可验证的（本脚本算出的）": "① 7 元素对合（严格）；② 7 元素 HS 正交（群表示正交性，严格）；③ 结果空间 2³（3 独立本征值，群论计数坑，严格）；④ 选择空间 2⁷（组合计数）",
    "核心结构结论": "「观察层独立」的「7」是「HS 正交的可观察量个数」，不是「独立本征值数」——所以它【不违反】群论计数（3 个独立自由度）。「观察层独立」和「群论计数坑」说的是两个不同的维数：方向数 7 vs 自由度数 3",
    "最终卡点（本脚本算不出）": "「观察者对 7 个 HS 正交方向各自独立选择看/不看」的「独立选择」是否合法——它是「观察=有向区分」（区分可作用于任何可观察量）的推论，还是「新公设」（观察者有独立看/不看的自由）？这是公设级形式化的最后一步",
    "诚实定位（三档）": "「7 元素 HS 正交」=【严格（群表示正交性）】；「选择空间 2⁷」=【组合计数】；「观察者独立选择」=【候选（观察=有向区分的诠释，待公设级形式化）】——不是【否证】",
    "DD 自反的贡献": "DD 自反把「观察层独立」从「语义争论」搬到「算子层」（7 元素 HS 正交 + 选择空间 2⁷ 可验证），但「独立选择」的合法性仍是「观察=有向区分」的诠释，DD 自反给的是「外部观察者」的载体，不是「独立选择」的证明",
}

report(R, "exp_gap15_observer_independence")
