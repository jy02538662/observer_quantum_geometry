"""
D-D 自反（多体入口）· 检查「U = V(d→0) 极限」的反着想（带/无自旋）

翻转（用户）：「同格点 U」=「相邻 V 在距离→0 的极限」——两者是同一个耦合（库仑）
在不同距离的投影，U 不是「缺口」是「V 的极限」。

关键（先查）：
- 无自旋：V(0) = c_i† c_i = n_i，V(0)² = n_i² = n_i（泡利，无双占据）→ 不给 Hubbard U；
- 带自旋：V(0) = n_{i↑} + n_{i↓}，V(0)² = n_{i↑}+n_{i↓} + 2 n_{i↑}n_{i↓} → 含「同格点双占据 2n_{i↑}n_{i↓}」= Hubbard U 的形式。

判据：带自旋的 V(0)² 是否给出 Hubbard U（2n_{i↑}n_{i↓}）？是则 U 从 V 的 d→0 极限内生。
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. 无自旋：V(0) = n_i，V(0)² = n_i（泡利，无双占据）
# ---------------------------------------------------------------------------
# 单格点无自旋：基 |0⟩, |1⟩（占据 0/1）
n = np.diag([0, 1])   # n_i = diag(0,1)
n2 = n @ n            # n_i² = n_i（泡利）

R["step1_spinless"] = {
    "无自旋 V(0) = n_i": "c_i† c_i = 占据数",
    "V(0)² = n_i² = n_i（泡利）": bool(np.allclose(n2, n)),
    "给 Hubbard U？": "否——无自旋无双占据（泡利禁止），不给 n_{i↑}n_{i↓}",
}

# ---------------------------------------------------------------------------
# 2. 带自旋：V(0) = n_{i↑} + n_{i↓}，V(0)² 含双占据
# ---------------------------------------------------------------------------
# 单格点带自旋：基 |0⟩, |↑⟩, |↓⟩, |↑↓⟩
n_up = np.diag([0, 1, 0, 1])      # n_{i↑}
n_down = np.diag([0, 0, 1, 1])    # n_{i↓}
n_total = n_up + n_down           # V(0) = n_{i↑} + n_{i↓}

V0_sq = n_total @ n_total         # V(0)² = (n_↑ + n_↓)²

# 双占据项 n_{i↑} n_{i↓} = diag(0,0,0,1)
double_occ = n_up @ n_down

# V(0)² 应 = n_↑ + n_↓ + 2 n_{i↑}n_{i↓}（泡利 n_↑²=n_↑, n_↓²=n_↓, 交叉项 2n_↑n_↓）
expected = n_up + n_down + 2 * double_occ

R["step2_spinful"] = {
    "带自旋 V(0) = n_↑ + n_↓": str((n_total.astype(int)).tolist()),
    "V(0)² 含双占据 2 n_{i↑}n_{i↓}": bool(np.allclose(V0_sq, expected)),
    "双占据项 = Hubbard U 的形式": "2 n_{i↑}n_{i↓}（同格点自旋 ↑↓ 密度乘积）",
    "说明": "带自旋的 V(0)² 给出 Hubbard U 的形式（系数 2）——U 从 V 的 d→0 极限内生",
}

# ---------------------------------------------------------------------------
# 3. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "无自旋 V(d→0)": "给 n_i（密度），V²=n_i 无双占据，不给 Hubbard U",
    "带自旋 V(d→0)": "给 n_↑+n_↓，V² 含 2 n_{i↑}n_{i↓}（双占据）= Hubbard U 的形式",
    "翻转是否成立": "部分成立——带自旋时 U 从 V(d→0)² 内生（2n_{i↑}n_{i↓}），但需「自旋」自由度 + 「d→0 连续极限」",
    "诚实卡点": "「d→0 极限」在离散格点需连续化（离散→连续 = 动力学缺口）；「自旋」自由度在框架里是 link 乘积（非对角）",
    "净判断": "U 不是「纯缺口」——带自旋的 V 极限给 Hubbard U 形式，但「d→0 连续化」和「自旋对角」仍是动力学缺口的两面",
}

report(R, "exp_bridge2_U_limit")
