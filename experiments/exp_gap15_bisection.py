"""
缺口 15 · N=128 形式化 /「区分 = 二分」的算子推导（谱分解）

承接前三个脚本（HS 正交 7 / 结果空间 2³ / 行为空间 2⁷），本脚本补上缺的那一环：
把「区分」这个行为，精确构造成「谱分解」算子，验证「区分 = 二分」是【严格】的算子结构。

核心命题（要程序推导的）：
  「观察 = 一次有向区分」的「区分」=「二分」。而「二分」对每个对合可观察量 O 是
  【唯一的】：O 的谱分解 O = P₊ − P₋，其中 P₊、P₋ 是 O 的 ±1 本征投影。
  「区分 O」=「做这个谱分解」= 在 P₊ / P₋ 之间二分。

  所以「区分 = 二分」不是诠释，是【对合可观察量的谱分解】，严格。

  然后「7 次区分」= 7 个谱分解各自「做/不做」= 2⁷。而「7 个谱分解」的独立性，
  来自「7 个可观察量 HS 正交」（7 个不同的可观察量，7 个不同的谱分解）。

本脚本算四件事：
  1. 每个对合可观察量的谱分解：P₊=(I+O)/2, P₋=(I−O)/2，验证 P₊+P₋=I, P₊P₋=0, O=P₊−P₋
  2. 7 个可观察量的 7 个谱分解是否「7 个不同」（两两不同）
  3. 「7 次二分」的选择空间 = 2⁷（幂集）
  4. 关键：验证「区分 = 二分」是谱分解（严格），「7 次独立」来自「7 个不同可观察量」

诚实边界：谱分解（P₊+P₋=I 等）是【严格】；7 个谱分解不同是【严格】（HS 正交）；
「做/不做」的「独立选择」仍是【诠释】（一次独立操作可重复）——但本脚本把「区分=二分」
的算子部分全部坐实，只剩「可重复性」这一个词义。
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 0. 构造 7 个对合可观察量（Γ,K,s,ΓK,Γs,Ks,ΓKs）
# ---------------------------------------------------------------------------
I2 = np.eye(2)
sz = np.array([[1, 0], [0, -1]])
I8 = np.eye(8)

def kron3(a, b, c):
    return np.kron(np.kron(a, b), c)

Gamma = kron3(sz, I2, I2)
K     = kron3(I2, sz, I2)
s     = kron3(I2, I2, sz)

observables = {
    "Γ":  Gamma,
    "K":  K,
    "s":  s,
    "ΓK": Gamma @ K,
    "Γs": Gamma @ s,
    "Ks": K @ s,
    "ΓKs": Gamma @ K @ s,
}

R["construction"] = {
    "7 个对合可观察量": list(observables.keys()),
    "说明": "每个 O 是对合（O²=I），本征值 ±1",
}

# ---------------------------------------------------------------------------
# 1. 谱分解：P₊=(I+O)/2, P₋=(I−O)/2，验证 P₊+P₋=I, P₊P₋=0, O=P₊−P₋
#    这是「区分 = 二分」的算子定义：对合可观察量 O 天然给唯一的二分
# ---------------------------------------------------------------------------
spectral = {}
for name, O in observables.items():
    Pp = (I8 + O) / 2.0   # +1 本征投影
    Pm = (I8 - O) / 2.0   # -1 本征投影
    spectral[name] = {
        "P₊+P₋=I": bool(np.allclose(Pp + Pm, I8)),
        "P₊P₋=0": bool(np.allclose(Pp @ Pm, np.zeros((8, 8)))),
        "O=P₊−P₋": bool(np.allclose(Pp - Pm, O)),
        "P₊²=P₊（幂等）": bool(np.allclose(Pp @ Pp, Pp)),
        "P₋²=P₋（幂等）": bool(np.allclose(Pm @ Pm, Pm)),
    }

all_spectral_ok = all(all(v.values()) for v in spectral.values())
R["step1_spectral"] = {
    "7 个可观察量的谱分解验证": spectral,
    "全部通过": all_spectral_ok,
    "状态": "【严格】每个对合可观察量 O 给唯一的二分（P₊=(I+O)/2, P₋=(I−O)/2），谱分解定理",
    "意义": "「区分 = 二分」不是诠释，是「对合可观察量的谱分解」——区分 O = 在 P₊/P₋ 间二分",
}

# ---------------------------------------------------------------------------
# 2. 7 个谱分解是否「7 个不同」？（不同可观察量 → 不同谱分解）
#    判据：P_{i,+} ≠ P_{j,+}（投影算子不同）
# ---------------------------------------------------------------------------
names = list(observables.keys())
P_plus = {name: (I8 + O) / 2.0 for name, O in observables.items()}
distinct = {}
for i in range(len(names)):
    for j in range(i+1, len(names)):
        distinct[f"P({names[i]})≠P({names[j]})"] = bool(
            not np.allclose(P_plus[names[i]], P_plus[names[j]]))
all_distinct = all(distinct.values())
R["step2_distinct"] = {
    "7 个 +1 投影两两不同": distinct,
    "全部不同": all_distinct,
    "状态": "【严格】7 个可观察量 HS 正交 → 7 个不同的谱分解（7 个不同的二分）",
}

# ---------------------------------------------------------------------------
# 3. 「7 次二分」的选择空间 = 2⁷（幂集）
#    每个谱分解「做/不做」= 二元，7 个 → 2⁷
# ---------------------------------------------------------------------------
choice_space = 2 ** 7
R["step3_choice_space"] = {
    "7 个谱分解各自做/不做": "x∈{0,1}⁷",
    "选择空间": f"2⁷ = {choice_space}",
    "状态": "【组合计数】幂集 2⁷（一旦承认 7 个二分可分离）",
}

# ---------------------------------------------------------------------------
# 4. 「区分 = 二分」的算子结论 + 剩余卡点
# ---------------------------------------------------------------------------
R["step4_conclusion"] = {
    "「区分 = 二分」的算子坐实": "谱分解（P₊+P₋=I, P₊P₋=0, O=P₊−P₋）——严格，不是诠释",
    "「7 个不同二分」的算子坐实": "7 个 HS 正交可观察量 → 7 个不同谱分解——严格",
    "「7 次独立二分 = 2⁷」": "组合计数（幂集）——严格（一旦承认 7 个二分可分离）",
    "剩余卡点（唯一，且是词义）": "「7 个二分可分离」（可以只做第 1 个不做第 2 个）=「一次独立操作可重复」。这是公设「观察=一次有向区分」里「一次」的语义：单个独立操作（可重复 7 次）还是 一次性强制整体（不可重复）？",
}

# ---------------------------------------------------------------------------
# 5. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "程序推导坐实的（严格）": "① 区分=二分=谱分解（P₊+P₋=I 等）；② 7 个不同二分（HS 正交）；③ 选择空间 2⁷（幂集）",
    "「区分=二分」是推导不是诠释": "对合可观察量的谱分解是唯一的，所以「区分 O = 在 ±1 间二分」是谱分解定理的推论，不是模糊的「测量自由性」",
    "剩余卡点收窄到词义": "唯一剩下的「7 个二分可分离」=「一次独立操作可重复」。公设「观察=一次有向区分」的「一次」=「单个独立操作」（可重复 7 次）还是「一次性整体」（不可重复）？这是作者对「一次」的语义决定",
    "三档措辞": "「区分=二分=谱分解」=【严格】；「7 个不同二分」=【严格】；「7 次可分离二分」=【候选（「一次」=独立操作的词义，待作者裁决）】——不是【否证】",
    "整体链条": "观察=一次有向区分 →（区分=二分=谱分解，严格）→（7 个 HS 正交可观察量=7 个二分，严格）→（7 次独立二分=2⁷，组合计数）→ N=128。只剩「一次=独立操作」这个词义裁决",
}

report(R, "exp_gap15_bisection")
