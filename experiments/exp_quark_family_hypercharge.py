# ---------------------------------------------------------------------------
# (4) 完整旋转（周期3）vs 投影（周期1）的分解
# ---------------------------------------------------------------------------
# 3-循环 P（3×3 颜色空间）的不可约分解：3 = 平凡 1 ⊕ 标准 2
# 平凡 1 = 对称方向 (r+g+b)/√3（P 不动，周期 1 = 投影）
# 标准 2 = 差空间 {r+g+b=0}（P 作用 = 120° 旋转，周期 3 = 完整旋转）
P123 = Matrix([[0,0,1],[1,0,0],[0,1,0]])
eigs = P123.eigenvects()  # [(eigenvalue, multiplicity, [eigenvectors])]
R["decomposition"] = {
    "3-循环 P 的不可约分解": "3 = 平凡 1 ⊕ 标准 2",
    "平凡 1（投影，周期1）": "对称方向 (1,1,1)/√3，特征值 1（不动）",
    "标准 2（完整旋转，周期3）": "差空间 {r+g+b=0}，特征值 ω,ω²（120°旋转）",
    "特征值": {str(k): m for k, m in [(e[0], e[1]) for e in eigs]},
}

# 每个色波函数 r,g,b 在「平凡1」和「标准2」上的分解（模²）
# r = (1,0,0)：平凡分量 = (1,1,1)/3（模²=1/3），标准分量 = (2,-1,-1)/3（模²=2/3）
def decompose(v):
    v = np.array(v, dtype=float)
    trivial = np.ones(3)/np.sqrt(3) * (v @ (np.ones(3)/np.sqrt(3)))
    standard = v - trivial
    return float(np.sum(trivial**2)), float(np.sum(standard**2))

r_dec = decompose([1,0,0])
g_dec = decompose([0,1,0])
b_dec = decompose([0,0,1])
R["color_wavefunction_decompose"] = {
    "r 的（平凡模², 标准模²）": r_dec,
    "g 的（平凡模², 标准模²）": g_dec,
    "b 的（平凡模², 标准模²）": b_dec,
    "观察": "r,g,b 的平凡:标准 = 1/3 : 2/3（对称，都是 1/3 投影 + 2/3 旋转）",
    "结论": "「上型走完整旋转、下型走投影」若指 r vs b 的平凡/标准分解，则不成立（对称 1/3:2/3）",
}

# ---------------------------------------------------------------------------
# (5) 关键：3-循环不保持超荷本征子空间（混合正负超荷）
# ---------------------------------------------------------------------------
# 正超荷子空间 = span{r,g}（λ₈=+1/(2√3)），负超荷子空间 = span{b}（λ₈=-1/√3）
# 3-循环 P 是否保持这两个子空间？
# P r = g（在正超荷里），P g = b（跑出正超荷到负超荷）→ P 不保持正超荷子空间
# 验证：P 作用在正超荷投影算子 Π_+ = r r† + g g† 上，P Π_+ P⁻¹ ≠ Π_+
r_v = np.array([1,0,0], dtype=float)
g_v = np.array([0,1,0], dtype=float)
b_v = np.array([0,0,1], dtype=float)
P = np.array([[0,0,1],[1,0,0],[0,1,0]], dtype=float)
Pi_plus = np.outer(r_v, r_v) + np.outer(g_v, g_v)  # 正超荷投影（对角 diag(1,1,0)）
Pi_minus = np.outer(b_v, b_v)                      # 负超荷投影（diag(0,0,1)）
P_Pi_plus_Pinv = P @ Pi_plus @ P.T
R["hypercharge_subspace_mixing"] = {
    "正超荷投影 Π₊": "diag(1,1,0)（r,g 两个态）",
    "负超荷投影 Π₋": "diag(0,0,1)（b 一个态）",
    "P Π₊ P⁻¹": str(P_Pi_plus_Pinv.tolist()),
    "P Π₊ P⁻¹ = Π₊？": np.allclose(P_Pi_plus_Pinv, Pi_plus),
    "意义": "3-循环不保持正超荷子空间（P Π₊ P⁻¹≠Π₊），即 3-循环把正超荷态(r,g)旋转到负超荷态(b)——超荷符号被 3-循环「循环」",
}

# ---------------------------------------------------------------------------
# (6) 弱同位旋方向（I₃）与 3-循环
# ---------------------------------------------------------------------------
# I₃ = λ₃/2，λ₃ = diag(1,-1,0)
