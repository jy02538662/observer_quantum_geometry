"""
远景线 5（质量谱）· 族维度第三刀：超荷符号与 3-循环的关系（色波函数精确计算）

用户直觉：不是「上型走 2、下型走 1」，而是「上型走 3-循环的完整旋转，下型走投影」，
「哪个走完整循环」由超荷符号（或弱同位旋方向）决定。

本脚本从 su(3) ⊃ su(2) 分支规则精确计算上下型的色波函数，检查：
  (1) 基本表示 3 的三个权 r,g,b 的 Cartan 坐标 (λ₃=弱同位旋方向, λ₈=超荷方向)；
  (2) 3-循环（Weyl 群 S₃ 的 3-循环元素）= Cartan 平面的 120° 旋转；
  (3) 3-循环对「超荷符号」的循环（正↔负）和对「弱同位旋方向」的循环；
  (4) 「完整旋转（周期3，差空间/标准2）」vs「投影（周期1，对称/平凡1）」的精确分解；
  (5) 检验：上下型色波函数在 3-循环下的行为，是否给出「3 vs 1」的不对称。
"""
import numpy as np
from sympy import Matrix, I, sqrt, Rational, eye, exp, pi, simplify
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (1) 基本表示 3 的三个权（Cartan 坐标）
# ---------------------------------------------------------------------------
# λ₃ = diag(1,-1,0)（弱同位旋方向，I₃=λ₃/2）
# λ₈ = diag(1,1,-2)/√3（超荷方向）
# 三个色波函数（颜色态）r, g, b 的权：
#   r: (λ₃, λ₈) = (1, 1/√3)   —— 未归一，λ₈ 用 diag(1,1,-2)/√3
#   g: (-1, 1/√3)
#   b: (0, -2/√3)
