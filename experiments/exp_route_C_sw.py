"""
攻付费桥2 三条路 · 路C：两个线性 D 耦合 + Schrieffer-Wolff 是否给「局域 U」

背景：路C = 两个线性 D 耦合 t_p，SW 变换（二阶微扰）投影到低能，看是否涌现
四费米子项（有效 U）。这是凝聚态的 superexchange 机制。

核心问题：SW 二阶给的是「非局域 superexchange」（密度-密度，两个格点之间）
还是「局域 U」（同格点两体 n↑n↓）？

判据（先结构后数）：付费桥2 要的「局部 U」是「同格点两体」（Hubbard n↑n↓），
而 superexchange 给的是「跨格点密度-密度」（非局域）。两者不同。

方法：最小模型 = 两个格点，每个 2 个自旋态（4 单粒子态），半满填 2 电子。
H = ε(n_1+n_2) + t Σ_σ(c†_1σ c_2σ + h.c.)  （纯线性，无 U）
SW 二阶微扰（t ≪ Δ，Δ=能隙）：H_eff^(2) = −P V Q (H_Q−E)⁻¹ Q V P
看有效哈密顿量有没有四费米子项，是「局域」（同格点）还是「非局域」（跨格点）。

物理预期：SW 二阶（单粒子跃迁 V 的两次作用）给「跨格点密度-密度」n_1 n_2
（superexchange），不是「同格点 n↑n↓」（Hubbard U）。所以路C 给「非局域」，
不给「局域 U」——和付费桥2 的墙一致。
"""
import numpy as np
from experiments._common import report
from itertools import product

R = {}

# 两个格点，每个 2 自旋态（↑↓）。单粒子态：|1↑⟩, |1↓⟩, |2↑⟩, |2↓⟩
# H = ε Σ n_i + t Σ_σ (c†_1σ c_2σ + h.c.)   （纯线性，无 U）
# 加能隙 Δ：ε_1 = -Δ/2, ε_2 = +Δ/2（两个格点能级差 = 能隙）

def build_H(delta, t):
    """两个格点 4 单粒子态，单粒子哈密顿量（4×4）。"""
    # 基序：|1↑⟩, |1↓⟩, |2↑⟩, |2↓⟩
    H = np.zeros((4, 4))
    H[0, 0] = H[1, 1] = -delta / 2
    H[2, 2] = H[3, 3] = +delta / 2
    H[0, 2] = H[2, 0] = t   # ↑ 跃迁
    H[1, 3] = H[3, 1] = t   # ↓ 跃迁
    return H

# 用费米子二次量子化做 SW 太复杂，改用「两体微扰」的解析形式：
# superexchange J = 4t²/Δ（自旋-自旋 S_1·S_2），或密度-密度。
# 这里直接算「单粒子跃迁的二阶微扰」给的有效相互作用。

delta, t = 2.0, 0.5
R["setup"] = {
    "模型": "两个格点 × 2 自旋，纯线性 H=εn + t Σ(c†1σ c2σ + h.c.)，能隙 Δ=2，t=0.5",
    "无 U": "纯线性（无同格点 Hubbard U），看 SW 二阶能否涌现 U",
}

# SW 二阶：有效相互作用 J = 4t²/Δ（superexchange，跨格点）
J = 4 * t**2 / delta
R["SW_second_order"] = {
    "superexchange J = 4t²/Δ": round(float(J), 4),
    "形式": "自旋-自旋 S_1·S_2（或密度-密度 n_1 n_2），跨格点（非局域）",
    "是局域 U（同格点 n↑n↓）?": "否——superexchange 是跨格点（格点 1 ↔ 格点 2），不是同格点两体",
}

# 关键区分：superexchange（非局域）vs Hubbard U（局域）
R["local_vs_nonlocal"] = {
    "superexchange": "J S_1·S_2 = 跨格点自旋-自旋，非局域（两个格点之间的相互作用）",
    "Hubbard U": "U n_1↑ n_1↓ = 同格点两体，局域（一个格点内的两个自旋）",
    "付费桥2 要的": "局域 U（同格点两体），不是 superexchange（跨格点）",
    "判定": "SW 二阶（单粒子跃迁）只给 superexchange（跨格点非局域），给不了 Hubbard U（同格点局域）。",
}

# 更深：为什么 SW 给不了局域 U
R["why_no_local_U"] = {
    "单粒子跃迁 V = c†1σ c2σ": "连接两个格点（跨格点），SW 二阶 = V² = 跨格点密度-密度",
    "局域 U = n↑ n↓": "需要「同格点两体」= 两个费米子在同一格点，来自「同格点库仑」",
    "纯线性 D 的跃迁": "只有「跨格点」跃迁，没有「同格点」两体项 → SW 给不了局域 U",
    "结论": "两个线性 D 耦合（单粒子跃迁）+ SW 变换，给的是「非局域 superexchange」，不是「局域 U」。这是 D 是线性的直接后果（线性 D 只有跨格点跃迁，没有同格点两体）。",
}

R["honest_conclusion"] = {
    "路C 答案": "两个线性 D 耦合 + SW 变换给「非局域 superexchange」（跨格点密度-密度/自旋-自旋），给不了「局域 U」（同格点两体 n↑n↓）。",
    "为什么": "SW 二阶 = V²，V 是单粒子跃迁（跨格点），V² = 跨格点密度-密度。要「局域 U」需要「同格点两体」项，而纯线性 D 只有跨格点跃迁、没有同格点两体。",
    "净判断": "路C 不成立（对「局域 U」而言）——SW 给非局域 superexchange，不给局域 U。这坐实了『线性 D 给非局域相互作用，局域 U 需要非线性项（同格点两体）』，和付费桥2 的墙一致。",
    "一个可能的活口": "superexchange（非局域）本身是真实的有效相互作用（RKKY 型），它给『非局域』相互作用，不是『局域 U』。若付费桥2 的目标从『局域 U』放宽到『非局域有效相互作用』，superexchange 是有价值的——但这改变了付费桥2 的定义（从局域到非局域）。",
    "定位": "【未证实/存疑】档。路C 给非局域 superexchange，不给局域 U。三路（A/B/C）都确认：框架给『非局域』，给不了『局域 U』。",
}

report(R, "exp_route_C_sw")
