import sympy as sp
from experiments._common import report

R = {}

# P1：有向区分 J，J² = −I（反对称 + 二分统一）
J = sp.Matrix([[0, 1], [-1, 0]])
J_sq = J * J
J_ev = J.eigenvals()

R["P1_directed_distinction"] = {
    "有向区分 J = [[0,1],[-1,0]]": str(J),
    "J 反对称（有向）": bool(J + J.T == sp.zeros(2)),
    "J² = −I（二分）": str(J_sq),
    "结构": "「有向」（反对称）和「区分」（J²=−I 二分）统一在同一个 J 里——公设的两个词是一个对象的两个面。",
}

# P2：J 本征值 ±i（2 个值）= 二分
R["P2_binary"] = {
    "J 本征值": {str(k): int(v) for k, v in J_ev.items()},
    "= 2 个值（±i）": bool(len(J_ev) == 2),
    "结构": "「区分 = 二分」给「2 个值」（±i）——一次区分 = 一个二值。",
}

# P3：2 值 = 有限（有限次操作）
R["P3_finiteness"] = {
    "本征值个数": len(J_ev),
    "= 2（有限整数）": bool(len(J_ev) == 2),
    "推论链": "J²=−I → 本征值 ±i（2 个）→ 2 是有限整数 → 「一次区分 = 一个二值 = 有限」。",
    "结构": "「一次」（有限次）从「区分 = 二分」（2 值）推出——「一次 → 有限」是数学推论，不是诠释桥。",
}

# P4：诚实分界——数学 vs 诠释
R["P4_boundary"] = {
    "数学（严格）": "「区分 = 二分」→「2 值」→「有限」——J²=−I→±i→2 是有限整数。这是「一次 → 有限」的严格部分。",
    "诠释（非数学）": "「有限（2 值）」→「泡利（占据 {0,1}）+ 截断（尺度 {λ_min,λ_c}）」——把「2 值」对应到「占据」和「尺度」两个具体物理对象。这是诠释桥（把抽象的「2 值」落到具体对象）。",
    "分界": "「公设 → 有限」是数学（J²=−I 直接给 2 值）；「有限 → 泡利 + 截断」是诠释（2 值 ↔ 占据/尺度的对应）。",
}

R["honest_conclusion"] = {
    "轻量级检查结果": "「公设 → 有限性」的桥，数学部分坐实了——「区分 = 二分（J²=−I）→ ±i（2 值）→ 有限」是严格的数学推论（sympy 坐实 J²=−I、±i、2 值）。",
    "精确分界": "「一次 → 有限」= 数学（不是诠释桥）；「有限 → 泡利 + 截断」= 诠释（把「2 值」落到「占据」「尺度」两个具体对象）。",
    "对「暂时不严格」的意义": "之前标「公设→有限性是诠释桥」其实过度保守了——「区分=二分→2值→有限」是数学；真正诠释的只是「2值→泡利+截断」这一小步。可以更精确地标：数学链「一次→有限」严格，诠释「有限→泡利+截断」待坐实。",
    "下一步": "「有限 → 泡利 + 截断」这一步，可以尝试严格化：验证「2 值（二分）」如何严格对应「占据 {0,1}」和「尺度 {λ_min,λ_c}」（两者都是「二分」的具体实现）。",
    "定位": "【部分坐实】。「公设→有限」数学坐实；「有限→泡利+截断」是诠释（待严格化）。",
}

