"""
远景线 2（尺度读出）· 宇宙学预言第一刀：β（跑动 G）能否从 f 推出

背景：哈勃张力用跑动引力常数 G(z)=G₀[1+βln(1+z)] 解释，β=−0.0211（拟合值，早期引力弱）。
f 来源：G = 3π/(f₂Λ²)，f₂ = ln(λ_c/λ_min)，λ_c=2，λ_min=π²/N²。

问题：f₂ 或 Λ 是否随红移 z 演化？若演化，β 的符号和数值？

本脚本算两个候选机制：
  (1) f₂ 演化（λ_min ∝ (1+z)^α）：β = α/f₂,0；
  (2) Λ 演化（Λ ∝ (1+z)^γ）：β = −2γ；
对比 β = −0.0211（哈勃张力），看符号和数值是否对得上。
"""
import numpy as np
from experiments._common import report

R = {}

N0 = 128
lc = 2.0
lm0 = np.pi**2 / N0**2
f20 = np.log(lc / lm0)

beta_target = -0.0211  # 哈勃张力拟合值（早期引力弱）

R["baseline"] = {
    "G = 3π/(f₂Λ²)": "静态 G，f₂ = ln(λ_c/λ_min)",
    "f₂,0 = ln(2/λ_min,0) (N=128)": f20,
    "β_target（哈勃张力）": beta_target,
}

# 机制 1：f₂ 演化，λ_min ∝ (1+z)^α
# G(z) = 3π/((f₂,0 - α ln(1+z)) Λ²) ≈ G₀(1 + (α/f₂,0) ln(1+z))
# β = α/f₂,0
alpha_for_target = beta_target * f20
R["mechanism1_f2_evolution"] = {
    "机制": "λ_min ∝ (1+z)^α ⟹ f₂(z) = f₂,0 − α ln(1+z) ⟹ β = α/f₂,0",
    "β = α/f₂,0（N=128）": "β = α/8.11",
    "要 β=−0.0211 需 α": alpha_for_target,
    "物理直觉 α（红外截断随红移）": "应为 α>0（红移大=宇宙小=红外截断大），α=−0.171<0 与物理直觉矛盾",
    "判断": "机制 1 符号反了（给早期引力强 β>0，哈勃张力要早期引力弱 β<0）",
}

# 机制 2：Λ 演化，Λ ∝ (1+z)^γ
# G = 3π/(f₂ Λ²)，Λ(z) = Λ₀(1+z)^γ ⟹ G(z) = G₀(1+z)^(−2γ) ≈ G₀(1 − 2γ ln(1+z))
# β = −2γ
gamma_for_target = -beta_target / 2
R["mechanism2_Lambda_evolution"] = {
    "机制": "Λ ∝ (1+z)^γ ⟹ G(z) ∝ Λ⁻² ∝ (1+z)^(−2γ) ⟹ β = −2γ",
    "β = −2γ": "符号对（γ>0 给 β<0，早期引力弱）",
    "要 β=−0.0211 需 γ": gamma_for_target,
    "物理 γ（能标随宇宙膨胀）": "γ=0.0106（极慢演化），但「能标随宇宙膨胀」的物理机制在 OQG 未建立（无绝对尺度 ⟹ Λ 是标定）",
    "判断": "机制 2 符号对，但 γ 的物理不明确（Λ 演化机制缺失）",
}

R["honest_conclusion"] = {
    "β 从 f 推出的困难": "G=3π/(f₂Λ²) 是静态的，要跑动需 f₂ 或 Λ 演化。",
    "机制 1（f₂ 演化）": "β=α/f₂,0>0（早期引力强），符号反了——哈勃张力要早期引力弱 β<0。",
    "机制 2（Λ 演化）": "β=−2γ 符号对，但 γ=0.0106 的「能标随宇宙膨胀」机制在 OQG 未建立（无绝对尺度 ⟹ Λ 标定输入，不演化）。",
    "核心问题": "「观察者有限性 N 随宇宙膨胀演化」的方向 +「Λ 随宇宙膨胀演化」的机制，都需要物理直觉。",
    "措辞": "符号验证两个候选机制，β 从 f 推出目前卡在「G 跑动的机制不明」，需用户直觉。",
}

report(R, "exp_beta_from_f")
