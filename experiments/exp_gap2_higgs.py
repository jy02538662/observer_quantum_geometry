"""
缺口 2（上型不对称「除以 3」）· 从希格斯结构 H vs H̃ 出发的推导尝试

之前四个角度（超荷模 / 颜色结构 / 三个 Z₂ / 超荷 H₂）都从「颜色内部」找，卡在
「颜色 × 超荷耦合不存在」（超荷是色单态 [Y,SU(3)]=0）。

本脚本换角度：从希格斯结构 H vs H̃ 出发。标准模型里：
  上型 u_R（正超荷）耦合 H̃（负超荷），下型 d_R（负超荷）耦合 H（正超荷）；
  H̃ = iσ₂ H* 是 H 的超荷共轭（电荷共轭 + Kramers T）。

核心待验证的符号事实：
  1. 超荷守恒反推：3Y(H)=+3、3Y(H̃)=-3（框架归一化 Y，Q=I₃+Y/2，3Y 整数）；
  2. 希格斯超荷与费米子超荷「反号」（超荷守恒强制）；
  3. 「除以 3」因子（×3/×1）读费米子超荷 → 与观测一致；读希格斯超荷 → 反号；
  4. H̃ = iσ₂ H* 的「复共轭」= 反向区分（e^{iθ}→e^{-iθ}）= 框架 §22 的「反向」。
"""
import numpy as np
from sympy import Matrix, I, Rational, simplify, sqrt, exp, symbols, conjugate
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (0) 框架量子数（族维度笔记 §9.1，3Y 整数，Q = I₃ + Y/2）
# ---------------------------------------------------------------------------
# 3Y 值（框架归一化，使得 3Y ∈ ℤ）：
#   Q_L: +1,  u_R: +4,  d_R: -2,  e_R: -6,  L: -3
# 上型 u_R 3Y=+4=+3+1（正），下型 d_R 3Y=-2=-3+1（负）
threeY = {
    "Q_L": Rational(1),   "u_R": Rational(4),  "d_R": Rational(-2),
    "e_R": Rational(-6),  "L":   Rational(-3),
}
R["framework_quantum_numbers"] = {
    "Q_L (3Y)": str(threeY["Q_L"]),
    "u_R (3Y)": str(threeY["u_R"]),
    "d_R (3Y)": str(threeY["d_R"]),
    "上型 3Y = +4 = +3+1（正，三重态方向 +3）": "",
    "下型 3Y = -2 = -3+1（负，三重态方向 -3）": "",
}

# ---------------------------------------------------------------------------
# (1) 超荷守恒反推希格斯 3Y
# ---------------------------------------------------------------------------
# 下型 Yukawa：Q̄_L · H · d_R  →  -3Y(Q_L) + 3Y(H) + 3Y(d_R) = 0
#   ⟹ 3Y(H) = 3Y(Q_L) - 3Y(d_R)
# 上型 Yukawa：Q̄_L · H̃ · u_R →  -3Y(Q_L) + 3Y(H̃) + 3Y(u_R) = 0
#   ⟹ 3Y(H̃) = 3Y(Q_L) - 3Y(u_R)
threeY_H  = simplify(threeY["Q_L"] - threeY["d_R"])   # = 1 - (-2) = +3
threeY_Ht = simplify(threeY["Q_L"] - threeY["u_R"])   # = 1 - (4)  = -3

R["hypercharge_conservation"] = {
    "3Y(H)  = 3Y(Q_L) - 3Y(d_R)": str(threeY_H),
    "3Y(H̃) = 3Y(Q_L) - 3Y(u_R)": str(threeY_Ht),
    "结论": "H 超荷 = +3（正），H̃ 超荷 = -3（负）——H 给下型、H̃ 给上型，超荷守恒强制",
}

# ---------------------------------------------------------------------------
# (2) 希格斯与费米子超荷「反号」
# ---------------------------------------------------------------------------
# H（+3 正）↔ d_R（-2 负）：反号
# H̃（-3 负）↔ u_R（+4 正）：反号
sign_H_dR  = "反号" if threeY_H * threeY["d_R"] < 0 else "同号"
sign_Ht_uR = "反号" if threeY_Ht * threeY["u_R"] < 0 else "同号"
R["higgs_fermion_opposite_sign"] = {
    "H(+3) vs d_R(-2)": sign_H_dR,
    "H̃(-3) vs u_R(+4)": sign_Ht_uR,
    "结论": "希格斯超荷与所耦合费米子超荷「反号」（超荷守恒强制正负配对）",
}

# ---------------------------------------------------------------------------
# (3) 「除以 3」因子读谁：费米子 vs 希格斯（核心判别）
# ---------------------------------------------------------------------------
# 框架机制（§20-22）：正超荷（+3 方向）→ 三重态（×3）；负超荷（-3 方向）→ 单态（×1）
# 观测事实（§2.1）：上型 ×3、下型 ×1
#
# 读【费米子】超荷：
#   上型 u_R（+4 正）→ 三重态 ×3  ✓（观测上型 ×3）
#   下型 d_R（-2 负）→ 单态 ×1   ✓（观测下型 ×1）
#
# 读【希格斯】超荷：
#   上型耦合 H̃（-3 负）→ 单态 ×1  ✗（观测上型 ×3）
#   下型耦合 H（+3 正）→ 三重态 ×3 ✗（观测下型 ×1）
def factor_of(sign):
    return "三重态(×3)" if sign > 0 else "单态(×1)"

fermion_read = {
    "上型 u_R(+4)": factor_of(threeY["u_R"]),
    "下型 d_R(-2)": factor_of(threeY["d_R"]),
}
higgs_read = {
    "上型耦合 H̃(-3)": factor_of(threeY_Ht),
    "下型耦合 H(+3)":  factor_of(threeY_H),
}
R["divide_by_3_read_fermion_vs_higgs"] = {
    "观测": "上型 ×3、下型 ×1",
    "读费米子超荷": fermion_read,
    "读希格斯超荷": higgs_read,
    "结论": "读费米子超荷 → 与观测一致；读希格斯超荷 → 反号（上型×1、下型×3）",
}

# ---------------------------------------------------------------------------
# (4) H̃ = iσ₂ H* 的「复共轭」= 反向区分
# ---------------------------------------------------------------------------
# H̃ = iσ₂ H*：iσ₂ = Kramers T（时间反演），* = 复共轭（翻转 U(1) 荷 Y→-Y）
# 复共轭把 e^{iθ}→e^{-iθ}，即「反向区分」（框架 §22：反向区分 = 单态投影）
s2 = Matrix([[0, -I], [I, 0]])            # iσ₂（Kramers T）
H_vec = Matrix([symbols("h1"), symbols("h2")])   # SU(2) 二重态 H
Ht_vec = simplify(s2 * H_vec.applyfunc(conjugate))  # H̃ = iσ₂ H*

# 复共轭的相位翻转：一个含 U(1) 相位 e^{iθ} 的标量，共轭后相位 → -θ
theta = symbols("theta", real=True)
phase = exp(I * theta)
conj_phase = simplify(conjugate(phase))
R["conjugation_is_reversal"] = {
    "H̃ = iσ₂ H*（iσ₂ = Kramers T + 复共轭）": str(Ht_vec),
    "复共轭 e^{iθ} → ": str(conj_phase),
    "复共轭 = 相位翻转 = 反向区分": "e^{iθ}→e^{-iθ}，与框架 §22「反向区分 = 单态投影」同源",
}

# ---------------------------------------------------------------------------
# (5) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实（符号）": "① 3Y(H)=+3、3Y(H̃)=-3（超荷守恒反推）；② 希格斯超荷与费米子反号；③ H̃=iσ₂H* 的复共轭=反向区分",
    "核心发现（澄清性负结果）": "「除以 3」因子（×3/×1）必须读【费米子】超荷符号；读【希格斯】超荷符号会得到反方向（上型×1、下型×3），与观测「上型×3、下型×1」矛盾",
    "精确定位": "「除以 3」机制在费米子侧（费米子超荷符号→颜色三重态/单态），不在希格斯侧。排除了「希格斯超荷决定因子」整类解释",
    "未解决（保持开放）": "费米子超荷符号→三重态/单态 的机制本身（= §22.4「正向/反向区分的显式形式」）",
    "措辞（三档）": "「希格斯决定因子」是【未证实/待推导】且被符号反号排除；「除以 3 在费米子侧」是【精确定位】；机制本身仍【待推导】",
}

report(R, "exp_gap2_higgs")
