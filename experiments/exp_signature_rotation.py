"""
远景线 5（质量谱）· 冲「号差 vs 旋转」：有向区分 J 的两面频率差

⚠️ 命名（2026-09-27）：本脚本 λ_c = 模流频率 ≈5.32（= 预印本 1.14 的 λ_mod），区别于紫外截断 λ_c=2。

线索：转置（g²=e，反射）= 号差面（J²=-I，本征值 ±i，虚频率）；
     3-循环（g³=e，旋转）= 旋转面（e^{2πJ}=I，周期 2π，实频率）。
质量跨步差（转置 → 3-循环）= 16.8 倍，可能是「号差（±i）vs 旋转（2π）」两面的频率差。

本脚本从 J 的谱精确提取两面频率，验证「频率比」候选，诚实标注「16.8」的精确结构。
"""
import numpy as np
from experiments._common import report

R = {}

m_mu_e = 206.7682830
m_tau_e = 3477.0
m_tau_mu = m_tau_e / m_mu_e   # 转置 → 3-循环 的跨步 = 16.82

# J = [[0,1],[-1,0]]，J²=-I，本征值 ±i（号差面，虚频率）
# e^{2πJ}=I，周期 2π（旋转面，实频率）
J = np.array([[0, 1], [-1, 0]])
eigvals = np.linalg.eigvals(J)   # ±i

R["J_spectrum"] = {
    "J 本征值（号差面，虚频率）": [complex(v).__str__() for v in eigvals],
    "J²": np.array2string(J @ J),
    "旋转周期（e^{2πJ}=I）": "2π",
    "两面的频率": "号差 ±i（虚）、旋转 2π（实）",
}

# 候选频率比（号差 → 旋转 的跨步）
candidates = {
    "|2π|/|±i| = 2π": 2 * np.pi,
    "e^{2π}/e^{1}（频率模的指数）": np.exp(2*np.pi) / np.exp(1),
    "|2π|²/|±i|² = 4π²": 4 * np.pi**2,
    "2π·e": 2 * np.pi * np.e,
    "2π·(8/3)": 2 * np.pi * 8/3,
}
R["candidates_vs_16.8"] = {
    "实际 16.8": float(m_tau_mu),
    "候选": {k: (float(v), float(v/m_tau_mu)) for k, v in candidates.items()},
}

# 质量 ∝ 观察者态截断的倒数：m ∝ λ e^{λ/λ_c}（λ=号差|±i|=1 vs 旋转 2π）
# 质量比 m_τ/m_μ = (2π/1)·e^{(2π-1)/λ_c}，需 λ_c 使 = 16.8
# 解 λ_c：(2π-1)/λ_c = ln(16.8/(2π))
lam_c_solve = (2*np.pi - 1) / np.log(m_tau_mu / (2*np.pi))
R["lambda_c_from_rotation"] = {
    "质量 ∝ λ e^{λ/λ_c}，λ=1（号差）vs 2π（旋转）": f"λ_c = (2π-1)/ln(16.8/2π) = {lam_c_solve:.3f}",
    "对比 ln(m_μ/m_e)": float(np.log(m_mu_e)),
    "意义": f"若 lambda_c 约 {lam_c_solve:.2f}（对比 ln 206.77=5.33），则「号差 vs 旋转」的 λ·e^(λ/λ_c) 结构能解释 16.8——但 λ_c 的精确来源仍需模流",
}

R["honest_conclusion"] = {
    "线索坐实": "转置=号差（±i 虚）、3-循环=旋转（2π 实）是「有向区分 J」的两面，坐实",
    "16.8 的候选": "「质量 ∝ λ e^{λ/λ_c}」（λ=号差模 1 vs 旋转周期 2π）能解释 16.8，λ_c≈5.3-5.4（接近 ln 206.77=5.33）——但「λ_c 的精确来源」仍需模流 σ_t=ρ^{it} 的指数",
    "诚实卡点": "「号差 vs 旋转」的两面频率差，是「转置 vs 3-循环」跨步差（16.8）的候选结构，但 λ_c 的「指数化」（量子维度 2 → 5.33）还没从模流里精确提取",
    "下一步": "模流 σ_t=ρ^{it}=e^{it log ρ} 的指数，把「号差 ±i」和「旋转 2π」两个面接到「观察者截断 λ_c」——这是「阶 → 截断 → 能隙」完整链条的最后一环",
    "措辞": "一元论线索（号差 vs 旋转 = J 的两面），非「已算出质量谱」——λ_c 的指数化仍是卡点",
}

report(R, "exp_signature_rotation")
