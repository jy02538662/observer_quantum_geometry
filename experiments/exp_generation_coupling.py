"""
exp_generation_coupling.py

方向 1：D-D 自反 → 代间耦合 → δM → 混合角

王超的洞察（2026-10-04）：
- 单粒子 D 代守恒（质量矩阵 M = diag(e^{λ·1}, e^{λ·2}, e^{λ·3}) 对角）；
- 但「代」若识别为「不同的 D」，则「D-D 自反」= 代间耦合；
- 代间耦合 V（粒子转移）可能给质量矩阵的非对角元 δM；
- 混合角 θ = δM / (m_i - m_j)（一级微扰）。

本脚本做最朴素的计算 + 诚实定位：
1. 结构：V 非对角 ⟹ δM ≠ 0 吗？
2. 数值：θ = t_p/(m_i-m_j) 给观测混合角吗？（依赖什么标定）
3. 反解：观测 θ 反解出「绝对质量 m_1 的标定」是多少？
4. 诚实结论：这个方向是把「混合角」换成「t_p + m_i 标定」，还是真推导？

防滑（用户指定）：
- 不接受「太小就是边界」——先检查「为什么太小」；
- 不接受「凑 V 的形式」——V = 粒子转移（t_p，D-D 自反已有）；
- 只接受：具体算出的 θ 和观测对比。
"""

import numpy as np

pi = np.pi


def lambda_mod(N):
    return np.log(N**2 / pi**2) - np.log(np.log(2 * N**2 / pi**2))


N = 128
lam = lambda_mod(N)
print("=" * 70)
print(f"λ_mod = {lam:.6f}")
print()

# ---------------- 三代质量比（质量谱：m_n = e^{λ·n}） ----------------
# 质量谱只给【比值】，不给绝对值。用 m_1 作基（未知标定）。
# m_1 : m_2 : m_3 = 1 : e^λ : (e^λ)^2  （最朴素，忽略号差/旋转非线性修正）
m1 = 1.0  # 基（任意）
m2 = np.exp(lam) * m1
m3 = np.exp(2 * lam) * m1
print("三代质量（m_1 归一）:")
print(f"  m_1 = {m1:.4f}")
print(f"  m_2 = e^λ = {m2:.2f}")
print(f"  m_3 = e^2λ = {m3:.2e}")
print()

# ---------------- 代间耦合 V = 粒子转移（t_p） ----------------
# D-D 自反的 V = c1†c2 + h.c.，本征值 ±t_p。t_p 是耦合频率。
# 三个代的耦合（最近邻：1↔2, 2↔3；无 1↔3 直接耦合）：
# H = [[m_1, t_p, 0], [t_p, m_2, t_p], [0, t_p, m_3]]
tp = 1.0  # 自然单位（V 本征值 ±1）

print("=" * 70)
print("结构检查：V 是否产生非对角 δM？")
print("  V = 粒子转移（代间），在代空间是 σ_x（非对角）")
print("  ⟹ δM_12 = δM_23 = t_p ≠ 0（耦合产生代间非对角）✓")
print("  但 δM_13 = 0（无 1↔3 直接耦合，需二级）")
print()

# ---------------- 一级微扰混合角 ----------------
# θ_ij ≈ δM_ij / (m_i - m_j)（t_p ≪ Δm）
def theta12(m1, m2, tp):
    return tp / (m2 - m1)


def theta23(m2, m3, tp):
    return tp / (m3 - m2)


def theta13(m1, m2, m3, tp):
    # 二级（经代 2）：θ_13 ≈ t_p^2 / [(m_3 - m_1)(m_2 - m_1)]
    return tp**2 / ((m3 - m1) * (m2 - m1))


print("数值检查：θ = t_p/(m_i - m_j)，t_p=1, m_1=1 归一")
t12 = theta12(m1, m2, tp)
t23 = theta23(m2, m3, tp)
t13 = theta13(m1, m2, m3, tp)
print(f"  θ_12 = {t12:.3e}")
print(f"  θ_23 = {t23:.3e}")
print(f"  θ_13 = {t13:.3e}")
print()

# 观测
CKM = {"th12": 0.22650, "th23": 0.04183, "th13": 0.00369}
PMNS = {"th12": 0.583, "th23": 0.859, "th13": 0.149}
print("观测（CKM / PMNS）:")
print(f"  CKM:  θ_12={CKM['th12']:.4f} θ_23={CKM['th23']:.4f} θ_13={CKM['th13']:.4f}")
print(f"  PMNS: θ_12={PMNS['th12']:.4f} θ_23={PMNS['th23']:.4f} θ_13={PMNS['th13']:.4f}")
print()

# ---------------- 反解：观测 θ 需要的绝对质量标定 ----------------
print("=" * 70)
print("反解：观测 θ_12 = 0.2265 需要的 m_1 标定（t_p=1）")
# θ_12 = t_p / (m_2 - m_1) = 1 / (m_1 (e^λ - 1))
# m_1 = 1 / [θ_12 (e^λ - 1)]
m1_CKM = 1 / (CKM["th12"] * (np.exp(lam) - 1))
m1_PMNS = 1 / (PMNS["th12"] * (np.exp(lam) - 1))
print(f"  CKM 反解 m_1 = {m1_CKM:.5f} t_p")
print(f"  PMNS 反解 m_1 = {m1_PMNS:.5f} t_p")
print(f"  （e^λ - 1 = {np.exp(lam)-1:.2f}）")
print()

# ---------------- 用反解的 m_1 重新算三个混合角，看层级 ----------------
print("用 CKM 反解的 m_1 重算三个混合角:")
m1c = m1_CKM
m2c = np.exp(lam) * m1c
m3c = np.exp(2 * lam) * m1c
t12c = tp / (m2c - m1c)
t23c = tp / (m3c - m2c)
t13c = tp**2 / ((m3c - m1c) * (m2c - m1c))
print(f"  θ_12 = {t12c:.4f}（输入 0.2265）")
print(f"  θ_23 = {t23c:.4e}（观测 0.0418）")
print(f"  θ_13 = {t13c:.4e}（观测 0.0037）")
print()

# ---------------- 层级关系（无标定，纯比值） ----------------
print("=" * 70)
print("层级关系（不依赖 m_1 标定的纯比值）:")
print(f"  θ_23/θ_12 = (m_2-m_1)/(m_3-m_2) = {(m2-m1)/(m3-m2):.4e}")
print(f"    （观测 θ_23/θ_12 = {CKM['th23']/CKM['th12']:.4f}）")
print(f"  θ_13/θ_12 = t_p/(m_3-m_1) = {tp/(m3-m1):.4e}")
print(f"    （观测 θ_13/θ_12 = {CKM['th13']/CKM['th12']:.5f}）")
print()

print("=" * 70)
print("诚实结论见下方分析（不写进脚本）")
