"""
远景线 5（质量谱）· 候选结构：三个 Z₂ → 7 个非平凡元素 → Fano 平面 → 2⁷=128

用户直觉（关键）：7 最自然的来源 = 三个 Z₂ 的 7 个非平凡组合 → Fano 平面（7 点）→ PSL(2,7)（阶 168=7×24）。
N = 2⁷ = 128 = 7 个独立二进制自由度。
与「绕开八元数」不冲突：颜色三 = 两个 Z₂ → S₃ → 3；代/质量 = 三个 Z₂ → PSL(2,7) → 7。

本脚本验证：
  (1) Z₂³ 的 7 个非平凡元素 → Fano 平面（7 点 7 线，每线 3 点，和为 0 在 F₂）；
  (2) PSL(2,7) = Fano 自同构群，阶 168 = 7×24；
  (3) 第三个 Z₂ 的候选 = 观察者态 ρ 的「λ↔1/λ 对偶」（红外/紫外，尺度不变的对偶面）；
  (4) 三个 Z₂ 的独立性（二分 Γ / 复结构 K / 尺度对偶 λ↔1/λ）。
"""
import numpy as np
from itertools import combinations
from experiments._common import report

R = {}

# (1) Z₂³ 的 8 个元素（F₂³ 的向量），7 个非平凡
elements = [(a, b, c) for a in (0,1) for b in (0,1) for c in (0,1)]
nonzero = [v for v in elements if v != (0,0,0)]
R["Z2_cube"] = {
    "Z₂³ 元素数": 8,
    "非平凡元素数": 7,
    "7 个非平凡元素": [str(v) for v in nonzero],
}

# Fano 平面：7 条线，每线 3 个点（非零向量），和为 0（F₂ 加法）
lines = []
for comb in combinations(nonzero, 3):
    s = tuple((comb[0][i] + comb[1][i] + comb[2][i]) % 2 for i in range(3))
    if s == (0, 0, 0):
        lines.append(comb)
R["fano_plane"] = {
    "7 条线（每线 3 点，和=0）": len(lines),
    "线数验证": "7 条线，每点落在 3 条线上（Fano 平面）",
    "断言 7 线": len(lines) == 7,
}

# (2) PSL(2,7) = GL(3,F₂) 的自同构群，阶 = 7×24 = 168
# GL(3,F₂) 阶 = (2³-1)(2³-2)(2³-4) = 7·6·4 = 168（F₂ 上非奇异 3×3 矩阵）
order_GL = (2**3 - 1) * (2**3 - 2) * (2**3 - 4)
R["PSL_2_7"] = {
    "GL(3,F₂) 阶": order_GL,
    "PSL(2,7) = GL(3,F₂)": "168 = 7×24（Fano 平面自同构群）",
    "断言 168": order_GL == 168,
}

# (3) 第三个 Z₂ 的候选：λ↔1/λ 对偶（观察者态 ρ=C/λ 的红外/紫外对偶面）
R["third_Z2_candidate"] = {
    "第三个 Z₂ = λ↔1/λ 对偶": "观察者态 ρ=C/λ 的尺度不变对偶（红外↔紫外互换）",
    "对合性": "λ→1/λ 做两次回到原样（Z₂）",
    "一元论": "尺度不变 = 无偏好 = 无外部观察者的第三个面（前两个：二分 Γ、复结构 K）",
}

# (4) 三个 Z₂ 的独立性
R["three_Z2_independence"] = {
    "Γ（手征）": "二分（断裂，酉对合）——谱结构面",
    "K（共轭）": "复结构（厄米 D=D*，反酉对合）——复结构面",
    "λ↔1/λ（尺度对偶）": "红外/紫外对偶（尺度不变）——尺度对偶面",
    "独立性": "三个不同的结构（二分 vs 复结构 vs 尺度对偶），构成 Z₂³",
}

R["honest_conclusion"] = {
    "链条验证": "三个 Z₂ → Z₂³ → 7 非平凡元素 → Fano 平面（7 点 7 线）→ PSL(2,7)（阶 168=7×24），纯群论自动成立",
    "N=2⁷=128": "7 个独立二进制自由度 → 2⁷=128 层（观察者层数）→ λ_c → 207/3477",
    "第三个 Z₂ 候选": "λ↔1/λ 对偶（观察者态 ρ 的红外/紫外对偶面）——和 Γ（二分）、K（复结构）构成「无外部观察者」的三个面",
    "与绕开八元数不冲突": "颜色三 = 两个 Z₂→S₃→3；代/质量 = 三个 Z₂→PSL(2,7)→7——同一家族不同成员",
    "诚实卡点": "① 第三个 Z₂=λ↔1/λ 是候选，需验证它和 Γ、K 独立（不是 Γ 或 K 的组合）；② 从 7→λ_c→207/3477 的具体计算还没做（但 2⁷=128 和反解的 N≈128.7 几乎精确对上！）",
    "措辞": "候选结构（三个 Z₂→Fano→7），非「已算出质量谱」——第三个 Z₂ 的独立识别 + 7→λ_c 的计算是下一步",
}

report(R, "exp_three_Z2_fano")
