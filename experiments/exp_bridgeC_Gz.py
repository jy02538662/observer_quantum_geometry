"""
桥 C 候选出口：G(z) 的宇宙学跑动——重新检查「符号冲突」

之前 §9.1「β 放弃」只算了左旋钮（f₂ 演化，给 β>0 早期引力强），右旋钮（Λ 演化）
当时标「符号对，但 γ 机制未建立」。§9.6 引入 N_ext=S^{1/4} 后 γ 机制建立：

  G = 3π/(f₂·Λ_eff²)，两个旋钮都随红移演化：
  左旋钮 f₂ = ln(λ_c/λ_min)：λ_min（红外截断）∝ 1/R ∝ H，早期 H 大 → λ_min 大 → f₂ 小 → G 大（早期引力强，β_f>0）
  右旋钮 Λ_eff = M_P/N_ext：N_ext=S^{1/4}∝R^{1/2}，早期 R 小 → N_ext 小 → Λ_eff 大 → G 小（早期引力弱，β_Λ<0）

本脚本算净效应 β = β_f + β_Λ = -α/f₂₀ - 2γ，看哪个旋钮主导，符号是否反转。
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (1) 左旋钮 f₂ 演化：β_f = -d ln f₂ / d ln(1+z) = +α/f₂₀ > 0
# ---------------------------------------------------------------------------
# λ_min ∝ 1/R ∝ H ∝ (1+z)^{3/2}（早期物质主导），α = 3/2
# f₂ = ln(λ_c/λ_min)，f₂₀ = ln(λ_c/λ_min,0)
alpha = 3/2
R["left_knob_f2"] = {
    "λ_min ∝ 1/R ∝ H ∝ (1+z)^α": f"α = {alpha}",
    "β_f = α/f₂₀": "> 0（早期引力强，符号反）",
    "f₂₀ = ln(λ_c/λ_min,0)": "λ_c=2，λ_min,0 待定",
}

# ---------------------------------------------------------------------------
# (2) 右旋钮 Λ_eff 演化：β_Λ = -2·d ln Λ_eff / d ln(1+z) = -2γ < 0
# ---------------------------------------------------------------------------
# Λ_eff = M_P/N_ext，N_ext = S^{1/4}，S ∝ R²（视界面积），R = 1/H
# N_ext ∝ R^{1/2} = H^{-1/2}，Λ_eff ∝ H^{1/2} ∝ (1+z)^{3/4}（早期），γ = 3/4
gamma = 3/4
beta_Lambda = -2 * gamma
R["right_knob_Lambda"] = {
    "N_ext = S^{1/4} ∝ R^{1/2} = H^{-1/2}": "早期 R 小 → N_ext 小",
    "Λ_eff = M_P/N_ext ∝ H^{1/2} ∝ (1+z)^γ": f"γ = {gamma}",
    "β_Λ = -2γ": f"{beta_Lambda}（早期引力弱，符号对）",
}

# ---------------------------------------------------------------------------
# (3) 净效应：β = β_f + β_Λ = -α/f₂₀ - 2γ
# ---------------------------------------------------------------------------
# f₂₀ = ln(λ_c/λ_min,0)。λ_min,0 = π²/N_int²（内部 N_int=128）≈ 6.0e-4
N_int = 128
lambda_min0 = np.pi**2 / N_int**2
lambda_c = 2.0
f20 = np.log(lambda_c / lambda_min0)

beta_f = alpha / f20
beta_net = beta_f + beta_Lambda

R["net_effect"] = {
    "f₂₀ = ln(λ_c/λ_min,0)": f"{f20:.2f}（λ_min,0=π²/128²={lambda_min0:.2e}）",
    "β_f = α/f₂₀": f"{beta_f:.3f}（左旋钮，早期引力强）",
    "β_Λ = -2γ": f"{beta_Lambda:.3f}（右旋钮，早期引力弱）",
    "净 β = β_f + β_Λ": f"{beta_net:.3f}",
}

# ---------------------------------------------------------------------------
# (4) 对比哈勃张力
# ---------------------------------------------------------------------------
beta_hubble = -0.0211
R["vs_hubble_tension"] = {
    "哈勃张力 β": beta_hubble,
    "框架净 β": f"{beta_net:.3f}",
    "符号": "相同（都是负 = 早期引力弱）" if beta_net * beta_hubble > 0 else "相反",
    "量级比": f"{abs(beta_net/beta_hubble):.0f} 倍",
    "结论": "符号反转（用户对），但量级大 ~62 倍 → 「G(z) 跑动解释哈勃张力」仍不成立",
}

# ---------------------------------------------------------------------------
# (5) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "符号反转（用户对）": "考虑 Λ_eff 演化（右旋钮，γ 机制由 N_ext=S^{1/4} 建立）后，净 β < 0（早期引力弱），符号反转为对",
    "但量级不对": f"净 β ≈ {beta_net:.2f}，哈勃张力只要 {beta_hubble}，大 ~62 倍 → 「G(z) 跑动解释哈勃张力」仍不成立",
    "G(z) 跑动的真实性质": "β ≈ -1.3 意味着 G 在宇宙演化中跑动 ~100%，与「G 几乎常数」观测（LLR |Ġ/G|~10⁻¹³/年）硬冲突 → 是「被现有观测否掉的预言」，非「可检验新预言」",
    "更深的问题（诚实暴露）": "Λ 的双重角色——作为「宇宙学常数能标」（面积律暗能量 ρ_Λ∝R⁻² 需 Λ 随 N_ext 演化）vs 作为「引力常数标定」（G=3π/(f₂Λ²) 若 Λ 演化则 G 大幅跑动）。两者共享同一个 Λ（§9.2），若 Λ 演化则面积律暗能量成立但 G 大幅跑动被否 → 需厘清「引力 G 的 Λ」和「宇宙学常数 ρ_Λ 的 Λ」是否同一",
    "措辞（三档）": "「符号反转」=【坐实，用户对】；「量级差 62 倍」=【数值坐实】；「G(z) 跑动」=【被否的框架预言（若 Λ 演化），非桥 C 出口】——但「Λ 双重角色」是【真问题，需厘清】",
}

report(R, "exp_bridgeC_Gz")
