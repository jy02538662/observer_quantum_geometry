"""
思路 A 第二台阶：Hubbard U（同格点双占据 n_{i↑}n_{i↓}）从哪来？

第一台阶已证：「点」= Jones 投影 e_N（对角投影），从观察切割 E 涌现。
第二台阶问：基本构造 M₁ = ⟨M, e_N⟩（单体 + 投影）能不能产生「同格点双占据」U？

关键数学事实（先查）：
  「同格点双占据」n_{i↑}n_{i↓} = 格点 i 的自旋↑和↓同时占据。
  在「单体」（一个费米子）里，泡利禁戒 ⟹ n_{i↑}n_{i↓} = 0（一个粒子不能同时↑↓）。
  在「多体」（两个费米子 Fock 空间）里，n_{i↑}n_{i↓} = 投影到双占据态 |↑↓⟩ ≠ 0。

所以判死活：
  - 若基本构造 M₁（单体 + e_N）给非零 U ⟹ 一次基本构造就够；
  - 若 M₁ 给不了（泡利禁戒），U 是「多体」的 ⟹ 需要「两个费米子」（= D-D 自反 = 两次基本构造）。

Code: `py -m experiments.exp_jones_U_multibody`
"""
import numpy as np
from sympy import Matrix, zeros
from experiments._common import report

R = {}

# ===========================================================================
# 1. 泡利禁戒（符号）：单体 M_2 里 n_↑ n_↓ = 0
# ===========================================================================
n_up = Matrix([[1, 0], [0, 0]])    # 自旋↑占据（单体，格点 i 的↑）
n_dn = Matrix([[0, 0], [0, 1]])    # 自旋↓占据
prod = n_up * n_dn
R["1_pauli_single_body"] = {
    "单体 n_↑ n_↓": str(prod),
    "= 0（泡利禁戒，一个粒子不能同时↑↓）": prod == zeros(2, 2),
    "判读": "单体（一次基本构造 M₁ 是单体 + 投影）给不了非零 U",
}

# ===========================================================================
# 2. 多体（Fock 空间）：n_↑ n_↓ = 双占据投影 ≠ 0
# ===========================================================================
# 一个格点 i，两个自旋↑↓。Fock 空间 4 维：|0⟩, |↑⟩, |↓⟩, |↑↓⟩
n_up_fock = np.diag([0.0, 1.0, 0.0, 1.0])   # ↑ 占据（在 |↑⟩, |↑↓⟩ 上给 1）
n_dn_fock = np.diag([0.0, 0.0, 1.0, 1.0])   # ↓ 占据（在 |↓⟩, |↑↓⟩ 上给 1）
UU = n_up_fock @ n_dn_fock                  # 双占据投影
R["2_multibody_U"] = {
    "多体 n_↑ n_↓（Fock 空间，对角）": [float(x) for x in np.diag(UU)],
    "= 双占据投影 |↑↓⟩⟨↑↓|（≠0）": float(np.linalg.norm(UU - np.diag([0,0,0,1.0]))) < 1e-12,
    "判读": "U 是「多体」（两个费米子）的——Hubbard U = U·Σ_i n_{i↑}n_{i↓} 需要 Fock 空间",
}

# ===========================================================================
# 3. V²（D-D 自反，两个费米子）= 相邻密度，不是「同格点」双占据
# ===========================================================================
# 两个格点（无自旋），V = 粒子转移。V² 的「相邻密度」n₁n₂（1.29 §6.2 已算）。
# 对照：n₁n₂ 是「空间相邻」的两个格点；n_{i↑}n_{i↓} 是「同格点」的两个自旋。
R["3_V2_vs_U"] = {
    "V² = n₁+n₂−2n₁n₂（相邻密度，D-D 自反，1.29 §6.2）": "空间相邻两格点",
    "U = n_{i↑}n_{i↓}（同格点双占据）": "同格点两个自旋（内部自由度）",
    "区别": "相邻密度是「空间」自由度，同格点双占据是「内部（自旋/谷）」自由度——两者是不同对象",
    "判读": "V² 给「相邻」（空间），U 需要「同格点 + 内部自由度」，是另一层",
}

# ===========================================================================
# 4. 结论
# ===========================================================================
R["verdict"] = {
    "第二台阶判定": "「一次基本构造 M₁ 产生 U」判负——M₁ 是单体 + 投影，泡利禁戒 ⟹ n_{i↑}n_{i↓}=0",
    "U 的真正来源": "U 是「多体」（两个费米子）的，需要 Fock 空间（两个 D 的张量积 = D-D 自反 = 两次基本构造）",
    "思路 A 修正": "第一台阶（点=e_N）成立；但「补全 = 基本构造」这一步不是一次，而是「两次基本构造 / D-D 自反」才是「多体」（第二个费米子）的入口——U 从那里涌现，不从一次基本构造涌现",
    "下一步（第三台阶）": "把「两次基本构造 M → M₁ → M₂」或「D-D 自反（两个 D）」接到「同格点双占据」，看 U 是否从「第二个 e_N（第二个费米子）」涌现",
    "诚实边界": "这一步是「U 是多体的、泡利禁戒」这个已知事实的框架内重述，不是「U 已推出」——「第二个费米子从哪来」（内部自由度/自旋/谷）仍是框架的涌现内部 SU(2)（1.1）的活，不是 e_N 的活",
}

report(R, "exp_jones_U_multibody")
