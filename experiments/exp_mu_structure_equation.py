"""
推导「框架内部量 → 物理能标 μ」的结构等式（四条候选路径依次检查）

背景：β 函数跑动需要 μ，但「无绝对尺度」禁止绝对 μ。之前 μ/μ₀=N/N₀ 是识别（猜的）。
任务：从框架结构推 μ 是什么，不是猜。

四条候选：
  1. μ ~ λ_mod（模流频率）
  2. μ ~ 1/λ_min ~ N²（分辨率倒数）
  3. μ ~ N（RG 步长）
  4. μ ~ T = Λ/λ_mod（KMS 温度，最接近结构等式）

判据：哪条路径给出「结构等式」（从框架推，不是猜）→ 映射解决；
      四条都不给 → 映射是「未解决的结构问题」（开放问题，不是识别、不是缺口）。
"""
import numpy as np
import sympy as sp
from experiments._common import report

R = {}

# λ_mod(N) = log(N²/(π²·ln(2N²/π²)))
def lam_mod(N):
    return np.log(N**2 / (np.pi**2 * np.log(2 * N**2 / np.pi**2)))

# 框架的「自然」N 值（质量谱相关：3 生成元、7 非平凡、8 群阶、128 旧值）
Ns = [3, 7, 8, 128]
R["lambda_mod"] = {
    f"λ_mod(N={n})": round(float(lam_mod(n)), 4) for n in Ns
}

# 实验比值：μ(M_Z)/μ(m_τ) = 91.19 GeV / 1.777 GeV
mu_ratio_exp = 91.19 / 1.777
R["experiment"] = {
    "μ(M_Z)/μ(m_τ) ≈": round(float(mu_ratio_exp), 1),
    "含义": "M_Z 是 m_τ 的 51.3 倍能量",
}

# ---------------------------------------------------------------------------
# 四条路径的比值 f(N)/f(N₀)，取 N=128（高能）vs N₀=3（低能）
# ---------------------------------------------------------------------------
N_hi, N_lo = 128, 3
paths = {
    "1. μ ~ λ_mod": lam_mod(N_hi) / lam_mod(N_lo),
    "2. μ ~ 1/λ_min ~ N²": (N_hi**2) / (N_lo**2),
    "3. μ ~ N": N_hi / N_lo,
    "4. μ ~ T = Λ/λ_mod ~ 1/λ_mod": lam_mod(N_lo) / lam_mod(N_hi),
}
R["four_paths"] = {
    f"路径 {k}（N=128 vs N=3）比值": round(float(v), 2) for k, v in paths.items()
}
R["four_paths_vs_exp"] = {
    "实验 μ(M_Z)/μ(m_τ)": round(float(mu_ratio_exp), 1),
    "哪条接近": {k: f"差 {abs(v - mu_ratio_exp)/mu_ratio_exp*100:.0f}%" for k, v in paths.items()},
}

# ---------------------------------------------------------------------------
# 关键：路径 4（KMS）是「推导」吗？T = Λ/λ_mod 是推导，但 μ=T 是识别
# ---------------------------------------------------------------------------
# KMS 条件 T = Λ/λ_mod 是框架【推导】的（模流 → 温度）。
# 但「μ = T」是【识别】（把重整化标度 μ 等同于温度 T），不是推导。
# 且数值上：λ_mod 是 log 慢变函数，λ_mod(3)=0.419、λ_mod(128)=5.32，
#   比值 1/λ_mod 方向：λ_mod(3)/λ_mod(128)=0.079 ≠ 51.3（差 99.8%）。
R["path4_analysis"] = {
    "T = Λ/λ_mod 是推导": "是——KMS 条件从模流推温度（框架已有）",
    "μ = T 是识别还是推导": "【识别】——重整化标度 μ ≠ 温度 T（μ 是 UV 截断，T 是热标度），等同是约定不是推导",
    "数值 λ_mod(3)/λ_mod(128)": f"{lam_mod(3)/lam_mod(128):.4f}",
    "对比实验 51.3": "差 ~99.8%——路径 4 数值也对不上",
}

# ---------------------------------------------------------------------------
# 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "四条路径都给了「结构等式」吗": "【否】——四条都是 f(N) 的猜测（μ ~ λ_mod / 1/λ_min / N / T），没有一条从框架【推导】出 μ 的形式",
    "路径 4（最接近）": "T=Λ/λ_mod 是推导（KMS），但「μ=T」是识别不是推导，且数值对不上（0.079 vs 51.3）",
    "路径 3（数值最接近）": "μ~N 给 42.7（差 17%），但 μ~N 是纯猜测（μ 为何 ∝ N 无结构等式）",
    "结论": "映射「框架内部量 → μ」是【未解决的结构问题】——不是「识别」（需要结构等式），不是「缺口」（已查四条路径），是【开放问题】",
    "根因": "框架「无绝对尺度」⟹ 无绝对 μ；四条候选都是「μ = Λ·f(N)」形式，Λ（有量纲）是标定输入，f(N) 无结构等式确定",
    "开放问题的精确形态": "需要从公设推「μ 的 f(N) 形式」（不是 μ~N 这种猜测），或推「μ 是哪个内部量的哪个幂/对数」——目前框架没有这个推导",
}

report(R, "exp_mu_structure_equation")
