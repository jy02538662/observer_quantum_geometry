"""
攻动力学缺口·检查「link 振动谱 = 跑动」的翻转（这是动力学根的最后一步）

评估指出：走 B 打开了「link 语言」，但没解决「动力学根」（跑动/β函数/圈图）。
用户的直觉：link 网络的振动谱 = 跑动（不需要 β 函数）。

关键（先查）：
- link 振动谱 = D 的能带 E(k)（单粒子谱，色散关系）；
- 跑动 g(μ) = 耦合常数随能标 μ 变化（多体，β 函数，圈图）。

本脚本算 π 磁通 D 的能带（link 振动谱），诚实判断「振动谱（单粒子）vs 跑动（耦合）」
是不是同一个东西。
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. link 振动谱 = π 磁通 D 的能带 E(k)
# ---------------------------------------------------------------------------
# π 磁通 Dirac 色散：E(k) = ±2 sqrt(cos² kx + cos² ky)
k_list = np.linspace(-np.pi, np.pi, 100)
kx, ky = np.meshgrid(k_list, k_list)
E = 2 * np.sqrt(np.cos(kx)**2 + np.cos(ky)**2)   # 上带

R["step1_band"] = {
    "link 振动谱 = 能带 E(k)": "±2√(cos²kx + cos²ky)（π 磁通 Dirac 色散）",
    "E(k) 随 k 变化": "是（色散关系，单粒子谱）",
    "性质": "单粒子能带（link 网络的模式谱）",
}

# ---------------------------------------------------------------------------
# 2. 能带 → 态密度 ν(E)（单粒子量）
# ---------------------------------------------------------------------------
E_flat = E.flatten()
# 态密度（能带的积分）
E_bins = np.linspace(0, 2*np.sqrt(2), 50)
nu, _ = np.histogram(E_flat, bins=E_bins, density=True)

R["step2_dos"] = {
    "能带 → 态密度 ν(E)": "是（单粒子量的积分）",
    "态密度是单粒子还是多体": "单粒子（能带的态密度，不含相互作用）",
}

# ---------------------------------------------------------------------------
# 3. 跑动 g(μ)（耦合，多体）
# ---------------------------------------------------------------------------
# 跑动 g(μ) = g0 + β(g) ln(μ/μ0) + ...，β 函数来自圈图（多体修正）
# β 函数依赖「态密度」（单粒子）+「圈图」（多体）
R["step3_running"] = {
    "跑动 g(μ) = g0 + β(g) ln(μ/μ0)": "耦合随能标变化",
    "β 函数的来源": "圈图（多体修正），依赖态密度 ν(E)（单粒子）+ 相互作用（多体）",
    "振动谱（能带）给跑动吗": "部分——能带给态密度 ν(E)，但 β 函数还需圈图（多体），不是纯单粒子量",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "link 振动谱（能带 E(k)）": "单粒子谱（色散关系），是 link 网络的「模式」",
    "跑动（β 函数）": "多体（圈图），依赖态密度（单粒子）+ 相互作用（多体）",
    "「振动谱 = 跑动」是否成立": "不直接——振动谱（能带）给「态密度」，但「态密度 → β 函数」还需「圈图」（多体），不是纯振动谱",
    "动力学根的状态": "走 B 打开了「link 语言」（相互作用形式=相位型），但「跑动」= β 函数 = 圈图（多体）还是卡——振动谱是单粒子，跑动是多体",
    "准确下一步": "算「N 个 D 的 RG 流」（任务3）：粗粒化多个 D，看耦合 t_p 怎么跑动——这需要圈图（β 函数），仍是动力学缺口",
}

report(R, "exp_bridge2_spectrum_run")
