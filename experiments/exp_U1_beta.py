"""
任务 C · π 磁通规范场的 U(1) β 函数（一圈，标准 QED 型）

不用全空间对角化——用微扰论（费曼图）算一圈 β 函数，多项式复杂度。

框架的 U(1) 规范场来自内涨落 D→D+A，裸耦合 g² = 6π²（a₄ ⊃ −(1/24π²)∫tr(F²)）。
耦合到 Dirac 费米子（框架的 D 的模 = 3 代费米子），一圈 β 函数（费米子圈）：

  β(e) = de/dln μ = e³/(12π²) · Σ_f Q_f²     （标准 QED 一圈，Q_f = 费米子电荷）

判据：β(e) ≠ 0 = 有效耦合随尺度变 = 跑动（QED 不是渐近自由，Landau 极点方向）。

本脚本：
  1. 写出框架 U(1) 裸耦合 g²=6π²；
  2. 一圈 β 函数 β(e)=e³/(12π²)ΣQ_f²（符号 + 数值）；
  3. 跑动解 α⁻¹(μ)=α⁻¹(μ₀)−(2/3π)ΣQ_f²·ln(μ/μ₀)；
  4. 对比实验 α⁻¹(0)=137.036 → α⁻¹(M_Z)=127.955。
"""
import sympy as sp
import numpy as np
from experiments._common import report

R = {}
pi = sp.pi

# ---------------------------------------------------------------------------
# 1. 框架 U(1) 裸耦合（内涨落 a₄ 系数）
# ---------------------------------------------------------------------------
g2_bare = 6 * pi**2   # 裸 g² = 6π²（a₄ ⊃ −(1/24π²)∫tr(F²)，匹配 1/(4g²)=1/(24π²)）
R["step1_bare_coupling"] = {
    "内涨落 F² 项": "a₄ ⊃ −(1/24π²)∫tr(F²)",
    "裸 g² = 6π² ≈": f"{float(g2_bare.evalf()):.4f}",
    "裸 α = g²/(4π) = 3π/2 ≈": f"{float((g2_bare/(4*pi)).evalf()):.4f}",
}

# ---------------------------------------------------------------------------
# 2. 一圈 β 函数（费米子圈，标准 QED）
# ---------------------------------------------------------------------------
# β(e) = e³/(12π²) Σ_f Q_f²
# 标准模型 3 代 EM 电荷平方和：
#   上夸克 Q=2/3 ×3色×3代 = 9×(4/9)=4；下夸克 Q=-1/3 ×3色×3代=9×(1/9)=1；
#   电子 Q=-1 ×3代=3；中微子 Q=0 → ΣQ² = 8
sumQ2 = sp.Integer(8)
e = sp.symbols("e", positive=True)
beta_e = e**3 / (12 * pi**2) * sumQ2   # β(e)

# 换 α = e²/(4π)：dα/dlnμ = 2α²/(3π)·ΣQ²
alpha = sp.symbols("alpha", positive=True)
beta_alpha = 2 * alpha**2 / (3 * pi) * sumQ2   # dα/dlnμ

R["step2_beta_function"] = {
    "一圈 QED β(e) = e³/(12π²)·ΣQ_f²": str(sp.simplify(beta_e)),
    "ΣQ_f²（3 代 EM 电荷）": str(sumQ2),
    "β(e) 简化为": str(sp.simplify(beta_e)),
    "dα/dln μ = 2α²/(3π)·ΣQ_f²": str(sp.simplify(beta_alpha)),
    "符号（β>0）": "QED 不是渐近自由（Landau 极点，耦合随能量增大）",
}

# ---------------------------------------------------------------------------
# 3. 跑动解 α⁻¹(μ) = α⁻¹(μ₀) − (2/3π)ΣQ_f²·ln(μ/μ₀)
# ---------------------------------------------------------------------------
me = 0.511e-3      # GeV
MZ = 91.19         # GeV
lnMZ = np.log(MZ / me)
coeff = 2.0 / (3.0 * np.pi) * 8.0   # (2/3π)·ΣQ² = 16/(3π)

alpha0_inv = 137.036
alphaMZ_inv_pred = alpha0_inv - coeff * lnMZ   # 跑动预测（全 3 代，无阈值）

# 纯轻子（只 3 代轻子 Q²=3，忽略夸克阈值）：
coeff_lepton = 2.0 / (3.0 * np.pi) * 3.0
alphaMZ_inv_lepton = alpha0_inv - coeff_lepton * lnMZ

R["step3_running"] = {
    "ln(M_Z/me) ≈": round(float(lnMZ), 3),
    "(2/3π)·ΣQ² 系数（ΣQ²=8）": round(float(coeff), 4),
    "预测 α⁻¹(M_Z)（全 3 代，无阈值）": round(float(alphaMZ_inv_pred), 3),
    "预测 α⁻¹(M_Z)（纯轻子 ΣQ²=3）": round(float(alphaMZ_inv_lepton), 3),
    "实验 α⁻¹(M_Z)": 127.955,
    "实验 α⁻¹(0)": 137.036,
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["step4_honest_conclusion"] = {
    "算了什么": "一圈 QED β 函数（费米子圈），微扰论、多项式复杂度，不用全空间对角化",
    "β(e) = e³/(12π²)·ΣQ_f²（ΣQ_f²=8）": "非零 ⟹ 有效耦合【随尺度变】= 跑动",
    "跑动方向": "β>0 = 耦合随能量增大（QED 不是渐近自由，Landau 极点）——α 从 1/137 往 1/128 跑",
    "对比实验": "α⁻¹(0)=137.036 → α⁻¹(M_Z)≈127.955；纯轻子一圈给 ≈129.3（接近），全 3 代无阈值给 ≈116.5（需夸克阈值+QCD 修正）——量级/方向对，是标准 QED 跑动",
    "关键（回应防滑）": "跑动【不是】「多体指数维不可算」——一圈 β 函数是【多项式复杂度】（费曼图），微扰论直接算；「跑动」【不是】「动力学缺口」，是【标准 QED β 函数】，框架的内涨落耦合 g²=6π² 天然跑动",
    "诚实边界": "这是【标准 QED β 函数】（非框架独有）——框架的贡献是「内涨落给裸耦合 g²=6π² + 3 代费米子内容」；β 函数形式是 QED 标准结果，框架没算出「新」β 函数",
}

report(R, "exp_U1_beta")
