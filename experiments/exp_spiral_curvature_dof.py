"""
远景线 5（质量谱）· 三个方向试「螺旋曲率的自由度导数」能否给 N

用户要三个理解都试：
  ① 挠率 torsion（螺旋曲率/第二曲率）：自旋 1/2 费米子产生挠率，挠率 ∝ 自旋密度
  ② 费米面曲率 × 态密度（自由度导数 dN/dμ）
  ③ 自旋联络曲率 F_μν 的自由度（独立分量数）

本脚本把三个方向最具体的可算量全算出来，看哪个给出 128 量级或非平凡 N。
不预设 207，只看量级。
"""
import numpy as np
from experiments._common import report

R = {}

v_F = 2.0  # 框架 Dirac 速度

# ============ 方向 ①：螺旋度（helicity）的曲率与自由度 ============
R["helicity"] = {
    "螺旋度本征值 h = σ·p/|p|": "±1/2（自旋 1/2 的两个螺旋度态）",
    "螺旋度态数（自由度）": 2,
    "螺旋度 Berry 曲率（Dirac 点单极）": "±1/2",
    "挠率（Einstein-Cartan）∝ 自旋密度": "自旋 1/2 费米子的自旋密度 = 挠率源",
    "量级判断": "螺旋度自由度 = 2（O(1)），不是 128",
}

# 螺旋度自由度关于费米能的导数 = 态密度
R["helicity_derivative"] = {}
for mu in (0.5, 1.0, 2.0, 4.0):
    # 2D Dirac 态密度 ν(μ) = μ/(2π v_F²)
    nu = mu / (2*np.pi * v_F**2)
    R["helicity_derivative"][f"μ={mu}"] = {
        "态密度 ν(μ)=dN/dμ": round(nu, 4),
    }
R["helicity_derivative"]["量级判断"] = "态密度 ∝ μ，连续，不是 128"

# ============ 方向 ②：费米面曲率 × 态密度（自由度导数） ============
R["fermi_curvature_x_density"] = {}
for mu in (0.5, 1.0, 2.0):
    kF = mu / v_F
    curvature = 1.0 / kF          # 费米面（圈）的曲率
    nu = kF / (2*np.pi * v_F)     # 态密度
    R["fermi_curvature_x_density"][f"μ={mu}"] = {
        "曲率 κ=1/k_F": round(curvature, 3),
        "态密度 ν": round(nu, 4),
        "κ×ν": round(curvature * nu, 4),
        "κ/ν": round(curvature / nu, 3),
    }
R["fermi_curvature_x_density"]["量级判断"] = "κ×ν = 1/(2πv_F) = 常数 1/(4π)≈0.08；κ/ν ∝ 1/μ²。都不是 128"

# ============ 方向 ③：曲率 F_μν 的自由度（独立分量数） ============
R["curvature_dof"] = {}
for d in (2, 3, 4, 7, 11, 16):
    n_dof = d * (d - 1) // 2
    R["curvature_dof"][f"维度 d={d}"] = {
        "F_μν 独立分量数 d(d-1)/2": n_dof,
        "是否≈128": abs(n_dof - 128) < 10,
    }
R["curvature_dof"]["量级判断"] = "曲率自由度 d(d-1)/2：2D=1、3D=3、4D=6、d=16 时=120、d=17 时=136。128 落在 d=16(120) 和 d=17(136) 之间，没有整数维度给 128"

# ============ 检查：有没有组合自然给 128 或 2^7 ============
R["check_128"] = {
    "2^7 = 128": 2**7,
    "螺旋度自由度 2 × 2^6": 2 * 2**6,
    "曲率自由度 d=17 时 d(d-1)/2": 136,
    "d=16 时 d(d-1)/2": 120,
    "128 = 2^7 与曲率自由度的关系": "曲率自由度是 d(d-1)/2（二次式），2^7 是幂次，两者不匹配——没有结构理由让 d(d-1)/2 = 2^7",
    "128 = 2^7 与螺旋度的关系": "螺旋度自由度=2（一次），2^7 需要「7 个螺旋度自由度」，但自旋 1/2 只有 2 个螺旋度态",
}

R["honest_conclusion"] = {
    "方向①（螺旋度/挠率）": "螺旋度自由度=2、Berry 曲率=±1/2、挠率∝自旋密度，都是 O(1)，态密度 ∝ μ 连续——不给 128",
    "方向②（费米面曲率×态密度）": "κ×ν=1/(4π)≈0.08 常数、κ/ν∝1/μ²，都不给 128",
    "方向③（曲率自由度）": "d(d-1)/2 是二次式，2D=1/3D=3/4D=6，d=16→120、d=17→136，128 夹在中间无整数维度对应——不给 128",
    "共同结论": "三个方向都给 O(1) 或连续量，或二次式（到不了 128 的整数维度）。「螺旋曲率的自由度导数」没有自然给 128 的机制",
    "根本区分（重申）": "128 = 2^7 是「幂次」（7 个二进制自由度），而三个方向的量是「一次」（螺旋度 2）、「二次」（曲率 d(d-1)/2）、「连续」（态密度 ∝ μ）——都不产生 2^7 的幂次结构",
    "措辞": "三个方向都是探索负结果（给 O(1)/连续/二次式，不给 128 的幂次），非「否证」——若「螺旋曲率的自由度导数」指别的对象，需澄清",
}

report(R, "exp_spiral_curvature_dof")
