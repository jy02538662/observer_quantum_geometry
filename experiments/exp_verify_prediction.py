"""
远景线 5（质量谱）· 验证：这一轮新结论的边界（别又出「只作用左手」式的过度声称）

教训：之前「弱同位旋只作用左手」推了半天，结果数值坐实 P_R σ P_R ≠ 0（右手也作用），
是过度声称。这一轮验证两个新结论的边界，看哪些「真坐实」、哪些「候选」、哪些「反例」。

验证 1：手征规范（弱同位旋只作用左手）——是「投影到左手」还是「右手=0」？
验证 2：上型不对称（颜色单态投影）——「第二→第三=3」是否普适（第一→第二也是 3？）
"""
import numpy as np
from sympy import Matrix, I, Rational, simplify, sqrt
from experiments._common import report

R = {}

sx = Matrix([[0,1],[1,0]])
sy = Matrix([[0,-I],[I,0]])
sz = Matrix([[1,0],[0,-1]])
I2 = Matrix([[1,0],[0,1]])

# ---------------------------------------------------------------------------
# 验证 1：手征规范（弱同位旋只作用左手）的边界
# ---------------------------------------------------------------------------
J = I * sy  # 有向 J = iσ_y
plus_i = Matrix([1, I]) / sqrt(2)   # |+i>
minus_i = Matrix([1, -I]) / sqrt(2) # |-i>
PL = plus_i * plus_i.H  # 左手投影
PR = minus_i * minus_i.H  # 右手投影

# 弱同位旋 I₃ = σ_y/2 在左手/右手的投影
PL_sy_PL = simplify(PL * sy * PL)
PR_sy_PR = simplify(PR * sy * PR)

R["verify_chiral_gauge"] = {
    "P_L σ_y P_L（左手投影非零，I₃ 在左手作用）": PL_sy_PL != Matrix.zeros(2),
    "P_R σ_y P_R（右手投影是否非零）": PR_sy_PR != Matrix.zeros(2),
    "结论": "弱同位旋 =「投影到左手」（P_L σ P_L），但右手 P_R σ P_R 也非零——「只作用左手」是「投影」不是「右手=0」（标准模型更强）",
    "边界（诚实）": "框架坐实的是「弱同位旋投影到左手（I₃=+1/2）」，不是「弱同位旋在右手=0」——左右手命名是约定，右手是否真正=0 是标准模型的额外输入",
}

# ---------------------------------------------------------------------------
# 验证 2：上型不对称（颜色单态投影）是否普适
# ---------------------------------------------------------------------------
# 颜色单态投影机制预言：上型/下型代际比 = 3（三重态迹 3 ÷ 单态迹 1）
# 检验这个「3」是否对「第一→第二代」也成立
# 数据（exp_quark_family_probe 的精确值）：
# 上型：m_c/m_u = 577.27（第一→第二），m_t/m_c = 136.22（第二→第三）
# 下型：m_s/m_d = 19.79（第一→第二），m_b/m_s = 44.95（第二→第三）
up12, up23 = 577.27, 136.22
dn12, dn23 = 19.79, 44.95
ratio12 = up12 / dn12  # 第一→第二 上型/下型
ratio23 = up23 / dn23  # 第二→第三 上型/下型

R["verify_up_down_asymmetry"] = {
    "第二→第三 上型/下型 = m_t/m_c ÷ m_b/m_s": ratio23,
    "第一→第二 上型/下型 = m_c/m_u ÷ m_s/m_d": ratio12,
    "第二→第三 ≈ 3（颜色单态投影成立）": f"{ratio23:.2f} ≈ 3",
    "第一→第二 ≠ 3（颜色单态投影不成立）": f"{ratio12:.2f} ≠ 3",
    "结论（诚实）": "颜色单态投影（因子 3）只对「第二→第三代」（3-循环/颜色循环）成立，不对「第一→第二代」（转置/反射）成立——机制不普适，只解释第二→第三代",
}

# ---------------------------------------------------------------------------
# 诚实结论：这一轮有没有「可证伪预言」？
# ---------------------------------------------------------------------------
R["honest_prediction"] = {
    "这一轮的新结论": "手征规范（弱同位旋投影到左手）+ 上型不对称（颜色单态投影，只对第二→第三）——都是「机制/复现」，不是「预言新量」",
    "有没有「数值预言新量」": "没有——唯一「数值预言」是 1.14 的中微子=207（未测），这一轮没产生新的数值预言",
    "有没有「可证伪结构」": "有——「颜色单态投影只在 3-循环（第二→第三）出现、不在转置（第一→第二）出现」是「复现」已知结构，可证伪（若第一→第二也=3 则证伪），但已复现",
    "有没有「过度声称风险」": "已标注边界——手征规范是「投影」非「右手=0」；上型不对称「不普适」（第一→第二=29.2≠3）",
}

report(R, "exp_verify_prediction")
