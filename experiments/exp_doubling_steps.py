"""
远景线 5（质量谱）· 验证「7 个加倍步骤」vs「7 个自由度」是否同一个错误

用户修正：N=128 的来源候选 = 「7 个非平凡组合 × 每个对应一次自指加倍」，
区别于「7 个独立自由度」。用户主张「7 个加倍步骤」≠「7 个自由度」。

本脚本验证：这两个说法在数学上是否同一个错误。

关键事实：
  「一次区分（自指加倍）」= 增加一个 qubit = 一个独立二进制自由度 = 状态数 ×2。
  所以「N 次加倍」= N 个独立 qubit = N 个独立自由度 = 2^N。
  ⟹ 「7 次加倍」= 7 个独立 qubit = 7 个独立自由度 = 2^7 = 128。

  而三个 Z₂（Γ,K,s）只有 3 个独立生成元 = 3 个独立 qubit = 3 次独立加倍。
  7 个非平凡组合 = {Γ,K,s,ΓK,Γs,Ks,ΓKs}，其中 ΓK,Γs,Ks,ΓKs 是生成元的乘积，
  不是独立生成元。

  ⟹ 7 = 2³-1 是「3 个 qubit 的非平凡状态数」，不是「7 个 qubit」。
  ⟹ 「7 个加倍步骤」和「7 个自由度」是同一个错误：把「3 个 qubit 的状态数 7」
     当成了「7 个 qubit」。
"""
from itertools import combinations
from experiments._common import report

R = {}

# 三个 Z₂ 的生成元和组合
generators = {"Γ", "K", "s"}
# 7 个非平凡组合（幂集的非空子集）
combo_names = []
for r in (1, 2, 3):
    for c in combinations(sorted(generators), r):
        combo_names.append("".join(c))

R["generators_vs_combinations"] = {
    "独立生成元（独立 qubit）": sorted(generators),
    "独立生成元数": 3,
    "7 个非平凡组合": combo_names,
    "组合数": len(combo_names),
}

# 关键：组合里哪些是「独立生成元」，哪些是「生成元的乘积」
R["which_are_independent"] = {
    "独立（单生成元）": ["Γ", "K", "s"],
    "生成元乘积（非独立）": ["ΓK", "Γs", "Ks", "ΓKs"],
    "关键": "ΓK = Γ∘K 是「两个 qubit 的复合」，不是「第三个独立 qubit」",
}

# 「加倍 = 独立 qubit」的数学
R["doubling_math"] = {
    "一次区分（自指加倍）= 一个 qubit": "状态数 ×2",
    "N 次独立加倍 = N 个独立 qubit": "2^N",
    "3 个 Z₂ = 3 个独立 qubit = 3 次独立加倍": "2³ = 8 状态，7 非平凡",
    "7 次独立加倍 = 7 个独立 qubit": "2⁷ = 128",
    "关键判断": "「7 次加倍」需要「7 个独立 qubit」，但三个 Z₂ 只有「3 个独立 qubit」。7 = 2³-1 是「3 个 qubit 的状态数」，不是「7 个 qubit」",
}

R["honest_conclusion"] = {
    "核心结论": "「7 个加倍步骤」和「7 个自由度」是同一个错误——因为「加倍」=「独立区分」=「独立 qubit」，所以「7 次加倍」=「7 个独立 qubit」=「7 个自由度」。两者只是换了说法",
    "错误定位": "7 个非平凡组合里，只有 Γ,K,s 是「独立加倍」（3 个独立 qubit），ΓK,Γs,Ks,ΓKs 是它们的「复合」（非独立）。7 是「3 个 qubit 的状态数」（2³-1），不是「7 个 qubit」",
    "要 2⁷=128 的代价": "需要 7 个独立 qubit（7 次独立区分），但框架只有 3 个 Z₂（3 次独立区分）",
    "自指加倍机制本身": "✅ 对（一次区分 = 一个 qubit = 状态数 ×2，这个是对的）——但「7 个组合 = 7 次独立加倍」错，因为 7 个组合是 3 次加倍的产物",
    "措辞": "这是「群论计数」的坐实（生成元数 3 ≠ 组合数 7），非「否证」——自指加倍机制对，但 7→2⁷ 的映射错（7 是 3 个 qubit 的状态数，不是 7 个 qubit）",
}

report(R, "exp_doubling_steps")
