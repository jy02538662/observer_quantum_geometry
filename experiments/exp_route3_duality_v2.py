"""
路3（味结构）· 校正 λ_mod + 检查「离散 Poisson 对偶（N=3 → N²−1=8）」

校核（评估指出）：上一版 λ_mod 用了 λ_min=2−δ_N（精确），但质量谱链条实际用 λ_min=π²/N²
（近似），所以 λ_mod 应是 5.3217 不是 5.3355。差值 0.3% → 「λ_mod×λ_mix=8」精度依赖
这个候选，是「双重候选链」。

本脚本：
1. 校正 λ_mod（两种 λ_min 对比）；
2. 重算 λ_mod×λ_mix 的精确偏离；
3. 检查「离散 Poisson 对偶（N=3 → N²−1=8）」候选——是否「绝对阶↔阶差」对偶给乘积 8。
"""
import math
from experiments._common import report

R = {}

N = 128
lam_c = 2.0

# ---------------------------------------------------------------------------
# 1. λ_mod 两种 λ_min 对比
# ---------------------------------------------------------------------------
lam_min_approx = math.pi**2 / N**2          # 质量谱链条用的（π²/N²）
lam_min_exact = 2 - 2*math.cos(math.pi/(N+1))  # 精确（2−δ_N）

def lam_mod_from(lam_min):
    C = 1.0 / math.log(lam_c / lam_min)
    return math.log(C / lam_min)

lam_mod_approx = lam_mod_from(lam_min_approx)
lam_mod_exact = lam_mod_from(lam_min_exact)

R["step1_calibrate"] = {
    "λ_min = π²/N²（链条用）": f"{lam_min_approx:.6e}",
    "λ_min = 2−δ_N（精确）": f"{lam_min_exact:.6e}",
    "λ_mod（π²/N²）": f"{lam_mod_approx:.4f}",
    "λ_mod（2−δ_N）": f"{lam_mod_exact:.4f}",
    "差值": f"{abs(lam_mod_approx-lam_mod_exact)/lam_mod_approx*100:.2f}%",
}

# ---------------------------------------------------------------------------
# 2. λ_mod × λ_mix 的精确偏离（用 λ_mod = 5.3217）
# ---------------------------------------------------------------------------
lam_mod = lam_mod_approx
lam_mix_candidates = {
    "1.5（四舍五入）": 1.5,
    "1.514（-ln 0.22）": -math.log(0.22),
    "3/2（总拓扑荷候选）": 1.5,
}

products = {k: lam_mod * v for k, v in lam_mix_candidates.items()}

R["step2_product"] = {
    "λ_mod（5.3217）× λ_mix": {k: f"{v:.4f}" for k, v in products.items()},
    "目标 8": 8.0,
    "偏离": {k: f"{abs(v-8)/8*100:.2f}%" for k, v in products.items()},
}

# ---------------------------------------------------------------------------
# 3. 检查「离散 Poisson 对偶（N=3 → N²−1=8）」
# ---------------------------------------------------------------------------
# 候选 1：λ_mod × λ_mix = 2³ = 8（三个 Z₂ 元素数）
# 候选 2：λ_mod × λ_mix = N²−1 = 8（N=3 时 SU(3) 伴随维数）
# 候选 3：λ_mod × λ_mix = 2π（标准 Poisson）
for name, val in [("2³=8（三个Z₂元素数）", 8.0),
                  ("3²−1=8（SU(3)伴随）", 3**2 - 1),
                  ("2π（标准Poisson）", 2*math.pi)]:
    pass

R["step3_poisson"] = {
    "候选「乘积」结构量": {"2³（三个Z₂元素数）": 8, "3²−1（SU(3)伴随维数）": 8, "2π（标准Poisson）": round(2*math.pi, 3)},
    "关键问题": "「绝对阶 n ↔ 阶差 Δn」的对偶，是什么数学？标准 Poisson 对偶给 2π，不是 8；离散 Poisson（N²−1=8）是候选但无精确推导",
    "「绝对阶↔阶差」对偶定义": "没有（不像位置↔动量有傅里叶变换 ΔxΔp≥ħ）——「阶」和「阶差」的对偶数学未定义",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "λ_mod 校正": "5.3217（π²/N²，链条用），不是 5.3355（2−δ_N），差 0.3%",
    "λ_mod×λ_mix=8 偏离": "0.2%~0.7%（依赖 λ_mix 取值），且 λ_mod 依赖候选 N=128 + λ_min——双重候选链",
    "「绝对阶↔阶差」对偶": "无精确数学（不像傅里叶对偶有 ΔxΔp≥ħ），「乘积=8」无结构等式支撑",
    "判断": "λ_mod×λ_mix=8 是「巧合」或「待精确化猜测」，非「结构等式」——路3 定量收口（定性对、定量卡）",
}

report(R, "exp_route3_duality_v2")
