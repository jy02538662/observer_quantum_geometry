"""
攻「U_i 不唯一」第一刀：规范自由度 = 物理自由度？

核心区分（必须先厘清）：
  - 框架公设「无外部观察者 = 无偏好方向」给的是「全局 SO(3)」（Born 规则 p=f(m̂·n̂)）。
  - 「U_i 不唯一」（补四十六）是「局域 SU(2)」（每格点独立旋转），这是「自旋联络/分离不可分」，
    不是全局 SO(3)。

本脚本验证第一刀的两个关键断言：
  ① 「相对方向 n_i·n_j」只在「全局」旋转下不变，在「局域」旋转下不变（需要自旋联络）；
  ② 但「U = 格点双占据 Σ n_{i↑}n_{i↓}」是「标量」（单态），在「任意」（全局+局域）旋转下都
     不变 —— 所以 U_i 不唯一「不阻挡 U」。

Code: `py -m experiments.verify_gauge_physical`
"""
import numpy as np

print("=" * 72)
print("第一刀：规范自由度 = 物理自由度？")
print("=" * 72)

# ---------------------------------------------------------------------------
# ① 相对方向 n_i·n_j 的规范不变性
# ---------------------------------------------------------------------------
# n_i 是 S² 上的方向（3 维实矢量）。局域 SO(3) 变换 n_i -> R_i n_i。
n1 = np.array([1.0, 0.0, 0.0])
n2 = np.array([0.0, 1.0, 0.0])
rel = n1 @ n2  # 相对方向

# 全局旋转（同一个 R）
theta = 0.7
R_global = np.array([
    [np.cos(theta), -np.sin(theta), 0],
    [np.sin(theta), np.cos(theta), 0],
    [0, 0, 1],
])
rel_global = (R_global @ n1) @ (R_global @ n2)

# 局域旋转（不同 R1 != R2）
R1 = np.array([[np.cos(0.7), -np.sin(0.7), 0], [np.sin(0.7), np.cos(0.7), 0], [0, 0, 1]])
R2 = np.array([[np.cos(1.2), -np.sin(1.2), 0], [np.sin(1.2), np.cos(1.2), 0], [0, 0, 1]])
rel_local = (R1 @ n1) @ (R2 @ n2)

print("\n[① 相对方向 n_i·n_j 的规范不变性]")
print(f"  原相对方向 n1·n2 = {rel:.6f}")
print(f"  全局旋转后       = {rel_global:.6f}  {'（不变 [OK] 全局 SO(3)）' if abs(rel_global-rel)<1e-12 else '（变了！）'}")
print(f"  局域旋转后       = {rel_local:.6f}  {'（不变）' if abs(rel_local-rel)<1e-12 else '（变了 [X] 局域 SU(2) 下 n_i·n_j 非不变）'}")
print("  → 局域规范不变量需要「自旋联络」（平行移动），这正是「分离不可分」的墙")

# ---------------------------------------------------------------------------
# ② U = 格点双占据（单态）的规范不变性
# ---------------------------------------------------------------------------
# 单格点自旋-1/2：|0⟩空、|↑⟩、|↓⟩、|↑↓⟩双占据。双占据 = 单态 = 旋转不变量。
# 双占据投影 P_double = n_↑ n_↓ = |↑↓⟩⟨↑↓|
# 单态 |↑↓⟩ = (|↑⊗↓⟩ - |↓⊗↑⟩)/√2 是 SU(2) 不变的（标量，自旋 0）。
sx = np.array([[0, 1], [1, 0]])
sy = np.array([[0, -1j], [1j, 0]])
sz = np.array([[1, 0], [0, -1]])

def rot_su2(axis, theta):
    """SU(2) 旋转矩阵 exp(-i θ/2 (n·σ))。"""
    n = {"x": sx, "y": sy, "z": sz}[axis]
    return np.cos(theta/2) * np.eye(2) - 1j * np.sin(theta/2) * n

# 单态 |↑↓⟩ = (|↑⟩⊗|↓⟩ - |↓⟩⊗|↑⟩)/√2，在 (↑,↓) 基下是 (0,1,-1,0)/√2
singlet = np.array([0, 1, -1, 0]) / np.sqrt(2)

# 双占据投影 P = |↑↓⟩⟨↑↓|（在 2 电子态空间）
P_double = np.outer(singlet, singlet)

# 局域 SU(2) 旋转 R（作用在单电子自旋上，2 电子态 = R⊗R）
R = rot_su2("y", 0.9)
R2 = np.kron(R, R)  # 2 电子态上的旋转

# 双占据投影在局域旋转下：
P_rot = R2 @ P_double @ R2.conj().T

print("\n[② U = 格点双占据（单态）的规范不变性]")
print(f"  双占据投影 P = |↑↓⟩⟨↑↓| 在局域 SU(2) 旋转 R⊗R 下：")
print(f"  ‖P_rot - P‖ = {np.max(np.abs(P_rot - P_double)):.2e}  "
      f"{'（不变 [OK] 单态是标量，自旋 0）' if np.max(np.abs(P_rot - P_double)) < 1e-12 else '（变了！）'}")

# 更直接：双占据算符 n_↑ n_↓ 在旋转后的基下是否还给同一个物理量
# 关键：总占据 n = n_↑ + n_↓ 不变，双占据 = n(n-1)/2 只依赖总占据 → 旋转不变
print(f"  物理理由：双占据 = n_i(n_i-1)/2 只依赖「总占据 n_i」，不依赖「自旋轴」→ 任意旋转不变")

print("\n" + "=" * 72)
print("结论")
print("=" * 72)
print("① 「相对方向 n_i·n_j」只在「全局 SO(3)」下不变，在「局域 SU(2)」下变（需自旋联络）。")
print("   → 第一刀「物理只依赖 n_i·n_j」作为「局域规范不变性」的论证不成立（n_i·n_j 非局域不变）。")
print("② 但「U = 格点双占据」是「标量（单态，自旋 0）」，在任意（全局+局域）旋转下不变。")
print("   → 所以 U_i 不唯一「确实不阻挡 U」—— 但理由不是「相对方向」，是「U 是标量」。")
print("③ 框架「无外部观察者 = 无偏好方向」= 全局 SO(3)（Born 规则），与「U_i 局域 SU(2)」是两个层面。")

