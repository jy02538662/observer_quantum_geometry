"""
质量谱动力学核心计算：从「排斥+吸引」相互作用 → 隧穿率（单体 WKB）

链（用户对齐）：相互作用（排斥+吸引）→ 势垒 → 隧穿率 e^{-λ} → 绕数穿越 → 质量指数 e^{λ·n}。

关键：隧穿是「单体」问题（一个粒子穿势垒），不是圈图（多体）——绕开「多粒子 Fock 空间」。

本脚本算第 2 步：从「排斥+吸引」的势 V(r) 算 WKB 隧穿指数 λ，对比质量谱的 λ_mod≈5.32。

势（框架已有，第一性）：
  - 排斥 = 真空关联 χ = -|G₀|²（泡利反关联，长程 ~1/r^3.2）
  - 吸引 = 软模（关联刚度 J_s，相位相干吸引，势阱）

WKB 隧穿指数（单体）：
  λ = (1/ħ) ∫_{r1}^{r2} √(2m(V(r)-E)) dr，沿 V(r)>E 的势垒区。

问题：这个 λ 能不能给 λ_mod ≈ 5.32（即 e^{λ} ≈ 207）？

诚实边界：这是「机制探索」，V(r) 的具体形式（排斥+吸引的组合）是候选，不是唯一；
WKB 是半经典近似。先看「量级能不能对上」，再看「结构来源」。
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 势 V(r) = 排斥 + 吸引
# ---------------------------------------------------------------------------
# 排斥：泡利排斥，来自真空关联 χ=-|G₀|² ~ 1/r^3.2（长程排斥，正势）
# 吸引：软模/关联刚度，势阱（负势，~ -1/r 或 -1/r^2）
def V_repulsion(r, A=1.0):
    return A / r**3.2

def V_attraction(r, B=1.0):
    return -B / r

def V_total(r, A=1.0, B=1.0):
    return V_repulsion(r, A) + V_attraction(r, B)

# 势垒位置：V(r) 的极大值（排斥+吸引的交界）
# V(r) = A/r^3.2 - B/r，极大在 dV/dr = 0：
# -3.2 A/r^4.2 + B/r^2 = 0 → r^2.2 = 3.2 A/B → r* = (3.2 A/B)^{1/2.2}
def barrier_position(A, B):
    return (3.2 * A / B) ** (1 / 2.2)

R["potential"] = {
    "排斥 V_rep = A/r^3.2": "泡利排斥（真空关联 χ=-|G₀|²）",
    "吸引 V_att = -B/r": "软模（关联刚度）势阱",
    "势垒位置 r* = (3.2A/B)^{1/2.2}": "排斥+吸引交界（V 极大）",
}

# ---------------------------------------------------------------------------
# WKB 隧穿指数 λ = ∫ √(V(r)-E) dr
# ---------------------------------------------------------------------------
def wkb_index(A, B, E, r1, r2, n=10000):
    """从 r1 到 r2（势垒区，V>E）的 WKB 指数。"""
    rs = np.linspace(r1, r2, n)
    integrand = np.sqrt(np.maximum(V_total(rs, A, B) - E, 0.0))
    return float(np.trapz(integrand, rs))

# 扫描 (A, B, E) 看 WKB 指数能否给 λ_mod≈5.32
lam_target = 5.32
R["wkb_scan"] = {}
for A, B in [(1.0, 1.0), (1.0, 2.0), (2.0, 1.0), (3.0, 1.0), (1.0, 3.0)]:
    r_star = barrier_position(A, B)
    # 隧穿路径：从 r* 到某个远处（势垒区 V>E）
    # 取 E = V_total 的极小值附近（束缚态能量）
    # 简化：从 r* 隧穿到 r=10（远处自由）
    lam = wkb_index(A, B, E=0.0, r1=r_star, r2=10.0)
    R["wkb_scan"][f"A={A},B={B}"] = {
        "势垒位置 r*": round(float(r_star), 3),
        "WKB 指数 λ（E=0，r*→10）": round(float(lam), 3),
        "e^λ": round(float(np.exp(lam)), 1),
        "距 λ_mod=5.32": round(float(lam - lam_target), 3),
    }

# ---------------------------------------------------------------------------
# 关键：隧穿率 = 绕数穿越（拓扑视角）
# ---------------------------------------------------------------------------
R["tunneling_to_winding"] = {
    "隧穿率（单体 WKB）": "e^{-λ}，一个粒子穿势垒",
    "质量（穿透难度的倒数）": "m ∝ e^{λ}（穿透越难，质量越大）",
    "绕数穿越（拓扑）": "隧穿 n 次 = 绕 n 圈（拓扑荷 n）",
    "质量指数": "m_n ∝ e^{λ·n}，n = 绕数 = 代阶",
    "与质量谱形式对应": "e^{λ·n} = 框架已有的 e^{λ_mod·n}（λ=隧穿率，n=代阶）",
}

R["honest_conclusion"] = {
    "本脚本做了什么": "从「排斥（1/r^3.2）+ 吸引（-1/r）」的势，算 WKB 隧穿指数 λ，看能否给 λ_mod≈5.32。",
    "关键机制": "隧穿是「单体」问题（一个粒子穿势垒），不需要圈图（多体）——绕开「多粒子 Fock 空间」。",
    "判据": "若 WKB 指数 λ ≈ 5.32（量级对）→ 隧穿机制有戏，继续「绕数穿越」步；若 λ ≪ 5.32（量级差大）→ V(r) 形式需调整或机制需改。",
    "⚠️ 诚实边界": "① V(r) 的「排斥+吸引」具体形式是候选（1/r^3.2 + -1/r 是简化），真实形式需从 χ=-|G₀|² 和软模 J_s 第一性推导；② WKB 是半经典；③ 「绕数穿越 = 隧穿 n 次」的对应是「结构假设」，需进一步坐实（不是数字等同）。",
    "下一步": "若量级对上 → 算「绕数穿越」的精确对应（隧穿 = 绕数的结构等式），再提取质量指数 e^{λ·n} 对比 207/3477。",
}

report(R, "exp_mass_tunneling_from_interaction")
