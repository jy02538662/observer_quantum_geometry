"""
核心任务包 · 框架「无绝对尺度」如何重现实验跑动（α、α_s、sin²θ_W）？

一句话：算框架内生尺度谱 λ_min、λ_c、λ_mod 随观察者尺度 N 的变化，对比实验跑动。

必须算的对象（任务包指定）：
  1. 写出框架所有内生尺度：λ_min = π²/N²、λ_c = 2、λ_mod = log(C/λ_min)。
  2. 算这些量随 N 的变化（导数 / 斜率）。
  3. 对应到跑动：哪个对应 α？α_s？sin²θ_W？
  4. 对比实验值（α(M_Z)≈1/128、α_s(M_Z)≈0.118、sin²θ_W≈0.231）。

防滑条款（任务包三条，必须遵守）：
  - 不接受「结构预言（无绝对尺度）」——实验测到跑动，矛盾必须解释；
  - 不接受「边界（动力学缺口）」——那是「没算」，不是「不存在」；
  - 不接受「算格点 β 函数（套标准 QCD）」——那是引用，不是推导。
  只接受：具体算出的数值/公式 + 对比实验。

本脚本逐条做：内生尺度定义（符号）→ N 导数（符号）→ 对数斜率 → 映射到三个耦合
→ 对比实验斜率 → 用 AGENTS 三问判「真推进 / 换名字 / 矛盾」。
"""
import sympy as sp
import numpy as np
from experiments._common import report

R = {}

N = sp.symbols("N", positive=True)
pi = sp.pi

# ---------------------------------------------------------------------------
# 1. 框架所有内生尺度（显式写全）
# ---------------------------------------------------------------------------
# λ_min = π²/N²（尺度破缺 2−δ_N 的领头阶，IR 截断）
# λ_c   = 2（量子维度经典极限，UV 截断，独立常数）
# λ_mod = log(C/λ_min) = log(1/λ_min) − log(ln(λ_c/λ_min))（模流频率）
lam_min = pi**2 / N**2
lam_c = sp.Integer(2)
lam_mod = sp.log(lam_c / lam_min) - sp.log(sp.log(lam_c / lam_min))  # = log(C/λ_min)

R["step1_endogenous_scales"] = {
    "λ_min = π²/N²": str(lam_min),
    "λ_c = 2": str(lam_c),
    "λ_mod = log(C/λ_min) = log(1/λ_min) − log(ln(λ_c/λ_min))": str(lam_mod),
    "λ_mod 简化 = log(N²/(π²·ln(2N²/π²)))": str(sp.simplify(sp.log(N**2 / (pi**2 * sp.log(2 * N**2 / pi**2))))),
    "说明": "λ_min、λ_mod 是 N 的函数；λ_c=2 是独立常数（经典极限，不随 N 变）",
}

# ---------------------------------------------------------------------------
# 2. 随 N 的变化（符号导数 + 对数斜率）
# ---------------------------------------------------------------------------
d_lam_min = sp.diff(lam_min, N)
d_lam_c = sp.diff(lam_c, N)
d_lam_mod = sp.simplify(sp.diff(lam_mod, N))

R["step2_N_derivatives"] = {
    "dλ_min/dN": str(sp.simplify(d_lam_min)),
    "dλ_c/dN": str(d_lam_c),
    "dλ_mod/dN": str(d_lam_mod),
}

# 对数斜率 d ln X / d ln N（跑动是「对数斜率」，这里统一成这个）
dln_lam_min = sp.simplify(N * d_lam_min / lam_min)   # = −2
dln_lam_c = sp.simplify(N * d_lam_c / lam_c)         # = 0
dln_lam_mod = sp.simplify(N * d_lam_mod / lam_mod)

R["step2_log_slopes"] = {
    "d ln(λ_min)/d ln N": str(dln_lam_min),
    "d ln(λ_c)/d ln N": str(dln_lam_c),
    "d ln(λ_mod)/d ln N": str(dln_lam_mod),
}

# ---------------------------------------------------------------------------
# 3. 映射到跑动：框架里「耦合」从哪来？
# ---------------------------------------------------------------------------
# 框架唯一给过「耦合」的地方 = exp_gauge_coupling_rederive 第一刀：
#   g² ∝ λ_min = π²/N²（硬截断谱作用量 F² 项 ∝ Tr[D^{-6}] ∝ 1/λ_min）
#   但 exp_gauge_coupling_spectral_flow 已坐实：含谱流后 F²=0，规范场走内涨落
#   （D→D+A 的 a₄ ⊃ −(1/24π²)∫tr(F²)），g 的来源是内涨落、不是 λ_min。
# 所以「g² ∝ λ_min」是【已作废的第一刀】，这里如实标注，仍算出它的斜率作对照。
g2_propto_lam_min = lam_min                       # 若 g² ∝ λ_min（已作废）
dln_g2 = sp.simplify(N * sp.diff(sp.log(g2_propto_lam_min), N))  # = −2

R["step3_mapping_to_couplings"] = {
    "框架唯一给过耦合的地方": "exp_gauge_coupling_rederive 第一刀：g² ∝ λ_min = π²/N²",
    "但（谱流已坐实）": "含谱流后 F²=0（体项+边界 δ 精确抵消），第一刀作废；规范场走内涨落 D→D+A，g 的来源不是 λ_min",
    "若 g² ∝ λ_min 的斜率 d ln g²/d ln N": str(dln_g2),
    "λ_c=2 对应什么耦合": "无对应（它是经典极限常数，不给耦合跑动）",
    "λ_mod 对应什么耦合": "无对应（它给质量比 e^{λ_mod}≈207，是质量谱，不是规范耦合）",
    "sin²θ_W 在框架里出现": "只在 SU(3)_k 量子维度 [3]_q = 3−4sin²(π/(k+3))（色禁闭线），不是 Weinberg 角 sin²θ_W = g'²/(g²+g'²)",
}

# ---------------------------------------------------------------------------
# 4. 对比实验（跑动的对数斜率，d ln 耦合 / d ln μ）
# ---------------------------------------------------------------------------
# 实验值（PDG）：α⁻¹(M_Z)=127.955、α⁻¹(0)=137.036、α_s(M_Z)=0.1179、sin²θ_W(M_Z)=0.23122
# 跑动区间取 μ ∈ [me, M_Z]：me=0.511 MeV、M_Z=91.19 GeV
me = 0.511e-3   # GeV
MZ = 91.19      # GeV
ln_range = np.log(MZ / me)   # ≈ 12.09

# α：电磁（不渐近自由，往上跑）
a0_inv, aZ_inv = 137.036, 127.955
slope_alpha = np.log(a0_inv / aZ_inv) / ln_range          # d ln α / d ln μ ≈ +0.0057

# α_s：强（渐近自由，往下跑，单圈 β 系数 b=23/3 for n_f=5）
a_s_Z = 0.1179
b_strong = 23.0 / 3.0
slope_alpha_s = -b_strong * a_s_Z / (2 * np.pi)  # = −b·α_s/(2π)，d ln α_s/d ln μ 单圈

# sin²θ_W：弱混合角（往下微跑）
sw0, swZ = 0.2387, 0.23122
slope_sw = np.log(swZ / sw0) / ln_range                    # ≈ −0.0026

R["step4_experiment"] = {
    "跑动区间 μ ∈ [me, M_Z]，ln(M_Z/me)": round(float(ln_range), 3),
    "α(M_Z)≈1/128, α(0)≈1/137": "α 往上跑（非渐近自由，屏蔽）",
    "d ln α/d ln μ": round(float(slope_alpha), 4),
    "α_s(M_Z)≈0.118": "α_s 往下跑（渐近自由，单圈 b=23/3）",
    "d ln α_s/d ln μ（单圈 −b·α_s/2π）": round(float(slope_alpha_s), 4),
    "sin²θ_W(M_Z)≈0.231, sin²θ_W(0)≈0.239": "sin²θ_W 往下微跑",
    "d ln sin²θ_W/d ln μ": round(float(slope_sw), 4),
}

# ---------------------------------------------------------------------------
# 5. 判据：真推进 / 换名字 / 矛盾（AGENTS 三问 + 任务包判据）
# ---------------------------------------------------------------------------
R["step5_verdict"] = {
    "框架给的（单一斜率）": "若 g²∝λ_min，d ln g²/d ln N = −2（且这一步已作废，见 step3）",
    "实验要的（三个独立斜率）": {
        "α": "+0.0057（往上，小）",
        "α_s": "−0.14（往下，大）",
        "sin²θ_W": "−0.0026（往下，微）",
    },
    "符号都对不上": "框架单一斜率 −2 vs 实验两上一下三个斜率——连符号都不同（α 往上，框架只有往下）",
    "AGENTS 三问①（同一对象吗）": "否——λ_min 是观察者侧无量纲 IR 截断（N 的函数），耦合 g 跑动变量是能量尺度 μ（有量纲）。两个量作用在不同对象上，不能直接等",
    "AGENTS 三问②（计数对吗）": "框架一个旋钮 N，实验三个独立耦合——计数对不上（1 个 N 给不出 3 个独立跑动）",
    "AGENTS 三问③（先结构等式还是先数）": "g²∝λ_min 是第一刀（已被谱流作废），无结构等式把 N↔μ 连起来——连「先有结构等式」这一步都没有",
    "任务包判据": "既非「真推进」（对不上实验），也非「换名字」（不是标准 β 函数的翻译，是根本没有跑动变量 μ），是「框架与实验矛盾」",
}

R["honest_conclusion"] = {
    "算出的结果": "λ_min、λ_c、λ_mod 的 N 导数都算出来了（dλ_min/dN=−2π²/N³、dλ_c/dN=0、dλ_mod/dN=(2/N)(1−1/ln(2N²/π²))）；框架唯一「耦合」候选 g²∝λ_min 给单一对数斜率 −2。",
    "对比实验": "实验三个耦合 α(+0.0057)、α_s(−0.14)、sin²θ_W(−0.0026) 是三个独立斜率、两种符号；框架只有单一斜率 −2、一个旋钮 N、没有能量尺度 μ。对不上。",
    "防滑条款落实情况": "① 没有拿「结构预言/无绝对尺度」搪塞——如实报告对不上；② 没有拿「边界/动力学缺口」搪塞——真的算了，算出「无 μ ⟹ 无跑动」这个结构结果，它与实验跑动冲突；③ 没有套标准 QCD β 函数——只用了框架自己的 λ_min/λ_c/λ_mod。",
    "结论（措辞三档·诚实档）": "框架当前【无法重现】α、α_s、sin²θ_W 的跑动，这是「未解决的真矛盾」，不是「否证」（框架骨架未错），也不是「边界」（已算、算出来对不上）。",
    "要解决矛盾需要的新结构": "① 一个 N↔μ 的结构等式（框架目前没有：无绝对尺度 ⟹ 无 μ）；② 三个独立耦合的来源（框架目前只有一个候选 g²∝λ_min，且已作废）；③ 内涨落 D→D+A 的圈图（= 规范场 β 函数，框架的动力学缺口）——这三者任一打通才算真推进。",
}

report(R, "exp_scale_running")
