"""
路3（味结构）· 检查「λ_mod × λ_mix = 8 = 2³」的对偶（防盯数）

翻转（用户）：λ_mod（质量指数，看绝对阶 n）和 λ_mix（混合指数，看阶差 Δn）可能是
「对偶」的（像位置-动量），乘积是结构常数：

  λ_mod · λ_mix = 2³ = 8（三个 Z₂ 的元素数）

则 λ_mix = 8/λ_mod 是「推出来的」，不是「反推的」。

判据（诚实）：
  - 若 λ_mod · λ_mix 精确 = 8，且「乘积=8」有结构理由 → 对偶成立，定量通了；
  - 若只是「5.32 × 1.5 ≈ 7.98 接近 8」，且「乘积=8」无结构理由 → 巧合（盯数）。

本脚本精确算 λ_mod（用 λ_min=2−δ_N 精确），检查 λ_mod × λ_mix 是否精确 = 8。
"""
import math
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. 精确 λ_mod（λ_min = 2−δ_N 精确，非 π²/N² 近似）
# ---------------------------------------------------------------------------
N = 128
lam_c = 2.0
delta_N = 2 * math.cos(math.pi / (N + 1))       # 量子维度
lam_min_exact = 2 - delta_N                      # 尺度破缺（精确）
C = 1.0 / math.log(lam_c / lam_min_exact)        # 归一化
lam_mod = math.log(C / lam_min_exact)            # 模流频率（精确）

lam_min_approx = math.pi**2 / N**2               # 近似值（π²/N²）

R["step1_lam_mod"] = {
    "λ_min 精确（2−δ_N）": f"{lam_min_exact:.6e}",
    "λ_min 近似（π²/N²）": f"{lam_min_approx:.6e}",
    "λ_mod 精确": f"{lam_mod:.4f}",
    "λ_mod（旧近似 5.32）": 5.32,
}

# ---------------------------------------------------------------------------
# 2. 检查 λ_mod × λ_mix = 8
# ---------------------------------------------------------------------------
lam_mix_candidates = {
    "1.5（四舍五入）": 1.5,
    "1.514（-ln 0.22）": -math.log(0.22),
    "8/λ_mod（对偶反解）": 8.0 / lam_mod,
}

products = {k: lam_mod * v for k, v in lam_mix_candidates.items()}
target = 8.0

R["step2_duality"] = {
    "λ_mod × λ_mix 各候选": {k: f"{v:.4f}" for k, v in products.items()},
    "目标 8 = 2³": target,
    "偏差": {k: f"{abs(v-target)/target*100:.2f}%" for k, v in products.items()},
}

# ---------------------------------------------------------------------------
# 3. 若 λ_mix = 8/λ_mod（对偶成立），θ12 = e^{-λ_mix} 是多少
# ---------------------------------------------------------------------------
lam_mix_duality = 8.0 / lam_mod
theta12_duality = math.exp(-lam_mix_duality)
theta12_actual = 0.23   # Cabibbo 角 ≈ 13°

R["step3_theta"] = {
    "λ_mix = 8/λ_mod": f"{lam_mix_duality:.4f}",
    "θ12 = e^{-λ_mix}（对偶）": f"{theta12_duality:.4f}",
    "实际 θ12（Cabibbo）": theta12_actual,
    "偏差": f"{abs(theta12_duality-theta12_actual)/theta12_actual*100:.2f}%",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "「乘积=8」是否精确": f"{abs(lam_mod*1.5 - 8)/8*100:.2f}%（λ_mix=1.5 时）",
    "关键问题": "「λ_mod × λ_mix = 2³ = 8」这个等式，是否有结构理由？还是 5.32×1.5≈7.98 的巧合？",
    "结构理由检查": "λ_mod = log(1/λ_min)（IR 截断对数），λ_mix = ?（混合指数无定义），「乘积 = 三个 Z₂ 元素数 8」无直接结构来源",
    "判断": "若「乘积=8」无结构等式支撑，则 λ_mix=8/λ_mod 仍是「先有 8 再凑」，是盯数；需先有「绝对阶↔阶差 对偶给乘积 8」的结构推导",
}

report(R, "exp_route3_duality")
