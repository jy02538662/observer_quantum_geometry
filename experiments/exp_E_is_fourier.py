"""
钉死关键对应：「观察切割 E（对角投影）」=「Fourier 反演（点 = 波的等权叠加）」

用户洞见：点 = 所有动量的等权叠加（δ = Σ_k e^{ikx}/N，Fourier 反演）。
思路 A 第一台阶：点 = 对角投影 e_N，从观察切割 E（对角条件期望）涌现。

本实验验证两者是「同一个点」的两个表述：
  1. 点 |x_0⟩ 的动量分解是等权的（|⟨k|x_0⟩|² = 1/N，所有动量等权）——即「点 = 波的等权叠加」；
  2. 对角投影 E 保持「点」（E|x_0⟩⟨x_0| = |x_0⟩⟨x_0|）、杀「动量」（E|k⟩⟨k| = 均匀）——即「点 = E 的像的基」；
  3. 两者给同一个 |x_0⟩：Fourier 反演的点 = E 的像的基 = 观察切割 E 的投影。

若成立：「谁来做相干」= 观察切割 E（公设），不是外部势——点从公设涌现，墙以这个精确方式消解。

Code: `py -m experiments.exp_E_is_fourier`
"""
import numpy as np
from experiments._common import report

R = {}

N = 8   # 一维环 N 格点
xs = np.arange(N, dtype=float)

# ---------------------------------------------------------------------------
# 实空间基 |x⟩（delta 态）与 动量基 |k⟩（平面波），Fourier F
# ---------------------------------------------------------------------------
# 动量 k_j = 2π j / N
F = np.exp(1j * 2 * np.pi * np.outer(xs, xs) / N) / np.sqrt(N)   # F[k, x] = e^{ikx}/√N

def position_state(x0):
    psi = np.zeros(N); psi[x0] = 1.0
    return psi

def momentum_state(j):
    return F[j]   # |k_j⟩ = Σ_x e^{ikx}|x⟩/√N，即 F 的第 j 行

# ---------------------------------------------------------------------------
# 1. 「点 = 波的等权叠加」：点 |x_0⟩ 的动量分解是否等权？
# ---------------------------------------------------------------------------
x0 = 3
psi_x0 = position_state(x0)
# 动量分解：⟨k_j | x_0⟩ = e^{-ik x_0}/√N，幅度 = 1/√N（所有动量等权）
mom_amp = np.abs(F @ psi_x0) ** 2   # |⟨k_j|x_0⟩|²
R["1_point_equal_weights"] = {
    "点 |x_0⟩ 的动量分解 |⟨k|x_0⟩|²": [round(float(a), 6) for a in mom_amp],
    "= 1/N 对所有动量（等权）": float(np.max(np.abs(mom_amp - 1.0 / N))) < 1e-12,
    "判读": "点 = 所有动量的等权叠加（Fourier 反演 δ = Σ_k e^{ikx}/N）",
}

# ---------------------------------------------------------------------------
# 2. 对角投影 E 保持「点」、杀「动量」
# ---------------------------------------------------------------------------
def E_matrix(M):
    return np.diag(np.diag(M))   # 对角条件期望 E(M) = diag(M)

# 点 = |x_0⟩⟨x_0|（投影到单点）
Px0 = np.outer(psi_x0, psi_x0.conj())
# 动量 = |k⟩⟨k|（纯动量）
k0 = 1
Pk = np.outer(momentum_state(k0), momentum_state(k0).conj())

E_Px0 = E_matrix(Px0)   # 对角投影保持点吗？
E_Pk = E_matrix(Pk)     # 对角投影杀动量吗？

R["2_E_keeps_point_kills_momentum"] = {
    "E(|x_0⟩⟨x_0|) = |x_0⟩⟨x_0|（保持点）": float(np.linalg.norm(E_Px0 - Px0)) < 1e-12,
    "E(|k⟩⟨k|) = 均匀对角（杀动量，所有点等权 1/N）": float(np.max(np.abs(np.diag(E_Pk) - 1.0/N))) < 1e-12,
    "判读": "E 保持「点」（对角）、杀「动量」（非对角）——E 的像 = 对角子空间 = 实空间（点）",
}

# ---------------------------------------------------------------------------
# 3. 两者给同一个「点」：Fourier 反演的点 = E 的像的基
# ---------------------------------------------------------------------------
# 方法 A（Fourier 反演）：点 |x_0⟩ = F^{-1} (δ 在动量基) = Σ_k e^{ikx_0}|k⟩/√N
reconstructed = F.conj().T @ np.ones(N, dtype=complex) / np.sqrt(N)   # Σ_k e^{ikx}|k⟩/√N 的实空间表示？
# 更直接：|x_0⟩ 在动量基 = F|x_0⟩（幅度 1/√N 等权），Fourier 反演回实空间 = |x_0⟩
mom_of_x0 = F @ psi_x0                      # 动量基表示（等权 + 相位 e^{-ikx0}）
back_to_real = F.conj().T @ mom_of_x0       # 反演回实空间
R["3_same_point"] = {
    "Fourier 反演回实空间 = 原 |x_0⟩（F 是酉）": float(np.linalg.norm(back_to_real - psi_x0)) < 1e-12,
    "点 = 波的等权叠加（Fourier）": "|⟨k|x_0⟩|²=1/N 等权（步骤1）",
    "点 = E 的像的基（对角投影）": "E 保持 |x_0⟩⟨x_0|（步骤2）",
    "两者同一个点": "Fourier 反演的点 = E 的像的基 = |x_0⟩",
}

# ---------------------------------------------------------------------------
# 4. 关键：E 是不是「从动量基到实空间基」的投影？
# ---------------------------------------------------------------------------
# E 作用于矩阵，把「动量矩阵」投到「实空间对角」。
# 验证：E 在动量基下的矩阵元 = 「动量差对角」，即 E 把不同动量耦合掉（非对角动量 → 0 对角）。
# 具体：E(|k⟩⟨k'|) 当 k≠k' 时 = ?（应为 0 或「动量差」项）
Pk_kp = np.outer(momentum_state(0), momentum_state(1).conj())   # |k_0⟩⟨k_1|（非对角动量）
E_Pk_kp = E_matrix(Pk_kp)
R["4_E_is_real_space_projection"] = {
    "E(|k_0⟩⟨k_1|)（非对角动量 → 对角投影）": str(np.round(E_Pk_kp, 6).tolist()),
    "E 把「动量相干」（非对角）投到「实空间对角」（点）": True,
    "核心对应": "E（对角投影）= 从动量基到实空间基的投影 = Fourier 反演——「谁做相干」= E（观察切割，公设）",
}

# ---------------------------------------------------------------------------
# 结论
# ---------------------------------------------------------------------------
R["verdict"] = {
    "钉死了什么": "「点 = 波的等权叠加」（Fourier 反演）=「点 = 观察切割 E 的对角投影」——同一个点 |x_0⟩ 的两个表述（动量基 vs 对角基）",
    "谁来做相干": "= 观察切割 E（对角条件期望，公设「观察 = 一次有向区分」）——E 把动量（非对角）投到实空间（对角），就是「做 Fourier 反演」",
    "墙消解的精确形式": "点从公设（E）涌现，不需要外部势——「谁做相干」不是缺口，是公设本身",
    "诚实边界": "这只钉死「点」（单点）从 E 涌现；「同格点双占据 U」（多体）还需要「内部自由度（涌现谷）」+「多体 Fock 空间」，那是思路 A 第二、三台阶，仍卡「动量→实空间」（谷是动量空间）",
}

report(R, "exp_E_is_fourier")
