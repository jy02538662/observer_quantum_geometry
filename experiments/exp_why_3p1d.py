"""
攻「为什么是 3+1D」的成分论证（不是球坐标的组合，是「为什么是这三个成分」）

四个成分问题：
  1. 为什么径向是 1D（不是 0D/2D）？← 观察者态 ρ=C/λ 是 1 个标量参数
  2. 为什么 S² 是 2D（不是 S¹/S³）？← 断裂 SU(2)/U(1)，dim SU(2)=3、dim U(1)=1、商 2D
  3. 为什么时间是 1D？← 模流 σ_t 是 1 参数群
  4. 为什么是乘积不是纤维丛？← 三成分独立（观察者态谱 / 断裂 / 模流 来自独立结构）

验证：
  1. 观察者态 1 标量（径向 1D）
  2. SU(2) 3 生成元（内部三维）、U(1) 1 生成元、S²=SU(2)/U(1) 2D
  3. 模流 σ_tσ_s=σ_{t+s}（1 参数群）
  4. 三成分独立 → 乘积（无 twist = trivial 丛）
"""
import numpy as np
from experiments._common import report

R = {}

# ---- 1. 径向 1D：观察者态是 1 个标量参数 ----
# ρ = C/λ，λ 是 1 个标量（不是向量），所以观察者态谱 {λ} 是 1D
R["radial_1d"] = {
    "观察者态 ρ = C/λ": "λ 是 1 个标量（非向量），谱 {λ} 是 1 参数族",
    "径向坐标 s = logλ": "1D（1 个连续参数）",
    "为什么不是 0D/2D": "观察者态的结构就是 1 标量（框架公设：无偏好 ρ=C/λ 唯一）",
}

# ---- 2. S² 2D：断裂 SU(2)/U(1) ----
# SU(2) 有 3 个生成元（Pauli σ_x,σ_y,σ_z）= 内部三维；U(1) 1 个生成元（相位）
# 商 SU(2)/U(1) 维数 = 3 - 1 = 2 = S²
try:
    import sympy as sp
    # SU(2) 李代数 su(2)：3 生成元（Pauli），维度 3
    # U(1) 子代数：1 生成元（对角），维度 1
    # 商 su(2)/u(1)：余维 3-1=2 = S² 的切空间维度
    R["S2_dim"] = {
        "su(2) 生成元数（Pauli σ_x,σ_y,σ_z）": 3,
        "u(1) 生成元数（对角相位）": 1,
        "商 su(2)/u(1) 余维（=S² 切空间维度）": 3 - 1,
        "S² = SU(2)/U(1) 是 2D（不是 S¹/S³）": "因为 SU(2) 是 3D（内部三维，π 磁通反对易 T_xT_y=-T_yT_x），商 U(1)（相位）得 2D",
    }
except Exception as e:
    R["S2_dim"] = {"error": str(e)}

# ---- 3. 时间 1D：模流 1 参数群 ----
# σ_t = ρ^{it} = e^{it logρ}，σ_t σ_s = e^{i(t+s)logρ} = σ_{t+s}
try:
    import sympy as sp
    t, s = sp.symbols('t s', real=True)
    logrho = sp.symbols('logrho', real=True)
    sigma = lambda u: sp.exp(sp.I * u * logrho)   # σ_u = ρ^{iu} = e^{iu logρ}
    lhs = sp.simplify(sigma(t) * sigma(s))         # σ_t σ_s
    rhs = sp.simplify(sigma(t + s))                # σ_{t+s}
    R["time_1d"] = {
        "模流 σ_t = ρ^{it} = e^{it logρ}": "1 参数群（Tomita-Takesaki）",
        "σ_t σ_s = σ_{t+s}（群性质）": str(sp.simplify(lhs - rhs) == 0),
        "为什么时间 1D": "模流是 1 参数群 → 1 个时间参数 t",
    }
except Exception as e:
    R["time_1d"] = {"error": str(e)}

# ---- 4. 乘积（不是纤维丛）：三成分独立 ----
# 径向（观察者态谱 λ）、角向（断裂 S²）、时间（模流 t）来自独立结构
R["product"] = {
    "径向（观察者态谱）": "由 ρ=C/λ 唯一确定（1 参数 λ）",
    "角向（断裂 S²）": "由 π 磁通反对易 → SU(2)/U(1) 唯一确定（2 参数）",
    "时间（模流）": "由 Tomita-Takesaki 模流唯一确定（1 参数 t）",
    "三成分独立": "λ、S² 角度、t 是三个独立参数，无耦合（无 twist）",
    "乘积（trivial 丛，非纤维丛）": "独立参数 → 乘积 ℝ⁺×S²×ℝ；纤维丛需要 twist（transition functions 非平凡），框架三成分独立无 twist",
}

# ---- 总结论：为什么是 3+1D ----
R["conclusion"] = {
    "3D 空间": "径向 1D（观察者态谱）+ 角向 2D（断裂 S²=SU(2)/U(1)）= 3D",
    "1D 时间": "模流 1 参数群",
    "3+1D": "（1+2）空间 + 1 时间 = 3+1D",
    "为什么 3 维": "观察者态 1 标量（径向 1D）+ 断裂 SU(2)（内部三维）商 U(1) 得 S²（2D）= 1+2=3——「物理空间三维」从「内部三维 SU(2)」+「观察者态 1D」推出",
    "为什么乘积": "三成分独立（无 twist）→ 乘积（trivial 丛），不是纤维丛",
    "诚实边界": "「为什么 SU(2) 是 3D」= π 磁通反对易给内部三维（框架已推）；「为什么观察者态是 1 标量」= 框架公设；「为什么三成分独立」= 结构性（径向/角向/时间 来自 D 的不同部分）。这三个「为什么」的答案都是「框架结构 + 标准数学」，不是新卡点，但「乘积 vs 纤维丛」的严格论证（独立性 ⟹ 无 twist）仍需形式化",
}

report(R, "exp_why_3p1d")
