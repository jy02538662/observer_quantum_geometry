"""
继续推：掺杂 μ ↔ 观察者截断 λ_c 的精确对应（「Tc 完全内生」的最后一步）

已坐实（前一个脚本）：T_BKT = μ/32，只依赖相位刚度 J_s ∝ μ（几何），不依赖 V_eff（物质）。

本脚本试「μ = f(λ_c)」的候选，看「掺杂」能否从「观察者态 ρ = C/λ」内生：
  关键量纲：μ 是「能量」（费米能级），λ_c 是「无量纲截断比」——需要「能标 Λ」桥接。
  一元论：掺杂 = 偏离无偏好 = 观察者有限性；μ→0（无掺杂）↔ λ_c→∞（无偏好/全知）。

候选 f：
  A. μ = Λ/λ_c（费米能级 = 能标/观察者截断，最自然：μ→0 ↔ λ_c→∞）
  B. μ = Λ·λ_min（费米能级 = 能标×红外截断，λ_min = π²/N²）
  C. μ = Λ(λ_c − λ_min)（费米能级 = 能标×截断差）
"""
import numpy as np
from sympy import symbols, pi, sqrt, simplify, Rational
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 量纲桥：μ（能量）↔ λ_c（无量纲），需能标 Λ
# ---------------------------------------------------------------------------
Lambda, lambda_c, lambda_min = symbols("Lambda lambda_c lambda_min", positive=True)

R["dimension_bridge"] = {
    "μ 的量纲": "能量（费米能级）",
    "λ_c 的量纲": "无量纲（D²/Λ² 的截断比）",
    "桥": "μ = Λ · f(λ_c)，Λ = 能标（谱作用量能标 / 超导能带宽度 ~ eV）",
    "一元论": "掺杂 μ/Λ = 填充比例 ↔ 观察者有限性 1/λ_c",
}

# ---------------------------------------------------------------------------
# 候选 A：μ = Λ/λ_c（最自然：μ→0 ↔ λ_c→∞ 都是「无偏好」）
# ---------------------------------------------------------------------------
# 相位刚度 J_s = μ/16π（2D Dirac 掺杂），代入 μ = Λ/λ_c
mu_A = Lambda / lambda_c
J_s_A = mu_A / (16 * pi)
T_BKT_A = (pi / 2) * J_s_A

R["candidate_A"] = {
    "μ = Λ/λ_c": "费米能级 = 能标/观察者截断（μ→0 ↔ λ_c→∞ 无偏好）",
    "J_s = μ/16π = Λ/(16πλ_c)": str(simplify(J_s_A)),
    "T_BKT = μ/32 = Λ/(32λ_c)": str(simplify(T_BKT_A)),
    "物理含义": "Tc ∝ 1/λ_c —— 观察者越有限（λ_c 越小/分辨率越低），Tc 越高",
}

# ---------------------------------------------------------------------------
# 候选 B：μ = Λ·λ_min（费米能级 = 能标×红外截断）
# ---------------------------------------------------------------------------
mu_B = Lambda * lambda_min
J_s_B = mu_B / (16 * pi)
T_BKT_B = (pi / 2) * J_s_B

R["candidate_B"] = {
    "μ = Λ·λ_min": "费米能级 = 能标×红外截断（λ_min = π²/N² 量子化尺度破缺）",
    "T_BKT = μ/32 = Λ·λ_min/32": str(simplify(T_BKT_B)),
    "物理含义": "Tc ∝ λ_min = π²/N² —— Tc 由「量子化尺度破缺」决定，N 是观察者自由度（2⁷=128）",
}

# ---------------------------------------------------------------------------
# 候选 C：μ = Λ(λ_c − λ_min)（费米能级 = 能标×截断差）
# ---------------------------------------------------------------------------
mu_C = Lambda * (lambda_c - lambda_min)
J_s_C = mu_C / (16 * pi)
T_BKT_C = (pi / 2) * J_s_C

R["candidate_C"] = {
    "μ = Λ(λ_c − λ_min)": "费米能级 = 能标×截断差（紫外-红外截断差）",
    "T_BKT = μ/32 = Λ(λ_c−λ_min)/32": str(simplify(T_BKT_C)),
    "物理含义": "Tc ∝ (λ_c − λ_min) —— 呼应宇宙学常数 ρ_Λ ∝ (λ_c − λ_min)Λ⁴ 的「截断差」结构",
}

# ---------------------------------------------------------------------------
# 数值检验：哪个候选给「现实 Tc 量级」？
# ---------------------------------------------------------------------------
# 超导能带宽度 Λ ~ 1 eV（Dirac 能标），室温 300 K ≈ 25.8 meV
# 检验：候选 A（Tc = Λ/32λ_c），λ_c = 2（框架值）→ Tc = 1 eV/(32×2) = 15.6 meV ≈ 181 K
Tc_A_num = 1.0 / (32 * 2.0)   # Λ=1 eV, λ_c=2
R["numerical_check"] = {
    "候选 A：Tc = Λ/(32λ_c) = 1eV/(32×2)": f"{Tc_A_num*1e3:.1f} meV ≈ {Tc_A_num*1e3/0.0862:.0f} K",
    "对照：室温 300 K ≈ 25.8 meV": "候选 A 给 ~181 K，在「高温超导」量级（铜氧化物 ~100 K 族），不是室温",
    "候选 B：Tc = Λλ_min/32，λ_min=π²/N²": f"{1.0*(pi**2/128**2)/32*1e3:.4f} meV（N=128 时极低，不现实）",
    "候选 C：Tc = Λ(λ_c−λ_min)/32 ≈ Λλ_c/32": "与候选 A 同量级（λ_min≪λ_c）",
}

# ---------------------------------------------------------------------------
# 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "候选 A 最自然": "μ = Λ/λ_c 给「μ→0 ↔ λ_c→∞ 无偏好」的正确方向，且 Tc = Λ/(32λ_c) ≈ 181 K（高温超导量级）——但这是「候选」不是「坐实」",
    "关键缺口": "「μ = f(λ_c)」的精确 f 还没从「观察者态 ρ = C/λ」推导出来——目前是「一元论对应」（掺杂=观察者偏好）的「候选」，不是「从公设推导」",
    "能坐实的": "Tc ∝ 关联刚度（相位刚度 J_s）∝ 观察者有限性（1/λ_c 或 λ_min 或 λ_c−λ_min）——「Tc 从几何内生」的方向对，但「精确函数」待定",
    "边界（不变）": "① 2D 特有（BKT）；② 候选 A 给 ~181 K（高温超导），不给室温 300 K——「室温」还需别的机制（或 λ_c 更小/掺杂更强）",
    "措辞（三档）": "「Tc ∝ 观察者有限性」=【方向坐实】；「μ = Λ/λ_c」=【候选，未从公设推导】；「精确 f(λ_c)」=【待推导，留活口】",
}

report(R, "exp_superconducting_tc_mu_lambdac")
