"""
远景线 5（质量谱）· 攻「第一→第二代 = 29.2」的机制（转置/反射的颜色修正）

已知：第二→第三代 上型/下型 = 3.03（颜色单态投影，3-循环）。
缺口：第一→第二代 上型/下型 = 29.17（转置/反射，机制未知）。

本脚本探索「29.17」的候选结构，诚实标注「干净候选 vs 凑数字」。
红线：质量比是「凑数字」高发区，先看有没有干净候选，没有就诚实说。
"""
import numpy as np
from experiments._common import report

R = {}

# 精确数据（PDG MS̄）
m_c, m_u = 1273, 2.16      # MeV
m_s, m_d = 93.4, 4.67      # MeV
up12 = m_c / m_u           # m_c/m_u = 589
dn12 = m_s / m_d           # m_s/m_d = 20.0
ratio12 = up12 / dn12      # 上型/下型 第一→第二

R["data"] = {
    "上型 m_c/m_u": up12,
    "下型 m_s/m_d": dn12,
    "上型/下型（第一→第二）": ratio12,
}

# 候选结构
candidates = {
    "3³ = 27": 27,
    "3π² = 29.6": 3 * np.pi**2,
    "27+2 = 29": 29,
    "2π²+10 = 29.7": 2*np.pi**2 + 10,
    "3²·π = 28.27": 9 * np.pi,
    "e³ = 20.1": np.exp(3),
    "2⁵ = 32": 32,
}

R["candidates"] = {
    name: {
        "值": val,
        "误差": f"{abs(ratio12 - val)/ratio12*100:.1f}%"
    }
    for name, val in candidates.items()
}

# 关键：第一→第二代涉及「转置（反射，阶2）」，第二→第三代涉及「3-循环（旋转，阶3）」
# 转置的迹 = 1（反射保持 1 色），3-循环的迹 = 0（1+ω+ω²=0）
# 单位（阶1）的迹 = 3
R["group_theory"] = {
    "单位（阶1）迹": 3,
    "转置（阶2，反射）迹": 1,
    "3-循环（阶3，旋转）迹": 0,
    "第一→第二（单位→转置）": "迹 3 → 1（反射，保持 1 色）",
    "第二→第三（转置→3-循环）": "迹 1 → 0（旋转，全循环）",
    "线索": "转置（反射）保持 1 色（迹 1），3-循环（旋转）保持 0 色（迹 0）——第一→第二的「保持」是 1（不是 3），可能给不同的因子",
}

# 诚实结论
R["honest_conclusion"] = {
    "候选结构": "29.17 无干净候选——3³=27 差 8%、3π²=29.6 差 1.5%，都不干净",
    "红线判断": "「29.17」是「凑数字」高发区，没有干净的简单候选（3³、3π² 都差 1.5-8%），不应硬凑",
    "可能原因": "① 轻夸克（m_u, m_d, m_s）跑动误差大（~10%），29.17 本身误差大；② 第一→第二代涉及「转置（反射）」的修正，机制比「3-循环（单态投影）」复杂，可能不是单一因子",
    "诚实定位": "「第一→第二代 = 29.2」的机制未推出，且无干净候选（避免凑数字，守红线）——需要更精确的轻夸克数据或新的机制直觉",
}

report(R, "exp_first_second_generation")
