"""
远景线 5（质量谱）· 探「螺旋面积 + 1/2 自旋」能否给 N

用户直觉：N 跟「螺旋的面积」有关，具体是 1/2 自旋。

自旋 1/2 的「螺旋」= 旋量转 2π 反号、转 4π 回 +1 = SU(2)≅S³ 的 Hopf 纤维。
它的「面积」自然候选：
  - S² 面积 = 4π（单位球）
  - S³ 体积 = 2π²（单位三球）
  - Hopf 纤维 S¹ 周长 = 2π
  - 旋量转 4π 的 Berry 相位 = 2π（自旋 1/2 绕一圈 π，转 4π 得 2π）

本脚本算这些几何量，看它们（或它们的组合）能不能自然给 N=128 量级，
还是都是 O(1)。不预设 207，只看「1/2 自旋的螺旋面积」本身给什么。
"""
import numpy as np
from experiments._common import report

R = {}

# 自旋 1/2 旋量结构的几何量（单位半径）
candidates = {
    "S² 面积 4π": 4 * np.pi,
    "S³ 体积 2π²": 2 * np.pi**2,
    "Hopf 纤维 S¹ 周长 2π": 2 * np.pi,
    "自旋 1/2 转 2π 相位 π": np.pi,
    "自旋 1/2 转 4π 相位 2π": 2 * np.pi,
    "S³ 体积 / S¹ 周长 = π": np.pi,
}

R["spin_1_2_spiral_area"] = {
    k: round(float(v), 4) for k, v in candidates.items()
}

# 这些面积和 128 的关系
R["relation_to_128"] = {}
for k, v in candidates.items():
    R["relation_to_128"][k] = {
        "值": round(float(v), 4),
        "128/值": round(128 / float(v), 3),
        "值是否 O(1)": float(v) < 30,
    }

# 检查：有没有「螺旋面积」的自然组合给 128？
# 128 = 4π × 10.19（不干净）；128 = 2π² × 6.48（不干净）；128 = 2^7
# 螺旋面积都是 O(1)（4π≈12.6, 2π²≈19.7），要得到 128 需要「绕圈数」，但那是输入
R["natural_combinations"] = {
    "4π（S²面积）": round(4*np.pi, 3),
    "2π²（S³体积）": round(2*np.pi**2, 3),
    "2^7（旧 N）": 128,
    "128/(4π)": round(128/(4*np.pi), 3),
    "128/(2π²)": round(128/(2*np.pi**2), 3),
    "判断": "螺旋面积都是 O(1)（12.6/19.7），要给 128 需「绕 ~10 圈」或「面积 128 的螺旋」——但「绕几圈」是输入，不是螺旋面积自带的",
}

R["honest_conclusion"] = {
    "探索结果": "自旋 1/2 的「螺旋面积」候选（S²面积 4π、S³体积 2π²、S¹周长 2π、Berry 相位 π/2π）都是 O(1)（12.6/19.7/6.28/3.14/6.28），不是 128 量级",
    "要给 128 的代价": "需要「绕 ~10 圈」或「面积=128 的螺旋」，但「绕圈数」是输入，不是螺旋面积自带的",
    "诚实判断": "「螺旋面积」本身给 O(1) 的几何量，不产生 N=128。除非有一个框架结构说「螺旋绕多少圈」，而那个「圈数」正是 N 本身——循环",
    "措辞": "这是「螺旋面积给 O(1)、不自然给 128」的探索负结果；但若用户心中「螺旋面积」指别的对象，需澄清",
}

report(R, "exp_spiral_area")
