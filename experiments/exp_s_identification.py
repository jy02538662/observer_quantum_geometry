"""
远景线 5（质量谱）· 族维度第五刀：s 的识别（s = 超荷？电荷共轭？尺度对偶？代？）

用户直觉：s = 超荷，第二个 3 = 颜色 × 超荷的生成元。
做法：写出三个 Z₂ 在 H_F 上的显式矩阵，检查 s 的对角元是否 ∝ 超荷 Y。

本脚本构造 H_F 一代基（15 维）+ 超荷 Y，检查：
  (1) 超荷 Y 的 Z₂ 指数化 s = e^{3πi·Y}（因为 3Y 是整数）的对角元；
  (2) 这个 s 是否 ∝ 手征 Γ（关键：标准模型「3Y 奇偶 = 手征」结构）；
  (3) s = 超荷 与 s = 尺度对偶（λ↔1/λ，独立于 Γ）的张力。
"""
import numpy as np
from fractions import Fraction
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (1) H_F 一代基（15 维，不含右手中微子）+ 超荷 Y + 手征
# ---------------------------------------------------------------------------
# 基顺序（1.12）：ν_L, e_L, e_R, u_L(r,g,b), d_L(r,g,b), u_R(r,g,b), d_R(r,g,b)
fermions = [
    ("ν_L",  "左", Fraction(-1,1)),     # Y=-1
    ("e_L",  "左", Fraction(-1,1)),     # Y=-1
    ("e_R",  "右", Fraction(-2,1)),     # Y=-2
    ("u_L_r","左", Fraction(1,3)),      # Y=+1/3
    ("u_L_g","左", Fraction(1,3)),
    ("u_L_b","左", Fraction(1,3)),
    ("d_L_r","左", Fraction(1,3)),
    ("d_L_g","左", Fraction(1,3)),
    ("d_L_b","左", Fraction(1,3)),
    ("u_R_r","右", Fraction(4,3)),      # Y=+4/3
    ("u_R_g","右", Fraction(4,3)),
    ("u_R_b","右", Fraction(4,3)),
    ("d_R_r","右", Fraction(-2,3)),     # Y=-2/3
    ("d_R_g","右", Fraction(-2,3)),
    ("d_R_b","右", Fraction(-2,3)),
]

Y = np.array([float(f[2]) for f in fermions])
chirality = np.array([1.0 if f[1]=="左" else -1.0 for f in fermions])  # 左手 +1, 右手 -1

R["HF_basis"] = {
    "一代 15 维基": [f"{f[0]}(Y={f[2]},{f[1]})" for f in fermions],
    "超荷 Y": [str(Fraction(y).limit_denominator()) for y in Y],
    "手征（左+1/右-1）": chirality.tolist(),
}

# ---------------------------------------------------------------------------
# (2) s = e^{3πi·Y}（超荷的 3 倍相位，Z₂ 指数化）
# ---------------------------------------------------------------------------
# 3Y 是整数（因为 Y ∈ {-1,-2,+1/3,+4/3,-2/3}，×3 都是整数）
three_Y = 3 * Y
s_diag = np.exp(3j * np.pi * Y)   # = (-1)^{3Y}
R["s_hypercharge_exponentiation"] = {
    "3Y（×3 后为整数）": [int(v) for v in three_Y],
    "s = e^{3πi·Y} 的对角元（=(-1)^{3Y}）": [complex(v).real for v in s_diag],
    "3Y 奇偶": ["奇" if int(v) % 2 else "偶" for v in three_Y],
    "关键发现": "3Y 的奇偶 = 手征：左手（ν_L,e_L,u_L,d_L）3Y 奇，右手（e_R,u_R,d_R）3Y 偶",
}

# ---------------------------------------------------------------------------
# (3) 验证 s = e^{3πi·Y} = -Γ（超荷的 3 倍相位 = 负手征）
# ---------------------------------------------------------------------------
# Γ（手征）= 左手 +1, 右手 -1
Gamma = chirality  # +1 左, -1 右
s_real = np.real(s_diag)  # (-1)^{3Y}
R["s_equals_minus_Gamma"] = {
    "s = e^{3πi·Y} 的实部": s_real.tolist(),
    "-Γ（负手征，-1 左 +1 右）": (-Gamma).tolist(),
    "s = -Γ 是否成立": bool(np.allclose(s_real, -Gamma)),
    "意义": "超荷 Y 的 3 倍相位 = 负手征——「3Y 奇偶 = 手征」是标准模型的量子数结构（反常消除的体现）",
}

# ---------------------------------------------------------------------------
# (4) 关键张力：s = 超荷（=手征） vs s = 尺度对偶（独立于 Γ）
# ---------------------------------------------------------------------------
R["tension"] = {
    "s = 超荷（e^{3πi·Y}）": "= -Γ（手征），对角元 ∝ (-1)^{3Y}，保持谱（共轭）",
    "s = 尺度对偶（λ↔1/λ）": "改变谱（λ→1/λ），严格独立于 Γ,K（exp_third_Z2_strict 坐实）",
    "张力": "「s=超荷」给出 s=-Γ（手征，不独立）；「s=尺度对偶」要求 s 独立于 Γ——两个 s 不同",
    "判据": "若 s 对角元 ∝ Y 且是 Z₂，则 s=(-1)^{3Y}=-Γ（手征），不是独立的第三个 Z₂",
}

# ---------------------------------------------------------------------------
# (5) 但注意：超荷 Y 的「3 倍奇偶」结构本身是重要发现
# ---------------------------------------------------------------------------
R["hypercharge_chirality_color"] = {
    "三角关系": "超荷 Y（分数）→ ×3（颜色 3 重态）→ 3Y 整数 → 3Y 奇偶 = 手征 Γ",
    "颜色 3 的桥梁作用": "3Y ∈ 整数 是因为颜色是 3 重态（Y 的分数 1/3, 4/3, 2/3 的分母是 3）",
    "结构": "超荷 ↔ 手征 ↔ 颜色 3 三者通过「3Y 奇偶」联系——这是「颜色三和代三是同一 S₃ 两面」之外的另一条三角",
    "候选意义": "「s = 超荷」若理解为「超荷的 Z₂ 结构」，则 s = 手征 Γ（3Y 奇偶），与「s = 尺度对偶」是不同层面的 Z₂",
}

# ---------------------------------------------------------------------------
# (6) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实（精确）": "① 3Y 是整数（颜色 3 重态）；② s=e^{3πi·Y}=(-1)^{3Y} 是 Z₂；③ (-1)^{3Y} = 手征（3Y 奇偶 = 手征，精确成立）",
    "关键发现": "「超荷的 3 倍相位 = 手征」（s=e^{3πi·Y} = -Γ）——这是标准模型「3Y 奇偶 = 手征」量子数结构的精确数学形式",
    "张力（诚实）": "用户直觉「s=超荷」若取「s=e^{3πi·Y}」则 s=-Γ（手征，不独立于 Γ），与「三个 Z₂ 的 s=尺度对偶（独立）」矛盾——两个 s 是不同层面的 Z₂",
    "可能出路": "「s=超荷」可能不是「第三个 Z₂」，而是「超荷 Y 和手征 Γ 的同一性」（3Y 奇偶=手征）——这是「颜色 3 × 超荷 × 手征」的三角结构，可能是「族维度」的真正载体（而非「尺度对偶」）",
    "下一刀候选": "「超荷 ↔ 手征 ↔ 颜色 3」三角（3Y 奇偶=手征）能否给出「上型×3 vs 下型×1」——上型(u_R,Y=+4/3,3Y偶=右) vs 下型(d_R,Y=-2/3,3Y偶=右) 都是右手，需更细区分",
    "措辞": "符号坐实 + 张力暴露（非「已坐实 s=超荷」）——「3Y 奇偶=手征」坐实，「s=超荷 vs s=尺度对偶」的识别待定",
}

report(R, "exp_s_identification")
