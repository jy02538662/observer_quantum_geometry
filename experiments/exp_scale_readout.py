"""
尺度读出与宇宙学预言 · 第一刀：判定「m/G/g 的绝对值是标定还是推导」（2026-09-27 修正矩对应）

核心问题：物理质量 m（交错质量能隙）的「物理值（有单位）」从哪来？
符号推导 G、g、m 对谱作用量 (f 矩, Λ) 的依赖，判定：
  (A) 尺度不变（公理 3）是否 ⟹ 绝对尺度 Λ 自由 ⟹ 绝对耦合是标定输入；
  (B) 无量纲比值（f 矩比值）是否是唯一有预言力的出口。

⚠️ 修正（2026-09-27）：矩的物理对应（标准 Chamseddine-Connes）：
  - 宇宙学常数（a₀ 阶，Λ⁴）：f₀ = ∫ f(u) u du
  - 引力常数  （a₂ 阶，Λ²）：f₂ = ∫ f(u) du
  - 规范耦合  （a₄ 阶，Λ⁰）：f₄ = f(0)
旧代码把「∫ f u du（宇宙学常数系数）」误当规范耦合系数 f₄ 用进 g²=6π²/f₄。
"""
from sympy import symbols, pi, integrate, exp, oo, sqrt, simplify
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. 谱作用量耦合常数匹配（符号精确，修正矩对应）
# ---------------------------------------------------------------------------
f2, f4, L = symbols("f2 f4 Lambda", positive=True)  # f2=引力矩(∫f du), f4=规范矩(f(0))
G, g = symbols("G g", positive=True)

# 8πG 匹配：f2*Λ^2 * a2 = (1/16πG)∫R,  a2 = -R/(48π^2) (4D Dirac)
G_expr = 3 * pi / (f2 * L**2)
# YM 匹配：a4 ⊃ -(1/24π^2)∫tr F^2,  f4/(24π^2) = 1/(4g^2)  ->  g^2 = 6π^2/f4
#   其中 f4 = f(0)（a₄ 阶系数），非 ∫ f u du（那是宇宙学常数系数 f₀）
g2_expr = 6 * pi**2 / f4

R["coupling_matching"] = {
    "G": str(G_expr),
    "g_squared": str(g2_expr),
    "宇宙学常数 ρ_Λ = f0·Λ⁴（f0=∫f u du）": "单独列出（旧代码漏了这项）",
    "note": "G 和 g² 由 (Λ, f 矩) 决定；f₀=∫f·u du（宇宙学常数）、f₂=∫f du（引力）、f₄=f(0)（规范）",
}

# ---------------------------------------------------------------------------
# 2. 尺度不变（公理 3）⟹ 绝对尺度 Λ 自由（符号坐实）
# ---------------------------------------------------------------------------
R["scale_invariance_Lambda_free"] = {
    "claim": "S(cD) = S_{Λ/c}(D)：D->cD 等价于 Λ->Λ/c",
    "meaning": "尺度不变 ⟹ Λ 绝对值自由 ⟹ G=3π/(f2Λ²)、g²=6π²/f4 的绝对值都是标定输入",
    "status": "结构性结论（非「未做」）",
}

# ---------------------------------------------------------------------------
# 3. f 矩比值依赖 f 的形式（坐实「非框架逼出纯数」）
# ---------------------------------------------------------------------------
# 矩（正确）：f0(宇宙学常数)=∫f(u)u du, f2(引力)=∫f(u)du, f4(规范)=f(0)
u = symbols("u", positive=True)

def f0_of(f_expr):   # 宇宙学常数系数
    return simplify(integrate(f_expr * u**1, (u, 0, oo)))
def f2_of(f_expr):   # 引力系数
    return simplify(integrate(f_expr * u**0, (u, 0, oo)))

f_exp = exp(-u)
f_gauss = exp(-u**2)

R["f_moments_depend_on_f"] = {
    "宇宙学常数/引力 f0/f2，f=e^{-u}": str(simplify(f0_of(f_exp)/f2_of(f_exp))),
    "宇宙学常数/引力 f0/f2，f=e^{-u²}": str(simplify(f0_of(f_gauss)/f2_of(f_gauss))),
    "conclusion": "宇宙学常数/引力比值 f0/f2 依赖 f 的具体形式，非框架逼出的纯数 ⟹ 除非框架确定 f，否则无预言",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "第一刀答案": "尺度读出 = 标定（结构性），不是推导",
    "理由": "公理 3（ρ=C/λ 尺度不变 = 无外部观察者 = 无绝对尺度）⟹ Λ 绝对值自由 ⟹ m/G/g 的绝对值都是标定输入（与标准模型质量参数同为标定输入，非框架缺陷）",
    "修正": "宇宙学常数系数 = ∫f·u du（=λ_c−λ_min，O(1)），非旧代码 ∫f·u⁻¹ du（=1/λ_min，红外发散）；规范耦合 f₄=f(0)=0 是硬截断伪影（新问题）。",
    "剩余唯一出口": "无量纲比值 f 矩比值（不受尺度不变影响）；但比值依赖 f 的形式，需「确定 f」的机制（f=E 已内生，见 exp_f_observer）",
    "下一刀": "规范耦合 f(0)=0 的软截断处理 + N 的唯一值（λ_min↔λ_c 关系）",
}

report(R, "exp_scale_readout")
