"""
远景线 5（质量谱）· 族维度探测（攻族维度第一刀）

问题：把轻子的 λ_c 模流频率机制（N=2⁷=128 → λ_c → e^{λ_c}=207）推广到夸克族，
看「颜色 SU(3)（= 两个 Z₂ 的自同构 S₃，基本表示 3）」如何修正代际比，解释
夸克的质量分层（577/136 上型、19.8/44.9 下型）。

本脚本做系统探测（非拟合，找结构信号）：
  1. 精确数据 + S₃ 结构量对照（阶/类大小/特征标/Casimir）；
  2. 核心结构检验：上型第二→第三 vs 3 × 下型第二→第三（手动发现的候选命中）；
  3. 反解「等效 N」：把每个代际比当 e^{λ_c(N)} 反解 N，看是否有 S₃/颜色结构；
  4. 上下型质量比（同代）的「翻转」结构（m_u<m_d 但 m_c>m_s, m_t>m_b）；
  5. 候选机制测试（特征标 χ 耦合、Casimir、类大小 |C|）。
"""
import numpy as np
from scipy.optimize import brentq
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 0. 数据（CODATA 2022 / PDG，MS̄ 跑动质量）
# ---------------------------------------------------------------------------
masses = {
    "上型": {"u": 2.2e-3, "c": 1.27, "t": 173.0},   # GeV（m_t 用 pole~173）
    "下型": {"d": 4.7e-3, "s": 0.093, "b": 4.18},   # GeV
    "轻子": {"e": 0.511e-3, "mu": 0.10566, "tau": 1.77686},
}

def ratios(d):
    r12 = d[1] / d[0]
    r23 = d[2] / d[1]
    return r12, r23

up = list(masses["上型"].values())
dn = list(masses["下型"].values())
le = list(masses["轻子"].values())

up12, up23 = ratios(up)   # m_c/m_u, m_t/m_c
dn12, dn23 = ratios(dn)   # m_s/m_d, m_b/m_s
le12, le23 = ratios(le)   # m_mu/m_e, m_tau/m_mu

R["data"] = {
    "轻子": {"m_mu/m_e": le12, "m_tau/m_mu": le23, "m_tau/m_e": le12*le23},
    "上型": {"m_c/m_u": up12, "m_t/m_c": up23, "m_t/m_u": up12*up23},
    "下型": {"m_s/m_d": dn12, "m_b/m_s": dn23, "m_b/m_d": dn12*dn23},
}

# ---------------------------------------------------------------------------
# 1. 核心结构检验：上型第二→第三 = 3 × 下型第二→第三？
# ---------------------------------------------------------------------------
ratio_23 = up23 / dn23   # m_t/m_c ÷ m_b/m_s
R["core_structure_23"] = {
    "上型 m_t/m_c": up23,
    "下型 m_b/m_s": dn23,
    "比值 (m_t/m_c)/(m_b/m_s)": ratio_23,
    "对比 3": f"差 {abs(ratio_23-3)/3*100:.2f}%",
    "等价形式": "(m_t/m_b)/(m_c/m_s) 应同值（同一事实的两面）",
}

ratio_updn_tb = (up[2]/dn[2]) / (up[1]/dn[1])  # (m_t/m_b)/(m_c/m_s)
R["core_structure_23_equiv"] = {
    "(m_t/m_b)/(m_c/m_s)": ratio_updn_tb,
    "应等于 (m_t/m_c)/(m_b/m_s)": ratio_23,
    "一致性": f"差 {abs(ratio_updn_tb-ratio_23)/ratio_23*100:.4f}%",
}

# 第一→第二代际比是否也有「3 的幂」结构
ratio_12 = up12 / dn12   # m_c/m_u ÷ m_s/m_d
R["core_structure_12"] = {
    "上型 m_c/m_u": up12,
    "下型 m_s/m_d": dn12,
    "比值 (m_c/m_u)/(m_s/m_d)": ratio_12,
    "对比 3": f"差 {abs(ratio_12-3)/3*100:.2f}%",
    "对比 3^3=27": f"差 {abs(ratio_12-27)/27*100:.2f}%",
    "对比 3^4=81": f"差 {abs(ratio_12-81)/81*100:.2f}%",
    "ln 比值": float(np.log(ratio_12)),
    "ln 3": float(np.log(3)),
    "ln比值/ln3": float(np.log(ratio_12)/np.log(3)),
}

# ---------------------------------------------------------------------------
# 2. 反解「等效 N」：把每个代际比当 e^{λ_c(N)}，反解 N
# ---------------------------------------------------------------------------
def f_N(N):
    """λ_c 链条：e^{λ_c} = N²/(π² ln(2N²/π²))。"""
    return N**2 / (np.pi**2 * np.log(2 * N**2 / np.pi**2))

def invert_N(target, lo=2.0, hi=1e4):
    """反解 f(N) = target 的 N（f 单调递增）。"""
    return brentq(lambda N: f_N(N) - target, lo, hi)

lam_c_128 = np.log(f_N(128))
R["lambda_c_128"] = {"λ_c(128)": lam_c_128, "e^{λ_c}": np.exp(lam_c_128)}

R["invert_N"] = {
    "轻子 m_mu/m_e=206.77 → N": invert_N(le12),
    "上型 m_c/m_u=577 → N": invert_N(up12),
    "下型 m_s/m_d=19.8 → N": invert_N(dn12),
    "轻子 N=128（结构值）": 128,
}

# 也反解「第二→第三」代际比（注意轻子第二→第三是 2π e^{(2π-1)/λ_c}，不是纯 e^{λ_c}）
R["invert_N_23"] = {
    "上型 m_t/m_c=136 → N": invert_N(up23),
    "下型 m_b/m_s=44.9 → N": invert_N(dn23),
}

# ---------------------------------------------------------------------------
# 3. 上下型质量比（同代）的「翻转」结构
# ---------------------------------------------------------------------------
ud_ratio = [up[i]/dn[i] for i in range(3)]  # m_u/m_d, m_c/m_s, m_t/m_b
R["up_down_ratio"] = {
    "第一代 m_u/m_d": ud_ratio[0],
    "第二代 m_c/m_s": ud_ratio[1],
    "第三代 m_t/m_b": ud_ratio[2],
    "翻转判断": "第一代 m_u<m_d（0.47），第二三代 m_c>m_s, m_t>m_b（>1）",
    "比值 (m_t/m_b)/(m_c/m_s)": ud_ratio[2]/ud_ratio[1],
    "ln 序列": [float(np.log(x)) for x in ud_ratio],
    "ln 差 2→3 代": float(np.log(ud_ratio[2]/ud_ratio[1])),
}

# ---------------------------------------------------------------------------
# 4. S₃ 结构量（阶 / 类大小 / 特征标 / 类代数）
# ---------------------------------------------------------------------------
# 阶 (1,2,3)，类大小 (1,3,2)，特征标
chi = {
    "平凡 χ₁":   (1, 1, 1),
    "符号 χ₂":   (1, -1, 1),
    "标准 χ₃(2维)": (2, 0, -1),
    "基本3=1⊕2 χ_perm": (3, 1, 0),
}
orders = (1, 2, 3)
class_sizes = (1, 3, 2)

R["S3_structures"] = {
    "阶（代，轻子用）": orders,
    "类大小 |C|": class_sizes,
    "特征标表": chi,
    "类代数": "C2C2=3C1+3C3, C2C3=2C2, C3C3=2C1+C3",
    "su(3)基本表示 Casimir C2": 4/3,
}

# ---------------------------------------------------------------------------
# 5. 候选机制测试：质量比取 ln 后对照 S₃ 量
# ---------------------------------------------------------------------------
# 把「颜色修正」定义为夸克代际比 ln 与轻子 λ_c 的差
ln_up12 = np.log(up12); ln_dn12 = np.log(dn12)
ln_up23 = np.log(up23); ln_dn23 = np.log(dn23)
ln_le12 = np.log(le12); ln_le23 = np.log(le23)

R["ln_deltas"] = {
    "轻子 ln(m_mu/m_e)": ln_le12,
    "上型 ln(m_c/m_u)": ln_up12,
    "下型 ln(m_s/m_d)": ln_dn12,
    "上型-轻子 Δln(1→2)": ln_up12 - ln_le12,
    "下型-轻子 Δln(1→2)": ln_dn12 - ln_le12,
    "上型 ln(m_t/m_c)": ln_up23,
    "下型 ln(m_b/m_s)": ln_dn23,
    "上型-轻子 Δln(2→3)": ln_up23 - ln_le23,
    "下型-轻子 Δln(2→3)": ln_dn23 - ln_le23,
}

# 候选：颜色修正 ∝ 类大小 |C|（(1,3,2)）
# 第一→第二 Δln 对应 |C₂|-|C₁| = 3-1 = 2；第二→第三对应 |C₃|-|C₂| = 2-3 = -1
R["candidate_class_size"] = {
    "|C| 差（1→2）": class_sizes[1]-class_sizes[0],
    "|C| 差（2→3）": class_sizes[2]-class_sizes[1],
    "观察 Δln(1→2) 上型/下型": (ln_up12-ln_le12, ln_dn12-ln_le12),
    "观察 Δln(2→3) 上型/下型": (ln_up23-ln_le23, ln_dn23-ln_le23),
}

# 候选：颜色修正 ∝ 特征标 χ_perm（基本3=(3,1,0)）
# 1→2: χ(C₂)-χ(C₁)=1-3=-2；2→3: χ(C₃)-χ(C₂)=0-1=-1
R["candidate_chi_perm"] = {
    "χ_perm 差（1→2）": chi["基本3=1⊕2 χ_perm"][1]-chi["基本3=1⊕2 χ_perm"][0],
    "χ_perm 差（2→3）": chi["基本3=1⊕2 χ_perm"][2]-chi["基本3=1⊕2 χ_perm"][1],
    "标准χ₃ 差（1→2）": chi["标准 χ₃(2维)"][1]-chi["标准 χ₃(2维)"][0],
    "标准χ₃ 差（2→3）": chi["标准 χ₃(2维)"][2]-chi["标准 χ₃(2维)"][1],
}

# ---------------------------------------------------------------------------
# 6. 诚实结论（探测阶段，不下定论）
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "核心命中（手动发现，待验证）": "上型第二→第三 = 3 × 下型第二→第三（(m_t/m_c)/(m_b/m_s)≈3.03），且等价地 (m_t/m_b)/(m_c/m_s)≈3.01——「3」= 颜色基本表示 3 = 代三阶 3",
    "第一→第二无 3 结构": f"(m_c/m_u)/(m_s/m_d)={ratio_12:.2f}，非 3（也非 3^k 干净值）",
    "上下型翻转": f"第一代 m_u/m_d={ud_ratio[0]:.2f}<1，第二三代 >1——标准模型著名结构",
    "探测状态": "这是「探测」，不是「推导」——找结构信号，不拟合（守红线）",
    "措辞": "探测（找结构信号），非「已推导族维度」",
}

report(R, "exp_quark_family_probe")
