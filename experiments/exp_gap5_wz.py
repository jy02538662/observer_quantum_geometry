"""
v11 缺口 5 · w(z) 框架独立推出：尝试 + 诚实边界

现状：w_Λ = -(1/3)(1 + 2√Ω_Λ/c) 是 HDE（Li 2004）标准结果，框架只逼出 c。
目标：不从 HDE 独立推出 w(z)。

尝试三条路径，看框架能独立推到哪：
  A. 框架静态 ρ_Λ = 2M_P^4/S（N_ext 常数）→ 什么 w？
  B. 框架「面积律」ρ_Λ ∝ R^{-2}，若视界 R ∝ a（粒子/哈勃视界粗化）→ 什么 w？
  C. HDE「未来事件视界」R_h → phantom w<−1（标准结果，非框架独立）

w 的一般式（能量守恒 dρ/da = −3(ρ+p)/a）：
  w = −1 − (1/3) d ln ρ / d ln a
"""
import numpy as np
from experiments._common import report

R = {}

# w 的一般式：给定 ρ ∝ a^α，w = -1 - α/3
def w_from_scaling(alpha):
    return -1 - alpha/3

R["scaling_w"] = {
    "宇宙学常数 ρ∝a^0": f"w = {w_from_scaling(0):.2f}",
    "面积律+视界∝a（ρ∝a^-2）": f"w = {w_from_scaling(-2):.2f}",
    "物质 ρ∝a^-3": f"w = {w_from_scaling(-3):.2f}",
    "辐射 ρ∝a^-4": f"w = {w_from_scaling(-4):.3f}",
}

# A. 框架静态 ρ_Λ = 2M_P^4/S，S = N_ext^4（N_ext 常数，观察者不随宇宙膨胀变）
R["path_A_static"] = {
    "框架 ρ_Λ = 2M_P^4/S": "S = N_ext^4，N_ext 是观察者外部自由度（常数）",
    "⟹ ρ_Λ 常数": "w = -1（纯宇宙学常数），无 w(z) 演化",
    "结论": "框架静态 ρ_Λ 给 w=-1，不是 HDE 的 w(z)≠-1",
}

# B. 面积律 + 视界 R ∝ a（粒子/哈勃视界粗化）
R["path_B_area_law"] = {
    "框架 ρ_Λ = 2M_P²/R²": "面积律结构（层级问题解决 + 理由 B 独立推出）",
    "若 R ∝ a（视界随膨胀）": "ρ_Λ ∝ a^-2 ⟹ w = -1/3（曲率型，非 phantom）",
    "结论": "「面积律」是框架独立推出的结构，但「R∝a」给 w=-1/3，不对",
}

# C. HDE 未来事件视界
c = np.sqrt(2/3)
Omega0 = 0.7
w_HDE = -(1/3) * (1 + 2*np.sqrt(Omega0)/c)
R["path_C_HDE"] = {
    "HDE 用未来事件视界 R_h = a∫_t^∞ dt'/a'": "视界随膨胀的特殊演化（加速时 R_h 增长比 a 慢）",
    "⟹ ρ_Λ 随 a 增长 ⟹ w < -1（phantom）": f"w(Ω=0.7) = {w_HDE:.4f}",
    "phantom 条件": f"w<-1 ⟺ c < √Ω_Λ ≈ {np.sqrt(Omega0):.3f}，框架 c=√(2/3)={c:.4f} < √Ω_Λ ✓",
}

R["honest_conclusion"] = {
    "框架独立推到的": "① ρ_Λ = 2M_P²/R²（面积律，从层级问题解决 + 理由 B 独立推出，非借 HDE）；② c = √(2/3) < √Ω_Λ ≈ 0.837 ⟹ phantom 方向。",
    "框架没推到的": "「R 是未来事件视界」——这是 HDE 的核心假设（phantom 的来源），框架没有「未来事件视界」概念（框架 R 是静态宇宙尺度/观察者视界）。",
    "缺口 5 的诚实答案": "推不动。框架静态 ρ_Λ 给 w=-1（宇宙学常数），w(z)≠-1 的演化依赖「视界随膨胀演化」，而「未来事件视界」是 HDE 的输入，框架未独立推出。w(z) 函数形式仍是 HDE 标准结果，框架贡献 = 面积律结构 + c 值（逼出）+ phantom 方向（c<√Ω_Λ）。",
    "唯一可能的出路": "框架若能推出「观察者视界 = 未来事件视界」（观察者能影响的未来最远 = 因果未来边界），才能独立推出 w(z)——这是「互联=因果」线（[[互联=因果：把墙精确到保因果自同构]]）的宇宙学延伸，未做。",
    "措辞": "三档「未证实」——缺口 5 推不动（默认档，待新直觉：观察者视界=未来事件视界的识别），非「否证」。" ,
}

report(R, "exp_gap5_wz")
