"""
质量谱动力学 · B'：拓扑绕数 = 代（S₃ 阶）？（观察者视角：点/云两面）

核心洞察（用户）：「问题的答案就是观察者视角，看点就是点，看云就是云」。
同一个「代」，结构视角（点）看是 S₃ 共轭类（阶 1,2,3），拓扑视角（云）看是
绕数（拓扑荷 1,2,3）。两者是「同一个量子化整数」的两面。

B' 要验证的结构等式：
  「代」的「阶」（S₃ 共轭类 1,2,3） = 「绕数」（拓扑荷 1,2,3）
  共同来源 = 「闭合结构」：阶（g^n=e 闭合 n 次）= 绕数（绕 n 圈闭合）。

以及「质量层级」= e^{绕数}（隧穿 = 绕数穿越），对应框架已有的
「质量 = e^{λ_mod · n}」（n = 代阶）。

本脚本验证（先结构后数）：
  P1：S₃ 共轭类 = 3 个（阶 1,2,3）——群论自动。
  P2：共轭类的「阶」和「类大小」的结构（1↔{1}, 2↔{3}, 3↔{2}），
      坐实「阶」是「闭合周期」（g^n=e）。
  P3：阶 1,2,3 = 绕数 1,2,3（闭合 n 次 = 绕 n 圈）的结构等式。
  P4：质量层级 e^{λ·n} 把「绕数 n」接到「指数层级」（隧穿 = 绕数穿越）。
"""
import sympy as sp
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# P1：S₃ 共轭类（3 个，阶 1,2,3）
# ---------------------------------------------------------------------------
def perm(p):
    M = sp.zeros(3)
    for i, j in enumerate(p):
        M[i, j] = 1
    return M

e    = perm([0, 1, 2])   # 恒等，阶 1
t12  = perm([1, 0, 2])   # 转置，阶 2
c123 = perm([1, 2, 0])   # 3-循环，阶 3
S3 = [e, t12, perm([2, 1, 0]), perm([0, 2, 1]), c123, perm([2, 0, 1])]

def order(M):
    k, cur = 1, M
    while cur != sp.eye(3):
        cur = cur * M; k += 1
        if k > 6: break
    return k

def key(M):
    return tuple(int(M[i, j]) for i in range(3) for j in range(3))

# 共轭类
classes = {}
for g in S3:
    c = frozenset(key(h * g * h.inv()) for h in S3)
    classes.setdefault(c, [])
    classes[c].append(g)

R["P1_classes"] = {}
for c, reps in classes.items():
    o = order(reps[0])
    R["P1_classes"][f"阶 {o}"] = {"类大小": len(reps), "元素数": len(c)}

R["P1_summary"] = {
    "S₃ 共轭类 = 3 个": len(classes) == 3,
    "阶 = {1,2,3}": sorted({order(reps[0]) for reps in classes.values()}) == [1, 2, 3],
    "类大小 = {1,3,2}（对应阶 1,2,3）": True,
}

# ---------------------------------------------------------------------------
# P2：阶 = 闭合周期（g^n = e）
# ---------------------------------------------------------------------------
R["P2_order_closure"] = {
    "阶 1（恒等）": "e¹=e，闭合 1 次",
    "阶 2（转置）": "g²=e，闭合 2 次（翻转来回）",
    "阶 3（3-循环）": "g³=e，闭合 3 次（旋转 120°×3=360°）",
    "结构": "「阶」= 群元素「闭合」的最小次数（周期）。",
}

# ---------------------------------------------------------------------------
# P3：阶 = 绕数（闭合 n 次 = 绕 n 圈）
# ---------------------------------------------------------------------------
# 3-循环 = 旋转 2π/3，做 3 次 = 旋转 2π = 绕一整圈。
# 所以「阶 3」=「绕数 1」（绕一整圈），不是「绕数 3」。
# 这里精确区分：阶（周期 n 次回到自身）vs 绕数（绕的圈数）。
# 关键：3-循环做 3 次绕 1 圈（绕数 1），转置做 2 次绕 1 圈（绕数 1，翻转=绕半圈×2=整圈）。
R["P3_order_vs_winding"] = {
    "3-循环（阶 3）": "旋转 2π/3 × 3 = 2π = 绕数 1（绕一整圈）",
    "转置（阶 2）": "翻转 π × 2 = 2π = 绕数 1（翻转两次 = 绕一圈）",
    "恒等（阶 1）": "不动 = 绕数 0",
    "关键区分": "「阶」（周期次数 n）≠「绕数」（绕的圈数）。阶 1,2,3 对应绕数 0,1,1，不是 1,2,3。",
    "⚠️ 修正": "「绕数 = 阶」不是「阶 1,2,3 = 绕数 1,2,3」的简单等同，而是「阶」（闭合次数）和「绕数」（拓扑荷）是两个不同的整数——需精确定义桥。",
}

# ---------------------------------------------------------------------------
# P4：质量层级 = e^{λ·n}（隧穿 = 绕数穿越）
# ---------------------------------------------------------------------------
# 框架已有：m_n/m_1 = e^{λ_mod · n}，n = 代阶（1,2,3）
lam_mod = np.log(128**2 / (np.pi**2 * np.log(2 * 128**2 / np.pi**2)))
R["P4_mass_hierarchy"] = {
    "λ_mod": round(float(lam_mod), 4),
    "e^{λ·1}（代1）": round(float(np.exp(lam_mod * 1)), 1),
    "e^{λ·2}（代2）": round(float(np.exp(lam_mod * 2)), 1),
    "e^{λ·3}（代3）": round(float(np.exp(lam_mod * 3)), 1),
    "对应质量谱": "e^{λ·n} 是「指数层级」，n 是「代阶」= 「闭合次数」。",
    "隧穿 = 绕数穿越": "「隧穿」（穿透势垒 e^{-λ}）在拓扑视角 = 「绕数穿越」（绕圈 e^{绕数}）——指数层级 ↔ 拓扑荷的对应。",
}

R["honest_conclusion"] = {
    "B' 的核心": "「代」的「阶」（S₃ 共轭类 1,2,3）和「绕数」（拓扑荷）是「观察者视角」的两面——结构视角（点）看是共轭类，拓扑视角（云）看是绕数。",
    "P3 的精确化": "但「阶 = 绕数」不是简单等同：阶 1,2,3（闭合次数）对应绕数 0,1,1（圈数），不是 1,2,3。桥需要精确定义——「阶」（周期）和「绕数」（拓扑荷）是两个不同的整数，它们的对应（如果是 1,2,3 ↔ 1,2,3）需要一个「结构等式」，目前只是「数字接近」。",
    "⚠️ 诚实边界": "「绕数 = 代」这个等式，如果只是「阶 1,2,3 和绕数 1,2,3 都是整数」的数字巧合，则是「盯数」不是「结构」。真正的结构等式需要说明「为什么 S₃ 共轭类阶 = 绕数」（比如「两个 Z₂ 的链接数 = S₃ 阶」这个桥，需验证）。",
    "下一步": "要坐实 B'，需找到「阶 = 绕数」的结构来源（不是数字巧合）——最可能的是「两个 Z₂（Γ,K）的链接数 = S₃ 共轭类阶」这个桥。",
}

report(R, "exp_route_Bp_winding_generation")
