"""
远景线 5（质量谱）· 验证「128 = 7 个非平凡元素的幂集」是否绕开群论计数

关键区分（本轮探到的候选出口）：
  之前否定「7 个自由度 → 2⁷」的理由 = 「7 个非平凡元素 ≠ 7 个独立生成元」
  （7 = 2³-1 是 3 个生成元的状态数）。

  但「幂集」绕开了这个理由：
  - 「7 个独立生成元」→ Z₂⁷ → 128 状态（需要 7 个代数独立元素）
  - 「7 个元素的幂集」→ 2⁷ = 128 个子集（只需要 7 个元素「不同」，不要「独立」）

  幂集的数学：n 个不同元素的幂集 = 2^n 个子集，这**不要求** n 个元素是
  生成元——只要它们是 n 个「可区分」的对象。

  7 个非平凡元素 {Γ,K,s,ΓK,Γs,Ks,ΓKs} 是 7 个「不同的」元素（虽然由 3 个
  生成元生成），它们的幂集 = 2⁷ = 128 个子集。

本脚本验证：
  (1) 7 个非平凡元素的幂集 = 128（纯集合论，合法）；
  (2) 这个 128 不违反「3 个生成元」（幂集大小 ≠ 生成元数）；
  (3) 「幂集 128」在框架里对应什么（元观察方案数 = 自指的有限截断）。
"""
from itertools import combinations, chain
from experiments._common import report

R = {}

# 7 个非平凡元素（3 个生成元 Γ,K,s 的非空组合）
generators = ["Γ", "K", "s"]
nontrivial = []
for r in (1, 2, 3):
    for c in combinations(generators, r):
        nontrivial.append("".join(c))

R["nontrivial_elements"] = {
    "7 个非平凡元素": nontrivial,
    "数量": len(nontrivial),
    "来源": "3 个生成元 {Γ,K,s} 的 7 个非空组合（2³-1）",
}

# 幂集 = 2^7 = 128
n = len(nontrivial)
power_set_size = 2**n
R["power_set"] = {
    "7 个元素的幂集大小 2^7": power_set_size,
    "验证 = 128": power_set_size == 128,
    "关键": "幂集大小 = 2^7 = 128，这个「128」不要求 7 个元素是生成元，只要求它们是 7 个「可区分对象」",
}

# 关键：幂集 vs 生成元
R["power_set_vs_generator"] = {
    "「7 个独立生成元」→ Z₂⁷": "128 状态（需要 7 个代数独立元素）——❌ 不成立（只有 3 个生成元）",
    "「7 个元素幂集」→ 2⁷": "128 个子集（只需 7 个元素「不同」）——✅ 成立（7 个非平凡元素确实不同）",
    "区别": "幂集的「独立」是「子集选择独立」（每个元素独立选有/无），不是「生成元独立」（每个元素独立生成一维）。两者不同",
}

# 幂集在框架里的对应
R["framework_meaning"] = {
    "7 个非平凡观察方式": "3 个 Z₂ 的 7 个非平凡组合 = 7 种观察方式",
    "幂集 128": "对 7 种观察方式每个「观察/不观察」= 2⁷ = 128 个「元观察方案」",
    "自指对应": "「观察自己的观察」= 元观察 = 128 个方案 = 自指（观察的无限递归）的有限截断",
    "框架原型": "「观察的无限递归 D_n = M_{N^{2^n}}」——本脚本的幂集是它的「区分版」（加倍 2^n，而非平方 N^{2^n}）",
}

R["honest_conclusion"] = {
    "正面发现": "「128 = 2⁷ = 7 个非平凡元素的幂集」是合法的——幂集只需要 7 个元素「不同」（它们确实不同），不需要「7 个独立生成元」（那才需要 3 个）。这绕开了之前「7 ≠ 7 个自由度」的否定",
    "关键区分": "「7 个自由度」错（要 7 个生成元，只有 3 个）；「7 个元素的幂集」对（要 7 个不同对象，确实有 7 个）。两者都给 2⁷=128，但前者是「状态数」（错），后者是「子集数」（对）",
    "仍待论证": "「幂集 128 = 元观察方案数」要成为「质量谱 level N」，还需一步：为什么「level N」=「元观察方案数 128」？这一步是「幂集」和「量子化 level」的对应，未建立",
    "措辞": "这是「候选出口」（幂集绕开群论计数），非「已证 128 的来源」——最后一步「幂集 128 ↔ level N」是待论证的缺口。留活口",
}

report(R, "exp_power_set_128")
