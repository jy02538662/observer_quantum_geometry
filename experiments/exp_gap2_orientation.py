"""
缺口 2（上型不对称「除以 3」）· 补 §22.4：区分/等同 = 有向正/反 = 三重态/单态（显式算子）

用户诊断（镜子画面）：面朝（+i）映出三条河（×3）、背朝（-i）只映出后背（×1）。
数学化：公设「观察 = 有向区分」里，「区分」和「等同」本身就是「有向」的两个面：
  区分（正向 +i）= 把 3 色分开（保持独立）→ 显式算子 = I₃（恒等，迹 3，秩 3）
  等同（反向 -i）= 把 3 色合并（抹平差异）→ 显式算子 = P_singlet（迹 1，秩 1）

本脚本坐实「区分/等同 → I₃/P_singlet → 迹 3/迹 1」的显式对应，作为 §22.4 的显式形式候选：
  区分算子 = I₃（保持 3 色独立）= 三重态
  等同算子 = P_singlet（合并 3 色）= 单态
  而「有向 ±i」的「正 = 区分、反 = 等同」= 公设「有向区分」的字面含义。
"""
import numpy as np
from sympy import Matrix, I, Rational, simplify, sqrt
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (1) 有向 J 的 ±i = 区分（正向）/等同（反向）
# ---------------------------------------------------------------------------
J = Matrix([[0, 1], [-1, 0]])   # iσ_y，本征值 ±i
I2 = Matrix.eye(2)
P_plus  = simplify((I2 - I * J) / 2)   # +i 谱投影（正向，区分）
P_minus = simplify((I2 + I * J) / 2)   # -i 谱投影（反向，等同）
R["oriented_distinguish_identify"] = {
    "+i（正向）= 区分（分开）": str(P_plus),
    "-i（反向）= 等同（合并）": str(P_minus),
    "区分/等同 = 有向 ±i 的两个面": "公设「观察 = 有向区分」的字面含义",
}

# ---------------------------------------------------------------------------
# (2) 区分/等同在颜色空间的显式算子
# ---------------------------------------------------------------------------
# 区分 = 保持 3 色独立 = I₃（恒等，秩 3，迹 3）
# 等同 = 合并 3 色为单态 = P_singlet = |s><s|, s=(r+g+b)/√3（秩 1，迹 1）
I3 = Matrix.eye(3)
singlet = Matrix([1, 1, 1]) / sqrt(3)
P_singlet = singlet * singlet.T

R["explicit_operators"] = {
    "区分算子 = I₃（保持 3 色独立）": {"迹": simplify(I3.trace()), "秩": I3.rank()},
    "等同算子 = P_singlet（合并 3 色）": {"迹": simplify(P_singlet.trace()), "秩": P_singlet.rank()},
}

# ---------------------------------------------------------------------------
# (3) 「除以 3」= 区分迹 3 ÷ 等同迹 1 = 3
# ---------------------------------------------------------------------------
R["divide_by_3"] = {
    "上型（+i，区分）= I₃ 迹 3": 3,
    "下型（-i，等同）= P_singlet 迹 1": 1,
    "比值 = 3": "三重态迹 3 ÷ 单态迹 1 = 颜色数 3",
}

# ---------------------------------------------------------------------------
# (4) 关键：区分/等同算子与「有向」的关系（补 §22.4）
# ---------------------------------------------------------------------------
# 区分算子 I₃ = 「正向 +i」在颜色空间的实现（保持独立）
# 等同算子 P_singlet = 「反向 -i」在颜色空间的实现（合并）
# 而「+i = 区分、-i = 等同」= 公设「有向区分」的字面含义（区分=正向、等同=反向）
R["orientation_to_rank_bridge"] = {
    "正向 +i → 区分 → I₃（迹 3，秩 3）": "保持 3 色独立 = 三重态 ×3",
    "反向 -i → 等同 → P_singlet（迹 1，秩 1）": "合并 3 色 = 单态 ×1",
    "桥的性质": "「+i=区分、-i=等同」= 公设「有向区分」的字面含义（区分/等同是有向的两个面）",
    "补 §22.4 的候选": "显式形式 = 区分↔I₃（迹3）、等同↔P_singlet（迹1），由「有向区分」公设直接给",
}

# ---------------------------------------------------------------------------
# (5) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实（符号）": "① +i/-i 谱投影（区分/等同）；② 区分算子 I₃ 迹 3、等同算子 P_singlet 迹 1；③ 比值 = 3",
    "显式形式候选（补 §22.4）": "「有向 ±i」的「正 = 区分 = I₃（保持 3 色，迹 3）」、「反 = 等同 = P_singlet（合并 3 色，迹 1）」——区分/等同是「有向区分」公设的两个面",
    "关键判断": "如果接受「区分=正向、等同=反向」是「有向区分」的字面含义，则 §22.4 的显式形式补上：因子 3 vs 1 = 区分迹 3 vs 等同迹 1",
    "仍需谨慎（边界）": "「+i=区分、-i=等同」的「正/反」赋值（哪边是区分哪边是等同）仍是约定（+i/-i 对称）；但「区分↔迹3、等同↔迹1」的对应是显式的",
    "措辞（三档）": "「区分=迹3、等同=迹1」是【显式算子对应】（符号坐实）；「+i=区分、-i=等同」是【公设字面含义】+【约定】（正/反对称）；缺口从「缺显式算子」收窄为「正/反赋值是约定」",
}

report(R, "exp_gap2_orientation")
