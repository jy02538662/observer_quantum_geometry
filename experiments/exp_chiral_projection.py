"""
远景线 5（质量谱）· 深挖缺口1续三：手征投影 P_L 的框架来源（观察 +i 侧）

上一步坐实：反对易方向 σ_z 翻转手征（+i↔-i）= 有向。
最后一步：从「翻转」到「只作用 +i 侧」需要「手征投影 P_L = |+i⟩⟨+i|」。

本脚本检验「手征投影 P_L」如何给「弱同位旋只作用左手」，以及 P_L 的框架来源。
"""
import numpy as np
from sympy import Matrix, I, simplify
from experiments._common import report

R = {}

sx = Matrix([[0,1],[1,0]])
sy = Matrix([[0,-I],[I,0]])
sz = Matrix([[1,0],[0,-1]])
I2 = Matrix([[1,0],[0,1]])

# ---------------------------------------------------------------------------
# (1) 手征投影 P_L = |+i⟩⟨+i|（观察 +i 侧）
# ---------------------------------------------------------------------------
# J = iσ_y 的本征向量 |+i⟩=(1,i)/√2, |-i⟩=(1,-i)/√2
J = I * sy
plus_i = Matrix([1, I]) / (2**0.5)
minus_i = Matrix([1, -I]) / (2**0.5)
# P_L = |+i⟩⟨+i|
PL = plus_i * plus_i.H
PL = Matrix(PL)
# P_R = |-i⟩⟨-i|
PR = minus_i * minus_i.H
PR = Matrix(PR)

R["projection"] = {
    "P_L = |+i⟩⟨+i|": str(PL),
    "P_L² = P_L（投影）": simplify(PL*PL - PL) == Matrix.zeros(2),
    "P_L + P_R = I（完备）": simplify(PL + PR - I2) == Matrix.zeros(2),
}

# ---------------------------------------------------------------------------
# (2) 弱同位旋 σ_y（断裂 → SU(2）投影到 +i 侧
# ---------------------------------------------------------------------------
# 弱同位旋 I₃ = σ_y/2，检验 P_L σ_i P_L（投影到 +i 侧）
PL_sx_PL = simplify(PL * sx * PL)
PL_sy_PL = simplify(PL * sy * PL)
PL_sz_PL = simplify(PL * sz * PL)

R["weak_isospin_projection"] = {
    "P_L σ_x P_L": str(PL_sx_PL),
    "P_L σ_y P_L": str(PL_sy_PL),
    "P_L σ_z P_L": str(PL_sz_PL),
    "关键": "只有 σ_y 在 +i 侧非零（P_L σ_y P_L ≠ 0），σ_x σ_z 都 = 0——弱同位旋投影到 +i 侧后只剩 I₃=σ_y 分量",
}

# ---------------------------------------------------------------------------
# (3) 「弱同位旋只作用左手」= P_L σ P_L 的结构
# ---------------------------------------------------------------------------
# P_L σ_y P_L = |+i⟩⟨+i| σ_y |+i⟩⟨+i|
# σ_y = -iJ，J|+i⟩ = i|+i⟩，所以 σ_y|+i⟩ = -iJ|+i⟩ = -i·i|+i⟩ = |+i⟩
# 所以 P_L σ_y P_L = |+i⟩⟨+i|（σ_y 保持 |+i⟩，本征值 +1）
# 即弱同位旋 I₃ = σ_y/2 在左手（+i 侧）本征值 = +1/2
R["left_handed_I3"] = {
    "σ_y|+i⟩ = |+i⟩（σ_y 在 +i 侧本征值 +1）": simplify(sy * plus_i) == plus_i,
    "弱同位旋 I₃ = σ_y/2 在左手 = +1/2": "左手费米子 I₃=+1/2（上型）",
    "含义": "手征投影 P_L 把弱同位旋限制到左手，且 I₃=σ_y/2 在左手本征值 +1/2——「弱同位旋只作用左手」的显式",
}

# ---------------------------------------------------------------------------
# (4) 手征投影 P_L 的框架来源（候选）
# ---------------------------------------------------------------------------
# P_L = |+i⟩⟨+i| = 投影到手征 +i 侧 = 观察 +i 侧
# 而「观察 = 有向区分」（公设），「有向」= J = iσ_y（±i）
# 所以 P_L = 观察有向的 +i 侧 = 有向区分的「有向」部分的「观察」
R["PL_origin"] = {
    "P_L = |+i⟩⟨+i|": "投影到手征 +i 侧（观察 +i 侧）",
    "观察 = 有向区分（公设）": "有向 J = iσ_y（±i）",
    "候选推导": "P_L = 观察有向的 +i 侧 = 「有向区分」的「有向」部分的观察——手征投影是「观察」的直接结果，不是外部偏好",
    "状态": "这是候选机制（观察 → 手征投影），需坐实「观察」算子如何精确给 P_L",
}

# ---------------------------------------------------------------------------
# (5) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实": "① 手征投影 P_L 把弱同位旋限制到左手（只有 σ_y 分量非零，I₃=+1/2）；② 反对易方向翻转手征 = 有向（上一步）；③ 宇称矛盾是假的（澄清印证）",
    "从有向到 SU(2) 只作用左手的完整链条（候选）": "有向 J=iσ_y（±i）→ 手征投影 P_L=观察 +i 侧 → 弱同位旋 I₃=σ_y/2 投影到 +i 侧（只作用左手，I₃=+1/2）",
    "待坐实": "「手征投影 P_L = 观察 +i 侧」的精确框架来源——「观察」算子（条件期望 E）如何精确给 P_L = |+i⟩⟨+i|",
    "措辞": "符号坐实（手征投影给弱同位旋只作用左手）+ 候选机制（P_L = 观察 +i 侧）——最后一步「观察→P_L」待坐实",
}

report(R, "exp_chiral_projection")
