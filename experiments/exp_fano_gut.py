"""
远景线 5（质量谱）· 族维度第四刀：GUT 层入口（Fano 7 点分裂 3+3+1）

用户方向：从 su(3)=S₃ 走到 GUT 层，但不要一步跳 SU(5)。正确入口 =
「三个 Z₂ → Fano → 7 个点如何分裂成 3+3+1」——可能给出「颜色×弱同位旋×超荷」的结构。

本脚本精确构造并验证：
  (1) 三个 Z₂（Γ手征, K共轭, s=λ↔1/λ尺度对偶）的 7 个非平凡组合 = Fano 平面 7 点；
  (2) Fano 的 7 条线（每线 3 点，F₂³ 和=0）；
  (3) S₃ = Aut(Z₂×Z₂) = GL(2,2)（PSL(2,7)=GL(3,2) 的子群）的轨道分解 = 3+1+3；
  (4) GL(3,2) 阶 168 验证 + S₃ 是子群；
  (5) 超荷符号（λ₈ 在颜色线上的 2正1负）与 Fano 有向线（2个循环方向）的关系。
"""
import numpy as np
from itertools import product
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (1) 三个 Z₂ 的 7 个非平凡组合 = F₂³ 非零向量 = Fano 7 点
# ---------------------------------------------------------------------------
# 坐标 (a,b,c) = (Γ 分量, K 分量, s 分量)
points = {
    "Γ":   (1,0,0),
    "K":   (0,1,0),
    "ΓK":  (1,1,0),
    "s":   (0,0,1),
    "Γs":  (1,0,1),
    "Ks":  (0,1,1),
    "ΓKs": (1,1,1),
}
R["fano_points"] = {
    "7 个点（三个 Z₂ 的非平凡组合）": {k: v for k, v in points.items()},
    "坐标含义": "(a,b,c) = (Γ分量, K分量, s分量)，s = λ↔1/λ 尺度对偶",
}

# ---------------------------------------------------------------------------
# (2) Fano 的 7 条线（每线 3 点，F₂³ 和 = 0）
# ---------------------------------------------------------------------------
names = list(points.keys())
coords = list(points.values())

def xor(v1, v2, v3):
    return tuple((v1[i] + v2[i] + v3[i]) % 2 for i in range(3))

# 所有 3 点子集，筛选「三者和=0」= Fano 线
lines = []
for i in range(7):
    for j in range(i+1, 7):
        for k in range(j+1, 7):
            if xor(coords[i], coords[j], coords[k]) == (0,0,0):
                lines.append((names[i], names[j], names[k]))

R["fano_lines"] = {
    "7 条线（每线 3 点，和=0）": ["{"+",".join(l)+"}" for l in lines],
    "验证线数=7": len(lines) == 7,
}

# ---------------------------------------------------------------------------
# (3) S₃ = Aut(Z₂×Z₂) = GL(2,2) 作用（置换前两坐标 a,b，固定 c）
# ---------------------------------------------------------------------------
# GL(2,2) 的 6 个矩阵（2×2 over F₂）
gl22 = [
    np.array([[1,0],[0,1]], dtype=int),   # 恒等
    np.array([[0,1],[1,0]], dtype=int),   # 交换 a,b
    np.array([[1,1],[0,1]], dtype=int),   # a→a+b
    np.array([[1,0],[1,1]], dtype=int),   # b→a+b
    np.array([[0,1],[1,1]], dtype=int),
    np.array([[1,1],[1,0]], dtype=int),
]

def act(m, v):
    """3×3 矩阵作用在 (a,b,c)，前两坐标用 m（GL(2,2)），c 固定。"""
    a, b, c = v
    na = (m[0,0]*a + m[0,1]*b) % 2
    nb = (m[1,0]*a + m[1,1]*b) % 2
    return (na, nb, c)

# S₃ 作用在 7 个点上，算轨道
def orbit(v, group):
    seen = set()
    out = []
    for m in group:
        w = act(m, v)
        if w not in seen:
            seen.add(w)
            out.append(w)
    return out

# 用名字映射回坐标
coord2name = {v: k for k, v in points.items()}

# 轨道分解
visited = set()
orbits = []
for v in coords:
    if v in visited:
        continue
    orb = orbit(v, gl22)
    orbits.append([coord2name[w] for w in orb])
    visited.update(orb)

orbit_sizes = sorted([len(o) for o in orbits], reverse=True)
R["S3_orbits"] = {
    "S₃ 在 7 点上的轨道分解": orbits,
    "轨道大小": orbit_sizes,
    "验证 = 3+3+1": orbit_sizes == [3,3,1],
    "意义": "S₃（=Aut(Z₂×Z₂)=颜色 Weyl 群）在 Fano 7 点上的轨道 = 3+1+3：{Γ,K,ΓK}(颜色) + {s}(尺度对偶) + {Γs,Ks,ΓKs}(颜色×尺度对偶)",
}

# ---------------------------------------------------------------------------
# (4) GL(3,2) 阶 168 + S₃ 是子群
# ---------------------------------------------------------------------------
def det_mod2(M):
    return int(round(np.linalg.det(M))) % 2

# 生成所有 3×3 F₂ 矩阵，筛可逆
invertible = 0
all_mats = 0
for entries in product([0,1], repeat=9):
    M = np.array(entries, dtype=int).reshape(3,3)
    all_mats += 1
    if det_mod2(M) == 1:
        invertible += 1

R["GL32"] = {
    "所有 3×3 F₂ 矩阵数": all_mats,
    "可逆矩阵数（GL(3,2) 阶）": invertible,
    "验证 = 168": invertible == 168,
    "PSL(2,7) ≅ GL(3,2)": "Fano 平面自同构群阶 168（=7×24）",
}

# S₃ 嵌入 GL(3,2)：3×3 矩阵 [[m,0],[0,1]]，验证是子群（闭包在 GL(3,2) 内，含 6 元素）
def embed(m):
    M = np.zeros((3,3), dtype=int)
    M[:2,:2] = m
    M[2,2] = 1
    return M
embedded = [embed(m) for m in gl22]
all_det1 = all(det_mod2(M) == 1 for M in embedded)
R["S3_subgroup"] = {
    "S₃ 嵌入 GL(3,2) 的 6 个矩阵行列式都=1": all_det1,
    "验证 S₃ ⊂ GL(3,2)": all_det1 and len(embedded) == 6,
    "意义": "S₃ = GL(2,2) 是 PSL(2,7)=GL(3,2) 的子群（阶 6 ⊂ 168），作用 = 置换前两坐标（Γ,K），固定 s",
}

# ---------------------------------------------------------------------------
# (5) 超荷符号与 Fano 有向线
# ---------------------------------------------------------------------------
# 超荷 λ₈ = diag(1,1,-2)/√3 在颜色三重态 {Γ,K,ΓK} 上的值：
# 需要把颜色三重态 {Γ,K,ΓK} 映射到 su(3) 的权 r,g,b
# 颜色三重态 = 3 个权 (r,g,b)，超荷 λ₈ 值 = {+1/(2√3), +1/(2√3), -1/√3}（2正1负）
# 在 Fano 里，颜色线 = {Γ, K, ΓK}（c=0 的三个点）
color_line = {"Γ", "K", "ΓK"}
# 超荷符号：正超荷 = 弱同位旋 2（两个），负超荷 = 超荷 1（一个）
R["hypercharge_on_color_line"] = {
    "颜色线（c=0）": "{Γ, K, ΓK}",
    "超荷 λ₈ 值（2正1负）": "{+1/(2√3), +1/(2√3), -1/√3}",
    "正超荷（弱同位旋 2）": "2 个点（r,g 对应）",
    "负超荷（超荷 1）": "1 个点（b 对应）",
    "结构": "颜色线 3 点 = 2 正超荷（弱同位旋）+ 1 负超荷（超荷）——即颜色 3 = 2⊕1 在 Fano 颜色线上的体现",
}

# Fano 有向线：颜色线 {Γ,K,ΓK} 的 2 个循环方向
# 循环序：Γ→K→ΓK→Γ（一个方向）和 Γ→ΓK→K→Γ（反方向）
# 2 个方向对应「超荷符号 ±」？
R["oriented_line"] = {
    "颜色线的 2 个循环方向": ["Γ→K→ΓK→Γ", "Γ→ΓK→K→Γ"],
    "超荷符号 ±": "+（正超荷，弱同位旋） vs -（负超荷，超荷）",
    "候选对应": "有向线的 2 个方向 ↔ 超荷符号 ±（正超荷 vs 负超荷）——需进一步坐实",
}

# 检查：S₃ 的 3-循环（120° 旋转）在颜色线 {Γ,K,ΓK} 上的作用 = 循环置换
# 3-循环 = GL(2,2) 的 [[0,1],[1,1]]（阶 3 的元素）
cycle3 = np.array([[0,1],[1,1]], dtype=int)
# 作用在 Γ=(1,0,0) 上：
g = act(cycle3, (1,0,0))
g2 = act(cycle3, g)
g3 = act(cycle3, g2)
R["three_cycle_on_color_line"] = {
    "3-循环 [[0,1],[1,1]] 作用 Γ→": [coord2name[g], coord2name[g2], coord2name[g3]],
    "验证回到 Γ（周期3）": g3 == (1,0,0),
    "意义": "3-循环（代三阶3）= 颜色线 {Γ,K,ΓK} 的循环置换（120° 旋转），与第三刀的「3-循环=颜色循环」一致",
}

# ---------------------------------------------------------------------------
# (6) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实（符号精确）": "① Fano 7 点 = 三个 Z₂ 的 7 个非平凡组合；② S₃ 轨道 = 3+1+3（{Γ,K,ΓK} + {s} + {Γs,Ks,ΓKs}）；③ GL(3,2)=PSL(2,7) 阶 168，S₃=GL(2,2) 是子群；④ 3-循环=颜色线循环置换",
    "核心结构 3+3+1": "3（c=0，颜色{Γ,K,ΓK}）+ 1（s=尺度对偶）+ 3（c=1，颜色×尺度对偶{Γs,Ks,ΓKs}）",
    "物理对应（候选）": "3（颜色）= su(3) 手征×共轭；1（尺度对偶 s）= 超荷 u(1) 候选；3（颜色×尺度对偶）= 反颜色 3̄ 或代三候选",
    "下一步待坐实": "① 第二个 3（{Γs,Ks,ΓKs}）是反颜色还是代三；② 超荷符号（2正1负）与有向线 2 方向的确切对应；③ 「上型×3 vs 下型×1」能否从 3+3+1 读出",
    "措辞": "符号坐实 + 候选对应（非「已推导 GUT 层」）",
}

