"""
缺口 3 · 任务②：符号验证「转置=号差面 / 3-循环=旋转面」对应的严格性

背景（质量谱笔记 §五 埋下的猜想）：
  转置（g²=e，反射）= 号差面（J²=-I，本征值 ±i，虚频率）
  3-循环（g³=e，旋转）= 旋转面（e^{2πJ}=I，周期 2π，实频率）

本脚本符号验证这几个数学事实（sympy 精确），并坐实一个关键判断：
  「转置=号差」的对应是「松散类比」还是「严格同构」？
  关键检验点：转置平方 = +I，号差平方 = -I，两者「平方符号」相反。

任务①已发现：29.2 相对误差 ~20%，27(3³) 和 32(2⁵) 都在 1σ 内 →
  「29.2 不干净」的负预言不成立 → 本方向（号差面解释不干净）的动机已动摇。
本脚本只坐实数学事实 + 判断对应的严格性，不硬推数值。
"""
import numpy as np
import sympy as sp
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 0. S₃ 标准 2 维表示（差空间 {x+y+z=0}）
# ---------------------------------------------------------------------------
e = sp.Matrix([[1, 0], [0, 1]])            # 单位元
t12 = sp.Matrix([[-1, 0], [0, 1]])         # 转置 (12)：反射
c123 = sp.Matrix([[-sp.Rational(1, 2), -sp.sqrt(3)/2],
                  [sp.sqrt(3)/2, -sp.Rational(1, 2)]])  # 3-循环 (123)：120° 旋转

# ---------------------------------------------------------------------------
# 1. 命题 P1：转置 (12) 是反射（det=-1，迹=0，平方=+I）
# ---------------------------------------------------------------------------
R["P1_transpose_reflection"] = {
    "(12) det": float(sp.det(t12)),
    "(12) trace": float(sp.trace(t12)),
    "(12)^2 = e": bool(sp.simplify(t12**2 - e) == sp.zeros(2)),
    "判断": "转置 = 反射（det=-1），做两次回单位元（平方=+I）",
}

# ---------------------------------------------------------------------------
# 2. 命题 P2：3-循环 (123) 是 120° 旋转（det=+1，迹=-1，三次=+I）
# ---------------------------------------------------------------------------
R["P2_3cycle_rotation"] = {
    "(123) det": float(sp.det(c123)),
    "(123) trace": float(sp.trace(c123)),
    "(123)^3 = e": bool(sp.simplify(c123**3 - e) == sp.zeros(2)),
    "判断": "3-循环 = 120° 旋转（det=+1），做三次回单位元（三次=+I）",
}

# ---------------------------------------------------------------------------
# 3. 命题 P3：号差 J = [[0,1],[-1,0]]（反对称 J^T=-J，J²=-I，本征值 ±i）
# ---------------------------------------------------------------------------
J = sp.Matrix([[0, 1], [-1, 0]])
R["P3_signature_J"] = {
    "J 反对称 J^T = -J": bool(sp.simplify(J.T + J) == sp.zeros(2)),
    "J^2 = -I": bool(sp.simplify(J**2 + sp.eye(2)) == sp.zeros(2)),
    "J 本征值": [str(x) for x in sp.Matrix([[0,1],[-1,0]]).eigenvals().keys()],
    "判断": "号差 J 反对称，J²=-I，本征值 ±i（虚）",
}

# ---------------------------------------------------------------------------
# 4. 命题 P4：旋转 e^{θJ} = cosθ·I + sinθ·J，周期 2π（e^{2πJ}=I）
# ---------------------------------------------------------------------------
theta = sp.symbols("theta", real=True)
# 验证 e^{θJ} = cosθ·I + sinθ·J 的展开（用级数前几项 + 符号）
# 更直接：验证 e^{2πJ} = I（因为 J²=-I，e^{θJ}=cosθ·I+sinθ·J，θ=2π → cos2π=1, sin2π=0）
exp_2pi = sp.cos(2*sp.pi) * sp.eye(2) + sp.sin(2*sp.pi) * J
R["P4_rotation_period"] = {
    "e^{2πJ} = cos2π·I + sin2π·J = I": bool(sp.simplify(exp_2pi - sp.eye(2)) == sp.zeros(2)),
    "旋转周期 2π": "e^{θJ} 在 θ=2π 回到单位元（实频率，周期 2π）",
}

# ---------------------------------------------------------------------------
# 5. 命题 P5（关键判断）：「转置=号差」的对应严格性
#    转置平方 = +I（P1），号差平方 = -I（P3）→ 平方符号相反
# ---------------------------------------------------------------------------
# 转置 (12) 是 det=-1 的反射，但号差 J 是 det=+1 的反对称矩阵
R["P5_transpose_vs_signature"] = {
    "(12)^2": "= +I（转置做两次回单位元）",
    "J^2": "= -I（号差做两次回负单位元）",
    "平方符号": "+I vs -I，相反",
    "(12) det": float(sp.det(t12)),
    "J det": float(sp.det(J)),
    "det 符号": f"转置 det={float(sp.det(t12))}（反射），号差 J det={float(sp.det(J))}（旋转生成元）",
    "诚实判断": "「转置=号差」是松散类比：两者都是 Z₂ 类结构（做两次「回」），但转置平方=+I（反射/号差符号为 +），号差平方=-I（反酉 T²=-1 的 ±i）。数学上不是同构，只是「阶2 结构」的类比。",
}

# ---------------------------------------------------------------------------
# 6. 独立验证层：用「标准表示 vs 置换表示」的迹重新确认「迹=固定点数」
#    （这是族维度 §2.2/§25 的「转置迹1、3-循环迹0」的来源，独立核对）
# ---------------------------------------------------------------------------
# 置换表示（3 维）里的迹 = 固定点数
perm_e = sp.Matrix([[1,0,0],[0,1,0],[0,0,1]])          # 单位：迹3
perm_t12 = sp.Matrix([[0,1,0],[1,0,0],[0,0,1]])        # 转置 (12)：固定 b，迹1
perm_c123 = sp.Matrix([[0,0,1],[1,0,0],[0,1,0]])       # 3-循环 (123)：无固定点，迹0

R["P6_trace_fixed_points"] = {
    "置换表示 迹(e)": float(sp.trace(perm_e)),
    "置换表示 迹((12))": float(sp.trace(perm_t12)),
    "置换表示 迹((123))": float(sp.trace(perm_c123)),
    "迹 = 固定点数": "单位3 / 转置1 / 3-循环0，坐实（族维度 §2.2 来源）",
    "转置固定子空间": "转置 (12) 固定 b（第3色），交换 r,g → 颜色 3 = 2⊕1 分解",
}

report(R, "exp_gap3_signature_rotation")
