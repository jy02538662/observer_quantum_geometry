"""
看用户的「拓扑涡旋 + OQG → 自旋 2」提议：先验证涡旋相互作用的长程性 + 标量 vs 张量

关键问题：拓扑涡旋能不能绕过「长程 ⟂ 弯曲」墙？

先验一个基础事实：
  1. 2D 涡旋相互作用 V(r) ∝ ln r（对数长程，不是 1/r）
  2. 涡旋是「标量」（绕数 ∈ ℤ，相互作用是标量势）
  3. 度规是「张量」（g_μν = e·e，rank-2）

「长程 ⟂ 弯曲」墙的真正形状 = 「标量长程 ⟂ 张量弯曲」：
  - 长程（模流/尺度不变）→ 标量平（R=0，已验证）
  - 弯曲（缺陷/位置依赖）→ 张量位置依赖
  涡旋的 ln r 是「长程标量」，落在「长程」这半，不是「弯曲」这半。
"""
import numpy as np
from experiments._common import report

R = {}

# ---- 1. 2D 涡旋相互作用 V(r) ∝ ln r（对数长程）----
# XY 模型 / 2D 超导：涡旋-涡旋相互作用 V(r) = (J_s) ln(r/a)（a=芯半径）
r_vals = np.array([1.0, 2.0, 5.0, 10.0, 20.0, 50.0])
a = 0.1
V = np.log(r_vals / a)   # 对数势（2D 涡旋）
R["vortex_interaction"] = {
    "V(r) = ln(r/a)，r 扫描": {f"r={r}": f"V={np.log(r/a):.2f}" for r in r_vals},
    "性质": "对数长程（随 r 缓慢增长，无指数衰减）——拓扑保护",
    "不是 1/r": "1/r 是 3D 库仑；2D 涡旋是 ln r",
}

# ---- 2. 涡旋是标量，度规是张量 ----
R["scalar_vs_tensor"] = {
    "涡旋绕数 n ∈ ℤ": "标量（一个整数，无方向指标）",
    "涡旋相互作用 V(r)": "标量势（一个数）",
    "度规 g_μν": "rank-2 张量（4×4 或 d×d，有方向指标）",
    "关键": "「标量涡旋 → 张量度规」需要 promotion：涡旋的「方向」（向量）→ vielbein e → g=e·e。这个 promotion 是「长程 ⟂ 弯曲」墙的真正形状。",
}

# ---- 3. 结论 ----
R["conclusion"] = {
    "方向对的部分": "拓扑涡旋是「长程标量」（ln r），若能把「涡旋方向」promote 成「张量度规」，可能破墙——方向 plausible。",
    "精确的墙": "「长程 ⟂ 弯曲」= 「标量长程 ⟂ 张量弯曲」。涡旋 ln r 在「标量长程」这半，不在「张量弯曲」这半。",
    "所以关键未验步": "你的第 3/4 步（涡旋密度梯度 → 背景弯曲、涡旋方向 → ω_μ → e → g）正是「标量 → 张量」的 promotion，这是破墙的关键，未验。",
    "E 秩变化这个连接点": "具体、有价值（观察者看到的维度数变化 = 曲率），但它是新提议（OQG 的 E 目前是单一条件期望，非位置依赖），未验。",
}

report(R, "exp_vortex_long_range")
