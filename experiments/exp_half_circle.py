"""
远景线 5（质量谱）· 攻「半圆 vs 圆」缺口：有向=虚数、观察=实数 → cos 偶函数 → 半圆

缺口：为什么 128 个角度是「半圆 (0,π) 内点」（Chebyshev 零点，间隔 π/129），
不是「圆 [0,2π) 等分」（间隔 π/64）？

物理来源（候选）：
  1. 「有向」= 号差 J，J²=-I，本征值 ±i —— 有向是「虚数」的。
  2. 「观察」= 厄米 D=D*，谱实数 —— 观察是「实数」的。
  3. 「有向区分」= 观察「有向」= 取「有向」的实数部分。
     e^{iθ} 的实部 = cos θ。
  4. cos θ 是偶函数（cos θ = cos(-θ)）⟹ 方向 θ 和反方向 -θ 给同一个观察读数
     ⟹ 有效方向空间 = 半圆 [0,π]（不是圆 [0,2π)）。
  5. 「区分」= 离散 ⟹ 128 个角度在半圆等距。
  6. 「量子化 = 有限 N」⟹ 不含端点（δ≠2）⟹ 128 个内点，间隔 π/129。

本脚本验证每一步的数学，诚实标注 ✅/🟡。
"""
import numpy as np
from experiments._common import report

R = {}

# ============ 1. 有向 = 虚数（J²=-I，本征值 ±i） ============
J = np.array([[0, 1], [-1, 0]])
eigJ = np.linalg.eigvals(J)
R["step1_directed_imaginary"] = {
    "J = [[0,1],[-1,0]]": "反对称，J²=-I",
    "J 的本征值": [round(e.real, 2) + 1j*round(e.imag, 2) for e in eigJ],
    "验证 = ±i": np.allclose(np.sort(eigJ.imag), [-1, 1]),
    "状态": "✅ 有向 = 号差 J 是虚数（本征值 ±i）",
}

# ============ 2. 观察 = 实数（厄米 D，谱实数） ============
# 厄米矩阵本征值实数（框架已有：自反性 D=D* → 厄米 → 实数谱）
R["step2_observation_real"] = {
    "自反性 D=D*": "厄米 → 谱实数",
    "观察结果": "实数（可测量）",
    "状态": "✅ 观察 = 实数（框架已有：厄米谱实数）",
}

# ============ 3. 有向区分 = 取有向的实部 = cos θ ============
# 复数相位 e^{iθ} 的实部 = cos θ
theta = np.linspace(0, 2*np.pi, 1000)
phase = np.exp(1j * theta)
real_part = phase.real
R["step3_real_part_cos"] = {
    "e^{iθ} 的实部 Re = cos θ": np.allclose(real_part, np.cos(theta)),
    "状态": "✅ 观察「有向」（虚数 e^{iθ}）的实数部分 = cos θ",
}

# ============ 4. cos 偶函数 → 半圆 ============
# cos θ = cos(-θ)，方向 θ 和反方向 -θ 给同一个读数
R["step4_even_function_half_circle"] = {
    "cos θ = cos(-θ)": np.allclose(np.cos(theta), np.cos(-theta)),
    "含义": "方向 θ 和反方向 -θ 给同一个观察读数 → 正反方向不可区分",
    "有效方向空间": "半圆 [0,π]（[π,2π) 是 [0,π] 的镜像）",
    "数学对象": "圆/对径点 = 实射影线 RP¹ = 半圆（端点粘合）",
    "状态": "🟡 候选（cos 偶函数 → 半圆，数学成立；「观察取实部」的物理是候选）",
}

# ============ 5. 半圆 vs 圆 的数值差异 ============
# 圆 [0,2π) 128 等分：θ = k·2π/128
theta_circle = np.arange(128) * (2*np.pi/128)
lam_circle = 2*np.cos(theta_circle)

# 半圆 (0,π) 128 内点：θ = k·π/129
theta_half = np.arange(1, 129) * (np.pi/129)
lam_half = 2*np.cos(theta_half)

# 唯一值数（cos 偶函数，圆等分会给重复值）
R["step5_circle_vs_half"] = {
    "圆等分 λ 的唯一值数": len(np.unique(np.round(lam_circle, 6))),
    "半圆内点 λ 的唯一值数": len(np.unique(np.round(lam_half, 6))),
    "关键": "圆等分 128 个角度，但 cos 偶函数使 λ 只有 65 个唯一值（θ 和 -θ 重复）；半圆内点 128 个角度给 128 个唯一 λ —— 这正是「半圆」的原因：圆等分会浪费一半（镜像重复）",
}

# ============ 6. 半圆内点 = Chebyshev 零点 ============
def chebyshev_zeros(N):
    return 2*np.cos(np.arange(1, N+1)*np.pi/(N+1))

R["step6_chebyshev"] = {
    "半圆内点 λ = 2cos(kπ/129)": np.allclose(lam_half, chebyshev_zeros(128)),
    "状态": "✅ 半圆内点（不含端点）精确 = Chebyshev 零点",
}

# ============ 7. +1（不含端点）的来源 ============
# 端点 θ=0 → λ=2（经典极限 δ=2）；θ=π → λ=-2
# 量子化 δ=2cos(π/(N+1))≠2 → 到不了端点
R["step7_plus_one"] = {
    "端点 θ=0 给 λ=2": 2*np.cos(0),
    "端点 θ=π 给 λ=-2": 2*np.cos(np.pi),
    "量子化 δ_N=2cos(π/129)": round(2*np.cos(np.pi/129), 6),
    "δ_N ≠ 2（到不了端点）": abs(2*np.cos(np.pi/129) - 2) > 1e-6,
    "含义": "端点 = 经典极限（δ=2，N→∞）；量子化（有限 N）到不了端点 → 零点不含端点 → 128 内点间隔 π/129（+1）",
    "尺度破缺 2-δ_N": round(2 - 2*np.cos(np.pi/129), 6),
    "状态": "✅ +1 = 尺度破缺（框架已有 O(1/N²)）",
}

R["honest_conclusion"] = {
    "半圆的物理": "「有向」是虚数（J²=-I，本征值 ±i），「观察」是实数（厄米 D）。观察「有向」= 取实部 = cos θ。cos 偶函数 ⟹ 正反方向不可区分 ⟹ 有效方向 = 半圆（RP¹）",
    "半圆 vs 圆的数值坐实": "圆等分 128 角度给 65 个唯一 λ（cos 偶函数使一半镜像重复）；半圆内点 128 角度给 128 个唯一 λ = Chebyshev 零点。所以「半圆」不是手选，是「cos 偶函数」的必然",
    "+1 的来源": "端点 θ=0 是经典极限 δ=2，量子化（有限 N）到不了 → 零点不含端点 → 128 内点间隔 π/129（+1 = 尺度破缺 2-δ_N=π²/129²）",
    "剩的缺口": "「观察取实部（Re）」这一步，是「有向（虚数）→ 观察（实数）」的桥，需要更严格论证——为什么「观察」= 取实部，而非取模或别的。这是「虚数有向 → 实数观察」的最后一步",
    "整体": "「半圆」不再是手选——它是「有向=虚数、观察=实数、cos 偶函数」的必然。剩最后一步：论证「观察=取实部」",
    "措辞": "候选（半圆的物理来源已坐实：cos 偶函数 → RP¹），非严格证明。缺口 = 「观察=取实部」的严格化",
}

report(R, "exp_half_circle")
