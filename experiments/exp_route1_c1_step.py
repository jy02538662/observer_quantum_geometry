"""
路1（本征值流）· c=1 步长 = 阶的差（严格，非循环非巧合）

问题（承接 [[路1：N=128可分离性精确分级（严格数学 vs 结构论证）]] §十）：
质量指数 m_n = e^{λ·n} 的「步长 c=1」的来源。

- 审计（§十二）说「无绝对尺度 → 步长=1」= 循环论证（无绝对尺度约束不了无量纲系数）；
- 缺口15（§1.4）说「区分=二分±1 → |±1|=1」= 模（盯数找表达，两个不同的 1）；

正确来源：n = 阶 = {1,2,3}（S₃ 共轭类阶），步长 = 阶的差 = 2−1 = 3−2 = 1（连续整数，严格）。

诚实边界：步长 = 阶差 = 1 严格，但前提「n = 阶」是识别（= 路1 的统一识别，非严格）。
所以 c=1 是「条件严格」（依赖「n=阶」识别），不是「严格」。
"""
from sympy.combinatorics import Permutation
from sympy.combinatorics.named_groups import SymmetricGroup
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. S₃ 的共轭类及其阶
# ---------------------------------------------------------------------------
S3 = SymmetricGroup(3)
classes = {}
for p in S3.elements:
    order = int(p.order())
    key = tuple(sorted([len(c) for c in p.cyclic_form]))   # 循环类型
    classes.setdefault(key, []).append(order)

class_summary = {}
for key, orders in sorted(classes.items()):
    label = "恒等" if key == () else ("转置" if key == (2,) else "3-循环")
    class_summary[label] = {"循环类型": key, "阶": orders[0], "类大小": len(orders)}

orders_set = sorted(set(int(p.order()) for p in S3.elements))
diffs = [orders_set[i+1] - orders_set[i] for i in range(len(orders_set) - 1)]

R["step1_S3_orders"] = {
    "共轭类": class_summary,
    "阶（去重）": orders_set,
    "阶的差": diffs,
}

# ---------------------------------------------------------------------------
# 2. 步长 = 阶的差 = 1
# ---------------------------------------------------------------------------
step = diffs[0] if len(set(diffs)) == 1 else None
R["step2_step"] = {
    "步长 = 阶的差": diffs,
    "步长是否为 1": step == 1,
    "说明": "n = 阶 = {1,2,3} 连续整数，步长 = 相邻阶差 = 1（严格，给定 n=阶）",
}

# ---------------------------------------------------------------------------
# 3. 三问检验（AGENTS 第 7 条）
# ---------------------------------------------------------------------------
R["step3_three_questions"] = {
    "① 同一对象": "步长（n 的增量）和阶（n 的值）作用在同一对象 n 上 ✅；缺口15 的 |±1| 是「二分模」，和「阶差」是不同对象 ❌",
    "② 计数": "阶 = {1,2,3} 严格（群论），差 = 1 严格 ✅",
    "③ 结构等式": "「n=阶=1,2,3 → 步长=阶差=1」是结构推论 ✅；缺口15 的「|±1|=1」是「先有 1、再凑 |±1|」❌（盯数找表达）",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "步长 = 阶的差 = 1": "严格（S₃ 阶 {1,2,3} 连续整数）",
    "审计「无绝对尺度循环」": "找错来源（步长不从「无绝对尺度」来）",
    "缺口15「|±1|=1」": "找错来源（「阶差1」和「二分模1」是两个不同的 1，盯数找表达）",
    "c=1 最终状态": "条件严格（阶差=1 严格，但「n=阶」是识别）",
    "三档措辞": "「阶差=1」=【严格】；「n=阶」=【识别（路1 统一识别）】",
}

report(R, "exp_route1_c1_step")
