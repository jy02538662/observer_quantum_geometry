"""
检查：N 本质是连续还是离散？

背景：一元论翻转给出 N = 127.72（连续值），128 = 2^7 是「最近 2 的幂」舍入。
问题：框架的 N 本质是连续（127.72 有意义）还是离散（必须整数）？

框架里 N 的两个来源：
  1. 量子化 δ_N = 2cos(π/(N+1))（Chebyshev 截断层级）——N 是「零点数」，整数；
  2. 幂集 N = 2^7 = 128（组合计数）——N 是「子集数」，整数。

检查：
  ① Chebyshev 递推 Δ_{k+1}=δΔ_k−Δ_{k−1} 只对整数 k 定义，截断 Δ_N=0 在整数 N；
  ② 幂集 2^7 = 128 是组合计数（整数）；
  ③ 若 N 只对整数有意义 → 反解 N=127.72 是「连续近似离散」，识别① 保留。

判据：N 连续有意义 → 识别① 消除；N 必须整数 → 识别① 保留（需 128=2^7 结构推导）。
"""
import sympy as sp
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. 量子化来源：Chebyshev 截断层级 N 是整数
# ---------------------------------------------------------------------------
# Chebyshev 递推 Δ_0=1, Δ_1=δ, Δ_{k+1}=δΔ_k−Δ_{k−1}（k 是整数下标）
# Δ_n = U_n(δ/2)（第二类 Chebyshev），截断 Δ_N = 0 在整数 N
N_sym = sp.symbols("N", integer=True)   # N 是整数（层级的本质）
delta = 2 * sp.cos(sp.pi / (N_sym + 1))

# 截断条件：Δ_N = U_N(δ/2) = sin((N+1)θ)/sin(θ)，θ = π/(N+1) ⟹ Δ_N = 0
# U_N(cos(π/(N+1))) = sin((N+1)·π/(N+1))/sin(π/(N+1)) = sin(π)/sin(π/(N+1)) = 0
R["step1_quantization"] = {
    "量子化 δ_N = 2cos(π/(N+1))": "N 是 Chebyshev 截断层级",
    "Chebyshev 递推 Δ_{k+1}=δΔ_k−Δ_{k−1}": "只对【整数】k 定义（Δ_0,Δ_1,Δ_2,...是离散序列）",
    "截断 Δ_N = 0": "在【整数】N（U_N(cos(π/(N+1))) = sin(π)/sin(π/(N+1)) = 0）",
    "N 的本质（量子化来源）": "【整数】——是「零点数」/「层级」，不是连续参数",
}

# ---------------------------------------------------------------------------
# 2. 幂集来源：N = 2^7 = 128 是组合计数（整数）
# ---------------------------------------------------------------------------
# 两个 Z₂ → S₃，非平凡状态 7 = 2³−1，幂集 2^7 = 128
R["step2_powerset"] = {
    "7 = 2³−1": "两个 Z₂ → S₃ 的非平凡状态数（3 个 qubit 的状态数，整数）",
    "幂集 2^7 = 128": "7 个独立二分的做/不做组合数（组合计数，整数）",
    "N 的本质（幂集来源）": "【整数】——是「子集数」/「组合数」，不是连续参数",
}

# 数值验证：2^7 = 128 是整数，2^7.72 无组合意义
R["step2_check"] = {
    "2^7 = 128（整数）": 2**7,
    "2^127.72 有意义吗": "无组合意义——幂集只对整数个元素定义（2^k 的 k 是整数）",
    "2^7.72 ≈": round(float(2**127.72), 1),
}

# ---------------------------------------------------------------------------
# 3. λ_mod(N) 公式：连续 N 有意义吗？
# ---------------------------------------------------------------------------
# λ_mod(N) = log(N²/π²) − log(ln(2N²/π²)) 是 N 的连续函数（数学上）
# 但 N 在框架里是「层级」（整数），连续 N 是数学延拓，非物理
def lam_mod(N):
    return np.log(N**2 / np.pi**2) - np.log(np.log(2 * N**2 / np.pi**2))

R["step3_continuous_N"] = {
    "λ_mod(N) 公式对连续 N 有意义吗（数学）": "是——log/ln 对任何 N>0 定义，是连续函数",
    "但框架的 N 是连续还是离散": "【离散】——N 是「层级」（Chebyshev 零点数 / 幂集大小），只对整数有意义",
    "反解 N=127.72 的性质": "用「连续公式」反解「离散 N」，是【连续近似离散】，不是「N 本质连续」",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["step4_honest_conclusion"] = {
    "N 本质是连续还是离散": "【离散】——N 是「层级」，两个来源都是整数（Chebyshev 零点数 / 幂集 2^7）",
    "λ_mod(N) 公式连续有意义吗": "数学上连续，但【框架的 N 物理上离散】——连续 N 是数学延拓，非物理",
    "一元论翻转的 N=127.72": "是「连续近似离散」，不是「N 本质连续」——所以识别①【保留】",
    "判据对应": "N 必须整数（离散）→ 需要「128=2^7」的结构推导（识别① 保留，未消除）",
    "128=2^7 的状态（补二十）": "幂集 2^7=128 是【严格】（组合计数），但「N=组合数 128 而非基本数 7」是【识别】",
}

report(R, "exp_N_continuous_discrete")
