"""
远景线 5（质量谱）· 中微子 40.7 meV 张力 v2：40.7 对应哪个本征态 + Δm²₂₁ 的隐藏张力

承接 exp_neutrino_tension（只算了 Δm²₃₁ 的 23% 张力）。本脚本推进：seesaw 的
40.7 meV 是「单个质量标度」没分代，而「代际比 = 207」是相对预言。把「代际比 207/16.8」
应用到中微子，40.7 meV 对应哪个本征态，决定了 Δm²₃₁ 和 Δm²₂₁ 的预测。

三种排序假设（40.7 = m₃ / m₂ / m₁），算每个的 Δm²₃₁、Δm²₂₁，对比观测：
  - 轻子代际比：m_e:m_μ:m_τ = 1:207:3477，即 m₂/m₁=207, m₃/m₂=16.8, m₃/m₁=3477
  - 观测（PDG 2024 正序）：Δm²₂₁=7.41e-5 eV², Δm²₃₁=2.511e-3 eV²

关键发现（预期）：Δm²₂₁ 的张力可能比 Δm²₃₁ 更严重——「代际比 207」要求
m₃/m₂=16.8，而观测 Δm²₂₁ 要求 m₂≈8.6 meV，于是 m₃≈144 meV，远大于 seesaw 的 40.7。
"""
import numpy as np
from experiments._common import report

R = {}

# 常数（PDG 2024 正序 NO）
dm221 = 7.41e-5    # eV²（太阳）
dm231 = 2.511e-3   # eV²（大气）
m2_obs = np.sqrt(dm221) * 1000   # ≈ 8.6 meV（若 m₁ << m₂）
m3_obs = np.sqrt(dm231) * 1000   # ≈ 50.1 meV（若 m₁ << m₃）

# 轻子代际比（精确）
r12 = 206.768      # m₂/m₁
r23 = 16.817       # m₃/m₂
r13 = 3477.2       # m₃/m₁

mnu = 40.7  # seesaw 标度（meV）

R["constants"] = {
    "seesaw 标度 m_ν": f"{mnu} meV",
    "代际比 m₂/m₁=207, m₃/m₂=16.8, m₃/m₁=3477": [r12, r23, r13],
    "观测 Δm²₂₁": f"{dm221} eV² → m₂≈{m2_obs:.1f} meV",
    "观测 Δm²₃₁": f"{dm231} eV² → m₃≈{m3_obs:.1f} meV",
}

# ---------------------------------------------------------------------------
# 三种排序假设：40.7 = m₃ / m₂ / m₁
# ---------------------------------------------------------------------------
def predict(assign):
    """assign = 40.7 meV 对应哪个本征态，返回 (m1,m2,m3) in meV"""
    if assign == "m3":
        m3 = mnu; m2 = mnu / r23; m1 = mnu / r13
    elif assign == "m2":
        m2 = mnu; m1 = mnu / r12; m3 = mnu * r23
    elif assign == "m1":
        m1 = mnu; m2 = mnu * r12; m3 = mnu * r13
    return m1, m2, m3

def dmsq(m1, m2, m3):
    """返回 Δm²₃₁, Δm²₂₁ in eV²（meV² -> eV² ×1e-6）"""
    return (m3**2 - m1**2) * 1e-6, (m2**2 - m1**2) * 1e-6

for assign in ["m3", "m2", "m1"]:
    m1, m2, m3 = predict(assign)
    dm31_pred, dm21_pred = dmsq(m1, m2, m3)
    R[f"hypothesis_{assign}"] = {
        "本征态 (m₁,m₂,m₃) meV": [round(m1, 4), round(m2, 3), round(m3, 2)],
        "Δm²₃₁ 预测": f"{dm31_pred:.3e} eV²（观测 {dm231:.3e}，比值 {dm31_pred/dm231:.3f}）",
        "Δm²₂₁ 预测": f"{dm21_pred:.3e} eV²（观测 {dm221:.3e}，比值 {dm21_pred/dm221:.3f}）",
    }

# ---------------------------------------------------------------------------
# 核心：唯一合理排序（40.7=m₃）的 Δm²₂₁ 张力
# ---------------------------------------------------------------------------
m1, m2, m3 = predict("m3")
dm31_pred, dm21_pred = dmsq(m1, m2, m3)
R["core_tension"] = {
    "唯一合理排序": "40.7 = m₃（m₃=40.7, m₂=2.42, m₁=0.012 meV）——其他排序 Δm² 差几十~几百倍，荒谬",
    "Δm²₃₁ 张力": f"预测 {dm31_pred:.3e} vs 观测 {dm231:.3e}，差 {dm231/dm31_pred:.2f} 倍（= m₃ 差 23%，这是旧张力）",
    "Δm²₂₁ 张力（隐藏，更严重）": f"预测 {dm21_pred:.3e} vs 观测 {dm221:.3e}，差 {dm221/dm21_pred:.2f} 倍（= m₂ 差 {np.sqrt(dm221/dm21_pred):.1f} 倍）",
    "Δm²₂₁ 的物理含义": f"「代际比 207」要求 m₃/m₂=16.8，而观测 Δm²₂₁ 要求 m₂≈{m2_obs:.1f} meV → m₃=16.8×{m2_obs:.1f}={m2_obs*r23:.0f} meV，远大于 seesaw 的 40.7 meV",
}

# ---------------------------------------------------------------------------
# 反解：要同时对上 Δm²₃₁ 和 Δm²₂₁，代际比应该是多少？
# ---------------------------------------------------------------------------
# 观测 Δm² 反推：若 m₁≈0，则 m₂≈√Δm²₂₁，m₃≈√Δm²₃₁
# 观测的代际比 m₃/m₂ = √(Δm²₃₁/Δm²₂₁)
r23_obs = np.sqrt(dm231 / dm221)
R["what_ratio_matches"] = {
    "观测反推的代际比 m₃/m₂ = √(Δm²₃₁/Δm²₂₁)": round(r23_obs, 2),
    "框架代际比 m₃/m₂ = 16.8": r23,
    "矛盾": f"观测要求 m₃/m₂≈{r23_obs:.1f}，框架给 16.8——差 {r23/r23_obs:.2f} 倍。即中微子的代际比【不是】轻子的 16.8",
}

# ---------------------------------------------------------------------------
# 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "核心新发现": "「中微子=207 真预言」若成立（代际比=207/16.8），会和 Δm²₂₁ 严重冲突（12.6 倍，m₂ 差 3.6 倍）——这比旧张力 Δm²₃₁（23%）严重得多",
    "旧张力（Δm²₃₁）": "40.7 vs 50.1 meV，差 23%（只算 m₃，漏了 m₂）",
    "新张力（Δm²₂₁）": "代际比 16.8 要求 m₂=2.42 meV，观测 Δm²₂₁ 要求 m₂≈8.6 meV，差 3.6 倍（m² 差 12.6 倍）",
    "代际比的内在矛盾": "观测反推 m₃/m₂≈5.8，框架代际比给 16.8——中微子的代际比【不是】轻子的 16.8。所以「中微子=207」这个真预言，和现有 Δm²₂₁ 数据已经冲突（不需等 JUNO/DUNE）",
    "三种出路的更新": "① 40.7 不对应 m₃——已排除（其他排序荒谬）；② Y_ν≠1——只救 Δm²₃₁（50/40.7），救不了 Δm²₂₁（12.6 倍）；③ N≠128——同样只救 m₃ 的绝对值，救不了 m₂/m₃ 的代际比。所以真正的出路是：中微子代际比 ≠ 207（需新的代结构，挂缺口 14 味结构）",
    "三档措辞": "「40.7 对应 m₃」=【唯一合理排序】；「Δm²₃₁ 差 23%」=【旧张力，可 Y_ν/N 修正】；「Δm²₂₁ 差 12.6 倍」=【新张力，代际比 207 的内在矛盾，Y_ν/N 救不了】——「中微子=207」和 Δm²₂₁ 数据【冲突】，不是【否证】（因为中微子代际比未测，可能是代结构不同）",
}

report(R, "exp_neutrino_tension_v2")
