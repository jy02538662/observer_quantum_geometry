"""
缺口 15 · N=128 形式化 /「7 个可观察量的结果空间维数」—— 精确算「信息独立」

问题（承接 exp_gap15_observer_independence）：7 个可观察量（Γ,K,s,ΓK,Γs,Ks,ΓKs）的
「结果空间」维数是多少？

  - 结果空间 = 2⁷（7 个值独立）→ 观察层独立严格（7 个可观察量给 7 个独立比特）
  - 结果空间 = 2³（只有 3 个独立值）→ N=128 的来源是「选择空间」（观察者选择测哪些），
    不是「结果空间」，需要论证「选择」的合法性

上一个脚本（step4）已经定性说「结果空间 2³」，但那是「本征值由 3 独立变量决定」的断言。
本脚本把它算成「信息独立」的精确量：7 个测量结果的联合分布，独立比特数是多少。

方法：
  1. 3 个生成元 (γ,κ,σ) ∈ {±1}³，共 8 种，等概率（无偏好）；
  2. 7 个可观察量的结果 = 3 个生成元的乘积（Γ→γ, K→κ, s→σ, ΓK→γκ, ...）；
  3. 枚举 8 种 (γ,κ,σ)，得到 8 组「7 元组结果」，看有多少种不同（结果空间大小）；
  4. 算 7 个结果的联合熵 H(X₁...X₇) = 独立比特数。

判据：
  - 结果空间 2⁷ = 128、联合熵 7 比特 → 观察层独立严格；
  - 结果空间 2³ = 8、联合熵 3 比特 → 需要「选择空间」作为 N=128 来源，需论证。
"""
import itertools
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. 3 个生成元 (γ,κ,σ) ∈ {±1}³，8 种组合（等概率，无偏好）
# ---------------------------------------------------------------------------
vals = [+1, -1]
gen_combos = list(itertools.product(vals, repeat=3))   # 8 种 (γ,κ,σ)
R["step1_generators"] = {
    "3 生成元 (γ,κ,σ) ∈ {±1}³": f"{len(gen_combos)} 种组合（等概率，无偏好）",
    "说明": "γ,κ,σ 是 3 个独立比特，联合空间 2³=8",
}

# ---------------------------------------------------------------------------
# 2. 7 个可观察量的结果 = 3 个生成元的乘积
#    顺序：Γ, K, s, ΓK, Γs, Ks, ΓKs
# ---------------------------------------------------------------------------
def seven_results(gk):
    gamma, kappa, sigma = gk
    return (
        gamma,            # Γ
        kappa,            # K
        sigma,            # s
        gamma * kappa,    # ΓK
        gamma * sigma,    # Γs
        kappa * sigma,    # Ks
        gamma * kappa * sigma,  # ΓKs
    )

all_results = [seven_results(gk) for gk in gen_combos]
unique_results = set(all_results)

R["step2_results"] = {
    "7 可观察量结果公式": "Γ→γ, K→κ, s→σ, ΓK→γκ, Γs→γσ, Ks→κσ, ΓKs→γκσ",
    "8 种 (γ,κ,σ) 生成的 7 元组结果": [list(r) for r in all_results],
    "不同的 7 元组数": len(unique_results),
}

# ---------------------------------------------------------------------------
# 3. 结果空间维数：8 种 (γ,κ,σ) → 多少种不同的 7 元组结果？
#    如果 7 个结果独立，8 种 (γ,κ,σ) 应该给 8 种，但 7 元组结果的空间是 2⁷=128
#    如果 7 个结果不独立（由 3 变量决定），结果空间 = 2³=8
# ---------------------------------------------------------------------------
result_space = len(unique_results)
R["step3_result_space"] = {
    "结果空间大小": result_space,
    "对比 2⁷=128": 128,
    "对比 2³=8": 8,
    "结论": f"结果空间 = {result_space} = 2³，不是 2⁷ —— 7 个结果【不独立】，由 3 个生成元决定",
}

# ---------------------------------------------------------------------------
# 4. 信息独立：7 个结果的联合熵 = 独立比特数
#    联合熵 H = -Σ p log2 p，8 种结果等概率 p=1/8
# ---------------------------------------------------------------------------
p = 1.0 / len(gen_combos)
joint_entropy = -sum(p * np.log2(p) for _ in gen_combos)

# 单个结果的边际熵（每个对合 ±1 等概率）= 1 比特
single_entropy = 1.0

# 7 个结果的总边际熵（如果独立）= 7 比特
independent_entropy = 7.0

R["step4_information"] = {
    "联合熵 H(X₁...X₇)": f"{joint_entropy:.4f} 比特",
    "如果 7 个独立（7 比特）": independent_entropy,
    "冗余 = 7 - H": f"{independent_entropy - joint_entropy:.4f} 比特",
    "结论": f"7 个测量结果只携带 {joint_entropy:.0f} 个独立比特（= 3 个生成元），冗余 4 比特（ΓK,Γs,Ks,ΓKs 由前 3 个决定）",
}

# ---------------------------------------------------------------------------
# 5. 逐个可观察量的「新增信息」（条件熵）—— 证明后 4 个是冗余
# ---------------------------------------------------------------------------
# 用互信息或条件熵：给定前 k 个结果，第 k+1 个是否提供新信息
# 简单版：每个结果能否由前 3 个（γ,κ,σ）决定
def depends_on_generators(result, gk):
    """7 元组结果是否完全由 (γ,κ,σ) 决定（即后 4 个 = 前 3 个的乘积）"""
    gamma, kappa, sigma = gk
    expected = seven_results(gk)
    return result == expected

# 验证：每个 7 元组结果，其后 4 个分量由前 3 个分量决定
redundancy_check = []
for r in all_results:
    g, k, sg = r[0], r[1], r[2]   # 前 3 个 = γ,κ,σ
    # 后 4 个应该是 gk, gσ, kσ, gkσ
    redundant = (r[3] == g*k, r[4] == g*sg, r[5] == k*sg, r[6] == g*k*sg)
    redundancy_check.append(all(redundant))

R["step5_redundancy"] = {
    "后 4 个结果（ΓK,Γs,Ks,ΓKs）由前 3 个（γ,κ,σ）决定": bool(all(redundancy_check)),
    "结论": "7 个可观察量里，只有 3 个（Γ,K,s）是信息独立的，后 4 个是它们的乘积（冗余）",
}

# ---------------------------------------------------------------------------
# 6. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "结果空间维数": f"2³ = {result_space}（不是 2⁷ = 128）",
    "信息独立比特数": "3（γ,κ,σ），不是 7",
    "对「观察层独立」的影响": "【结果空间 = 2³】→ 7 个可观察量只给 3 个独立结果，不能从「结果」推出 2⁷=128。N=128 的来源必须是「选择空间」（观察者选择测哪些可观察量的 2⁷ 种组合），不是「结果空间」",
    "剩余卡点（更精确了）": "「选择空间 2⁷」的合法性 = 「观察者独立选择测量/不测量每个可观察量」的合法性——这是「观察=有向区分」的诠释（区分可独立作用于每个可观察量），还是「新公设」（观察者自由选择测量）？需要论证",
    "三档措辞": "「结果空间=2³」=【严格（信息独立=3 比特）】；「选择空间=2⁷」=【组合计数】；「观察者独立选择」=【候选（诠释，待论证）】",
    "和上一个脚本的关系": "上一个脚本证明了「HS 正交 7 ≠ 独立本征值 3」，本脚本进一步算清「结果空间=2³（信息独立 3 比特）」，所以 N=128 的来源【只能是选择空间】，不能是结果空间——剩余卡点收窄为「选择」的合法性论证",
}

report(R, "exp_gap15_result_space")
