"""
攻付费桥2 三条路 · 路A：真空长程关联 G₀ 能否给「质量层级」

背景：路A = 用「真空长程关联 G₀」代替「局域 U」。已有 G₀ ~ 1/r^1.6（单体相干），
χ = −|G₀|² ~ 1/r^3.2（两体密度-密度关联）。

核心问题：V_eff = ρ G₀ ρ 的物理后果，能不能给「质量层级」（跨代质量比 207/577/19.8）？

判据（先结构后数）：区分「相互作用」和「质量」两个对象：
  - 相互作用（两体）= ρ G₀ ρ = 缺陷-缺陷，标度是「幂律」（1/r^α，长程）
  - 质量层级（单体，指数）= 跨代质量比 207，标度是「指数」（e^{λ_mod}，截断）
  两者机制不同：幂律（长程关联）≠ 指数（截断层级）。

本脚本算三件事：
  P1：G₀ 和 χ 的长程标度（幂次 α），确认是幂律不是指数。
  P2：V_eff = ρ G₀ ρ 的「求和/积分」标度（能量标度），看是「有限常数」还是「发散对数」。
  P3：幂律关联能否生成指数层级（对数标度 vs 指数标度），诚实判定「相互作用 ≠ 质量层级」。
"""
import numpy as np
from experiments._common import report

R = {}

# P1：长程标度（幂律 vs 指数）
# G₀ ~ 1/r^1.6（异子格，已坐实）；χ = −|G₀|² ~ 1/r^3.2
R["P1_scale"] = {
    "G₀（单体相干）标度": "~ 1/r^1.6（幂律，Dirac 半金属长程相干）",
    "χ（两体关联）标度": "~ 1/r^3.2 = |G₀|²（幂律，密度-密度）",
    "质量层级标度": "~ e^{λ_mod} ≈ 207（指数，来自观察者截断 λ_mod=log(N²/…)）",
    "判定": "G₀/χ 是幂律（1/r^α），质量层级是指数（e^λ）——两者标度不同，不是同一对象。",
}

# P2：V_eff 的求和标度（2D 里的长程关联求和）
# 2D 里，幂律 1/r^α 的求和：Σ_{r=1}^{R} (1/r^α) · (周长 2πr)
#   = 2π Σ r^{1-α}
#   α>2 → 收敛（有限常数）；α<2 → 发散（幂律/对数）
# G₀：α=1.6 <2 → 求和 ~ R^{2-α} = R^{0.4}（发散，但慢）
# χ：α=3.2 >2 → 求和收敛（有限）
def power_sum(alpha, R):
    """2D 里 Σ_{r=1}^R 2π r · r^{-α} = 2π Σ r^{1-α}"""
    rs = np.arange(1, R + 1, dtype=float)
    return float(2 * np.pi * np.sum(rs ** (1 - alpha)))

R["P2_sum_scale"] = {}
for alpha in [1.6, 2.0, 3.2]:
    vals = {f"R={R}": round(power_sum(alpha, R), 2) for R in [10, 100, 1000]}
    R["P2_sum_scale"][f"α={alpha}"] = vals

R["P2_judge"] = {
    "G₀（α=1.6）求和": "发散（R^{0.4}，慢发散）→ 长程相干求和发散，类似 2D 库仑的对数发散",
    "χ（α=3.2）求和": "收敛（有限常数）→ 密度-密度关联求和有限",
    "含义": "长程关联的『积分』给的是『能量标度』（有限或发散常数），不是『指数层级』（e^λ 跨数量级）。",
}

# P3：幂律能否生成指数层级
# 指数层级 e^λ 需要「对数标度」λ = log(比值)；幂律 1/r^α 给「代数标度」。
# 关键：一个「距离 r」在幂律里是 r^{-α}，在指数里是 e^{-λr}（有特征长度 λ）。
R["P3_power_vs_exponential"] = {
    "幂律 1/r^α": "无特征长度（尺度不变），长程但代数衰减",
    "指数 e^{-λr}": "有特征长度 1/λ，短程",
    "质量层级 e^{λ_mod}": "指数（截断），不是幂律",
    "判定": "幂律关联（无特征长度）给『长程相互作用』，给不了『指数质量层级』（需要特征长度/截断）。两者是正交的标度。",
}

R["honest_conclusion"] = {
    "路A 答案": "真空长程关联 G₀（幂律 1/r^1.6）给『长程相互作用』（两体，ρG₀ρ ~ χ ~ 1/r^3.2 排斥），给不了『质量层级』（指数，跨代比 207）。",
    "为什么": "① 对象不同：G₀ 是单体相干、χ 是两体关联，都是『相互作用』；质量层级是『单体 Yukawa 质量』的跨代比，是『质量』。② 标度不同：G₀/χ 是幂律（1/r^α，无特征长度），质量层级是指数（e^λ，来自截断）。幂律 ≠ 指数，两者正交。",
    "净判断": "路A 不成立——长程关联给相互作用，不给质量层级。『相互作用从哪来』（排斥=真空关联、吸引=软模）已解决，但『质量层级从哪来』（指数截断）是另一个问题，长程关联补不上。",
    "定位": "【未证实/存疑】档。V_eff=ρG₀ρ 是『两体相互作用』（已坐实 χ），不是『单体质量层级』。路A 澄清了『相互作用 ≠ 质量』这个区分，但没有解决 29.2（质量层级）。",
}

report(R, "exp_route_A_scale")
