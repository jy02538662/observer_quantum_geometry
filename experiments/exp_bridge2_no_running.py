"""
攻动力学缺口·检查「跑动 = 观察者态随尺度变化」的反着想（无绝对尺度 ⟹ 无跑动？）

评估指出：我把「跑动」预设成「β函数/圈图/多体」是旧范式。用户的反着想：
跑动 = 观察者态随尺度 λ 的变化（不是 β 函数的能标 μ）。

关键（先查，接尺度读出笔记 §9.1「β 跑动 G 放弃」）：
- 观察者态 ρ = C/λ 是「尺度不变」的：ρ(cλ) = C/(cλ) = ρ(λ)/c（只差归一化）；
- 「尺度不变」⟹「无绝对尺度」⟹「无特征尺度让耦合跑动」；
- 「跑动 g(μ)」需要「绝对能标 μ」，框架「无绝对尺度」⟹「无 μ」⟹「无跑动」。

本脚本坐实「尺度不变 ⟹ 无绝对尺度 ⟹ 无跑动」，诚实判断「跑动 = 观察者尺度变化」是否旧范式。
"""
import sympy as sp
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. 观察者态 ρ = C/λ 的尺度不变性
# ---------------------------------------------------------------------------
C, lam, c = sp.symbols('C lambda c', positive=True)
rho = C / lam                    # ρ(λ) = C/λ
rho_scaled = C / (c * lam)       # ρ(cλ) = C/(cλ)

# 尺度不变：ρ(cλ) = ρ(λ)/c（只差归一化因子 1/c）
R["step1_scale_invariance"] = {
    "ρ(λ) = C/λ": str(rho),
    "ρ(cλ) = C/(cλ)": str(rho_scaled),
    "ρ(cλ) = ρ(λ)/c（尺度不变，只差归一化）": bool(sp.simplify(rho_scaled - rho / c) == 0),
    "说明": "观察者态 ρ = C/λ 是「尺度不变」的（无绝对尺度，无偏好）",
}

# ---------------------------------------------------------------------------
# 2. 尺度不变 ⟹ 无绝对尺度 ⟹ 无跑动
# ---------------------------------------------------------------------------
R["step2_no_running"] = {
    "尺度不变": "ρ(cλ) = ρ(λ)/c（无偏好，无绝对尺度）",
    "无绝对尺度 ⟹": "无特征尺度（能标 μ）让耦合「跑动」",
    "跑动 g(μ) 需要绝对能标 μ": "框架无 μ（无绝对尺度）⟹ 无跑动",
    "对应尺度读出 §9.1": "「无绝对尺度 ⟹ Λ 标定输入不演化」⟹ β 跑动 G 放弃（同一个理由）",
}

# ---------------------------------------------------------------------------
# 3. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "「跑动 = 观察者尺度变化」是否旧范式": "是——它预设「有尺度（λ 或 μ）让耦合演化」，而框架的观察者态是「尺度不变」的（无绝对尺度），恰恰排除「跑动」",
    "框架的准确结论": "「无绝对尺度 ⟹ 无跑动」（G 常数、无 β 函数）——这是【结构预言】，不是【动力学缺口】",
    "修正我之前的话": "之前说「跑动卡 β 函数（动力学缺口）」是旧范式——正确是「无绝对尺度 ⟹ 原则上无跑动」，框架预言 G 常数（与 LLR |Ġ/G|~1e-13 一致）",
    "尺度读出 §9.1 的关系": "「β 跑动 G 放弃」的「符号硬冲突」其实是「无绝对尺度 ⟹ 无跑动」这个结构预言的表象——不是「尝试失败」，是「原则上无跑动」",
}

report(R, "exp_bridge2_no_running")
