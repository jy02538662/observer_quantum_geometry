"""
远景线 5（质量谱）· 深挖缺口1续二：π 磁通反对易的显式计算（从有向到 SU(2) 手征选择）

用户澄清（关键）：「无外部观察者」给「无偏好外部方向」，不是「无偏好方向」；
「观察=有向区分」本身带内部方向（箭头），宇称破缺来自这个内部箭头，不是外部偏好。
所以「宇称守恒 vs 破缺」的矛盾是假的。

本脚本做 π 磁通反对易的显式计算，检验「反对易方向」与「手征（二分）」的精确关系，
看「从有向到 SU(2) 只作用左手」这一步。
"""
import numpy as np
from sympy import Matrix, I, simplify
from experiments._common import report

R = {}

sx = Matrix([[0,1],[1,0]])
sy = Matrix([[0,-I],[I,0]])
sz = Matrix([[1,0],[0,-1]])
I2 = Matrix([[1,0],[0,1]])

# ---------------------------------------------------------------------------
# (1) π 磁通反对易：T_xT_y = -T_yT_x
# ---------------------------------------------------------------------------
# 磁平移 T_x = σ_x, T_y = σ_y（泡利，反对易）
Tx = sx
Ty = sy
anti = simplify(Tx*Ty + Ty*Tx)
# 反对易方向 σ_z = -iT_xT_y
sz_from = simplify(-I * Tx * Ty)

R["anticommutation"] = {
    "T_xT_y + T_yT_x = 0（反对易）": anti == Matrix.zeros(2),
    "σ_z = -iT_xT_y（反对易方向）": sz_from == sz,
    "反对易方向本征值 ±1": {str(k): v for k, v in sz.eigenvals().items()},
}

# ---------------------------------------------------------------------------
# (2) 手征 J = iσ_y（有向箭头），与反对易方向 σ_z 的关系
# ---------------------------------------------------------------------------
J = I * sy  # 手征（有向箭头，±i）
# σ_z 与 J 的反对易关系
anti_sz_J = simplify(sz * J + J * sz)  # σ_zJ + Jσ_z = 0？
R["opposite_direction"] = {
    "反对易方向 σ_z 与手征 J 反对易（σ_zJ = -Jσ_z）": anti_sz_J == Matrix.zeros(2),
    "含义": "反对易方向 σ_z（±1）和手征 J（±i）是「正交」的两个方向——反对易方向翻转手征",
}

# ---------------------------------------------------------------------------
# (3) 关键：反对易方向 σ_z 是「有向」的体现（翻转手征 = 带方向）
# ---------------------------------------------------------------------------
# σ_z 翻转手征 J（σ_zJ = -Jσ_z），即 σ_z 把 +i 态翻到 -i 态
# 这个「翻转」= 反对易方向的「方向性」= 有向区分的箭头
# 而「弱同位旋只作用左手」= SU(2) 只作用手征 +i 侧 = 反对易方向的「选择」
R["directionality"] = {
    "σ_z 翻转手征（σ_zJ=-Jσ_z）": "反对易方向带「方向」（翻转 ±i）",
    "关键": "反对易 T_xT_y=-T_yT_x 的「方向」（σ_z 翻转手征）就是「有向」的显式——宇称破缺（手征选择）来自这个内部方向，不是外部偏好",
}

# ---------------------------------------------------------------------------
# (4) 显式检验：σ_z 在 J 的 ±i 本征基下的作用（手征选择）
# ---------------------------------------------------------------------------
# J = iσ_y 的本征向量 |+i⟩=(1,i)/√2, |-i⟩=(1,-i)/√2
plus_i = Matrix([1, I]) / (2**0.5)
minus_i = Matrix([1, -I]) / (2**0.5)
# σ_z 作用在 |+i⟩ 和 |-i⟩ 上
sz_plus = simplify(sz * plus_i)
sz_minus = simplify(sz * minus_i)
R["sigma_z_on_chirality"] = {
    "σ_z|+i⟩": str(sz_plus),
    "σ_z|-i⟩": str(sz_minus),
    "检验 σ_z 翻转 ±i（|+i⟩→|-i⟩ 型）": sz_plus == minus_i or sz_minus == plus_i,
    "含义": "反对易方向 σ_z 在 |+i⟩ 和 |-i⟩ 之间翻转——这是「手征选择」的显式（σ_z 把 +i 态翻到 -i 态）",
}

# ---------------------------------------------------------------------------
# (5) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实": "① 反对易 T_xT_y=-T_yT_x 的方向 σ_z=-iT_xT_y 翻转手征 J（σ_zJ=-Jσ_z）；② σ_z 在 |+i⟩/|-i⟩ 之间翻转——反对易方向带「方向」（手征翻转）",
    "用户澄清的印证": "「宇称破缺 = 手征选择 = 内部方向（反对易的箭头）」——反对易方向 σ_z 翻转手征，是「有向」的显式，不是「外部偏好」。宇称矛盾是假的",
    "从有向到 SU(2) 只作用左手的这一步": "反对易方向 σ_z 翻转手征（+i↔-i），但「只作用 +i 侧」（右手=0）还需要「选择 +i 侧」的机制（手征投影 P_L=|+i⟩⟨+i|）——这一步（从「翻转」到「只作用一侧」）还没坐实",
    "待坐实": "「翻转手征（σ_z 连接 ±i）」如何变成「只作用 +i 侧（σ_z 在 -i 侧=0）」——需要「手征投影 P_L」的框架来源（观察 +i 侧）",
    "措辞": "符号坐实（反对易方向翻转手征=有向）+ 印证澄清（宇称矛盾是假的）——但「只作用左手」的最后一步（翻转→选择）还没坐实",
}

report(R, "exp_pi_flux_chiral")
