"""
验证用户直觉：「掺杂 = λ_c/λ_min」+「N 随掺杂变 → Tc ∝ N → 穹顶」

用户想法：
  1. 掺杂 = λ_c/λ_min = 2N²/π²（「N 和 λ_c 的差」= 偏离经典极限）
  2. N 随掺杂变（未掺杂 N 小，最佳掺杂 N 大）→ Tc ∝ N → 穹顶（N 最大 = 128）

验证两个疑点：
  A. λ_c/λ_min = 2N²/π² 是大数还是小数？（「掺杂」应该是填充比例 0~1）
  B. N 到底固定不固定？（框架 N = 2^7 = 128，从三个 Z₂ 推出来）
"""
import numpy as np
from experiments._common import report

R = {}

# ---- A. λ_c/λ_min 的量级 ----
N = 128
lam_c = 2.0
lam_min = np.pi**2 / N**2
ratio_c_over_min = lam_c / lam_min          # = 2N²/π²
ratio_min_over_c = lam_min / lam_c          # = π²/(2N²)

R["A_ratio_magnitude"] = {
    "λ_c/λ_min = 2N²/π²": f"{ratio_c_over_min:.1f}",
    "λ_min/λ_c = π²/(2N²)": f"{ratio_min_over_c:.6f}",
    "「掺杂」物理上 = 填充比例（0~1，如铜氧化物 p≈0.16）": True,
    "结论": "λ_c/λ_min ≈ 3320 是大数（不是 0~1 的填充比例）；λ_min/λ_c ≈ 0.0003 是小量。用户写的「掺杂=λ_c/λ_min」= 大数，对不上「填充比例」。",
}

# ---- B. N 固定不固定 ----
# 框架：N = 2^7 = 128，来自「三个 Z₂」（每个 Z₂ 给 2 重，3 个 Z₂ → 2³=8？还是 2^7？）
# 对齐页/质量谱：N = 2^7 = 128（7 个独立二进制自由度）
R["B_N_fixed"] = {
    "框架 N": "N = 2^7 = 128（7 个独立二进制自由度，从量子化/三个 Z₂ 推出，是常数）",
    "N 是变量还是常数？": "常数——框架里 N=128 是固定值，不随掺杂变",
    "用户「N 随掺杂变」": "与框架矛盾——框架 N 固定，没有「N 随掺杂变」的机制",
}

# ---- C. 若「掺杂=观察者有限性」且 N、λ_c 都固定 → Tc 固定（无穹顶）----
# 候选 c：μ = Λ/√λ_c，λ_c=2 固定 → μ 固定 → Tc 固定
R["C_fixed_Tc"] = {
    "候选 c：μ = Λ/√λ_c，λ_c=2 固定": "μ = Λ/√2 = 0.707Λ（固定）",
    "Tc = μ/32": "0.707Λ/32（固定，不随掺杂变）",
    "矛盾": "铜氧化物 Tc 随掺杂变（穹顶 35K→133K→下降），但「掺杂=观察者有限性」（λ_c 固定）给固定 Tc，对不上穹顶",
}

R["conclusion"] = {
    "用户直觉的闪光点": "「Tc 穹顶」需要解释——这是对的，标准 BKT 给「Tc=min(T_BKT∝p, T_mf∝Δ)」的穹顶。",
    "但两步验证不过": "①「掺杂=λ_c/λ_min」=3320 大数（非填充比例 0~1）；② N=128 是框架固定常数，没有「N 随掺杂变」的机制。",
    "更深的矛盾": "若「掺杂=观察者有限性」且 λ_c=2 固定 → Tc 固定（无穹顶），对不上铜氧化物的穹顶——这比「没推出来」更严重：就算推出来，也解释不了穹顶。",
    "所以": "用户的「N 变 → 穹顶」是要给框架加一个「N 随掺杂变」的新机制，但这与框架的固定 N=128 矛盾。要么改框架（N 可变），要么承认「掺杂=观察者有限性」给固定 Tc（无穹顶），两者不能都要。",
}

report(R, "exp_superconducting_dome")
