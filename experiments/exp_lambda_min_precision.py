"""
质量谱选择点①精确化：2−δ_N 与 π²/N² 的关系精确到哪一阶

背景（对齐页补七 + 预印本 1.25 三合一）：
  补七说「λ_min 选 π²/N²（尺度破缺 2−δ_N）而非 3π²/N²（边缘间隔），选哪个无独立论证」。
  预印本 1.25 三合一说「质量 = m = Λ√(2−δ_N)，2−δ_N 是无量纲来源」，并诚实标注
  「质量那一项是近似（2−δ_N ≈ λ_min），光滑/黎曼是精确（= 2−δ_N）」。

本脚本精确化「2−δ_N 和 π²/N² 到底差多少」：
  δ_N = 2cos(π/(N+1))，2−δ_N = 2−2cos(π/(N+1)) = 4sin²(π/(2(N+1)))。
  精确展开（x = π/(N+1) 小量）：
    2−2cos(x) = x² − x⁴/12 + x⁶/360 − x⁸/20160 + ...
              = π²/(N+1)² − π⁴/(12(N+1)⁴) + π⁶/(360(N+1)⁶) − ...

要回答三个层次：
  1. 2−δ_N 的精确表达式（三角恒等式，精确）
  2. 2−δ_N vs π²/(N+1)²（预印本 1.25 的写法）：差 O(1/N⁴)
  3. 2−δ_N vs π²/N²（补七选择点①的写法）：差 O(1/N³)（因为 (N+1)⁻² 展开的领头修正 −2/N）
"""
import sympy as sp
from experiments._common import report

R = {}

N, x = sp.symbols("N x", positive=True)

# ---- 1. 精确表达式 ----
delta_N = 2 * sp.cos(sp.pi / (N + 1))
scale_break = 2 - delta_N                      # 2−δ_N
exact_form = 4 * sp.sin(sp.pi / (2 * (N + 1))) ** 2   # = 4sin²(π/(2(N+1)))
R["exact"] = {
    "2−δ_N = 2−2cos(π/(N+1))": str(scale_break),
    "= 4sin²(π/(2(N+1)))": str(exact_form),
    "三角恒等式精确成立 4sin²=2−2cos": str(sp.simplify(exact_form - scale_break) == 0),
}

# ---- 2. 大 N 级数展开（x=π/(N+1)，x→0）----
series_x = sp.series(2 - 2 * sp.cos(x), x, 0, 9)  # 展开到 x^8
R["series_x"] = {
    "2−2cos(x) 展开（x=π/(N+1)）": str(series_x),
    "解读": "x² − x⁴/12 + x⁶/360 − x⁸/20160 + O(x⁹)",
}

# 领头阶 π²/(N+1)²，下一阶 π⁴/(12(N+1)⁴)
lead_1 = sp.pi**2 / (N + 1) ** 2          # π²/(N+1)²
next_1 = sp.pi**4 / (12 * (N + 1) ** 4)   # π⁴/(12(N+1)⁴)
R["vs_Nplus1"] = {
    "2−δ_N − π²/(N+1)² 的领头修正": str(sp.series(scale_break - lead_1, sp.oo, 5)),
    "= −π⁴/(12(N+1)⁴) + O(1/N⁶)": True,
    "结论": "2−δ_N = π²/(N+1)² + O(1/N⁴)（预印本 1.25 写法，差下一阶 O(1/N⁴)）",
}

# ---- 3. vs π²/N²（补七选择点①的写法）----
lead_2 = sp.pi**2 / N**2                   # π²/N²
diff_N2 = sp.series(scale_break - lead_2, sp.oo, 5)
R["vs_N"] = {
    "2−δ_N − π²/N² 的领头修正": str(diff_N2),
    "解读": "π²/(N+1)² − π²/N² = π²·(1/(N+1)² − 1/N²) ≈ π²·(−2/N³) = −2π²/N³",
    "结论": "2−δ_N = π²/N² + O(1/N³)（补七写法，差 O(1/N³)，比 π²/(N+1)² 写法差一阶）",
}

# ---- 4. 数值：N=128 三个量的精确值 ----
def vals(N):
    db = 2 - 2 * sp.cos(sp.pi / (N + 1))
    p1 = sp.pi**2 / (N + 1)**2
    p2 = sp.pi**2 / N**2
    return db.evalf(15), p1.evalf(15), p2.evalf(15)

for NN in [16, 128]:
    db, p1, p2 = vals(NN)
    R[f"numeric_N={NN}"] = {
        "2−δ_N 精确值": f"{db:.10e}",
        "π²/(N+1)²": f"{p1:.10e}",
        "π²/N²": f"{p2:.10e}",
        "2−δ_N vs π²/(N+1)² 相对差": f"{float((db-p1)/db):.3e}",
        "2−δ_N vs π²/N² 相对差": f"{float((db-p2)/db):.3e}",
    }

# ---- 5. 结论：质量谱 λ_min 是「精确」还是「近似」----
R["conclusion"] = {
    "精确部分": "2−δ_N = 4sin²(π/(2(N+1))) = 2−2cos(π/(N+1)) 是精确恒等式（三角恒等式）",
    "近似部分": "质量谱里写 λ_min = π²/N² 是 2−δ_N 的「领头阶」，差 O(1/N³)；写 π²/(N+1)² 差 O(1/N⁴)",
    "预印本 1.25 的『近似 vs 精确』": "光滑/黎曼『精确 = 2−δ_N』（三角恒等式）；质量『近似 = λ_min = π²/N²』（只取 2−δ_N 的领头阶，丢掉 O(1/N³)）",
    "对补七措辞的意义": "选择点①『λ_min=π²/N²』的正确表述 = 『λ_min 是 2−δ_N 的领头阶近似（差 O(1/N³)），其结构来源是 2−δ_N（三合一的质量=尺度破缺），不是 3π²/N²（边缘间隔）』——即 λ_min 的选择点从『无独立论证』升级为『= 三合一质量项 2−δ_N 的领头阶』",
}

report(R, "exp_lambda_min_precision")
