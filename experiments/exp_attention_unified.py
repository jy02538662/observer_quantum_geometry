"""
验证「注意力」统一：ρ（态）、E 的秩（维度）、模流（时间）是不是同一个观察者的三面？

框架 OQG 三元组 (R, E, ρ)：
  ρ = C/λ（态，尺度不变 = 无偏好）
  E: R → D（条件期望，保迹，观察切割）
  模流 σ_t = ρ^{it} x ρ^{-it}（由 log ρ 生成）

关键关系：
  1. 模流由 log ρ 生成 ⟹ 模流是 ρ 的「动力学面」（时间 = 模流，框架已定）
  2. E 保迹：τ(E(x)) = τ(x)，态 ρ 由 τ(ρ·) 定义 ⟹ E 是 ρ 的「切割面」
  3. 所以 ρ / 模流 / E 是同一个「观察者」的三面（注意力 = 态）

验证：模流生成元 = log ρ（符号），E 保迹（= 态 ρ 的不动性）。
"""
import sympy as sp
from experiments._common import report

R = {}

# ---- 1. 模流由 log ρ 生成 ----
# 模流 σ_t(x) = ρ^{it} x ρ^{-it}，生成元是 [log ρ, ·]（Tomita-Takesaki）
# 对 ρ = C/λ（对角），log ρ = log C - log λ（对角）
lam = sp.symbols("lambda", positive=True)
C = sp.symbols("C", positive=True)
rho = C / lam
log_rho = sp.simplify(sp.log(rho))

R["modular_from_log_rho"] = {
    "ρ = C/λ（态，尺度不变）": str(rho),
    "log ρ = log C − log λ（模流生成元）": str(log_rho),
    "模流 = ρ 的动力学面（时间=模流，由 log ρ 生成）": True,
}

# ---- 2. E 保迹 = 态 ρ 的不动性 ----
# E 保迹 τ(E(x)) = τ(x)，态 ρ 定义为 τ(ρ·)（迹权）
# 所以 E 和 ρ 由同一个「迹 τ」联系 ⟹ E 是 ρ 的「切割面」
R["E_trace_preserving"] = {
    "E: R → D 保迹 τ(E(x))=τ(x)": "迹 τ 是态 ρ 的权（τ(ρ·)）",
    "E 保迹 ⟹ E 保 ρ 的迹结构": "E 是 ρ 的「切割面」（观察者能看到的维度 = E 的秩 = D 的维数）",
    "E 的秩 = 观察者看到的维度数": "= 态 ρ 的「分辨率面」",
}

# ---- 3. 结论：三个候选是同一个观察者的三面 ----
R["conclusion"] = {
    "ρ / 模流 / E 的关系": "ρ = 注意力（权重 C/λ）；模流 = 注意力的动力学（log ρ）；E 的秩 = 注意力的分辨率（D 的维数）。三者由 ρ（或迹 τ）统一。",
    "框架已有（一元论方法论）": "f/E（观察者态/截断两面）、N↔λ_c（有限性离散/连续两面）——ρ/E/模流 是同一个「观察者」的三面。",
    "所以 w(E) = ρ 统一": "「敏感度」权重 w(E) = 注意力 = ρ = C/λ（态），不是新对象，是已识别的「观察者态」。",
    "但诚实一点": "ρ = C/λ 是「无偏好」（尺度不变）。「掺杂/k」是「偏离无偏好」（有偏好）——所以 w(E)=ρ 给的是「无偏好」的注意力，掺杂的 w(E) 是「偏离 ρ」的有偏好注意力。",
}

report(R, "exp_attention_unified")
