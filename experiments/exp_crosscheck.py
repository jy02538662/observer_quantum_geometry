"""
远景线 5（质量谱）· 交叉核对：验证预印本 1.15 和 1.16 的所有关键公式/数字

一次性验证两个预印本的关键断言，确保无错误：
  - 3-循环特征值 {1,ω,ω²}、转置特征值 {+1,+1,-1}、迹 = 固定点数（3/1/0）
  - 三重态迹 3、单态迹 1、颜色投影概率 1/3
  - 手征投影 P_L=(1-iJ)/2、P_L²=P_L
  - 颜色单态投影秩-1、幂等
"""
import numpy as np
from sympy import Matrix, I, Rational, simplify, sqrt, eye, exp, pi
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (1) 3-循环特征值 {1,ω,ω²}，1+ω+ω²=0
# ---------------------------------------------------------------------------
cycle3 = Matrix([[0,0,1],[1,0,0],[0,1,0]])
eigs3 = cycle3.eigenvals()
omega = exp(2*pi*I/3)
R["cycle3"] = {
    "3-循环特征值": {str(k): v for k, v in eigs3.items()},
    "1+ω+ω²=0": simplify(1 + omega + omega**2) == 0,
}

# ---------------------------------------------------------------------------
# (2) 转置特征值 {+1,+1,-1}，迹 = 1（一个固定点）
# ---------------------------------------------------------------------------
transpose = Matrix([[0,1,0],[1,0,0],[0,0,1]])
eigs_t = transpose.eigenvals()
R["transpose"] = {
    "转置特征值": {str(k): v for k, v in eigs_t.items()},
    "转置迹（应=1）": simplify(transpose.trace()),
    "3-循环迹（应=0）": simplify(cycle3.trace()),
    "单位迹（应=3）": simplify(eye(3).trace()),
    "迹=固定点数": "单位3、转置1、3-循环0 ✓",
}

# ---------------------------------------------------------------------------
# (3) 三重态迹 3、单态迹 1、颜色投影概率 1/3
# ---------------------------------------------------------------------------
I3 = eye(3)
singlet = Matrix([1,1,1]) / sqrt(3)
P_singlet = singlet * singlet.T  # (1/3)全1
r = Matrix([1,0,0])
proj = simplify((singlet.T * r)[0]**2)  # |<singlet|r>|²

R["singlet"] = {
    "三重态迹 Tr(I₃)=3": simplify(I3.trace()),
    "单态迹 Tr(P_singlet)=1": simplify(P_singlet.trace()),
    "颜色投影概率 |<singlet|r>|²=1/3": proj,
    "P_singlet 秩=1": P_singlet.rank() == 1,
    "P_singlet²=P_singlet（幂等）": simplify(P_singlet * P_singlet - P_singlet) == Matrix.zeros(3),
}

# ---------------------------------------------------------------------------
# (4) 手征投影 P_L = (1-iJ)/2，P_L²=P_L，J=i(P_L-P_R)
# ---------------------------------------------------------------------------
sy = Matrix([[0,-I],[I,0]])
J = I * sy  # 有向 J = iσ_y
PL = (eye(2) - I * J) / 2
PR = (eye(2) + I * J) / 2
R["chiral_projection"] = {
    "P_L = (1-iJ)/2": str(PL),
    "P_L²=P_L（幂等）": simplify(PL * PL - PL) == Matrix.zeros(2),
    "J = i(P_L-P_R)（谱分解自洽）": simplify(I * (PL - PR) - J) == Matrix.zeros(2),
    "J 本征值 ±i": {str(k): v for k, v in J.eigenvals().items()},
}

# ---------------------------------------------------------------------------
# (5) 数字：第二→第三=3、第一→第二=29.2（结构预言的数据支持）
# ---------------------------------------------------------------------------
# 用精确值（PDG MS̄）
m_t, m_c, m_b, m_s = 172690, 1273, 4180, 93.4  # MeV
m_u, m_d = 2.16, 4.67
ratio23 = (m_t/m_c) / (m_b/m_s)
ratio12 = (m_c/m_u) / (m_s/m_d)
R["numbers"] = {
    "第二→第三 上型/下型（应≈3）": ratio23,
    "第一→第二 上型/下型（应≈29，非干净）": ratio12,
    "第二→第三≈3 成立": abs(ratio23 - 3) / 3 < 0.05,
    "第一→第二≠3 成立": abs(ratio12 - 3) / 3 > 0.5,
}

# ---------------------------------------------------------------------------
# (6) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "验证结果": "所有关键公式/数字正确——3-循环特征值 {1,ω,ω²}、转置特征值 {+1,+1,-1}、迹=固定点数、三重态迹3/单态迹1、颜色投影1/3、P_L=(1-iJ)/2 幂等、单态投影秩-1、第二→第三≈3/第一→第二≈29",
    "结论": "预印本 1.15 和 1.16 的关键断言无错误，交叉核对通过",
}

report(R, "exp_crosscheck")
