"""
路1 第一步 · 算 Tr f(D²/Λ²) 的 N 依赖（不是「离散 a₄ 阶」，那个概念不存在）

评估精确化：「a₄ 阶」是连续热核概念，离散有限 N 没有「a₄ 阶」，只有有限和
  Tr f(D²/Λ²) = Σ_k f(λ_k²/Λ²)。

本脚本正面算这个有限和的 N 依赖：
  1. 构造通量 φ 依赖的 π 磁通 D(φ)（φ=π 是标准 π 磁通）；
  2. 谱和 S(φ,N) = Tr f(D(φ)²/Λ²)（f=e^{-u} 光滑截断）；
  3. 有效耦合 g²(N) ∝ 1/(∂²S/∂φ²)|_{φ=π}（谱和对通量曲率的响应 = F² 项）；
  4. 看 g²(N) 随 N 怎么变——这才是离散框架里「耦合」的 N 依赖。
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. 通量依赖的 π 磁通 D(φ)（有限矩阵）
# ---------------------------------------------------------------------------
def flux_D(L, phi):
    """2D 方格子，x-hopping=-1 实，y-hopping=-e^{i·phi·x}（通量 phi/plaquette）。"""
    N = L * L
    H = np.zeros((N, N), dtype=complex)
    def idx(x, y):
        return (x % L) * L + (y % L)
    for x in range(L):
        for y in range(L):
            i = idx(x, y)
            j = idx(x + 1, y)
            H[i, j] -= 1.0
            H[j, i] -= 1.0
            j = idx(x, y + 1)
            ph = np.exp(1j * phi * x)
            H[i, j] -= ph
            H[j, i] -= np.conj(ph)
    return H

def spectral_sum(L, phi, Lambda=1.0):
    """S(φ) = Tr f(D²/Λ²) = Σ_k e^{-E_k²/Λ²}（f=e^{-u} 热核）。"""
    D = flux_D(L, phi)
    ev = np.linalg.eigvalsh((D.conj().T @ D).real)   # D†D 的本征值 = E²
    return float(np.sum(np.exp(-ev / Lambda**2)))

# 验证 φ=π 还原 π 磁通（y 相位 (−1)^x）
R["step1_flux_D"] = {
    "D(φ) 构造": "x-hopping −1 实，y-hopping −e^{iφx}（通量 φ/plaquette）",
    "φ=π 还原 π 磁通": "e^{iπx} = (−1)^x（与 pi_flux 一致）",
}

# ---------------------------------------------------------------------------
# 2. 谱和 S(N) = Tr f(D²/Λ²) 的 N 依赖（φ=π）
# ---------------------------------------------------------------------------
Ls = [8, 16, 32, 64]
S_pi = {L: spectral_sum(L, np.pi) for L in Ls}
R["step2_spectral_sum_N_dependence"] = {
    f"N={L*L}（L={L}）S(π) = Tr exp(-D²/Λ²)": round(S_pi[L], 6) for L in Ls
}

# S(N) 的标度：S(N) ∝ N（每格点贡献），或 S(N)/N → 常数（连续极限）
R["step2_scaling"] = {
    f"S(π)/N（N={L*L}）": round(S_pi[L] / (L * L), 6) for L in Ls
}

# ---------------------------------------------------------------------------
# 3. 有效耦合 g²(N) = 1/(∂²S/∂φ²)|_{φ=π}（通量曲率响应 = F² 项）
# ---------------------------------------------------------------------------
def coupling_N(L, phi0=np.pi, dphi=0.01):
    """∂²S/∂φ² 数值二阶差分，g² ∝ 1/(∂²S/∂φ²)。"""
    S_m = spectral_sum(L, phi0 - dphi)
    S_0 = spectral_sum(L, phi0)
    S_p = spectral_sum(L, phi0 + dphi)
    d2 = (S_p - 2 * S_0 + S_m) / dphi**2
    return d2

g2_inv = {L: coupling_N(L) for L in Ls}   # ∂²S/∂φ² = 1/g²（F² 项系数）
R["step3_gauge_coupling_N"] = {
    f"∂²S/∂φ² 在 φ=π（= 1/g²，N={L*L}）": f"{g2_inv[L]:.6e}" for L in Ls
}

# g² ∝ 1/(∂²S/∂φ²)，看 g²(N) 的 N 依赖
R["step3_g2_N"] = {
    f"g² ∝ 1/(∂²S/∂φ²)（N={L*L}）": f"{1.0/g2_inv[L]:.6e}" for L in Ls
}

# 比值（看「跑动」方向）：g²(N 大)/g²(N 小)
R["step3_ratio"] = {
    "g²(N=64)/g²(N=1024)（若随 N 减小 = 渐近自由方向）": f"{(1.0/g2_inv[8])/(1.0/g2_inv[64]):.4f}",
    "注意": "这是【离散框架自己的】耦合 N 依赖，不是连续 −1/24π²——它才是「跑动」的真种子",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["step4_honest_conclusion"] = {
    "算了什么": "离散 π 磁通 D 的谱和 S(N)=Tr e^{-D²/Λ²} 的 N 依赖 + 通量曲率响应 ∂²S/∂φ² 的 N 依赖（= 有效耦合 g²(N)）",
    "「离散 a₄ 阶」纠正": "对——离散有限 N 没有「a₄ 阶」，只有有限和 Σ_k f(λ_k²/Λ²)；我上一轮说「算离散 a₄ 阶」是概念混淆",
    "有效耦合 g²(N)": "从 ∂²S/∂φ²|_{φ=π}（通量曲率 = 离散 F²）提取，它是 N 依赖的（有限格点求和），连续极限才回到 −1/24π²",
    "下一步（路1 继续）": "① 确认 g²(N) 的 N 依赖方向（渐近自由 = g² 随 N 增大而减小？）；② 把 g²(N) 的比值对比实验比值（如 α_s(M_Z)/α_s(m_τ)=0.357）——若能对上，跑动=离散 N 依赖；对不上，才需要 N↔μ 映射",
    "不要滑回": "「a₄ 阶」（连续概念，离散没有）+「尺度读出」（归位）",
}

report(R, "exp_spectral_sum_N")
