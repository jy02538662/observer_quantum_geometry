eigs2 = rot.eigenvals()
R["up_down_standard_2d"] = {
    "3-循环在标准2维表示（上下型载体）的矩阵": "[[-1/2,-√3/2],[√3/2,-1/2]]（120°旋转）",
    "特征值": {str(k): v for k, v in eigs2.items()},
    "应为 {ω, ω²}": "ω=e^(2πi/3) 和 ω²=e^(-2πi/3)",
    "验证 det": float(rot.det()),
    "意义": "上下型 = 标准 2 维表示的两个复特征向量（特征值 ω vs ω²），3-循环(颜色循环)作用后各带 ±120° 相位",
}

# ---------------------------------------------------------------------------
# (4) 「3」只在阶 3 出现的结构判据
# ---------------------------------------------------------------------------
