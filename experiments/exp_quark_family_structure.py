# 第一→第二代际比涉及「e(阶1)→转置(阶2)」：阶 2 = 转置 = 反射，无 3-循环 → 不带「3」
R["why_only_order3"] = {
    "第一→第二代（阶1→2）": "转置=反射（号差面，±i），无 3-循环/颜色循环 → 上下型比值无「3」（实测 29.2，非 3）",
    "第二→第三代（阶2→3）": "3-循环=120°旋转=颜色循环（3 个颜色循环置换）→ 上下型比值 =「3」（实测 3.03）",
    "判据": "「3」= 颜色循环，只在「阶 3」的跃迁（第二→第三代）出现，不在「阶 2」的跃迁（第一→第二代）出现——与「颜色三和代三是同一 S₃ 两面」自洽",
}

# ---------------------------------------------------------------------------
