"""
缺口 2（上型不对称「除以 3」）· 卡点精确定位：从「朝向 ±i」到「因子 3 vs 1」的显式算子

用户诊断卡点：为什么 +i 看到 3 条河、-i 只看到 1 条。四个建议逐一检验：
  建议 1（谱投影秩）：J_3 的 ±i,0 谱投影都是秩 1，给不出 3 vs 1（排除）。
  建议 2（P_full vs P_singlet）：是「识别」（§20-22 已坐实），非新推导。
  建议 3（条件期望 E 的秩）：框架好，但「+i↔id、-i↔P_singlet」仍是识别。
  建议 4（迹 = 不动点数）：S₃ 单位元迹 3、转置迹 1、3-循环迹 0，最接近群论突破口。

本脚本做两件事：
  A. 坐实 S₃ 在颜色置换表示的「迹 = 不动点数」= {3,1,0}。
  B. 厘清「3」的三个来源（3-循环周期 / 单位元迹 / 三重态迹），确认哪个是「除以 3」的正确来源。
"""
import numpy as np
from sympy import Matrix, I, Rational, simplify, sqrt, exp, pi
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (A) S₃ 在颜色置换表示（3 维）的迹 = 不动点数
# ---------------------------------------------------------------------------
# 颜色基 {r, g, b}。S₃ = {e, (12), (13), (23), (123), (132)}
e    = Matrix([[1,0,0],[0,1,0],[0,0,1]])   # 单位元
s12  = Matrix([[0,1,0],[1,0,0],[0,0,1]])   # 转置 (12)：r<->g，固定 b
s123 = Matrix([[0,1,0],[0,0,1],[1,0,0]])   # 3-循环 (123)：r->g->b->r

R["S3_traces"] = {
    "单位元 e 迹（不动点 3）": e.trace(),
    "转置 (12) 迹（不动点 1）": s12.trace(),
    "3-循环 (123) 迹（不动点 0）": s123.trace(),
    "迹 = 不动点数": "单位元 3 / 转置 1 / 3-循环 0",
}

# ---------------------------------------------------------------------------
# (B) 厘清「3」的三个来源
# ---------------------------------------------------------------------------
# 来源 1：3-循环的周期（转 3 次回原点）
omega = exp(I * Rational(2, 3) * pi)   # ω = e^{2πi/3}
R["source_3_cycle_period"] = {
    "3-循环 (123)³ = e": str(simplify(s123**3)),
    "周期 = 3": "3-循环转 3 次回原点",
}

# 来源 2：单位元的迹 = 颜色维数 3
R["source_identity_trace"] = {
    "单位元迹 = 3": "= 颜色置换表示维数 3 = 三重态维数",
}

# 来源 3：三重态迹 Tr(I₃) = 3
I3 = Matrix.eye(3)
singlet = Matrix([1,1,1]) / sqrt(3)
P_singlet = singlet * singlet.T
R["source_triplet_trace"] = {
    "Tr(I₃)（三重态）": simplify(I3.trace()),
    "Tr(P_singlet)（单态）": simplify(P_singlet.trace()),
    "比值 = 3": "三重态迹 3 ÷ 单态迹 1 = 3",
}

# ---------------------------------------------------------------------------
# (C) 关键对照：三个「3」的关系 + 上型/下型的对应
# ---------------------------------------------------------------------------
# 框架 §1.3：上型 = ω、下型 = ω²（3-循环在标准 2 维表示的特征值）
# 3-循环在 3 维置换表示的特征值 = {1, ω, ω²}
ev123 = s123.eigenvals()
R["up_down_vs_S3_elements"] = {
    "3-循环特征值 {1, ω, ω²}": {str(k): v for k, v in ev123.items()},
    "1 = 平凡（单态）": "标准模型上下型之外的单态方向",
    "ω, ω² = 标准 2 维（上下型）": "上型 = ω（+旋转）、下型 = ω²（-旋转）",
    "注意": "上型/下型 = 3-循环的 ω/ω² 特征值，不是「单位元/转置」——建议 4 的「上型=单位元、下型=转置」映射与 §1.3 不一致",
}

# ---------------------------------------------------------------------------
# (D) 转置的不动点 b vs 单态 (r+g+b)/√3（建议 4 的潜在混淆）
# ---------------------------------------------------------------------------
# 转置 (12) 的不动点 = b（本征值 1 的本征矢）
ev12 = s12.eigenvects()
# 单态 = (r+g+b)/√3
R["transposition_fixed_point_vs_singlet"] = {
    "转置 (12) 不动点": "b = (0,0,1)（超荷方向，λ₈ 负本征值）",
    "单态 (r+g+b)/√3": "SU(3) 完全对称（S₃ 平凡表示）",
    "关键区别": "转置不动点 b ≠ 单态 (r+g+b)/√3——两者都是 1 维，但方向不同",
    "建议 4 的细微问题": "「下型=转置（迹1）」的 1 = 不动点 b；「除以3」的 ×1 = 单态 (r+g+b)/√3。数值同 1 但方向不同，需厘清",
}

# ---------------------------------------------------------------------------
# (E) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "建议 1（谱投影秩）": "排除——J_3 的 +i/-i/0 谱投影都秩 1，给不出 3 vs 1",
    "建议 2（P_full/P_singlet）": "识别（已坐实），非新推导",
    "建议 3（E 的秩）": "框架好（OQG 同源），但「+i↔id、-i↔P_singlet」仍是识别 = §22.4 缺口本身",
    "建议 4（迹=不动点数）": "最接近群论突破口：S₃ 迹 {3,1,0} 天然给「3 和 1」。但「上型=单位元、下型=转置」映射与 §1.3（上型=ω、下型=ω²）不一致，且「转置不动点 b」≠「单态 (r+g+b)/√3」——需厘清「3」是「3-循环周期」还是「单位元迹」",
    "「3」的三个来源": "① 3-循环周期 3（§5.2）② 单位元迹 3 = 颜色维数（建议4）③ 三重态迹 3（§20.2）。①②③ 是「同一颜色 3」的三个面（一元论），但「除以 3」的正确机制需厘清用哪个",
    "措辞（三档）": "缺口仍在【待推导】；建议 4 的「迹=不动点」是【候选结构】待验证；建议 1 是【已排除】",
}

report(R, "exp_gap2_trace")
