"""
远景线 5（质量谱）· 深挖缺口1：手征规范理论（弱同位旋只作用左手）的框架来源

深挖发现的关键区分：框架里有两个不同的「反演」——
  (1) 时间反演 T（Kramers，T²=-1）= 有向 J = iσ_y → 「手征来源」（已推，第八~十一刀）
  (2) 电荷共轭 J（实结构，KO维数6，J²=1，Jγ=-γJ）→ 「手征规范」（左作用 vs 右作用，未推）

本脚本坐实这两个反演的区分，并检验「手征规范」（弱同位旋只作用左手）的卡点。
"""
import numpy as np
from sympy import Matrix, I, simplify
from experiments._common import report

R = {}

sx = Matrix([[0,1],[1,0]])
sy = Matrix([[0,-I],[I,0]])
sz = Matrix([[1,0],[0,-1]])
I2 = Matrix([[1,0],[0,1]])

# ---------------------------------------------------------------------------
# (1) 时间反演 T（Kramers，T²=-1）
# ---------------------------------------------------------------------------
T = I * sy  # = iσ_y（Kramers 时间反演）
T_sq = simplify(T * T)
R["time_reversal"] = {
    "T = iσ_y（Kramers 时间反演）": T == I * sy,
    "T² = -1？": T_sq == -I2,
    "本征值": {str(k): v for k, v in T.eigenvals().items()},
    "角色": "有向 J = iσ_y = T → 「手征来源」（有向区分的箭头 = Kramers 时间反演）",
}

# ---------------------------------------------------------------------------
# (2) 电荷共轭 J（实结构，KO维数6，J²=1）
# ---------------------------------------------------------------------------
# 实结构 J（电荷共轭）：反酉，J²=1，JD=DJ，Jγ=-γJ
# 在手征基（γ 对角）下，J 交换左右手（Jγ=-γJ）
# 2×2 最小模型：γ = σ_z（手征），J = 复共轭（反酉，J²=1）
# J 作为反酉算子：J = K（复共轭），J² = K² = 1
R["charge_conjugation"] = {
    "J（电荷共轭，实结构）": "反酉，J²=1，JD=DJ，Jγ=-γJ（KO 维数 6）",
    "J² = 1（vs T²=-1）": "电荷共轭 J 是「对合」（J²=1），时间反演 T 是「反对合」（T²=-1）——两个不同的反演",
    "Jγ=-γJ": "电荷共轭 J 交换左右手（反对易手征 γ）",
    "角色": "实结构 J → 「手征规范」（左作用 L vs 右作用 R=JAJ⁻¹ 的区分）",
}

# ---------------------------------------------------------------------------
# (3) 关键区分：T（时间反演）≠ J（电荷共轭）
# ---------------------------------------------------------------------------
R["T_vs_J"] = {
    "T（时间反演）": "T²=-1（反对合），作用：有向 ±i（手征来源）",
    "J（电荷共轭）": "J²=1（对合），作用：交换左右手（手征规范）",
    "关键": "框架推了「时间反演 T → 手征来源」（第八~十一刀），但「电荷共轭 J → 手征规范」（左作用 vs 右作用）是另一条线，还没推",
}

# ---------------------------------------------------------------------------
# (4) 手征规范（弱同位旋只作用左手）的卡点
# ---------------------------------------------------------------------------
# 标准模型：弱同位旋 SU(2)_L 只作用 H_L（左手），H_R（右手）是单态
# 来源：代数 A 的左作用 L 只作用 H_L（H 块在左作用，不在右作用 R=JAJ⁻¹）
# 而「H_L 是二重态、H_R 是单态」是标准模型量子数赋值（识别），非推导
R["chiral_gauge_gap"] = {
    "弱同位旋只作用左手": "= H 块在左作用 L，不在右作用 R",
    "左作用 vs 右作用": "来自实结构 J（电荷共轭）交换左右手（Jγ=-γJ）",
    "卡点": "「H_L 二重态、H_R 单态」是标准模型量子数赋值（= 3Y 奇偶 = 手征 的识别），非推导——因为 Y 数值是标定输入（尺度读出墙）",
}

# ---------------------------------------------------------------------------
# (5) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "深挖发现": "框架里「时间反演 T（T²=-1）」和「电荷共轭 J（J²=1）」是两个不同的反演：T 给「手征来源」（有向 ±i，已推），J 给「手征规范」（左作用 vs 右作用，未推）",
    "手征规范卡点": "弱同位旋只作用左手 = H 块在左作用 L（H_L 二重态、H_R 单态），这是「识别」（3Y 奇偶=手征）非「推导」（Y 数值标定）",
    "候选突破口": "「电荷共轭 J（实结构）交换左右手（Jγ=-γJ）」能否从「时间反演 T（有向 ±i）」推出？——若 T 和 J 是同一个 Z₂ 的两面（时间反演 vs 电荷共轭），则手征规范 = 手征来源的另一个面，可坐实",
    "下一步": "检验 T（时间反演，T²=-1）和 J（电荷共轭，J²=1）是否是「同一个 Z₂ 的两面」（如 T 的平方 = J 的某种组合，或 T 和 J 通过 Wick 转动联系）",
}

report(R, "exp_chiral_gauge")
