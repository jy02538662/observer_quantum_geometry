"""
缺口 3 · 「5=S₃ 非平凡元素数 → 2⁵」的结构一致性检验

用户候选：「32=2⁵」的「5」= S₃ 非平凡元素数（类比 N=128 的「7=Z₂³ 非平凡元素数→2⁷」）。

关键检验（先于数值，纯结构）：
  「二分选择」只能作用在「二分对象」（阶 2 元素）上。
  检查 Z₂³ 和 S₃ 的「非平凡元素」里，有多少是「二分对象」（阶 2）：
  - Z₂³：7 个非平凡元素，是否全阶 2（对合）？
  - S₃ ：5 个非平凡元素，几个阶 2（转置）、几个阶 3（3-循环）？

若 Z₂³ 全阶 2 而 S₃ 混阶 2/阶 3，则「5→2⁵」类比不成立：
  5 个非平凡元素里只有 3 个是二分对象，2 个（3-循环）是三分对象，
  不能做「二分选择」→ 2⁵ 的「5 个二分对象」不成立。
"""
import sympy as sp
from experiments._common import report

R = {}

def perm_matrix(p):
    M = sp.zeros(3)
    for i, j in enumerate(p):
        M[i, j] = 1
    return M

def order(M):
    k = 1
    cur = M
    while not (cur == sp.eye(3)):
        cur = cur * M
        k += 1
        if k > 6:
            break
    return k

# S₃ 的 6 个元素（置换 [p0,p1,p2] 表示）
S3_names = {
    (0, 1, 2): "e",
    (1, 0, 2): "(12)",
    (2, 1, 0): "(13)",
    (0, 2, 1): "(23)",
    (1, 2, 0): "(123)",
    (2, 0, 1): "(132)",
}

S3 = {}
for p, name in S3_names.items():
    S3[name] = perm_matrix(p)

R["S3_elements"] = {name: f"阶 {order(M)}" for name, M in S3.items()}

# 分类：阶 1 / 阶 2 / 阶 3
order1 = [n for n, M in S3.items() if order(M) == 1]
order2 = [n for n, M in S3.items() if order(M) == 2]
order3 = [n for n, M in S3.items() if order(M) == 3]

R["S3_order_classification"] = {
    "阶 1（单位元）": order1,
    "阶 2（转置，二分对象）": order2,
    "阶 3（3-循环，三分对象）": order3,
    "非平凡元素总数": len(order2) + len(order3),
    "其中二分对象（阶2）数": len(order2),
    "其中三分对象（阶3）数": len(order3),
}

# ---------------------------------------------------------------------------
# Z₂³ 的 8 个元素（三个对合 Γ,K,s 的非平凡组合），全阶 2 或 1
# ---------------------------------------------------------------------------
# Z₂³ 元素 (a,b,c) ∈ {0,1}³，阶 = 1（单位元）或 2（非平凡）
R["Z2x3_elements"] = {
    "非平凡元素数": 7,
    "全部阶 2（对合）?": True,
    "说明": "Z₂³ = 三个 Z₂ 的直积，每个非平凡元素 g≠e 满足 g²=e（阶 2）——7 个非平凡元素全是二分对象",
}

# ---------------------------------------------------------------------------
# 关键对比：二分对象的数量
# ---------------------------------------------------------------------------
R["binary_object_compare"] = {
    "Z₂³ 非平凡元素（全二分）": 7,
    "S₃ 非平凡元素（混二分+三分）": 5,
    "S₃ 里真正的二分对象（阶2 转置）": len(order2),
    "S₃ 里的三分对象（阶3 3-循环）": len(order3),
}

# ---------------------------------------------------------------------------
# 结论
# ---------------------------------------------------------------------------
R["conclusion"] = {
    "结构事实（坐实）": f"S₃ 非平凡元素 {len(order2)+len(order3)} 个 = {len(order2)} 转置（阶2，二分）+ {len(order3)} 3-循环（阶3，三分）；Z₂³ 非平凡元素 7 个全阶 2（二分）",
    "「5→2⁵」的矛盾": "「二分选择」只能作用于「二分对象」（阶2）。S₃ 的 5 个非平凡元素里只有 3 个是二分对象（转置），2 个是三分对象（3-循环）——把阶 3 的也当二分对象，混了",
    "若只用二分对象": f"S₃ 只有 {len(order2)} 个二分对象 → 2³=8，不是 2⁵=32",
    "对照 N=128": "Z₂³ 的 7 个非平凡元素全是二分对象 → 2⁷=128 一致（无矛盾）；「5→2⁵」把三分对象混进二分选择，不一致",
    "对「5=S₃ 非平凡元素数」的裁定": "【不成立/结构矛盾】——「5」把阶 2 和阶 3 的元素混数，但「二分递归」只能作用在阶 2（二分）对象上。这与「7=2³−1 是状态数非自由度」是同类但不同的错误：这次是「把三分对象当二分对象数」",
    "诚实定位": "「32=2⁵」的「2 的幂」结构兼容框架（坐实），但「5=S₃ 非平凡元素数」这个具体的指数来源【结构矛盾，排除】——「5」没有「先于 32」的二分结构支撑",
}
report(R, "exp_gap3_s3_binary")
