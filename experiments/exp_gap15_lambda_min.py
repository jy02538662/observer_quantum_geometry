"""
缺口 15 遗留 · 质量谱「λ_min 选择点」：尺度破缺 vs 边缘间隔

背景（质量谱审计补七/补八 + 预印本 1.21 §2.1′）：质量谱「无自由参数」的三个选择点之一：
  λ_min 选 π²/N²（尺度破缺 2−δ_N）而非 3π²/N²（边缘间隔）——两个不同量、差 3 是 cos 泰勒系数必然，
  但「选哪个」无独立论证。之前审计的结论是「换 3π² 则 207 消失」，所以 π² 是「为凑 207 选」。

本脚本攻这个选择点：**λ_min = 尺度破缺 还是 边缘间隔？框架有没有结构理由？**

两个量（Chebyshev 零点 λ_k = 2cos(kπ/(N+1))）：
  - 尺度破缺 = 2 − δ_N = 2 − 2cos(π/(N+1)) ≈ π²/N²（量子维度 δ_N 偏离经典极限 2 的量）
  - 边缘间隔 = λ₁ − λ₂ = 2cos(π/(N+1)) − 2cos(2π/(N+1)) ≈ 3π²/N²（相邻能级间距）

本脚本算三件事：
  1. 符号：两个量的泰勒展开，坐实「差 3」是 cos 泰勒系数（cos 2x 偏离 4 倍 vs cos x 偏离 1 倍）
  2. 数值：N=128 时两个量的精确值
  3. 结构理由：「质量」= 尺度不变破缺（2−δ_N），不是能级间距（λ₁−λ₂）——这是「λ_min 选 π²」的结构依据

诚实边界：结构理由（质量=尺度破缺）是「框架的物理诠释」（质量=偏离尺度不变的量），
不是「从公设严格推」。但它比「为凑 207 选 π²」强——它是一个【结构候选】，不是【盯数】。
"""
import math
import numpy as np
from sympy import symbols, cos, series, pi, Rational
from experiments._common import report

R = {}

N = 128

# ---------------------------------------------------------------------------
# 1. 符号：两个量的泰勒展开（x = π/(N+1)，小量）
# ---------------------------------------------------------------------------
x = symbols("x", positive=True)
# 尺度破缺 = 2 - 2cos(x) = 2(1 - cos x) ≈ x²
scale_break_series = series(2 - 2 * cos(x), x, 0, 4)
# 边缘间隔 = 2cos(x) - 2cos(2x) ≈ 3x²
edge_gap_series = series(2 * cos(x) - 2 * cos(2 * x), x, 0, 4)

R["step1_taylor"] = {
    "尺度破缺 2−2cos x ≈": str(scale_break_series),
    "边缘间隔 2cos x − 2cos 2x ≈": str(edge_gap_series),
    "比值（边缘间隔/尺度破缺）": "3x² / x² = 3",
    "「3」的来源": "cos 2x ≈ 1−2x²（偏离 2x²），cos x ≈ 1−x²/2（偏离 x²/2）。2cos x−2cos 2x = 2[(1−x²/2)−(1−2x²)] = 3x²；而 2−2cos x = x²。所以差 3 是 cos 泰勒系数必然，不是结构选择",
}

# ---------------------------------------------------------------------------
# 2. 数值：N=128 时两个量的精确值
# ---------------------------------------------------------------------------
lam1 = 2 * math.cos(math.pi / (N + 1))   # λ₁ = δ_N
lam2 = 2 * math.cos(2 * math.pi / (N + 1))  # λ₂
scale_break = 2 - lam1                    # 尺度破缺
edge_gap = lam1 - lam2                    # 边缘间隔

R["step2_numeric"] = {
    "λ₁ = δ_N = 2cos(π/129)": f"{lam1:.6f}",
    "λ₂ = 2cos(2π/129)": f"{lam2:.6f}",
    "尺度破缺 2−λ₁": f"{scale_break:.6e}（≈ π²/N² = {math.pi**2/N**2:.6e}）",
    "边缘间隔 λ₁−λ₂": f"{edge_gap:.6e}（≈ 3π²/N² = {3*math.pi**2/N**2:.6e}）",
    "比值（边缘间隔/尺度破缺）": f"{edge_gap/scale_break:.4f}（≈ 3）",
}

# ---------------------------------------------------------------------------
# 3. 结构理由：质量 = 尺度破缺（不是边缘间隔）
# ---------------------------------------------------------------------------
R["step3_structure"] = {
    "「质量」在框架里 = 什么": "能隙 = 尺度不变破缺的平方根 m = Λ·(2−δ_N)^{1/2}（尺度读出 §9.8）",
    "「无质量」对应什么": "尺度不变（经典极限 δ=2，N→∞，无破缺）",
    "「有质量」对应什么": "尺度破缺（有限 N，δ_N<2，尺度不变被破缺）",
    "所以「质量」= 偏离尺度不变的量": "m ∝ (2−δ_N)^{1/2} = (尺度破缺)^{1/2} —— 这是「尺度破缺」的结构角色",
    "「边缘间隔」对应什么": "λ₁−λ₂ = 相邻能级间距 = 激发能（基态→第一激发态），不是「质量」（基态能隙 2−λ₁）",
    "结构理由（候选）": "「质量」=「尺度不变破缺」，而「尺度不变破缺」= 量子维度偏离经典极限（2−δ_N），不是「能级间距」（λ₁−λ₂）。所以 λ_min 应选「尺度破缺」π²/N²，不是「边缘间隔」3π²/N²",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "符号坐实": "尺度破缺 ≈ π²/N²，边缘间隔 ≈ 3π²/N²，差 3 是 cos 泰勒系数必然（cos 2x 偏离 4 倍 vs cos x 偏离 1 倍）",
    "结构理由（候选，不是盯数）": "「质量 = 尺度不变破缺」→ λ_min = 尺度破缺 π²/N²，不是边缘间隔 3π²/N²。这是「质量=偏离尺度不变」的物理诠释给出的结构理由，不是「为凑 207 选 π²」",
    "强度（三档）": "「尺度破缺 vs 边缘间隔 差 3」=【严格（cos 泰勒系数）】；「质量=尺度破缺」=【结构候选（物理诠释，质量=偏离尺度不变的量）】；「λ_min 选 π² 有结构理由」=【候选，比盯数强，但非公设级严格】",
    "和「无自由参数」的关系": "若「质量=尺度破缺」成立，则 λ_min 选 π² 有结构理由，三个选择点里少一个「盯数」；但仍剩「步长 c=1」（循环论证）这个选择点",
    "下一步": "若这个结构理由站得住，转攻「步长 c=1」（无绝对尺度能否给无量纲步长=1）；若站不住，λ_min 选 π² 仍是「盯数」",
}

report(R, "exp_gap15_lambda_min")
