"""
远景线 5（质量谱）· 族维度第八刀·续二：手征性的精确形式（σ_y 保持手征，σ_x σ_z 翻转）

第八刀核心：有向 J=iσ_y（反对称）本征值 ±i = 手征；反对易 T_xT_y=-T_yT_x 带方向。
本脚本坐实「手征性」的精确形式：

  有向 J = iσ_y（±i = 手征/左右手）
  弱同位旋 = 断裂 = 反对易的「方向」= σ_y（有向 J 本身）
  关键：σ_y 对易 J（保持手征），σ_x σ_z 反对易 J（翻转手征）

⟹ 「弱同位旋只作用左手」= σ_y（有向 J 的方向）保持手征 ±i，而 σ_x σ_z 是手征翻转。
"""
import numpy as np
from sympy import Matrix, I, sqrt, simplify
from experiments._common import report

R = {}

sx = Matrix([[0, 1], [1, 0]])
sy = Matrix([[0, -I], [I, 0]])
sz = Matrix([[1, 0], [0, -1]])
J = Matrix([[0, 1], [-1, 0]])  # = iσ_y（有向，反对称）

# ---------------------------------------------------------------------------
# (1) 有向 J = iσ_y，本征值 ±i（手征）
# ---------------------------------------------------------------------------
J_is_i_sy = simplify(J - I * sy)  # J - iσ_y = 0？
R["J_equals_i_sy"] = {
    "J = iσ_y？": J_is_i_sy == Matrix.zeros(2),
    "J 本征值 ±i（手征）": {str(k): v for k, v in J.eigenvals().items()},
}

# ---------------------------------------------------------------------------
# (2) σ_y 保持手征（对易 J），σ_x σ_z 翻转手征（反对易 J）
# ---------------------------------------------------------------------------
comm_sy = simplify(sy * J - J * sy)   # σ_y J - J σ_y（对易 = 0）
anti_sx = simplify(sx * J + J * sx)   # σ_x J + J σ_x（反对易 = 0）
anti_sz = simplify(sz * J + J * sz)   # σ_z J + J σ_z（反对易 = 0）

R["chirality_commutation"] = {
    "σ_y 对易 J（σ_yJ - Jσ_y = 0，保持手征）": comm_sy == Matrix.zeros(2),
    "σ_x 反对易 J（σ_xJ + Jσ_x = 0，翻转手征）": anti_sx == Matrix.zeros(2),
    "σ_z 反对易 J（σ_zJ + Jσ_z = 0，翻转手征）": anti_sz == Matrix.zeros(2),
    "关键发现": "σ_y = 有向 J 的方向，保持手征 ±i（对易 J）；σ_x, σ_z 翻转手征（反对易 J）",
}

# ---------------------------------------------------------------------------
# (3) 手征性的精确形式：弱同位旋 = σ_y（保持手征），σ_x σ_z = 手征翻转
# ---------------------------------------------------------------------------
# 弱同位旋第三分量 I₃ = σ_y/2（有向 J 的方向，保持手征）
# 弱同位旋升降算符 T_± = (σ_x ± iσ_z)/2（翻转手征，连接左右手）
# 检验：T_± 是否翻转手征（反对易 J）
T_plus = (sx + I * sz) / 2
T_minus = (sx - I * sz) / 2
anti_Tp = simplify(T_plus * J + J * T_plus)   # T_+ J + J T_+（反对易 = 0？）
anti_Tm = simplify(T_minus * J + J * T_minus) # T_- J + J T_-

R["weak_isospin_chirality"] = {
    "I₃ = σ_y/2（有向 J 方向，保持手征）": "对易 J（保持 ±i）",
    "T_+ = (σ_x+iσ_z)/2 反对易 J（翻转手征）": anti_Tp == Matrix.zeros(2),
    "T_- = (σ_x-iσ_z)/2 反对易 J（翻转手征）": anti_Tm == Matrix.zeros(2),
    "手征性结构": "弱同位旋 I₃（σ_y）保持手征 = 「只作用左手」；T_±（σ_x±iσ_z）翻转手征 = 连接左右手",
}

# ---------------------------------------------------------------------------
# (4) 完整链条：有向区分 → 手征性
# ---------------------------------------------------------------------------
R["full_chain"] = {
    "链条": "有向区分 = 区分（对称 σ_z，±1）+ 有向（反对称 J=iσ_y，±i）→ 手征 = J 的 ±i → 弱同位旋 = 反对易的方向 σ_y（保持手征）→ 只作用左手",
    "「有向」= 反对称 J（±i）= 手征": "坐实",
    "「反对易带方向」= σ_z=-iT_xT_y（±1）= 区分": "坐实",
    "「弱同位旋 = σ_y（有向 J 方向）保持手征」": "坐实（σ_y 对易 J）",
    "「σ_x σ_z 翻转手征（连接左右手）」": "坐实（反对易 J）",
}

# ---------------------------------------------------------------------------
# (5) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实（精确）": "① 有向 J=iσ_y 本征值 ±i（手征）；② σ_y 对易 J（保持手征），σ_x σ_z 反对易 J（翻转手征）；③ T_±=(σ_x±iσ_z)/2 反对易 J（翻转手征）",
    "手征性的精确形式": "弱同位旋 I₃ = σ_y/2（有向 J 的方向）保持手征 ±i = 「只作用左手」；T_± = 手征翻转（连接左右手）——「手征性」= 有向区分「有向」部分（反对称 J）的 ±i 天然手征，而弱同位旋继承这个方向（σ_y）",
    "突破点": "「弱同位旋只作用左手」从「标准模型设定」降级为「有向 J 的方向 σ_y 保持手征」的框架结构——手征性来源 = 有向区分的箭头（反对称 J 的 ±i）",
    "待坐实": "① 「弱同位旋 = σ_y 单独」还是「σ_x σ_y σ_z 的某种手征保持组合」需对照标准模型（标准模型弱同位旋是完整 SU(2)_L，非 U(1)）；② 「σ_y 保持手征」推广到 4×4 Dirac（含 Kramers）需验证",
    "措辞": "符号坐实（有向=±i=手征，σ_y 保持手征、σ_x σ_z 翻转手征）+ 手征性框架来源候选",
}

