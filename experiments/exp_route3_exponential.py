"""
路3（味结构）· 翻转：混合角 = 阶差的指数（和质量谱机制同构）

翻转（用户洞察）：离散和连续是视角，不是对立。质量谱 m_n = e^{+λ_mod·n} 已经是
「离散阶 → 连续质量」的现成例子。混合角应该同样从「离散阶差」通过指数得到：

  θ_ij ~ e^{-λ·|Δn|}，Δn = |n_i - n_j| = 阶差

和质量谱同构：质量看「点」（阶 n 的指数），混合看「距离」（阶差 |Δn| 的指数）。

本脚本算基础版本 θ_ij = e^{-λ·|Δn|}，对比 CKM 的层级结构（θ13 最小、θ12 最大），
诚实报告「层级结构对否」和「指数是否匹配」两个问题。
"""
import numpy as np
from experiments._common import report

R = {}

# 阶：代 = S3 共轭类阶 {1,2,3}
n = [1, 2, 3]

# 阶差 |Δn|
delta = {
    "θ12 (1↔2)": abs(n[1] - n[0]),   # |2-1| = 1
    "θ23 (2↔3)": abs(n[2] - n[1]),   # |3-2| = 1
    "θ13 (1↔3)": abs(n[2] - n[0]),   # |3-1| = 2
}

R["step1_order_diff"] = {
    "阶差 |Δn|": delta,
    "观察": "θ12 和 θ23 阶差都是 1，θ13 阶差是 2",
}

# ---------------------------------------------------------------------------
# 2. 基础版本 θ = e^{-λ·|Δn|}，用两个 λ：
#    λ_mod = 5.32（质量指数，e^{5.32}=207）
#    λ_Wolf = 1.5（Wolfenstein λ≈0.22≈e^{-1.5}）
# ---------------------------------------------------------------------------
lam_mod = 5.32
lam_wolf = 1.5

def theta_base(lam):
    return {k: np.exp(-lam * d) for k, d in delta.items()}

theta_mod = theta_base(lam_mod)
theta_wolf = theta_base(lam_wolf)

# 实际 CKM（弧度）
ckm_actual = {
    "θ12 (1↔2)": 0.23,    # ≈13°
    "θ23 (2↔3)": 0.042,   # ≈2.4°
    "θ13 (1↔3)": 0.0035,  # ≈0.2°
}

R["step2_theta"] = {
    "基础版本 θ（λ=5.32）": {k: f"{v:.4e}" for k, v in theta_mod.items()},
    "基础版本 θ（λ=1.5）": {k: f"{v:.4e}" for k, v in theta_wolf.items()},
    "实际 CKM（rad）": {k: v for k, v in ckm_actual.items()},
}

# ---------------------------------------------------------------------------
# 3. 层级结构对比
# ---------------------------------------------------------------------------
def hierarchy(d):
    """返回层级排序：最大→最小"""
    return sorted(d.items(), key=lambda x: -x[1])

R["step3_hierarchy"] = {
    "基础版本（λ=5.32）层级": [k for k, v in hierarchy(theta_mod)],
    "基础版本（λ=1.5）层级": [k for k, v in hierarchy(theta_wolf)],
    "实际 CKM 层级": [k for k, v in hierarchy(ckm_actual)],
    "关键对比": "基础版本 θ12=θ23（阶差都 1），但实际 θ12≫θ23（差 5 倍）",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "翻转（对的部分）": "离散→连续 是视角切换，质量谱 m_n=e^{λn} 已是现成例子，混合角应从阶差指数得到",
    "基础版本的两个问题": "① θ12=θ23（阶差都 1），但实际 θ12≫θ23，需「S3 表示修正」区分；② 混合指数（~1.5=Wolfenstein）≠ 质量指数（5.32），两者关系待理清",
    "层级结构": "基础版本给 θ13 最小（对），但 θ12=θ23（错）",
    "下一步": "先定「混合指数」λ 的取值（为何 ~1.5 而非 5.32），再补「S3 表示修正」区分 θ12 vs θ23",
}

report(R, "exp_route3_exponential")
