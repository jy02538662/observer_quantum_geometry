"""
远景线 5（质量谱）· 最后一环：Δλ=λ_c² 的平方来自 D²（Dirac 算子平方），隧穿开方回 λ_c

⚠️ 命名（2026-09-27）：本脚本 λ_c = 模流频率 ≈5.32（= 预印本 1.14 的 λ_mod），区别于紫外截断 λ_c=2。

用户直觉（关键）：卡点「Δλ=λ_c²」的平方，来自谱作用量里的 D²——Dirac 算子的平方。
  D² 给出势垒高度 ∝ λ_c²，而隧穿的平方根把它开方回 λ_c，所以质量 ∝ e^{λ_c}。
  平方不是反推的，是结构逼出的——D² 是谱作用量的根本（S=Tr f(D²/Λ²)），
  隧穿的开方是物理的（WKB √(势垒)），两者结合自然给出指数。

物理链条：
  谱作用量 S = Tr f(D²/Λ²)：D² 的谱 ∝ λ²（本征值 = λ 的平方）——「平方」的结构来源；
  势垒 V ∝ D² 的谱 ∝ λ_c²（观察者截断 λ_c 处的 D² 本征值）——「平方」；
  WKB 隧穿概率幅 T ∝ e^{-S}，S = ∫√(V) ∝ ∫√(λ²) = ∫λ = λ_c ——「开方」（√(λ_c²)=λ_c）；
  质量 = 1/T ∝ e^{λ_c} ——「指数」。

本脚本符号验证「平方 → 开方 → 指数」的链条。
"""
from sympy import symbols, sqrt, exp, integrate, simplify
from experiments._common import report

R = {}

lam, lam_c = symbols("lambda lambda_c", positive=True)

# 1. D² 的谱 ∝ λ²（Dirac 算子平方，本征值 = λ 的平方）
R["D2_spectrum"] = {
    "谱作用量 S = Tr f(D²/Λ²)": "D² 是 Dirac 算子的平方",
    "D² 的谱": "λ²（本征值 = λ 的平方）——「平方」的结构来源",
    "势垒 V ∝ D² 谱": "∝ λ_c²（观察者截断 λ_c 处的势垒高度）",
}

# 2. WKB 隧穿：概率幅 T ∝ e^{-S}，S = ∫√(V) dλ
# V ∝ λ²，所以 S = ∫√(λ²) dλ = ∫λ dλ = λ²/2（从 0 到 λ_c）= λ_c²/2？还是 λ_c？
# 关键：√(λ²) = λ（开方），S = ∫λ dλ = λ_c²/2
S_integrand = sqrt(lam**2)  # √(λ²) = λ（开方）
S = integrate(S_integrand, (lam, 0, lam_c))
R["wick_tunneling_sqrt"] = {
    "√(λ²)": str(simplify(sqrt(lam**2))),
    "S = ∫√(λ²) dλ = ∫λ dλ": str(simplify(S)),
    "意义": "WKB 作用量 = ∫√(势垒) = ∫√(λ²) = ∫λ（开方了平方），S ∝ λ_c（开方回 λ_c，不是 λ_c²）",
}

# 3. 隧穿概率幅 T ∝ e^{-S}，质量 = 1/T ∝ e^{S}
S_simplified = simplify(S)
T = exp(-S)  # 概率幅 ∝ e^{-S}
m = 1 / T      # 质量 ∝ 1/概率幅 = e^{S}
R["mass_exponent"] = {
    "隧穿概率幅 T ∝ e^{-S}": f"e^-S = e^-({S_simplified})",
    "质量 = 1/T ∝ e^{S}": f"e^S = e^({S_simplified})（S=λ_c²/2 时）",
    "关键检查": "S = λ_c²/2（不是 λ_c）——若「势垒高度∝λ_c²、穿透宽度∝1」，则 S∝λ_c；若「穿透宽度∝λ_c」，则 S∝λ_c²",
}

R["honest_conclusion"] = {
    "直觉验证（半）": "「平方来自 D²、隧穿开方」的直觉方向对——D² 的谱 ∝ λ²（平方是结构根本），WKB 的 √(λ²)=λ（开方是物理）。但「开方」的结果取决于「穿透宽度」：",
    "两种可能": "① 若穿透宽度 ∝ 常数（势垒是「薄」的），S = √(λ_c²)×宽度 ∝ λ_c，质量 = e^{λ_c} ✅；② 若穿透宽度 ∝ λ_c（势垒是「厚」的），S = ∫λ dλ = λ_c²/2，质量 = e^{λ_c²/2} ❌（不对）",
    "关键卡点（诚实）": "「平方 → 开方 → 指数」的链条方向对，但「开方回 λ_c」需要「穿透宽度 ∝ 常数」（薄势垒），而「薄势垒」的物理（穿透宽度 = 观察者截断的「厚度」= 1？）还没从「交错质量 gap」推出",
    "进展": "「Δλ=λ_c² 的平方」不再是「反推」，而是「D² 的结构（平方）+ WKB 开方（√）」的自然结合——但「开方回 λ_c 还是 λ_c²/2」取决于「穿透宽度」，这是最后一环的精确位置",
    "措辞": "直觉验证（平方来自 D²，方向对），非「闭合最后一环」——「穿透宽度 = 常数」的物理（薄势垒）还没推出",
}

report(R, "exp_mass_D2_tunneling")
