"""
缺口 8 · 电弱标度 v 的「八刀」（$v\\sim M_P/N_{\\text{int}}^8$ 的「8」）——查证「8」是结构还是巧合

判据（v13 §3.1 判据 1）：「8」是看 v 之前从框架独立推出的，还是看了 v 之后反推的？
  前者 → 结构来源可推；后者 → 爱丁顿凑数陷阱（「盯 128 为 8 找表达」）。

本脚本做三层查证（守红线：不先知道 v 再凑 8，纯粹钉「8」的反推性质）：

1. 数值层：反解指数 log_128(M_P/v)，看是否精确 = 8；扫描整数指数 k，
   看「8」是唯一命中还是「最接近的整数」（非精确命中）。
2. 结构层（符号）：候选「三个 Z₂ → 2³=8（群阶）」的对象区分——
   群阶 8（集合意义，Z₂³ 的元素数）vs 指数 8（乘法意义，N^8），
   两者作用在不同对象上（AGENTS 三问①）。
3. 位置错位（数值）：若「8」来自「群阶 2³」，它在公式里的合法位置是
   N=8（v~M_P/8），不是 N^8（v~M_P/128^8）——前者差 1e16 倍完全不对，
   后者接近 v。即「群阶 8」是「N 取什么值」，「指数 8」是「N 乘几次方」，位置错位。

量：
  v      = 246.22 GeV（PDG 电弱 VEV，v = (√2 G_F)^{-1/2}）
  M_P    = 1.22089e19 GeV（约化普朗克质量，CODATA）
  N_int  = 128 = 2^7
"""
import math
import numpy as np
from sympy import Rational, Integer, log, simplify
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 0. 数据（CODATA 2022 / PDG 2022）
# ---------------------------------------------------------------------------
V_GEV = 246.22          # 电弱真空期望值
MP_GEV = 1.22089e19     # 约化普朗克质量
N_INT = 128             # 2^7

R["data"] = {
    "v (GeV)": V_GEV,
    "M_P (GeV)": MP_GEV,
    "N_int = 2^7": N_INT,
    "v/M_P": V_GEV / MP_GEV,
    "1/N_int^8 = 1/2^56": 1.0 / N_INT**8,
}

# ---------------------------------------------------------------------------
# 1. 数值层：反解指数 + 整数指数扫描
# ---------------------------------------------------------------------------
log_exponent = math.log(MP_GEV / V_GEV, N_INT)  # log_128(M_P/v)
R["exponent_inversion"] = {
    "log_128(M_P/v)": round(log_exponent, 6),
    "精确 = 8 吗?": log_exponent == 8,
    "离 8 的距离": round(log_exponent - 8, 6),
    "判断": "7.923 非精确 8（差 0.077），「8」是取整，不是框架逼出的精确值",
}

# 扫描整数指数 k ∈ {5,6,7,8,9,10,11}，看谁最接近 v
scan = {}
for k in [5, 6, 7, 8, 9, 10, 11]:
    v_pred = MP_GEV / N_INT**k
    scan[f"k={k}"] = {
        "v_pred (GeV)": f"{v_pred:.4g}",
        "v/v_pred": round(V_GEV / v_pred, 3),
        "相对差 |1-v_pred/v|": round(abs(1 - v_pred / V_GEV), 4),
    }
R["integer_exponent_scan"] = scan

# ---------------------------------------------------------------------------
# 2. 结构层（符号）：群阶 vs 指数的对象区分
#   候选「三个 Z₂ → 2³=8」给的是「群阶 8」（Z₂³ 的元素个数），
#   不是「指数 8」（N_int 连乘 8 次）。
# ---------------------------------------------------------------------------
# 群阶：|Z₂³| = 2³ = 8（集合意义的 8，加法/计数）
group_order = Integer(2) ** 3  # 8
# 指数：N_int^8 = 2^56（乘法意义的 8，连乘）
exponent_form = Integer(N_INT) ** 8  # 2^56

R["group_order_vs_exponent"] = {
    "群阶 2³": int(group_order),           # 8
    "指数 N_int^8 = 128^8": int(exponent_form),  # 2^56
    "群阶 = 2^3 = 8（Z₂³ 元素个数）": "集合意义的 8（计数）",
    "指数 = 128^8 = 2^56（N 连乘 8 次）": "乘法意义的 8（幂次）",
    "对象区分": "「群阶 8」是「N 取什么值」，「指数 8」是「N 乘几次方」——两者作用在不同对象（AGENTS 三问①）",
    "2^3 vs 2^56": f"群阶给 {int(group_order)}，指数给 {int(exponent_form)}，差 {int(exponent_form - group_order)} 倍——不是同一个 8",
}

# 关键：若「8」来自群阶 2³，它在公式里的合法位置是 N=8，不是 N^8
# 位置错位验证：v ~ M_P/8（群阶位置）vs v ~ M_P/128^8（指数位置）
R["position_mismatch"] = {
    "若「8」= 群阶 → N=8 → M_P/8 (GeV)": f"{MP_GEV/8:.4g}",
    "M_P/8 与 v 的比": f"{MP_GEV/8/V_GEV:.2e}（差 1e16 倍，完全不对）",
    "若「8」= 指数 → N^8 → M_P/128^8 (GeV)": f"{MP_GEV/N_INT**8:.2f}",
    "M_P/128^8 与 v 的比 (v_pred/v)": f"{MP_GEV/N_INT**8/V_GEV:.3f}（即 v/v_pred = {V_GEV/(MP_GEV/N_INT**8):.3f}，差 1.45 倍，接近但非精确）",
    "结论": "「8」只有放在「指数」位置才接近 v；但「群阶 2³」是「值」位置（N=8），位置错位 → 候选 1 排除",
}

# 中间桥：N=2^7 的「7」本身是事后对齐（质量谱审计已确认）
# 若「8」来自「三个 Z₂」，那 N^8 应拆成 (2^?)^8，需要 N=2^? 里的 ? 有结构来源
R["bridge_7"] = {
    "N_int = 2^7": "若「8」来自三个 Z₂（2³），则 N^8 = (2^7)^8 = 2^56，需先有「N=2^7 的 7」",
    "「7」的来源": "事后对齐（质量谱审计：先有 207 → 反解 N≈128.7 → 构造 2^7）",
    "结论": "「8」若要连「三个 Z₂」，须先经过「7」这个事后对齐的桥 → 双重事后对齐，非结构",
}

# ---------------------------------------------------------------------------
# 3. 候选 2（Chebyshev N=8）排除：N 值 ≠ 指数
# ---------------------------------------------------------------------------
R["candidate_chebyshev_N8"] = {
    "候选": "Chebyshev N=8（小 N 量子化）",
    "问题": "这是「N 的值 = 8」（N_int 取 8），不是「指数 = 8」（N_int^8）",
    "对象区分": "N=8 → v~M_P/8（差 1e16 倍）；N^8 → v~M_P/128^8（接近）。「N 值 8」≠「指数 8」",
    "排除": "把 N 值当指数，对象错误（同候选 1）",
}

# ---------------------------------------------------------------------------
# 4. 结论层（三档措辞）
# ---------------------------------------------------------------------------
R["verdict"] = {
    "判据 1 答案": "「8」是看了 v 之后反推的（事后对齐），非框架独立推出",
    "证据 1（历史）": "原始出处（2026-09-27）先算 v/M_P=2.46e-17 再凑 1/128^8=1.4e-17，作者当场标「待查的巧合」",
    "证据 2（数值）": f"log_128(M_P/v)={log_exponent:.3f} 非精确 8；k=8 给 169 GeV vs v=246 GeV（差 1.45 倍），8 只是 7/9 间最近整数",
    "证据 3（结构）": "群阶 2³=8（元素数）≠ 指数 8（N 连乘 8 次），对象错误；且须经「7」这个事后对齐的桥",
    "候选全排除": "2³（群阶，位置错位）/ Chebyshev N=8（N 值非指数）/ 2×4（无机制）",
    "结论（三档）": "「8 有结构来源」=【否证/排除】；「v~M_P/N^8 的 8」=【巧合，事后对齐】；v 绝对标度=【标定输入/约定档，同 Y_ν=1、π 因子】",
    "守红线": "标巧合，不硬推（v13 守红线 3：数值是观察者内化的边界，不当待攻破的硬骨头）",
}

report(R, "exp_gap8_badao")
