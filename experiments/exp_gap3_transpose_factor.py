"""
缺口 3 · 转置主导因子的「先推结构、后看数」检验（不预设 27/32）

原则（AGENTS.md 第 7 条教训）：不能「先有 27/32，再找结构」（盯数）。
本脚本只做结构推导：把族维度 §25 已坐实的「区分/等同」机制
（区分=保持差异=迹3三重态、等同=抹平差异=迹1单态）作用在
「转置的对称化/反对称化投影」上，看自然给什么因子，然后才和 29.2 对比。

关键事实（第二十六刀已坐实）：
  - 3-循环 = 完整循环（迹0），把 3 色全轮换 → 完全对称化 → 单态（迹1）→ 因子 3
  - 转置  = 部分交换（迹1），固定 b + 交换 r,g → 颜色 3 = 2⊕1（2对称 + 1反对称）

本脚本验证：转置的对称化/反对称化投影的秩与迹，给出自然因子候选，
看是否命中 27 或 32（不预设，纯算）。
"""
import sympy as sp
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 0. 颜色 3 维置换表示里的 S₃ 元素
# ---------------------------------------------------------------------------
I3 = sp.eye(3)
t12 = sp.Matrix([[0, 1, 0], [1, 0, 0], [0, 0, 1]])      # 转置 (12)：交换 r,g，固定 b
c123 = sp.Matrix([[0, 0, 1], [1, 0, 0], [0, 1, 0]])      # 3-循环 (123)：r→g→b→r
c132 = sp.Matrix([[0, 1, 0], [0, 0, 1], [1, 0, 0]])      # 3-循环 (132)：逆

# ---------------------------------------------------------------------------
# 1. 命题 1：转置的对称化投影 P_sym = (I + (12))/2
# ---------------------------------------------------------------------------
P_sym = (I3 + t12) / 2
R["P1_transpose_sym"] = {
    "P_sym = (I+(12))/2": sp.latex(P_sym),
    "秩": int(P_sym.rank()),
    "迹": float(sp.trace(P_sym)),
    "含义": "对称化投影（把 r,g 等同），秩=迹=2（对称子空间 r+g, b 维数）",
}

# ---------------------------------------------------------------------------
# 2. 命题 2：转置的反对称化投影 P_anti = (I - (12))/2
# ---------------------------------------------------------------------------
P_anti = (I3 - t12) / 2
R["P2_transpose_anti"] = {
    "P_anti = (I-(12))/2": sp.latex(P_anti),
    "秩": int(P_anti.rank()),
    "迹": float(sp.trace(P_anti)),
    "含义": "反对称化投影（保留 r-g 差异），秩=迹=1（反对称子空间 r-g 维数）",
}

# ---------------------------------------------------------------------------
# 3. 命题 3：3-循环的完全对称化 P_tot = (I + (123) + (132))/3
# ---------------------------------------------------------------------------
P_tot = (I3 + c123 + c132) / 3
R["P3_3cycle_sym"] = {
    "P_tot = (I+(123)+(132))/3": sp.latex(P_tot),
    "秩": int(P_tot.rank()),
    "迹": float(sp.trace(P_tot)),
    "含义": "完全对称化（把 r,g,b 全等同），秩=迹=1（单态，颜色单态投影）",
}

# ---------------------------------------------------------------------------
# 4. 命题 4：验证投影算子的幂等性 + 正交性 + 完备性
# ---------------------------------------------------------------------------
R["P4_projection_props"] = {
    "P_sym 幂等 P_sym^2=P_sym": bool(sp.simplify(P_sym**2 - P_sym) == sp.zeros(3)),
    "P_anti 幂等": bool(sp.simplify(P_anti**2 - P_anti) == sp.zeros(3)),
    "P_sym + P_anti = I": bool(sp.simplify(P_sym + P_anti - I3) == sp.zeros(3)),
    "P_sym · P_anti = 0（正交）": bool(sp.simplify(P_sym * P_anti) == sp.zeros(3)),
    "P_tot 幂等": bool(sp.simplify(P_tot**2 - P_tot) == sp.zeros(3)),
}

# ---------------------------------------------------------------------------
# 5. 命题 5：转置的谱分解（特征值 + 特征子空间维数）
# ---------------------------------------------------------------------------
R["P5_transpose_spectrum"] = {
    "(12) 特征值": [str(x) for x in t12.eigenvals().items()],
    "+1 子空间维数": int((I3 + t12).rank()),   # 对称
    "-1 子空间维数": int((I3 - t12).rank()),   # 反对称
    "分解": "颜色 3 = 2(+1对称) ⊕ 1(-1反对称) = 弱同位旋2 ⊕ 超荷1",
}
R["P5_3cycle_spectrum"] = {
    "(123) 特征值": [str(x) for x in c123.eigenvals().items()],
    "说明": "3-循环特征值 {1, ω, ω²}（三个不同复数，ω=e^{2πi/3}），无实对称/反对称分解",
}

# ---------------------------------------------------------------------------
# 6. 命题 6（核心）：自然因子候选——不预设 27/32，纯结构组合
# ---------------------------------------------------------------------------
# 族维度 §25 机制：因子 = 区分迹 ÷ 等同迹（3-循环给 3/1 = 3，坐实）
# 转置主导时，「区分/等同」作用在转置的对称/反对称分解上，自然候选：
natural_factors = {
    "3-循环：区分(I3迹3) ÷ 等同(P_tot迹1)": 3.0 / 1.0,       # 观测第二→第三=3 ✓
    "转置：区分(I3迹3) ÷ 等同(P_sym迹2)": 3.0 / 2.0,          # = 1.5
    "转置：区分(P_anti迹1) ÷ 等同(P_sym迹2)": 1.0 / 2.0,      # = 0.5
    "转置：对称(P_sym迹2) ÷ 反对称(P_anti迹1)": 2.0 / 1.0,    # = 2
    "转置：区分(I3迹3) ÷ 反对称(P_anti迹1)": 3.0 / 1.0,       # = 3（和3-循环同，无区分）
}
R["P6_natural_factors"] = natural_factors

# 对比 29.2 中心值（29.4）和干净数 27/32
target = 29.4
R["P6_compare"] = {
    "29.2 中心值（PDG u=2.16）": target,
    "干净数 27(3³)": 27,
    "干净数 32(2⁵)": 32,
    "自然因子候选集合": sorted(natural_factors.values()),
    "判断": "自然因子候选 {0.5, 1.5, 2, 3} 都不接近 29.2，也不等于 27 或 32",
}

# ---------------------------------------------------------------------------
# 7. 诚实结论
# ---------------------------------------------------------------------------
R["conclusion"] = {
    "结构事实（坐实）": "转置=部分交换 → 对称化投影迹2 + 反对称化投影迹1（2⊕1分解）；3-循环=完整循环 → 完全对称化迹1（单态）",
    "自然因子": "转置的「区分/等同」机制自然给 {0.5, 1.5, 2, 3}，都不接近 29.2，也≠27、≠32",
    "含义": "「27=3³」和「32=2⁵」都不在「对称化/投影」机制的射程内——转置主导的因子，用现有机制推不出 27 或 32",
    "诚实定位": "29.2 的「干净数」解释（无论 27 还是 32）目前无结构支撑；29.2 兼容 27/32 是「未被排除」，不是「理论预测」",
    "措辞": "「29.2=27 是理论预测」=【未证实/待推导】（转置因子机制未定义）；「转置=部分交换（2⊕1）」=【结构事实，坐实】",
}
report(R, "exp_gap3_transpose_factor")
