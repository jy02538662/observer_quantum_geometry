"""
比值跑动 · 评估修正：「无绝对尺度 ⟹ 无跑动」这个推理本身可能是错的

上一轮 exp_scale_running 下「框架与实验矛盾」的结论，评估指出下得太快——
关键逻辑跳跃在「无绝对尺度 → 无 μ → 无跑动」的第二步。

本脚本纠正这个跳跃，聚焦【比值】而非【绝对值】：

  - 实验测到的「跑动」的物理内容 = 耦合【比值】随能标变（无量纲），不是绝对数值；
  - 「无绝对尺度」排除的是「绝对标定」，不排除「比值跑动」；
  - 框架的量子化（有限 N）本身【打破】尺度不变（λ_min = 2−δ_N = π²/N² ≠ 0），
    这就是跑动的种子（= 量纲嬗变 QCD Λ_QCD 的框架版）。

要算的三件事（评估指定）：
  1. 实验的比值跑动 α_s(M_Z)/α_s(m_τ)、α(M_Z)/α(0)、sin²θ_W(M_Z)/sin²θ_W(0)；
  2. 框架的对应比值（从 N 或 λ_min 或 λ_mod 来）；
  3. 三个耦合能不能都是 N 的不同函数（不同结构位置）。

逐条符号+数值验证。
"""
import sympy as sp
import numpy as np
from experiments._common import report

R = {}

N, lam, c = sp.symbols("N lambda c", positive=True)
pi = sp.pi

# ---------------------------------------------------------------------------
# 1. 纠正「无绝对尺度 ⟹ 无跑动」
# ---------------------------------------------------------------------------
# 观察者态 ρ = C/λ 尺度不变（这是「无绝对尺度」的精确含义）
rho = c / lam
rho_scaled = c / (2 * lam)
R["step1_no_absolute_scale"] = {
    "ρ(λ) = C/λ": str(rho),
    "ρ(2λ) = ρ(λ)/2（尺度不变，只差归一化）": str(sp.simplify(rho_scaled - rho / 2) == 0),
    "「无绝对尺度」的精确含义": "观察者态 ρ 尺度不变（无外部标尺，无绝对数值）",
}

# 但量子化（有限 N）【打破】尺度不变：λ_min = 2−δ_N = 4sin²(π/(2(N+1))) ≠ 0
delta_N = 2 * sp.cos(pi / (N + 1))
scale_break = 2 - delta_N   # = 2−δ_N = 4sin²(π/(2(N+1)))
R["step1_quantization_breaks_scale_invariance"] = {
    "量子化 δ_N = 2cos(π/(N+1))": str(delta_N),
    "尺度破缺 λ_min = 2−δ_N = 4sin²(π/(2(N+1)))": str(scale_break),
    "N→∞ 时 λ_min → ?": "→ 0（尺度不变恢复），有限 N 时 λ_min = π²/N² ≠ 0（尺度不变被打破）",
    "关键纠正": "「无绝对尺度」是【经典】尺度不变；【量子化（有限 N）打破它】→ λ_min=π²/N² 就是跑动的种子（= 量纲嬗变，QCD 的 Λ_QCD 框架版）",
    "所以「无绝对尺度 ⟹ 无跑动」是错的": "量子化已经打破了尺度不变，跑动的种子（λ_min=2−δ_N）框架本身就有",
}

# ---------------------------------------------------------------------------
# 2. 框架的「比值」能力：它已经给过一个比值（质量比 207）
# ---------------------------------------------------------------------------
lam_min = pi**2 / N**2
lam_c_val = sp.Integer(2)
lam_mod = sp.log(N**2 / (pi**2 * sp.log(2 * N**2 / pi**2)))  # = log(C/λ_min)

mass_ratio = sp.exp(lam_mod)   # m_μ/m_e = e^{λ_mod}
R["step2_framework_ratio_capability"] = {
    "λ_min = π²/N²": str(lam_min),
    "λ_mod = log(N²/(π²·ln(2N²/π²)))": str(lam_mod),
    "质量比 m_μ/m_e = e^{λ_mod}（N=128）": f"{float(sp.exp(lam_mod.subs(N, 128)).evalf()):.2f}",
    "说明": "框架【已经】用 λ_mod 给过一个无量纲比值（质量比 207）——证明「无绝对尺度」下框架【能】给比值",
    "这个比值的来源": "λ_mod = log(C/λ_min) 是 N 的函数，比值的「跑动」= λ_mod 随 N 变",
}

# ---------------------------------------------------------------------------
# 3. 实验的比值跑动（物理内容）
# ---------------------------------------------------------------------------
me = 0.511e-3
MZ = 91.19
m_tau = 1.777
ln_MZ_tau = np.log(MZ / m_tau)     # α_s 的两个参考点
ln_MZ_me = np.log(MZ / me)         # α、sin²θ_W 的两个参考点

# α_s：α_s(M_Z)=0.1179，α_s(m_τ)=0.330（PDG）
a_s_Z, a_s_tau = 0.1179, 0.330
ratio_as = a_s_Z / a_s_tau          # = 0.357

# α：α(M_Z)⁻¹=127.955，α(0)⁻¹=137.036
ratio_a = 137.036 / 127.955         # α(M_Z)/α(0) = 1.071

# sin²θ_W：sin²θ_W(M_Z)=0.23122，sin²θ_W(0)≈0.2386
ratio_sw = 0.23122 / 0.2386         # = 0.969

R["step3_experiment_ratio"] = {
    "α_s(M_Z)/α_s(m_τ)": round(float(ratio_as), 3),
    "α(M_Z)/α(0)": round(float(ratio_a), 3),
    "sin²θ_W(M_Z)/sin²θ_W(0)": round(float(ratio_sw), 3),
    "三个比值（跑动的物理内容）": "0.357 / 1.071 / 0.969——三个不同值，跑动就是这三个无量纲比值",
    "关键": "这三个比值【不需要绝对标定】——它们是纯比值，正是「无绝对尺度」不排除的东西",
}

# ---------------------------------------------------------------------------
# 4. 框架能否重现这三个比值？
# ---------------------------------------------------------------------------
# 框架的比值候选：若耦合 g² ∝ λ_min（第一刀，已作废），比值 = λ_min(N₁)/λ_min(N₂) = (N₂/N₁)²
# 若 g² ∝ λ_min 且 N ↔ μ，则 α_s(M_Z)/α_s(m_τ) = (N_τ/N_Z)²
N_Z_over_N_tau_needed = sp.sqrt(1 / ratio_as)   # 要 (N_τ/N_Z)² = 0.357 ⟹ N_τ/N_Z = 1/√0.357 ≈ 1.67

R["step4_framework_ratio"] = {
    "框架唯一耦合候选 g² ∝ λ_min（第一刀，已作废）": "比值 g²(N₁)/g²(N₂) = λ_min(N₁)/λ_min(N₂) = (N₂/N₁)²",
    "若用它重现 α_s(M_Z)/α_s(m_τ)=0.357": f"需 N_τ/N_Z = 1/√0.357 ≈ {float(N_Z_over_N_tau_needed.evalf()):.2f}",
    "但这需要": "① g²∝λ_min 成立（已被谱流作废）；② N↔μ 的结构等式（框架没有）",
    "λ_c=2、λ_mod 能否给耦合比值": "λ_c=2 是常数（比值恒 1，无跑动）；λ_mod 给的是质量比，不是规范耦合比",
    "三个耦合能否都是 N 的函数": "原则上可能（一个 N 出现在 λ_min、λ_c、λ_mod 三个位置，给三个不同函数），但需要每个耦合的结构等式 f₁(N)、f₂(N)、f₃(N)——目前一个都没有（唯一候选 g²∝λ_min 已作废）",
}

# ---------------------------------------------------------------------------
# 5. 诚实结论（修正上一轮）
# ---------------------------------------------------------------------------
R["step5_honest_conclusion"] = {
    "上一轮的错误": "把「无绝对尺度 ⟹ 无 μ ⟹ 无跑动」当结构结果，直接下「框架与实验矛盾」——跳过了一步：绝对 vs 比值没区分",
    "这一轮的修正": "「无绝对尺度」只排除【绝对标定】，不排除【比值跑动】；且框架的量子化（有限 N）本身【打破】尺度不变，λ_min=2−δ_N 就是跑动的种子（= 量纲嬗变）",
    "框架已经给的比值": "质量比 m_μ/m_e = e^{λ_mod} ≈ 207（证明框架【能】给比值，只是还没给到耦合上）",
    "真正缺的（不是「无绝对尺度」）": "① 耦合的函数（g、g'、g_s 各自随 N/λ_min/λ_mod 怎么变——唯一候选 g²∝λ_min 已作废，需内涨落 D→D+A 的圈图 = 规范场 β 函数）；② N↔μ 的结构等式",
    "措辞三档": "不是「矛盾」（无绝对尺度不排除比值跑动），是【未证实的开放】——框架有跑动的种子（尺度破缺 λ_min=2−δ_N），但把种子接到耦合比值（α、α_s、sin²θ_W 三个比值）上，缺内涨落的 β 函数（= 已知的动力学缺口）",
    "下一步该算的（真推进）": "算内涨落 D→D+A 的圈图（规范场 β 函数），看能否从框架给出 α_s 的比值跑动（渐近自由方向）——这是「尺度破缺种子」接到「耦合比值」的唯一活路，也是已知动力学缺口的正面进攻",
}

