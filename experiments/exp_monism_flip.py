"""
一元论翻转 · 从物理质量比「切割」出观察者层级 N

方向（翻转）：不是「从 N 推质量」（旧方向，撞墙：三个选择点），
而是「从物理质量比 m_μ/m_e = 206.77（观测）出发，用观察切割 E（条件期望）反推 N」。

框架结构：
  - 质量比 m_μ/m_e = e^{λ_mod}（λ_mod = 模流频率 = log ρ 谱最大特征值）
  - λ_mod(N) = log(C/λ_min) = log(N²/π²) − log(ln(2N²/π²))，λ_min = π²/N²（尺度破缺）
  - 观察切割 E：从观测 λ_mod_obs = ln(m_μ/m_e) 反解 N

判据：E(206.77) = N 是不是整数？是不是 128？
  - 若 N 干净 = 128（整数）→ 一元论翻转在质量谱上成立（观测唯一确定 N）；
  - 若 N ≈ 128.7（非整数）→ 翻转给出 N 但「128」仍是舍入选择（事后对齐未消）。
"""
import numpy as np
import sympy as sp
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. 观测质量比 m_μ/m_e（PDG 精确值）
# ---------------------------------------------------------------------------
m_mu_over_me = 206.7682830   # PDG 2024
lam_mod_obs = np.log(m_mu_over_me)
R["step1_observed"] = {
    "m_μ/m_e（PDG）": m_mu_over_me,
    "λ_mod_obs = ln(m_μ/m_e)": round(float(lam_mod_obs), 6),
}

# ---------------------------------------------------------------------------
# 2. λ_mod(N) 公式 + 反解 N（观察切割 E）
# ---------------------------------------------------------------------------
def lam_mod(N):
    return np.log(N**2 / np.pi**2) - np.log(np.log(2 * N**2 / np.pi**2))

# 二分法解 λ_mod(N) = λ_mod_obs
def solve_N(target, lo=2.0, hi=1e6, tol=1e-10):
    for _ in range(200):
        mid = (lo + hi) / 2
        if lam_mod(mid) < target:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2

N_solved = solve_N(lam_mod_obs)
R["step2_solved_N"] = {
    "λ_mod(N) 公式": "log(N²/π²) − log(ln(2N²/π²))",
    "反解 N = E(206.77)": round(float(N_solved), 4),
    "N 是整数吗": bool(abs(N_solved - round(N_solved)) < 1e-6),
    "最近整数": int(round(N_solved)),
    "距 128 的差": round(float(N_solved - 128), 4),
    "距 128 的相对差": round(float(abs(N_solved - 128) / 128 * 100), 3),
}

# 验证：λ_mod(反解 N) 是否回到观测值
R["step2_check"] = {
    "λ_mod(反解 N) = ln(206.768)": round(float(lam_mod(N_solved)), 6),
    "与观测一致": bool(abs(lam_mod(N_solved) - lam_mod_obs) < 1e-9),
}

# ---------------------------------------------------------------------------
# 3. 检查：N=128（框架自然值 2⁷）给什么质量比？
# ---------------------------------------------------------------------------
lam_mod_128 = lam_mod(128.0)
R["step3_N128"] = {
    "λ_mod(128)": round(float(lam_mod_128), 6),
    "e^{λ_mod(128)} = 预测 m_μ/m_e": round(float(np.exp(lam_mod_128)), 3),
    "对比观测 206.768": f"差 {abs(np.exp(lam_mod_128) - m_mu_over_me)/m_mu_over_me*100:.3f}%",
}

# 关键：反解 N vs 128 的「质量比」差异
R["step3_key"] = {
    "反解 N 给的质量比（=观测，精确）": m_mu_over_me,
    "N=128 给的质量比": round(float(np.exp(lam_mod_128)), 3),
    "两者差异来源": "反解 N ≈ 128.7，N=128 差 0.5%——这是「事后对齐」的精确形态",
}

# ---------------------------------------------------------------------------
# 4. 诚实结论
# ---------------------------------------------------------------------------
R["step4_honest_conclusion"] = {
    "一元论翻转结果": "E(206.77) = N ≈ 128.7（非精确整数，距 128 差 0.5%）",
    "N 是整数吗": "否——反解 N ≈ 128.7，不是干净整数",
    "是不是 128": "接近 128（差 0.5%），但不是精确 128",
    "一元论翻转成立吗": "部分——观测【确定】了 N（128.7，不是自由选择），但「128」仍是【舍入选择】（128.7→128 是舍入，非推导）",
    "对比旧方向": "旧方向「选 N=128 → 推 204.5（差 1%）」；翻转「观测 206.77 → 反解 128.7（差 0.5%）」——翻转【消除】了「选 N」的自由，但「128=2⁷」仍是「最近自然值」的舍入，不是从观测【逼出】",
    "根因（诚实）": "λ_mod(N) 公式本身含「λ_min=π²/N²（尺度破缺，非 3π²/N² 边缘间隔）」和「步长=1」两个假设——翻转只固定了质量比，没消除这两个假设；「128=2⁷」是「反解 128.7 的最近 2 的幂」，仍是事后对齐",
}

report(R, "exp_monism_flip")
