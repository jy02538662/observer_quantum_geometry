"""
继续推：框架里「N ↔ λ_c」的「两面」到底是 N↔λ_c=2 还是 N↔λ_mod？

从 OQG 1.13 §（line 523-524）+ 质量谱 1.14 笔记 line 96：
  「N↔λ_c（离散/连续截断）= 观察者有限性的两面（模流频率 λ_mod = log(N²/(π²·ln(2N²/π²)))，
    注意：λ_mod 是模流频率，非紫外截断 λ_c=2）」

所以框架的「观察者有限性」N 的「连续面」是 λ_mod（模流频率），不是 λ_c=2（紫外截断）。

质量谱：N=2^7=128 → λ_c(=λ_mod) = log(N²/(π²·ln(2N²/π²))) → m_μ/m_e = e^{λ_c} = 207。

验证：λ_mod 和 λ_c=2 到底差多少，以及「掺杂 = 观察者有限性」该挂哪个。
"""
import numpy as np
from experiments._common import report

R = {}

# ---- 1. 框架的「N ↔ λ_mod」关系 ----
N = 128
N2 = N**2
inner = 2 * N2 / np.pi**2          # 2N²/π²
ln_inner = np.log(inner)            # ln(2N²/π²)
lam_mod = np.log(N2 / (np.pi**2 * ln_inner))   # λ_mod = log(N²/(π²·ln(2N²/π²)))

R["N_to_lambda_mod"] = {
    "N = 2^7": N,
    "2N²/π²": f"{inner:.2f}",
    "ln(2N²/π²)": f"{ln_inner:.4f}",
    "λ_mod = log(N²/(π²·ln(2N²/π²)))": f"{lam_mod:.6f}",
    "e^{λ_mod}": f"{np.exp(lam_mod):.4f}",
    "对照 m_μ/m_e = 207": "≈ 207（质量谱 1.14 的结果）",
}

# ---- 2. λ_mod vs λ_c=2（UV 截断）----
R["lam_mod_vs_lam_c"] = {
    "λ_mod（模流频率，N↔λ_c 两面的连续面）": f"{lam_mod:.4f}",
    "λ_c（紫外截断，OQG 的 λ_c=2）": 2.0,
    "差": f"{lam_mod / 2.0:.2f} 倍",
    "结论": "λ_mod ≈ 5.32 ≠ λ_c = 2，是两个不同的量",
}

# ---- 3. 「掺杂 = 观察者有限性」挂哪个？ ----
# 若「掺杂 n = 1/λ」挂 λ_mod 还是 λ_c，给的 μ 不同
# μ = Λ/√λ（候选 c 形式），λ 取 λ_mod vs λ_c=2
R["doping_which_face"] = {
    "若「掺杂 = 1/λ_c」（λ_c=2，UV 截断）": "μ = Λ/√2 = 0.707 Λ",
    "若「掺杂 = 1/λ_mod」（λ_mod=5.32，模流面）": "μ = Λ/√5.32 = 0.434 Λ",
    "差": f"{np.sqrt(lam_mod/2.0):.2f} 倍（幂次一样，系数差）",
    "关键": "框架的「N↔λ_c」两面用的是 λ_mod（模流频率），不是 λ_c=2。若「掺杂=观察者有限性」走这个两面，该挂 λ_mod，不是 λ_c=2。",
}

# ---- 4. 净结论 ----
R["conclusion"] = {
    "框架「N↔λ_c」两面的真相": "= N↔λ_mod（模流频率 λ_mod=log(N²/(π²ln(2N²/π²)))≈5.32），不是 N↔λ_c=2（紫外截断）。",
    "λ_mod 的角色": "λ_mod 是「观察者有限性」的连续面，e^{λ_mod}=207=m_μ/m_e（质量谱用它）。λ_c=2 是另一回事（紫外截断/经典极限）。",
    "对「掺杂=观察者有限性」的影响": "之前笔记用「掺杂=1/λ_c=1/2」挂的是 λ_c=2。但框架的「观察者有限性」连续面是 λ_mod（不是 λ_c）——若「掺杂」挂「观察者有限性」的连续面，该挂 λ_mod，不是 λ_c=2。",
    "但注意": "这仍是「挂哪个量」的问题（λ_c vs λ_mod vs N），不是「幂次」的问题。幂次（1/λ vs 1/√λ vs log）还没锁死。",
}

report(R, "exp_superconducting_doping_lambda_mod")
