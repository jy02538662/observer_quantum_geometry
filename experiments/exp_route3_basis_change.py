"""
路3（味结构）· 味混合 = 换基（翻转）：先算清「代基」与「味基」的数学对象

翻转（用户洞察）：味混合不是「打破代守恒」，是「同一个质量矩阵的两个基」——
代基（S₃ 共轭类）下对角，味基（弱本征态）下非对角。V = 代基 → 味基的变换矩阵。

本脚本先做「侦察」：把 S₃ 的完整结构（共轭类、阶、不可约表示、置换表示）算清楚，
明确「代基」和「味基」各自的数学对象，以及 V 的维度匹配问题。

关键疑点（先查）：代基是 3 维（三代），但「手征 Γ」是 2 维（左/右手）——
若味基是「手征」（2 维），则 V 是 3×2 不是 3×3（CKM 是 3×3）。
"""
from sympy.combinatorics import Permutation
from sympy import Matrix
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. S3 完整结构：元素、循环类型、阶、共轭类
# ---------------------------------------------------------------------------
S3 = [Permutation([0,1,2]), Permutation([1,0,2]), Permutation([0,2,1]),
      Permutation([2,1,0]), Permutation([1,2,0]), Permutation([2,0,1])]

def cycle_type(p):
    return tuple(sorted([len(c) for c in p.cyclic_form]))

classes = {}
for p in S3:
    classes.setdefault(cycle_type(p), []).append(p)

# 代基 = 3 个共轭类（阶 1,2,3）
gen_basis = {}
for ct, els in sorted(classes.items()):
    gen_basis[str(ct)] = {"阶": int(els[0].order()), "类大小": len(els), "元素": [str(list(e.cyclic_form)) for e in els]}

R["step1_gen_basis"] = {
    "代基（共轭类）": gen_basis,
    "说明": "代 = 共轭类（阶 1,2,3），3 维",
}

# ---------------------------------------------------------------------------
# 2. S3 不可约表示（特征标表）
# ---------------------------------------------------------------------------
# S3 有 3 个不可约表示：平凡 1、符号 ε、标准 2 维 V
# 特征标（在 3 个类 [(), (2,), (3,)] 上）：
# χ_1   = (1, 1, 1)
# χ_ε   = (1, -1, 1)
# χ_V   = (2, 0, -1)
char_table = {
    "χ_1（平凡）": [1, 1, 1],
    "χ_ε（符号）": [1, -1, 1],
    "χ_V（标准 2 维）": [2, 0, -1],
}

R["step2_irreps"] = {
    "不可约特征标表（类 [恒等, 转置, 3-循环]）": char_table,
    "说明": "S3 有 3 个不可约表示（1+1+2），代基的「不可约」描述",
}

# ---------------------------------------------------------------------------
# 3. 置换表示（候选味基）：S3 置换 {1,2,3}，3 维
# ---------------------------------------------------------------------------
# 置换表示的特征标 = 固定点数：恒等 3、转置 1、3-循环 0
chi_perm = [3, 1, 0]

# 分解：χ_perm = χ_1 + χ_V（3,1,0 = (1,1,1) + (2,0,-1)）
chi_1 = [1, 1, 1]
chi_V = [2, 0, -1]
decomp = [chi_1[i] + chi_V[i] for i in range(3)]

R["step3_perm_rep"] = {
    "置换特征标 χ_perm（固定点数）": chi_perm,
    "分解 = χ_1 + χ_V": decomp,
    "是否匹配（χ_perm = χ_1+χ_V）": decomp == chi_perm,
    "说明": "置换表示（3 维）= 平凡 ⊕ 标准（1 ⊕ 2），可约",
}

# ---------------------------------------------------------------------------
# 4. 维度匹配检查：代基 vs 味基（手征）
# ---------------------------------------------------------------------------
# 代基 = 共轭类 = 3 维（三代）
# 手征 Γ = 断裂 = 二分 = 2 维（左/右手）
R["step4_dimension_check"] = {
    "代基维度": 3,
    "手征 Γ 维度": 2,
    "味混合 CKM 维度": 3,
    "问题": "若味基 = 手征 Γ（2 维），则 V 是 3×2 非 3×3（CKM 是 3×3）——维度不匹配",
    "候选味基（3 维）": "置换表示（3 维）或「3 代费米子的弱本征态」（上型/下型的 3 代）",
}

# ---------------------------------------------------------------------------
# 5. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "翻转（对的部分）": "味混合 = 换基（不是打破守恒），「对角 vs 非对角是基依赖的」是量子力学基本事实",
    "需先厘清": "「味基」的精确 3 维对象——手征 Γ 是 2 维（左/右），不是 3 维（代）；候选是置换表示（3 维）或「3 代弱本征态」",
    "下一步": "明确味基 = 什么 3 维对象，再算 V = 代基 → 味基 的变换，对比 CKM/PMNS",
}

report(R, "exp_route3_basis_change")
