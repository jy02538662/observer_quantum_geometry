"""
远景线 5（质量谱）· 深挖缺口1续：时间反演 T 与电荷共轭 J 的精确关系

深挖发现：时间反演 T（T²=-1，手征来源）和电荷共轭 J（J²=1，手征规范）是两个不同反演。
本脚本坐实它们的精确关系：J T J⁻¹ = -T（电荷共轭翻转时间反演）。

关键：若 J 翻转 T，则「手征规范（J）」和「手征来源（T）」是反对易的（非阿贝尔），
这可能给「手征规范只作用左手」的框架来源（方向 = 反对易）。
"""
import numpy as np
from sympy import Matrix, I, simplify, conjugate
from experiments._common import report

R = {}

sx = Matrix([[0,1],[1,0]])
sy = Matrix([[0,-I],[I,0]])
sz = Matrix([[1,0],[0,-1]])
I2 = Matrix([[1,0],[0,1]])

# ---------------------------------------------------------------------------
# (1) 时间反演 T = iσ_y（酉部分），T²=-1
# ---------------------------------------------------------------------------
T = I * sy
T_sq = simplify(T * T)
R["T"] = {
    "T = iσ_y": T == I * sy,
    "T² = -1": T_sq == -I2,
}

# ---------------------------------------------------------------------------
# (2) 电荷共轭 J = 复共轭 K（反酉），J²=1
# ---------------------------------------------------------------------------
# 复共轭 K 作用在矩阵上：K M K⁻¹ = M*（共轭）
# σ_y 纯虚：K σ_y K⁻¹ = σ_y* = -σ_y
# 所以 J T J⁻¹ = K(iσ_y)K⁻¹ = (iσ_y)* = -iσ_y = -T
# 验证：σ_y 的共轭 = -σ_y
sy_conj = Matrix([[0, conjugate(-I)],[conjugate(I),0]])  # σ_y* = -σ_y
R["J"] = {
    "J = K（复共轭，反酉）": "J²=1（对合）",
    "σ_y* = -σ_y（σ_y 纯虚）": sy_conj == -sy,
}

# ---------------------------------------------------------------------------
# (3) 关键关系：J T J⁻¹ = -T（电荷共轭翻转时间反演）
# ---------------------------------------------------------------------------
# J T J⁻¹ = K (iσ_y) K⁻¹ = (iσ_y)* = -i σ_y* = -i(-σ_y) = iσ_y = T？
# 等等，让我仔细算。
# (iσ_y)* = i* σ_y* = (-i)(-σ_y) = iσ_y = T
# 所以 J T J⁻¹ = T（不是 -T）？

# 让我重新算。T = iσ_y。
# K T K⁻¹ = K (iσ_y) K⁻¹ = (iσ_y)* = i* σ_y* = (-i)(-σ_y) = iσ_y = T
# 所以 K T K⁻¹ = T（复共轭保持 T = iσ_y，因为 iσ_y 是实的）

# 验证 iσ_y 是否是实的（共轭 = 自身）
T_conj = Matrix([[0, conjugate(1)],[conjugate(-1),0]])  # (iσ_y)* = [[0,1],[-1,0]] = iσ_y
R["JTJ"] = {
    "T = iσ_y = [[0,1],[-1,0]]（实矩阵）": T == Matrix([[0,1],[-1,0]]),
    "(iσ_y)* = iσ_y（T 是实的，复共轭保持 T）": T_conj == T,
    "关键": "T = iσ_y 是「实」的（反对称实矩阵），所以复共轭 K 保持 T（K T K⁻¹ = T），不是翻转",
    "结论": "电荷共轭 K（复共轭）不翻转时间反演 T（因为 T 是实的）；翻转的是「虚」的 σ_y（K σ_y K⁻¹ = -σ_y）",
}

# ---------------------------------------------------------------------------
# (4) 修正：翻转关系是 K σ_y K⁻¹ = -σ_y（不是 K T K⁻¹ = -T）
# ---------------------------------------------------------------------------
# σ_y = -iT（纯虚），K σ_y K⁻¹ = -σ_y（翻转）
# 而 T = iσ_y（实），K T K⁻¹ = T（保持）
# 所以「虚 vs 实」的区分：σ_y 虚（翻转），T = iσ_y 实（保持）
R["corrected_relation"] = {
    "K σ_y K⁻¹ = -σ_y": "复共轭翻转 σ_y（虚）",
    "K T K⁻¹ = T": "复共轭保持 T = iσ_y（实）",
    "关键": "时间反演 T = iσ_y 是「实」的（反对称实矩阵），电荷共轭 K 不翻转它；翻转的是 σ_y（虚）",
    "深层结构": "「实（T）vs 虚（σ_y）」的区分 = 有向 ±i 的实/虚面",
}

# ---------------------------------------------------------------------------
# (5) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实": "① T=iσ_y 是实矩阵（反对称实）；② 复共轭 K 保持 T（K T K⁻¹=T）、翻转 σ_y（K σ_y K⁻¹=-σ_y）；③ 「实 T vs 虚 σ_y」是有向 ±i 的实/虚面",
    "修正深挖": "之前「J 翻转 T」的猜想不对——T=iσ_y 是实的，电荷共轭 K 不翻转它。翻转的是虚的 σ_y",
    "手征规范卡点仍在": "电荷共轭 J 的左作用（弱同位旋只作用左手）还是「识别」（H_L 二重态、H_R 单态）非「推导」（Y 数值标定）",
    "新线索": "「实 T vs 虚 σ_y」的区分，可能对应「时间反演（实）vs 手征（虚 ±i）」——手征规范（电荷共轭）翻转虚的 σ_y，保持实的时间反演 T",
    "措辞": "符号坐实（T 实、σ_y 虚）+ 修正（J 不翻转 T）——手征规范卡点仍在，但「实/虚」是新线索",
}

report(R, "exp_T_J")
