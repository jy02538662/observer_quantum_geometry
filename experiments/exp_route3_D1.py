"""
路3（味结构）· D1 方向：V = 3-循环特征基 ↔ 转置特征基 的变换

画面（用户）：3 = 一个三角形，上型看「边」（3-循环，旋转），下型看「中心」（转置，反射）。
CKM = 从「3-循环特征基」到「转置特征基」的变换。

数学：S₃ 的 3 维置换表示。
  - 3-循环 (123)：本征值 {1, ω, ω²}（ω=e^{2πi/3}，单位立方根），本征向量 = 傅里叶基；
  - 转置 (12)：本征值 {1, 1, −1}，本征向量 = {对称, 不变, 反对称}；
  - V = ⟨转置基 | 3-循环基⟩（3×3 酉矩阵）。

对比 CKM：看 V 的模（混合角）和相位（CP 相位）是否像 CKM（三级混合、θ₁₃ 最小、CP 只在第三代）。
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 1. 置换矩阵：转置 (12) 和 3-循环 (123)
# ---------------------------------------------------------------------------
# 作用在 {1,2,3} 上（基 e1,e2,e3）
transpose_12 = np.array([[0, 1, 0],
                         [1, 0, 0],
                         [0, 0, 1]])   # 交换 1↔2

cycle_123 = np.array([[0, 0, 1],
                      [1, 0, 0],
                      [0, 1, 0]])      # 1→2→3→1

R["step1_matrices"] = {
    "转置 (12)": "[[0,1,0],[1,0,0],[0,0,1]]（交换 1↔2，反射）",
    "3-循环 (123)": "[[0,0,1],[1,0,0],[0,1,0]]（1→2→3，旋转 120°）",
}

# ---------------------------------------------------------------------------
# 2. 本征值 / 本征向量
# ---------------------------------------------------------------------------
ev_transpose, evec_transpose = np.linalg.eig(transpose_12)
ev_cycle, evec_cycle = np.linalg.eig(cycle_123)

# 排序（转置按本征值 1,1,-1；3-循环按 1,ω,ω²）
def sort_eig(ev, evec):
    idx = np.argsort([np.angle(z) for z in ev])   # 按相位排序
    return ev[idx], evec[:, idx]

ev_t, evec_t = sort_eig(ev_transpose, evec_transpose)
ev_c, evec_c = sort_eig(ev_cycle, evec_cycle)

R["step2_eigen"] = {
    "转置 (12) 本征值": [f"{z.real:.3f}+{z.imag:.3f}i" for z in ev_t],
    "转置本征值（期望 1,1,-1）": np.allclose(sorted(np.round(ev_t.real)), [1, 1, -1]),
    "3-循环 (123) 本征值": [f"{z.real:.3f}+{z.imag:.3f}i" for z in ev_c],
    "3-循环本征值（期望 1,ω,ω²）": np.allclose(sorted(np.round(ev_c.real, 2)), [-0.5, -0.5, 1.0]),
}

# ---------------------------------------------------------------------------
# 3. V = ⟨转置基 | 3-循环基⟩
# ---------------------------------------------------------------------------
# V 的矩阵元 V_ij = 转置本征向量 w_i 与 3-循环本征向量 v_j 的内积
# 即 V = evec_t^H @ evec_c（把 3-循环基表示为转置基的线性组合）
V = evec_t.conj().T @ evec_c

R["step3_V"] = {
    "V = ⟨转置基 | 3-循环基⟩（模）": [[round(abs(V[i, j]), 3) for j in range(3)] for i in range(3)],
    "V（相位）": [[f"{np.angle(V[i,j]):.3f}" for j in range(3)] for i in range(3)],
    "V 是酉矩阵（V†V=I）": bool(np.allclose(V.conj().T @ V, np.eye(3))),
}

# ---------------------------------------------------------------------------
# 4. 对比 CKM 的结构
# ---------------------------------------------------------------------------
# CKM 的近似结构（模）：对角主导，θ13 最小，θ12 最大，θ23 中等
# |V_CKM| ≈ [[0.974, 0.225, 0.003],
#            [0.224, 0.974, 0.042],
#            [0.009, 0.041, 0.999]]
V_abs = np.abs(V)
R["step4_compare"] = {
    "V 的模": [[round(x, 3) for x in row] for row in V_abs],
    "CKM 参考（模）": [[0.974, 0.225, 0.003], [0.224, 0.974, 0.042], [0.009, 0.041, 0.999]],
    "观察": "看 V 是否「对角主导 + θ13 最小 + CP 相位」",
}

# ---------------------------------------------------------------------------
# 5. 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "V 的具体结构": "见 step3_V / step4_compare 的模和相位",
    "判断依据": "若 V ≈ CKM（对角主导、θ13 最小、CP 只在第三代）→ D1 成立；否则需修正",
    "提醒": "「上型=3-循环、下型=转置」是候选对应（族维度 1.16 §五 标注非严格），D1 结果是候选层的计算",
}

report(R, "exp_route3_D1")
