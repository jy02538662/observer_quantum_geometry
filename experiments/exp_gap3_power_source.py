"""
缺口 3 · 幂次来源检验（路径1「三个转置→3³」的群论坐实）

用户候选路径1：转置作用在 3 维颜色空间 → 三个转置的「独立作用」→ 3³=27。
关键缺口：「三个转置的独立作用」是否成立。

本脚本不预设结论，符号验证三个群论事实，坐实「幂次」到底从哪来：
  P1：三个转置 (12),(13),(23) 生成整个 S₃（群论上不独立）
  P2：转置共轭类大小 = 3（「3 个转置」是状态数，不是自由度）
  P3：转置阶 2（二元）、3-循环阶 3（三元）——「区分」本质是二分
  P4：幂次来源 = 递归（重复），不是「类大小相乘」——N=128=2⁷ 的机制是「二分递归 7 次」
  P5：诚实结论：「3 的幂」需要「三分递归」，框架的区分是二分 → 无自然来源
"""
import sympy as sp
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# 0. S₃ 的元素（用置换矩阵表示，颜色基 {r, g, b}）
# ---------------------------------------------------------------------------
def perm_matrix(p):
    """p = [p0, p1, p2] 表示置换，返回 3×3 置换矩阵。"""
    M = sp.zeros(3)
    for i, j in enumerate(p):
        M[i, j] = 1
    return M

e    = perm_matrix([0, 1, 2])   # 恒等
t12  = perm_matrix([1, 0, 2])   # (12)：交换 r,g
t13  = perm_matrix([2, 1, 0])   # (13)：交换 r,b
t23  = perm_matrix([0, 2, 1])   # (23)：交换 g,b
c123 = perm_matrix([1, 2, 0])   # (123)：r→g→b→r
c132 = perm_matrix([2, 0, 1])   # (132)：r→b→g→r

S3 = [e, t12, t13, t23, c123, c132]

# ---------------------------------------------------------------------------
# P1：三个转置生成整个 S₃（群论上不独立）
# ---------------------------------------------------------------------------
# 枚举 {t12, t13, t23} 生成的子群，看是否 = S₃（6 个元素）
generators = [t12, t13, t23]
generated = set()

def mat_to_key(M):
    return tuple(int(M[i, j]) for i in range(3) for j in range(3))

def closure(gens):
    """由 gens 生成的乘法闭包。"""
    s = set(mat_to_key(g) for g in gens)
    s.add(mat_to_key(e))
    changed = True
    while changed:
        changed = False
        items = [sp.Matrix(3, 3, list(k)) for k in s]
        for a in items:
            for b in items:
                k = mat_to_key(a * b)
                if k not in s:
                    s.add(k)
                    changed = True
        if len(s) >= 6:
            break
    return s

closure_transpositions = closure(generators)
R["P1_three_transpositions_generate_S3"] = {
    "三个转置生成的群元素数": len(closure_transpositions),
    "S3 元素数": 6,
    "生成整个 S3（不独立）?": bool(len(closure_transpositions) == 6),
    "含义": "三个转置 (12),(13),(23) 乘积生成整个 S₃——群论上它们不独立（(12)(13)=(132) 等）",
}

# ---------------------------------------------------------------------------
# P2：转置共轭类大小 = 3（「3 个转置」是状态数）
# ---------------------------------------------------------------------------
def conj_class(g, group):
    """g 在 group 里的共轭类。"""
    return set(mat_to_key(h * g * h.inv()) for h in group)

conj_t12 = conj_class(t12, S3)
R["P2_transposition_class_size"] = {
    "(12) 共轭类元素数": len(conj_t12),
    "共轭类 = {(12),(13),(23)}": bool(len(conj_t12) == 3),
    "含义": "转置共轭类大小 3 = 3 个共轭代表（状态数），不是 3 个独立自由度",
}

# ---------------------------------------------------------------------------
# P3：转置阶 2（二元）、3-循环阶 3（三元）
# ---------------------------------------------------------------------------
def order(M):
    k = 1
    cur = M
    while not (cur == sp.eye(3)):
        cur = cur * M
        k += 1
        if k > 6:
            break
    return k

R["P3_orders"] = {
    "ord((12))": order(t12),
    "ord((123))": order(c123),
    "含义": "转置阶 2（二分，做两次回来）、3-循环阶 3（三分，做三次回来）——「区分」本质是二分（±1）",
}

# ---------------------------------------------------------------------------
# P4：幂次来源 = 递归（重复），不是「类大小相乘」
#     N=128=2⁷ 的机制：区分=二分，递归 7 次 → 2⁷
# ---------------------------------------------------------------------------
R["P4_power_source"] = {
    "N=128=2⁷ 的来源": "有向区分推导链：区分=二分递归，递归 7 次 → 2⁷（2 的幂）",
    "2 的幂（区分递归 n 次）": [2**n for n in range(1, 5)],
    "3 的幂（三分递归 n 次）": [3**n for n in range(1, 5)],
    "关键区分": "「3 个转置」（类大小=状态数，同时的 3 个对象）≠「3 次重复」（递归=幂次）。幂次需要「重复」，而「重复」的本质是「区分递归」= 二分。",
}

# ---------------------------------------------------------------------------
# P5：诚实结论
# ---------------------------------------------------------------------------
R["P5_conclusion"] = {
    "结构事实（坐实）": "① 三个转置生成 S₃（不独立）；② 转置类大小 3（状态数，非自由度）；③ 转置阶 2（二分），3-循环阶 3（三分）",
    "「3 个转置→3³」的问题": "把「类大小 3（同时的 3 个对象）」当「3 次重复（递归=幂次）」——混淆了「状态数」和「递归次数」",
    "框架的幂次来源": "N=128=2⁷ 的幂次来自「区分=二分」递归 7 次 → 2 的幂。区分本质是二分（±1，看/不看），所以框架的幂次只能是 2 的幂",
    "「3 的幂」需要什么": "「三分递归」（三分=三个方向区分），但框架的区分是二分 → 没有「三分」结构 → 3 的幂无自然来源",
    "和「维数比」的关系": "「3」（颜色维数）= 同时的 3 个对象 → 维数比 3/1（OK）；「3³」= 3 次重复 → 需要三分递归（框架没有）。这就是「维数比 vs 幂次」的根源：维数=同时对象，幂次=递归重复，框架递归是二分",
    "诚实定位": "「三个转置→3³」=【群论计数错误】（类大小≠递归次数，与「7=2³−1 是状态数非自由度」同款）；「框架幂次=二分递归」=【结构事实，坐实（N=128）】",
}
report(R, "exp_gap3_power_source")
