def perm(p):
    M = sp.zeros(3)
    for i, j in enumerate(p):
        M[i, j] = 1
    return M

def order(M):
    k, cur = 1, M
    while cur != sp.eye(3):
        cur = cur * M; k += 1
        if k > 6: break
    return k

