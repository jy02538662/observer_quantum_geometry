"""
远景线 5（质量谱）· 验证「区分=方向」推导里 圆参数化 vs 半圆参数化 的矛盾

用户推导（第六步）：区分 = 方向，θ_x = 2π·n(x)/128 —— 这是「圆 [0,2π)」参数化。
用户推导（第四步）：cos 偶函数 → 半圆 —— 正反方向等同。

矛盾：第四步已缩成「半圆」，第六步又用「圆」参数化。
数值：圆 128 等分经 cos 偶函数后 = 65 唯一值（对不上 128）；
      半圆 128 内点经 cos = 128 唯一值 = Chebyshev。

本脚本验证这个矛盾，并给出正确参数化（半圆）。
"""
import numpy as np
from experiments._common import report

R = {}

# ============ 1. 用户第六步：圆参数化 θ = 2πn/128 ============
# 128 种模式 n=0..127 → 圆上 128 等分点
n = np.arange(128)
theta_circle = 2 * np.pi * n / 128
cos_circle = np.cos(theta_circle)
unique_circle = len(np.unique(np.round(cos_circle, 6)))

R["user_circle_param"] = {
    "θ = 2πn/128（圆 [0,2π) 128 等分）": "128 个角度",
    "含端点 θ=0（n=0）": True,
    "cos 后唯一值数": unique_circle,
    "矛盾": "cos 偶函数（第四步）使 θ 和 2π-θ 重复，128 圆点 → 65 唯一值，对不上「128 个方向」",
}

# ============ 2. 正确：半圆参数化 θ = (n+1)π/129 ============
# 半圆 (0,π) 128 内点（量子化到不了端点）
theta_half = (n + 1) * np.pi / 129
cos_half = np.cos(theta_half)
unique_half = len(np.unique(np.round(cos_half, 6)))

# Chebyshev 零点
cheb = 2 * np.cos((n + 1) * np.pi / 129)

R["correct_half_param"] = {
    "θ = (n+1)π/129（半圆 (0,π) 128 内点）": "128 个角度",
    "不含端点（θ=0 对应 n=-1 不存在）": True,
    "cos 后唯一值数": unique_half,
    "是否 = Chebyshev 零点 2cos(kπ/129)": np.allclose(cos_half, np.cos((n+1)*np.pi/129)),
}

# ============ 3. 关键对比 ============
R["key_comparison"] = {
    "圆参数化（用户第六步）": f"128 圆点 → cos 后 {unique_circle} 唯一值（镜像重复，浪费一半）",
    "半圆参数化（修正）": f"128 半圆内点 → cos 后 {unique_half} 唯一值 = Chebyshev 零点",
    "结论": "第六步的「圆参数化 θ=2πn/128」是错的——和第四步「半圆」矛盾。正确是「半圆参数化 θ=(n+1)π/129」",
}

# ============ 4. 为什么是「半圆」不是「圆」：cos 偶函数的顺序 ============
# 逻辑顺序：
#   1. 有向 J²=-I → 圆 [0,2π)
#   2. cos 偶函数（自反性取实部）→ 正反方向等同 → 半圆 [0,π]
#   3. 区分 = 方向 → 半圆上 128 个方向（不是圆上）
#   4. 无偏好 → 均匀 → 128 内点（量子化到不了端点）
R["order_of_operations"] = {
    "正确顺序": "先 cos 偶函数（半圆），再参数化（半圆内点）",
    "用户推导顺序": "第四步 cos 偶函数（半圆），第六步圆参数化（圆）—— 顺序颠倒/不一致",
    "修正": "第六步的「圆参数化」应改为「半圆参数化」：θ = (n+1)π/129",
}

R["honest_conclusion"] = {
    "发现": "用户「区分=方向」的核心洞察（二进制参数化）是对的，但具体参数化用错了——「圆」应为「半圆」",
    "矛盾根源": "第四步 cos 偶函数已把方向空间缩成半圆，第六步却用圆 [0,2π) 参数化，二者不一致",
    "数值坐实": "圆参数化 cos 后 65 唯一值（对不上 128）；半圆参数化 cos 后 128 唯一值 = Chebyshev",
    "修正": "θ = 2πn/128（圆）→ θ = (n+1)π/129（半圆内点），这样才自洽",
    "措辞": "这是「圆 vs 半圆」的参数化 bug，核心洞察（区分=方向=二进制参数化）仍成立，但具体形式要改半圆",
}

report(R, "exp_circle_half_contradiction")
