"""
远景线 5（质量谱）· 族维度第七刀：「3Y 奇偶=手征」能否从公设推出（手征性的来源）

第六刀坐实「3Y 奇偶 = 手征」=「颜色 3=2⊕1」的体现。本刀检验它能否从公设「推导」，
核心是「手征性」（弱同位旋 = 左手）的来源。

框架里的候选链条：
  断裂 → 二元闭环 → U(2) → SU(2)（弱同位旋，家底 3）
  手征 Γ = 二分 = 断裂（1.14 的三个 Z₂ 识别）
  ⟹ 弱同位旋（断裂）作用在左手（Γ 的一侧）？——「手征性」的框架来源

本脚本检验：
  (1) 手征 Γ = 二分（Γ²=1, ΓD=-DΓ，谱 ±E 对称）；
  (2) 断裂 = 二元闭环（π 磁通反对易 T_xT_y=-T_yT_x → SU(2)）；
  (3) 「断裂 = 二分」是否同一 Z₂（1.14 识别）；
  (4) 「弱同位旋 = 左手」= 断裂作用在 Γ 的一侧（候选，检验能否坐实）。
"""
import numpy as np
from experiments._common import report

R = {}

# ---------------------------------------------------------------------------
# (1) 手征 Γ = 二分（π 磁通格点）
# ---------------------------------------------------------------------------
# 构造 4×4 π 磁通格点的 Dirac 算符（二分反对角），手征 Γ = diag((-1)^{i+j})
N = 4
Gamma = np.diag(np.array([(-1.0)**(i + j) for i in range(N) for j in range(N)]))
# Γ²=1
Gamma_sq = Gamma @ Gamma
# 构造一个二分反对角的 D（连接 A/B 子格），验证 ΓD = -DΓ
# 二分：A 子格 = (i+j) 偶，B 子格 = (i+j) 奇
idx = [(i, j) for i in range(N) for j in range(N)]
A = [k for k, (i, j) in enumerate(idx) if (i+j) % 2 == 0]
B = [k for k, (i, j) in enumerate(idx) if (i+j) % 2 == 1]
# D 是二分反对角：D[A,B] 和 D[B,A] 非零，D[A,A]=D[B,B]=0
D = np.zeros((N*N, N*N))
# 最近邻 hopping（A↔B）
for k, (i, j) in enumerate(idx):
    for di, dj in [(1,0), (-1,0), (0,1), (0,-1)]:
        ni, nj = i+di, j+dj
        if 0 <= ni < N and 0 <= nj < N:
            l = idx.index((ni, nj))
            if (i+j) % 2 != (ni+nj) % 2:  # 二分：只连 A↔B
                D[k, l] = 1.0
D = (D + D.T) / 2  # 厄米

GD_comm = Gamma @ D - D @ Gamma  # ΓD - DΓ（应 = 0 若 ΓD=DΓ）
GD_anti = Gamma @ D + D @ Gamma   # ΓD + DΓ（应 = 0 若 ΓD=-DΓ）

R["chirality_gamma"] = {
    "Γ²=I": bool(np.allclose(Gamma_sq, np.eye(N*N))),
    "ΓD = DΓ？（对易，应 False）": bool(np.allclose(GD_comm, 0)),
    "ΓD = -DΓ？（反对易，应 True）": bool(np.allclose(GD_anti, 0)),
    "谱 ±E 对称（D 的谱关于 0 对称）": bool(np.allclose(np.sort(np.linalg.eigvalsh(D)), -np.sort(np.linalg.eigvalsh(D))[::-1])),
    "意义": "手征 Γ = 二分（bipartite sign），ΓD=-DΓ，谱 ±E 对称",
}

# ---------------------------------------------------------------------------
# (2) 断裂 = 二元闭环 = π 磁通反对易 → SU(2)
# ---------------------------------------------------------------------------
# π 磁通：磁平移 T_x, T_y 反对易（T_xT_y = -T_yT_x）
# 用泡利矩阵表示：T_x = σ_x, T_y = σ_y（反对易 σ_xσ_y = -σ_yσ_x）
sx = np.array([[0, 1], [1, 0]], dtype=complex)
sy = np.array([[0, -1j], [1j, 0]], dtype=complex)
sz = np.array([[1, 0], [0, -1]], dtype=complex)
anti_comm = sx @ sy + sy @ sx  # σ_xσ_y + σ_yσ_x（应 = 0）
# SU(2) 生成元 = 反对易的磁平移生成的 σ_x, σ_y, σ_z = -iσ_xσ_y
R["breaking_su2"] = {
    "T_xT_y + T_yT_x（反对易，应 0）": bool(np.allclose(anti_comm, 0)),
    "SU(2) 生成元 = {σ_x, σ_y, σ_z}（σ_z = -iσ_xσ_y）": "非阿贝尔，内部三维 SU(2)≅S³",
    "意义": "断裂（π 磁通反对易）→ 非阿贝尔 → SU(2)（弱同位旋）",
}

# ---------------------------------------------------------------------------
# (3) 「断裂 = 二分」的识别（1.14）
# ---------------------------------------------------------------------------
# 1.14 识别：Γ（手征）= 二分 = 断裂
# 二分（bipartite sign）和断裂（二元闭环）是「无外部观察者」的同一面（谱结构面）
R["breaking_equals_bipartite"] = {
    "1.14 识别": "Γ（手征）= 二分 = 断裂（谱结构面）",
    "二分": "bipartite sign（A/B 子格），Γ²=1",
    "断裂": "二元闭环（i↔j），→ U(2) → SU(2)",
    "识别依据": "二分和断裂都是「2 的结构」（A/B vs i/j），是「无外部观察者」的谱结构面",
    "状态": "这是 1.14 的「识别」（把二分和断裂识别为同一 Γ），不是「推导」（从公设推出同一性）",
}

# ---------------------------------------------------------------------------
# (4) 「弱同位旋 = 左手」= 断裂作用在 Γ 的一侧（候选）
# ---------------------------------------------------------------------------
# 关键：若「断裂 = 二分 = 手征 Γ」，则「弱同位旋（断裂）作用在左手（Γ 的一侧）」
# = 「Γ 的自我作用」（Γ 既是手征，又产生 SU(2)，SU(2) 作用在 Γ 的一侧）
# 这个「自我作用」是「手征规范理论」（弱同位旋只作用左手）的框架来源候选
R["weak_isospin_left_handed"] = {
    "候选机制": "断裂 = 手征 Γ 的自我作用：Γ 产生 SU(2)（断裂），SU(2) 作用在 Γ 的 +1 侧（左手）",
    "手征性（弱同位旋只作用左手）": "标准模型设定（1.12 的 H_L/H_R 分解），框架能否推出待定",
    "卡点": "「断裂 = 二分」是「识别」非「推导」；「SU(2) 作用在 Γ 的一侧」的机制未坐实",
}

# ---------------------------------------------------------------------------
# (5) 诚实结论
# ---------------------------------------------------------------------------
R["honest_conclusion"] = {
    "坐实（符号）": "① 手征 Γ = 二分（Γ²=1, ΓD=-DΓ, 谱 ±E 对称）；② 断裂 = π 磁通反对易（T_xT_y=-T_yT_x）→ SU(2)",
    "识别（非推导）": "「断裂 = 二分 = 手征 Γ」是 1.14 的「识别」（二分和断裂识别为同一 Γ），不是「推导」（从公设推出同一性）",
    "核心卡点": "「手征性」（弱同位旋 = 左手）是标准模型设定（1.12 H_L/H_R），框架还没从公设推出「弱同位旋只作用左手」——「3Y 奇偶=手征」的「推导」卡在这一步",
    "候选突破口": "「Γ 的自我作用」：Γ 既是手征（二分）又产生 SU(2)（断裂），SU(2) 作用在 Γ 的一侧（左手）——这是「手征规范理论」的框架来源候选，需坐实「断裂=二分」的「推导」（而非「识别」）",
    "措辞": "符号坐实 + 卡点定位（非「已推导手征性」）——「手征 Γ=二分」和「断裂→SU(2)」坐实，「断裂=二分」的推导和「SU(2)作用在Γ一侧」待定",
}

report(R, "exp_chirality_origin")
